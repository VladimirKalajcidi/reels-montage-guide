"""Проверка начал фраз ролика 66 по огибающей (урок ролика 57 v2 + 60): первое слово каждой фразы CAPS сравнивается
с фактическим началом звука — первый кадр RMS 10 мс ≥ −36 дБ после ≥80 мс тишины (< −36 дБ) в окне ±0.35с.
Расхождение > 0.06с печатается: слово всплывёт раньше/позже, чем его скажут. Норма — только фразы, где первое слово
идёт после опущенного в субтитре (у ролика 66 — после фраз, которые несёт графика)."""
import env166 as e, render166 as r

db = e.db
bad = 0
for ci, cap in enumerate(r.CAPS):
    t = r.WORD_T[ci][0]
    i0 = max(0, int((t - 0.35) * 100))
    run, onset = 0, None
    for k, v in enumerate(db[i0:int((t + 0.35) * 100)]):
        if v < -36:
            run += 1
        else:
            if run >= 8:
                onset = (i0 + k) / 100
            run = 0
    if onset is not None and abs(onset - t) > 0.06:
        bad += 1
        print(f"{ci:2d} {' '.join(x[0] for x in cap[2])[:28]:28s} слово {t:.2f}  звук {onset:.2f}  Δ {onset - t:+.2f}")
print("расхождений:", bad)
