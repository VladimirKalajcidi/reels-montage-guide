"""Генерирует монтажный лист ролика 18 из раскадровки."""
import sys, os
from decimal import Decimal

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard18 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS, CENTURIES,
                          YEAR_J_SHORT, YEAR_G, DIFF)

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "div4": ("R4+R10", "сетка: шкала лет, каждый четвёртый год — высокая засечка, подпись года и квадрат добавленного дня"),
    "noexc": ("R4+R10", "сетка: та же шкала едет влево, ни один четвёртый год не пропущен"),
    "drift": ("R4+R10", "сетка: месячная календарная сетка, тонкая рамка — где дата должна быть, залитая клетка уезжает вправо"),
    "y36525": ("R4+R5a", "сетка: белое «365,25» и квадрат, у которого закрашена одна четверть"),
    "y3652425": ("R4+R5b", "сетка: синее «365,2425», разряды набираются синхронно речи"),
    "diff": ("R4+R5b", "сетка: «365,2500» над «365,2425», расхождение в рамке, синяя разница «0,0075»"),
    "over4": ("R4+R10", "сетка: четыре года, в четвёртый кладут целый день — он выше клетки, излишек уходит в копилку"),
    "accum": ("R4+R10", "сетка: курсор идёт по линии лет, излишки сыплются в накопитель, он переполняется и выдаёт целый день"),
    "rule4": ("R4+R10", "сетка: ряд веков, всем галка (все делятся на 4)"),
    "rule100": ("R4+R10", "сетка: галки гаснут, всем векам крест (все делятся на 100)"),
    "rule400": ("R4+R10", "сетка: 2000 возвращает галку и берётся в рамку (делится на 400)"),
    "y2000": ("R4+R10", "сетка: «2000», три проверки делимости, решающая ÷400 в рамке, итог — галка"),
    "y1900": ("R4+R10", "сетка: «1900», те же три проверки, ÷400 не проходит, итог — крест"),
}


def leap(y):
    return y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    yj = Decimal(YEAR_J_SHORT.replace(",", "."))
    yg = Decimal(YEAR_G.replace(",", "."))
    diff = yj - yg
    per400 = diff * 400
    dropped = [y for y in range(1700, 2001, 100) if not leap(y)]   # один 400-летний цикл

    print("# Монтажный лист — «правило високосного года»\n")
    print(f"Исходник: `videos/18/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (теги сверены, конверсия не нужна)")
    print("Готовый ролик: `videos/18/leap_edit.mp4` · 1080×1920\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {(lens[(len(lens)-1)//2] + lens[len(lens)//2]) / 2:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 2 ({YEAR_G} · {DIFF})\n")
    print("Речь не резана: резы только по картинке, все — на границах фраз "
          "по пословным таймингам whisper.\n")

    print("## Арифметика ролика (пересчитана кодом)\n")
    print(f"- Правило четырёх считает год равным **{YEAR_J_SHORT}** суток, "
          f"средний григорианский год — **{YEAR_G}**.")
    ru = lambda v: str(v.normalize()).replace(".", ",")
    print(f"- Разница **{ru(diff)}** суток в год — это и есть синее число на плане `diff`.")
    print(f"- За 400 лет набегает {ru(diff)} × 400 = **{ru(per400)}** суток.")
    print(f"- Столько високосных дней и снимает уточнение «÷100, кроме ÷400»: "
          f"за один 400-летний цикл (1601–2000) високосными перестают быть "
          f"{', '.join(str(y) for y in dropped)} — ровно {len(dropped)}, "
          f"что и сходится с {ru(per400)} набежавшими сутками.")
    print(f"- Проверка примеров из речи: 2000 — {'високосный' if leap(2000) else 'не високосный'}, "
          f"1900 — {'високосный' if leap(1900) else 'не високосный'}.\n")
    print(f"Ряд веков на экране: {', '.join(str(y) for y in CENTURIES)} — все делятся на 4 и на 100, "
          "на 400 из них делится только 2000.\n")

    print("Зоны на планах с графикой: субтитры y 300…600, графика y 700…1560 "
          "(`brand-kit.md §5`). Числа, которые звучат в речи (365,25 · 365,2425 · 2000 · 1900), "
          "пишет только графика — субтитра на этих планах либо нет вовсе, либо он несёт "
          "одни слова. Слова из речи («четыре», «сто», «четыреста») графика не пишет.\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        if not txt:
            txt = "— (пауза в речи)" if kind in FACE_KINDS else "— (говорит графика)"
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | {txt} |")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки. Исходная дорожка -21.7 LUFS, LRA 3.5.")
    print("- Whoosh на каждой склейке (0.040 от пика), импакт под синим числом (0.070), "
          "тики каскада (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее ролика — "
          "идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор volume/alimiter.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/18/stock/`, источник Mixkit (свободная лицензия):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")

    print("\n## Решения по этому дублю")
    print("- **Исходник 720×1280**, а не 1080×1920 как в прошлых роликах, поэтому `FRAMINGS` "
          "пересчитаны заново: детектор даёт лицо x≈235 y≈513 d≈303 (после `hflip`), "
          "линия глаз y≈640, кроп ставит глаза на 41% высоты карточки A. Карточка собирается "
          "апскейлом 667→870 по ширине — на готовом кадре это не читается, но исходник "
          "в 1080p дал бы более чистую картинку.")
    print("- **`hflip` включён.** Надписи в кадре нет, поэтому зеркальность проверена по руке "
          "с петличкой: в сыром экспорте она входит справа — ровно как в ролике 17, "
          "где зеркальность подтверждена надписью на футболке.")
    print("- **A-roll не грейдится** — только `hflip` и кроп. Средний RGB кадра 126/116/109, "
          "R>G>B, кадр уже тёплый; ориентир `brand-kit §6` (130/112/104) достигается только "
          "ценой шума (проверено на ролике 16).")
    print("- **Кадры идут в кодек одним проходом** — сырой поток в ffmpeg вместо "
          "промежуточного `cv2.VideoWriter(mp4v)`.")

    print("\n## Расхождения с гайдом, названные числами")
    print("- **Кегль синего числа 104 вместо XL 150–200.** «365,2425» это 8 глифов; "
          "при кегле 150 строка занимает 936px, а зона графики — 730px "
          "(`brand-kit §5`: x 175…905). Правило «графика не выходит из своей зоны» жёстче "
          "шкалы кеглей, поэтому кегль подобран под ширину: 104 → 649px + свечение.")
    print("- **Белое «365,25» — кегль 150** (нижняя граница XL) по той же причине: "
          "при 175 строка 792px и вылезает из зоны.")
    print("- **Ряд веков — 5 значений, кегль 36.** Шесть веков (с 1600) при шаге, "
          "который влезает в зону, дают зазор между подписями меньше 20px и слипаются "
          "на кадре — проверено рендером. Пять (1700…2100) держат зазор 36px и покрывают "
          "оба примера из речи: 1900 и 2000.")

    print("\n## Чего в ролике сознательно нет (по рецептам)")
    print("- **R3 (очередь быстрых резов)** — материал предметный: у Mixkit нет ни одного "
          "релевантного клипа под «календарь съезжает» или «лишний день», а очередь пришлось "
          "бы набивать случайными перебивками. `assets-manifest.md §2`: лучше своя графика.")
    print("- **Сток под «календарь»** — все календарные клипы Mixkit (17412, 17413, 34197, "
          "2847) пересвечены: в полосе субтитров карточки B средняя яркость после штатного "
          "притемнения ×0.72 держится на 170–183 из 255, белый текст на них не читается. "
          "План закрыт собственной календарной сеткой, которая вдобавок показывает само "
          "«съезжание» — этого не даёт ни один сток.")
    print("- **R6 (крупное слово в карточке)** — полоса над головой это подсвеченный "
          "натяжной потолок со светодиодной лентой; белое слово на 62% там разрывается светом.")
    print("- **R8 (пруф-вставка)** и **R9 (предметный PNG)** — в речи нет ни ссылки "
          "на источник, ни предмета, который стоило бы вклеить отдельным PNG.")
    print("- **Третье и четвёртое синее число** — в сценарии всего два числа-результата "
          "(365,2425 и 0,0075). `brand-kit §4` ставит потолок в 4, а не план.")
    print("\n## Результаты проверок на сданном файле")
    print("| проверка | результат | норма |")
    print("|---|---|---|")
    print("| текст ярче 200 вне карточки (скан через 3 кадра) | **0 кадров** | 0 |")
    print("| графика × субтитры, общие пиксели при альфе >40 | **0 кадров** | 0 |")
    print("| графика вне зоны y700…1560 / x175…905 | **0 кадров** | 0 |")
    print("| субтитры вне карточки (отступ 30px) | **0 кадров** | 0 |")
    print("| пересечение строк внутри блока | **0 пар** | 0 |")
    print("| резы в середине слова (по `source_words.json`) | **0 из 23** | 0 |")
    print("| интегрированная громкость | **-14.1 LUFS** | ≈ -14 |")
    print("| истинный пик | **-1.6 dBTP** | ≤ -1 |")
    print("| LRA | 2.6 LU | 3–5 — **уже нормы** на 0.4 LU |")
    print("| PSNR кадра к тому, что отдал рендер | **44.8 / 46.6 / 48.7 dB** | ≥ 40 (один кодек) |")
    print("| средний RGB карточки A: сданный минус исходный кроп | **−2.9…−0.3** | грейда нет; "
          "тот же сдвиг даёт принятый ролик 17 (−3.0…+0.1) — это round-trip RGB→yuv420p |")
    print("\nLRA 2.6 вместо 3–5: дубль записан очень ровно (исходник -21.7 LUFS при LRA 3.5), "
          "музыка на −19 dB подтягивает тихие места. Расширять диапазон значило бы либо резать "
          "речь, либо снимать музыку — оба хуже.")



if __name__ == "__main__":
    emit()
