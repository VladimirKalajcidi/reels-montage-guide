"""Генерирует монтажный лист ролика 19 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard19 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS, QR_TEXT,
                          QR_VERSION, QR_ECC, QR_N, TOTAL_CW, DATA_CW, ECC_CW,
                          RECOVER_PCT)
import render19

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "qrlogo": ("R4+R10", "сетка: QR набирается модулями, в центр садится плашка логотипа"),
    "qrok": ("R4+R10", "сетка: по QR с логотипом идёт луч сканера, снизу проявляется галка"),
    "qrbuild": ("R4+R10", "сетка: QR собирается волной модулей от угла"),
    "qrcells": ("R4+R10", "сетка: символ распадается на 16 белых блоков данных "
                          "и 28 лаймовых блоков резерва"),
    "rsdata": ("R4+R5a", "сетка: 16 блоков данных с белым числом 16"),
    "rsmethod": ("R4+R10", "сетка: от блоков данных стрелка вниз в пустую пунктирную зону"),
    "rsappend": ("R4+R5a", "сетка: пунктирная зона заполняется 28 лаймовыми блоками, число 28"),
    "rsback": ("R4+R10", "сетка: 44 блока схлопываются обратно в символ"),
    "damage1": ("R4+R10", "сетка: из QR выедается рваный кусок"),
    "damage2": ("R4+R10", "сетка: добавляются две царапины и плашка логотипа"),
    "restore": ("R4+R10", "сетка: утраченные модули возвращаются лаймом и гаснут в чёрный"),
    "pct30": ("R4+R5b", "сетка: повреждение доходит до 30% модулей, синее «30 %»"),
    "redund2": ("R4+R10", "сетка: под символом пульсирует лаймовая полоса из 28 блоков резерва"),
    "qrworn": ("R4+R10", "сетка: потрёпанный символ — рваный кусок и две царапины"),
    "qrok2": ("R4+R10", "сетка: по потрёпанному символу идёт луч, снизу галка"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    print("# Монтажный лист — «QR-код и код Рида-Соломона»\n")
    print(f"Исходник: `videos/19/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (теги сверены с hook1/hook2, конверсия не нужна)")
    print("Готовый ролик: `videos/19/qr_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 1 ({RECOVER_PCT} %)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам whisper (`qa19.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## QR на экране — настоящий")
    print(f"- Символ построен `segno`: версия **{QR_VERSION}**, уровень коррекции "
          f"**{QR_ECC}**, **{QR_N}×{QR_N}** модулей, содержимое `{QR_TEXT}` "
          "(обычное слово, не ссылка).")
    print(f"- Кодовых слов у {QR_VERSION}-{QR_ECC}: всего **{TOTAL_CW}**, из них "
          f"**{DATA_CW}** данных и **{ECC_CW}** резерва Рида-Соломона. "
          "Это и есть 16 белых и 28 лаймовых блоков на экране.")
    print(f"- Уровень {QR_ECC} восстанавливает до ~**{RECOVER_PCT}%** символа — "
          "число из речи, поэтому его пишет только графика.")
    print("- Панель белая, модули чёрные: инвертированный QR штатный декодер "
          "не читает — проверено.")
    print("- **Проверка декодером идёт по готовому кадру ролика** (`qa19.qr_decodes`): "
          "на планах `qrok` (символ под логотипом), `qrbuild`, `restore`, `redund2`, "
          "`qrworn` и `qrok2` cv2 действительно считывает "
          f"`{QR_TEXT}`. Там, где графика обещает «считывается» лучом и галкой, "
          "код читается на самом деле.")
    print("- Поисковые узоры, узор выравнивания и синхродорожки из повреждений "
          "исключены: без них декодер не находит символ вообще.")
    print(f"- Доли повреждения на планах: `damage2` — {100*len(render19.LOST_CELLS)/render19.QR_N**2:.0f}% "
          f"модулей, `qrworn`/`qrok2` — {100*len(render19.WORN_CELLS)/render19.QR_N**2:.0f}%, "
          f"`pct30` — ровно {100*len(render19.PCT_CELLS)/render19.QR_N**2:.0f}%.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print("- Whoosh на каждой склейке (0.040 от пика), импакт под синим числом (0.070), "
          "тики каскада (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее ролика — "
          "идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор volume/alimiter.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/19/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции).")
    print("Все клипы **приведены к 30 fps**: оригинал лежит рядом как `raw_<id>.mp4`, "
          "в сборку идёт `stock_<id>.mp4`. Клипы приходят 23.976 / 24 / 25 fps, а рендер "
          "читает их кадр в кадр — без конформа вставка играет на 25% быстрее "
          "(`delivery-specs.md §2`).\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")

    print("\n## Решения по этому дублю")
    print("- **A-roll не грейдится** — только `hflip` и кроп. Дубль дневной и уже светлый.")
    print("- **`hflip` включён**: дубль снят фронталкой, как и все предыдущие. "
          "Надписи в кадре нет, проверить зеркальность по тексту не на чем — "
          "ориентир: рука с петличкой стоит в кадре с той же стороны, что в ролике 17, "
          "где зеркальность подтверждена надписью на футболке.")
    print("- **Исходник 720×1280**, а карточка A — 870×1380. Кадр апскейлится "
          "в 1.24 раза (`INTER_CUBIC`). Предыдущие дубли приходили в 1080×1920. "
          "Замер: PSNR кадров с лицом (рендер до кодека против готового файла) "
          "**38.3–40.0 dB** против **40.4 dB** у ролика 17, и это при более "
          "щадящем crf (15 против 16). Разница — цена апскейла и более заметного "
          "шума 720p-дубля, а не пережатия: планы с графикой дают 43–47 dB. "
          "Поднимать битрейт смысла нет — по прошлому замеру crf 12 против 15 "
          "даёт +0.4 dB при файле в 1.65 раза больше. Лечится только съёмкой "
          "в полном разрешении.")
    print("- **Кадры идут в кодек одним проходом** — сырой поток в ffmpeg вместо "
          "промежуточного `cv2.VideoWriter(mp4v)`.")
    print("- **Грейда на лице нет — проверено числами.** Средний RGB карточки A "
          "в готовом файле против того же кропа из исходника расходится на "
          "**2.4–3.4 единицы** по каналу. Ровно такой же разброс (2.4–3.1) даёт "
          "сданный ролик 17 — это цена round-trip RGB → yuv420p, а не коррекция.")
    print("- **Наблюдение, не правил:** выходной файл выходит без тегов "
          "цветового пространства (`color_space`/`color_primaries`/`color_transfer` "
          "= unknown). Так же отдавались все прошлые ролики, включая 17-й, поэтому "
          "трогать это в одном ролике не стал — иначе он будет выглядеть иначе, "
          "чем остальная лента. Если проставлять теги bt709, это надо делать "
          "разом для всего пайплайна.")
    print("- **Лайм `#C3DB4E` — один смысловой элемент на весь ролик**: он всегда и "
          "только «резервные данные» (28 блоков, пунктирная зона под них, "
          "восстановленные модули). Другого второго акцента в ролике нет.")

    print("\n## Чего в ролике сознательно нет")
    print("- **R6 (крупное слово в карточке)** — над головой в кадре потолок с "
          "точечными светильниками; белое слово на 62% там садится прямо на "
          "светящиеся пятна и рвётся.")
    print("- **R3 (очередь быстрых резов)** — материал предметный, очередь пришлось бы "
          "набивать нерелевантным стоком.")
    print("- **R8 (пруф-вставка)** и **R9 (предметный PNG)** — в речи нет ни ссылки "
          "на источник, ни предмета, который стоило бы вклеить отдельным PNG.")
    print("- **Сток под сам QR-код и сканирование** — на Mixkit нет ни одного клипа "
          "с QR-кодом, сканером или штрих-кодом (`qr-code`, `scanner`, `barcode` — пусто; "
          "поиск перепроверен исправленным парсером, который берёт id из слага клипа). "
          "По правилу «лучше своя графика, чем случайная перебивка» весь предметный слой "
          "нарисован на сетке, а сток взят только под три буквальных существительных "
          "из речи: кофе, телефон, недостающие части.")


if __name__ == "__main__":
    emit()
