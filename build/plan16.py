"""Генерирует монтажный лист ролика 16 из раскадровки."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard16 import SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "sheet": ("R4+R10", "сетка: вычерчивается лист А4, внутри проступают строки"),
    "fold": ("R4+R10", "сетка: верхняя половина листа ложится на нижнюю по линии сгиба"),
    "half": ("R4+R10", "сетка: получившаяся половинка отделяется и встаёт в центр"),
    "same": ("R4+R10", "сетка: половинка поворачивается на 90° и растёт в √2 — "
                       "и точно ложится на контур исходного листа"),
    "sides": ("R4+R10", "сетка: обе стороны листа берутся в мерные скобки"),
    "ratio": ("R4+R5b", "сетка: у короткой стороны белая «1», у длинной синяя «√2»"),
    "halfproof": ("R4+R10", "сетка: каскад вложенных половинок — каждая вдвое меньше "
                            "и той же формы"),
    "algebra": ("R4+R5b", "сетка: вывод x : 1 = 1 : x/2 → x² = 2 → x = √2 (синяя)"),
    "ladder": ("R4+R10", "сетка: линейка из семи форматов, подписаны А0 и А6"),
    "scale": ("R4+R10", "сетка: два А5 влетают внутрь контура А4 и заполняют его целиком"),
    "cut": ("R4+R10", "сетка: рез идёт поперёк листа, половинки расходятся"),
    "next": ("R4+R10", "сетка: нижняя половина встаёт вертикально — следующий формат"),
    "sameprop": ("R4+R10", "сетка: лист и половинка с одинаковой меткой «1 : √2» и знаком ="),
    "unique": ("R4+R10", "сетка: лист 1 : 1.15 после сгиба не попадает в свою же форму, "
                         "зазор показан скобкой, результат перечёркнут"),
}

face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

print("# Монтажный лист — «почему формат А4 — это 1 : √2»\n")
print(f"Исходник: `videos/16/source.mov` · 1080×1920 · 30 fps · {DUR:.2f}с · "
      "SDR bt709 (теги сверены, конверсия не нужна)")
print("Готовый ролик: `videos/16/a4_edit.mp4`\n")
print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
      f"медиана {(lens[len(lens)//2-1]+lens[len(lens)//2])/2:.2f}с · мин {lens[0]:.2f}с · "
      f"макс {lens[-1]:.2f}с · первый рез {SHOTS[0][1]:.2f}с")
print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
      f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 2 (√2 у стороны листа "
      "и √2 в конце вывода)\n")
print("Речь не резана: резы только по картинке, все — на границах фраз "
      "по пословным таймингам Whisper (`videos/16/source.json`).\n")
print("Зоны на планах с графикой: субтитры y 300…600, графика y 700…1560 "
      "(`brand-kit.md §5`).\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
    rec, desc = NAMES[kind]
    if prm.get("clip"):
        desc = STOCK_NAMES[prm["clip"]]
    txt = " / ".join("".join(r[0] for r in runs).strip()
                     for (a, b, runs, _s) in CAPS if t0 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
          f"| {txt or '— (говорит графика)'} |")

print("\n## Где смысл несёт графика, а не субтитр")
print("`brand-kit.md §5` — «одно и то же не пишется дважды»:\n")
print("- **19.42–21.58 (`ratio`)** — в речи «один к квадратному корню из двух». "
      "Это ровно то, что написано у сторон листа, поэтому субтитра на плане нет вообще.")
print("- **28.88–30.40 (`ladder`)** — в речи «от а0 до а6». Подписи стоят под крайними "
      "прямоугольниками линейки, субтитр на этом куске речи не ставится.")
print("- **8.24–10.96 (`half`)** — в речи «это формат а5», значит подписи «А5» "
      "на графике нет: слово несёт субтитр.")
print("- Выкладка `x : 1 = 1 : x/2 → x² = 2 → x = √2` вслух не звучит — "
      "это добавление к речи, а не дубль субтитра.")

print("\n## Картинка")
print("- **A-roll не грейдится.** Кадр с лицом идёт в карточку A только через `hflip`, "
      "кроп и ресайз — ни гамма-кривой, ни баланса каналов, ни насыщенности.")
print("- Это расхождение с `brand-kit.md §1/§6`, где грейд обязателен и задан ориентир "
      "~130/112/104 по средним. На этом дубле выход на ориентир требовал гаммы 1.60 "
      "с подъёмом чёрной точки, и это поднимало шум с 1.45 до 2.11 и вымывало лицо.")
print("- Факт: средний RGB карточки A в сданном файле **77.7 / 66.6 / 58.4**, "
      "тот же кроп прямо из исходника — **77.6 / 65.2 / 59.0**. Расхождение до 1.4 единицы, "
      "то есть картинка отдана как снята.")
print("- **Кодек один.** Кадры уходят в ffmpeg сырыми (`rawvideo bgr24`) и кодируются "
      "один раз, libx264 crf 12 preset slow. Промежуточного файла нет.")
print("- Раньше в тракте стоял `cv2.VideoWriter` с кодеком `mp4v`: он писал MPEG-4 Part 2 "
      "на 3.8 Мбит/с при исходнике 12.75 Мбит/с, и это ещё раз жалось в H.264.")
print("- Проверка: PSNR собранного кадра к тому, что отдал рендер до кодека — "
      "**41.0 dB**, средняя ошибка 1.5 единицы на 0–255.\n")

print("\n## Звук")
print("- Речь исходника целиком, без резки.")
print("- Whoosh на каждой склейке (0.040 от пика), импакт под синими числами (0.070), "
      "тики каскада (0.030).")
print("- Музыка `audios/song2.mp3`: −19 dB от RMS голоса, петля с кроссфейдом 0.25с, "
      "фейды 0.8 / 2.0с.")
print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + volume/alimiter.")

print("\n## Сток")
print("Скачан под этот ролик в `videos/16/stock/`, источник Mixkit "
      "(свободная лицензия, коммерческое использование без атрибуции):\n")
for cid, name in STOCK_NAMES.items():
    print(f"- `stock_{cid}.mp4` — {name}")
print("\nБольше стока в ролике нет сознательно: тема предметная (лист, сгиб, рез, "
      "пропорция), и по `assets-manifest.md §2` такие биты закрываются своей графикой, "
      "а не перебивкой ради ритма. Живого видео «лист режут ровно пополам» "
      "в свободных библиотеках не нашлось — этот бит нарисован (план `cut`).")

print("\n## Чего в ролике сознательно нет")
print("- **R6 (крупное слово в карточке)** — над головой в этом дубле светлый потолок "
      "с точечными светильниками; белое слово на 62% там не читается, а опустить его "
      "ниже нельзя — сядет на голову.")
print("- **R3 (очередь быстрых резов)** — материал предметный, очередь пришлось бы "
      "набивать нерелевантным стоком.")
print("- **R8 (пруф-вставка)** и **R9 (предметный PNG)** — в речи нет ни ссылки "
      "на источник, ни названного предмета, который стоило бы вклеить отдельно.")
