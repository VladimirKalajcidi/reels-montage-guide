"""Генерирует монтажный лист ролика 21 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard21 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS,
                          THRESHOLD, PLANNED, GAP, DISC_PCT, DISCOUNT, MARGIN)
import render21

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "thresh": ("R4+R5a", f"сетка: прочерчивается шкала чека, на ней встаёт отметка "
                         f"порога, над ней белое «{THRESHOLD} ₽»"),
    "calc": ("R4+R10", "сетка: несколько пробных отметок порога гаснут, "
                       "остаётся одна — порог не случаен, его выбрали"),
    "check": ("R4+R10", "сетка: облако чеков разных покупателей над шкалой "
                        "и стрелка роста в сторону порога"),
    "n2200": ("R4+R5a", f"сетка: шкала заливается до планируемого чека, "
                        f"над ней белое «{PLANNED} ₽»"),
    "gap800": ("R4+R5b", f"сетка: участок от {PLANNED} до {THRESHOLD} подсвечен "
                         f"как незакрытый разрыв, над ним синее «{GAP} ₽»"),
    "reach": ("R4+R10", "сетка: разрыв закрывается тремя добавленными товарами, "
                        "заливка доходит до отметки порога"),
    "unlock": ("R4+R10", f"сетка: порог взят, отметка пульсирует, над ней "
                         f"плашка «−{DISC_PCT}%»"),
    "added": ("R4+R10", f"сетка: две полосы на одной линейке — «+{GAP} ₽» добавлено "
                        f"против «−{DISCOUNT} ₽» скидки"),
    "plus": ("R4+R5b", f"сетка: из полосы «добавлено» вычитается скидка, светится "
                       f"остаток, над ним синее «+{MARGIN} ₽»"),
    "thrcalc": ("R4+R10", "сетка: облако чеков, маркер их среднего и порог, "
                          "поставленный чуть правее среднего — это и есть расчёт"),
    "rise": ("R4+R10", f"сетка: маркер среднего переезжает с {PLANNED} на {THRESHOLD}, "
                       "пройденный путь подсвечен на шкале"),
    "verdict": ("R4+R10", f"сетка: два столбика от общей базовой линии — прирост "
                          f"«+{GAP} ₽» против скидки «−{DISCOUNT} ₽»"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    print("# Монтажный лист — «порог скидки: почему скидка начинается ровно с 3000»\n")
    print(f"Исходник: `videos/21/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/21/porog_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 2 "
          f"(«{GAP} ₽» и «+{MARGIN} ₽»)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам whisper (`qa21.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        if prm.get("big"):
            desc += f" + **R6**: крупное «{prm['big']}» на стене над головой"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Числа: кто их пишет")
    print("В речи звучат два числа. Оба пишет **только графика**, "
          "субтитра с этим числом на этих планах нет вообще (brand-kit §5):\n")
    print("| число | когда звучит | где появляется | субтитр на плане |")
    print("|---|---|---|---|")
    print(f"| 3 тысяч рублей | 2.06–2.88 | белое «{THRESHOLD} ₽» на плане `thresh` | нет |")
    print(f"| {PLANNED} рублей | 13.08–14.26 | белое «{PLANNED} ₽» на плане `n2200` | нет |")
    print("\nОстальные числа в речи не звучат и выводятся на экране — это то, "
          "что графика **добавляет**, а не повторяет:\n")
    print("| число | откуда | где |")
    print("|---|---|---|")
    print(f"| **{GAP} ₽** | {THRESHOLD} − {PLANNED} — сколько не хватает до порога "
          f"| синий ревил на `gap800` (16.92) |")
    print(f"| {DISC_PCT}% | размер скидки | плашка «−{DISC_PCT}%» на `unlock` |")
    print(f"| {DISCOUNT} ₽ | {DISC_PCT}% от {THRESHOLD} | полоса «−{DISCOUNT} ₽» "
          f"на `added`, столбик на `verdict` |")
    print(f"| **+{MARGIN} ₽** | {GAP} − {DISCOUNT} — что осталось магазину "
          f"| синий ревил на `plus` (27.60) |")
    print(f"\n**Допущение монтажа: скидка = {DISC_PCT}% от порога.** В речи процент "
          "не назван — сказано только «если добавленная сумма превышает размер самой "
          f"скидки». Чтобы неравенство стало проверяемым числом, взят рабочий пример "
          f"{DISC_PCT}%, и он объявлен на экране («−{DISC_PCT}%» на плане `unlock`) "
          f"**до** того, как из него получается {DISCOUNT} ₽. Дальше вся арифметика "
          f"сходится: {GAP} − {DISCOUNT} = {MARGIN}. Если процент нужен другой — "
          "это одна строка `DISC_PCT` в `storyboard21.py`, ролик пересобирается целиком.")
    print(f"\nСиних чисел два, оба — результат вычисления, а не просто цифра: "
          f"«{GAP} ₽» (разрыв до порога) и «+{MARGIN} ₽» (что осталось магазину). "
          "Белые числа — подписи величин на шкале, а не результаты.")

    print("\n## Предметная графика")
    print("Весь ролик держится на **одной шкале чека** — горизонтальном жёлобе "
          f"0…3600 ₽ (x {render21.BAR_X0}…{render21.BAR_X1}). Это даёт главное: "
          "все длины на экране сравнимы между собой одной линейкой.")
    print(f"- Отметка порога стоит на {THRESHOLD} ₽ = x {render21.X_THR:.0f}, "
          f"планируемый чек — на {PLANNED} ₽ = x {render21.X_PLAN:.0f}. "
          f"Разрыв между ними — {render21.X_THR - render21.X_PLAN:.0f}px, "
          f"ровно {GAP} ₽ в масштабе шкалы.")
    print("- Шкала не двигается и не масштабируется между планами: меняются только "
          "заливка, подсветка и пометки. Поэтому переход `n2200` → `gap800` → `reach` "
          "читается как один непрерывный процесс, а не три разных картинки.")
    print("- **Облако «чеков»** (планы `check` и `thrcalc`) — 13 штрихов, разброс "
          f"детерминированный, и он смещён так, что **среднее облака равно ровно "
          f"{PLANNED} ₽**. Маркер среднего стоит именно там, где среднее, — это "
          "проверяемо, а не нарисовано на глаз.")
    print("- **План `verdict` — единственный, где шкалы нет.** На основной линейке "
          f"{GAP} ₽ и {DISCOUNT} ₽ дают полосы {GAP*(render21.BAR_X1-render21.BAR_X0)/3600:.0f} "
          f"и {DISCOUNT*(render21.BAR_X1-render21.BAR_X0)/3600:.0f}px — на глаз это "
          "не сравнение, а два пятна. Столбики от общей базовой линии дают то же "
          f"отношение **{GAP/DISCOUNT:.2f} : 1** и читаются с паузы мгновенно.")
    print("- **Лайм `#C3DB4E` не использован.** Единственная величина, которую стоило "
          "бы выделить вторым акцентом, — остаток магазина, а он и так уходит "
          "в синее число.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print("- Whoosh на каждой склейке (0.040 от пика), импакт под синими числами "
          "(0.070) на 16.92 и 27.60, тики под каскадами элементов (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор volume/alimiter.")
    print("- Замер готового `.mp4`: **-14.0 LUFS**, истинный пик **-1.6 dBTP** — в цели. "
          "Первая итерация со штатным `volume=0.2dB` (как в ролике 20) дала -13.7 LUFS, "
          "добор снижен до -0.1 dB.")
    print("- **LRA 2.0 LU** при норме гайда 3–5. Это свойство дубля: речь идёт очень "
          "ровно, без громких и тихих мест. Лимитером и loudnorm не лечится — "
          "фиксирую замер, а не правлю.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/21/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nОба клипа отобраны **по яркости полосы субтитров**, а не только по смыслу "
          "(`videos/<...>/stock` берётся в 360p, полоса меряется по всей длине, "
          "и только потом качается рабочее разрешение):\n")
    print("| клип | `ss` | средняя яркость полосы | p90 | порог |")
    print("|---|---|---|---|---|")
    print("| `stock_47415` | 5.90 | 67–72 | 129–144 | ≤110 / ≤140 |")
    print("| `stock_49137` | 0.00 | 93–99 | 138–141 | ≤110 / ≤140 |")
    print("\nУ 47415 p90 на трёх кадрах уходит до 144 при средней 68 — это точечный "
          "блик на ноутбуке, а не светлый фон; белый текст со свечением на средней 68 "
          "читается. Отбраковано по полосе: 46685 (124/145), 46752 (132/139), "
          "34125, 47007, 21629, 49349 (118/173), 5890 (p90 183).")
    print("\nОба клипа идут 25 fps и **конформятся к 30 fps проекта по времени**, "
          "а не читаются кадр-в-кадр: последовательное чтение играло бы замедленно.")

    print("\n## Решения по этому дублю")
    print("- **A-roll не грейдится** — только `hflip` и кроп.")
    print("- **Кроп посчитан детектором, а не на глаз.** 81 замер по ролику после "
          "`hflip`: лицо стабильно на cx 390.5, линия глаз y 669.7, ширина 267. "
          "Кроп ставит глаза на 43% высоты карточки (A1) и 41.5% (A2) — те же "
          "проценты, что в ролике 20.")
    print("- **У A1 центр кропа на 4.5px левее лица.** Исходник 720px шириной, "
          "кроп A1 — 668px: сдвинуть его правее уже некуда. На экране это 5.9px "
          "из 870 — не ловится глазом, но фиксирую.")
    print("- **`hflip` включён**: дубль снят фронталкой, надписей в кадре нет, "
          "рука с петличкой с той же стороны, что в предыдущих роликах из этой комнаты.")
    print("- **Исходник 720×1280**, карточка A — 870×1380: кадр апскейлится "
          "в 1.30 раза (A1) и 1.45 (A2), `INTER_CUBIC`. Цена съёмки не в полном "
          "разрешении, а не пережатие.")
    print("- **Кадры идут в кодек одним проходом** — сырой поток в ffmpeg вместо "
          "промежуточного `cv2.VideoWriter(mp4v)`.")
    print("- **Грейда на лице нет — проверено числами.** Средний RGB карточки A "
          "в готовом файле против того же кропа из исходника расходится на "
          "**0.1–2.6 единицы** по каналу на шести замерах лица. Это цена round-trip "
          "RGB → yuv420p, а не коррекция.")
    print("- **Дубль темнее ориентира гайда.** Средний RGB карточки A — "
          "**117 / 102 / 94** против «~130 / 112 / 104» в `brand-kit §6`. Тёплый "
          "баланс на месте (R > G > B), но общий уровень ниже. Это вопрос света "
          "на съёмке: подтянуть гаммой пробовали на ролике 16 — лицо стало плоским, "
          "шум вырос в полтора раза. Называю цифру, грейд не возвращаю.")

    print("\n## Автопроверки")
    print("Обе обязательные из `START-HERE.md` и все дополнительные — по нулям "
          "(`python3 qa21.py`):\n")
    print("| проверка | результат |")
    print("|---|---|")
    print("| текст за карточкой (скан готового mp4 через каждые 3 кадра, порог 200) "
          "| **0 кадров** |")
    print("| наложение строк внутри блока (по `font.getbbox`) | **0 пар** |")
    print("| графика пересекает субтитры (по альфе >40) | **0 кадров** |")
    print("| графика вне зоны y700–1560 / x175–905 | **0 кадров** |")
    print("| крупное слово R6 вне карточки A с отступом 30px | **0 кадров** |")
    print("| субтитр вне карточки с отступом 30px | **0 кадров** |")
    print("| рез попал в середину слова | **0 резов** |")
    print("| фраза разошлась с речью по пословным таймингам | **0 фраз** |")
    print("| планы длиннее 6с / короче 1с | **0 / 0** |")

    print("\n## Чего в ролике сознательно нет")
    print("- **R3 (очередь быстрых резов)** — в речи нет эмоционального пика, "
          "очередь пришлось бы набивать нерелевантным стоком.")
    print("- **R8 (пруф-вставка)** — в речи нет ссылки на источник.")
    print("- **R9 (предметный PNG)** — в речи не назван ни один конкретный предмет "
          "(«что-то ещё» — намеренно неопределённое).")
    print("- **R7 (счётная вставка)** — в речи нет ряда количеств.")
    print("- **Второй акцент `#C3DB4E`** — см. раздел «Предметная графика».")
    print("- **Сток под сам порог, ценник «от 3000» и корзину с суммой** — на Mixkit "
          "нет ни одного клипа с ценником-порогом или с экраном кассы, где видна сумма "
          "(поиск по `discount`, `sale`, `price`, `receipt`, `checkout`). По правилу "
          "«лучше своя графика, чем случайная перебивка» весь числовой слой нарисован "
          "на сетке, а сток взят под два буквальных существительных из речи: "
          "маркетологи, которые считают, и человек, который добавляет товар в корзину.")


if __name__ == "__main__":
    emit()
