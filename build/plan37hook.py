"""Монтажные листы версий ролика 37 с другим хуком.

    python3 plan37hook.py h1 > ../videos/37/montage-plan-hook1.md
    python3 plan37hook.py h2 > ../videos/37/montage-plan-hook2.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hook37 as HK
import storyboard37 as SB
from plan37 import NAMES, A, AN
from style import FPS

# замеры сданных файлов (qa37hooks.log)
MEAS = {
    "h1": dict(lufs=-14.2, tp=-1.6, lra=2.4, frames=1663, dur=55.43,
               shots=28, avg=1.98, median=1.93, shortest=1.23, longest=3.30,
               first_cut=1.93, face_pct=32.7,
               seam_same=0.92, seam_diff=11.02, tail_diff=6.13,
               old_face_min=9.66, old_face_thr=4.00,
               body_worst=2.0, click=(0.00430, 0.15506),
               pause=0.173, rgb_hook=(123, 110, 101), rgb_main=(123, 110, 102),
               deform="кроп ×0.98: ширина карточки A 869.78px → 887.74px = "
                      "**×1.0206** при ожидаемых ×1.0208 (ffmpeg режет кроп до "
                      "целых: 1080×0.98 = 1058.4 → 1058, отсюда 1080/1058)",
               band=(36.4, 47.0), motion=7.55),
    "h2": dict(lufs=-14.2, tp=-1.6, lra=2.7, frames=1667, dur=55.57,
               shots=29, avg=1.92, median=1.80, shortest=1.21, longest=3.24,
               first_cut=1.31, face_pct=33.6,
               seam_same=0.04, seam_diff=10.68, tail_diff=57.35,
               old_face_min=9.49, old_face_thr=2.04,
               body_worst=1.03, click=(0.00031, 0.15533),
               pause=0.188, rgb_hook=(122, 109, 101), rgb_main=(123, 110, 102),
               deform="ускорение ×1.02: ширина карточки A 869.78px → 869.78px = "
                      "**×1.0000** (кадр не деформирован, и не должен), fps на "
                      "выходе **30/1**, длительность 55.567с при расчётных "
                      "55.556с, расхождение видео/звук 0.018с",
               band=(58.5, 63.5), motion=9.30),
}

DEFORM_RULE = {
    "h1": "версия 2 — кроп ×0.98",
    "h2": "версия 3 — ускорение ×1.02 (картинка и звук вместе)",
}


def emit(key):
    cfg = HK.HOOKS[key]
    m = MEAS[key]
    v = cfg["version"]
    rate = 1.02 if cfg.get("post_a") else 1.0
    shots = HK.shots_of(cfg)
    nf = cfg["frames"]
    dt = nf / FPS - HK.CUT_V

    print(f"# Монтажный лист — версия {v}, хук {key[-1]}\n")
    print(f"Новое начало: {cfg['title']}\n")
    print(f"Исходник хука: `videos/37/{os.path.basename(cfg['src'])}` · 720×1280 · "
          f"30 fps · {cfg['src_frames']/FPS:.3f}с · SDR bt709 "
          "(`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print(f"Тело: готовые кадры из `assets/_video_{SB.TAG}.mp4` с кадра "
          f"{HK.CUT_F}, без пересборки")
    print(f"Готовый файл: `videos/37/{os.path.basename(cfg['out'])}` · 1080×1920 · "
          f"30 fps · {m['frames']} кадров · {m['dur']:.2f}с\n")

    print(f"**Планов:** {m['shots']} · средняя **{m['avg']:.2f}с** · медиана "
          f"{m['median']:.2f}с · мин {m['shortest']:.2f}с · макс {m['longest']:.2f}с · "
          f"первый рез {m['first_cut']:.2f}с · **лицо {m['face_pct']}%**\n")

    print("## Блок хука — единственное, что перерисовано\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(shots, 1):
        rec, desc = NAMES[kind]
        if kind == "stock":
            desc = ("руки с колодой (mixkit 100377); карточка B, притемнение 28% · "
                    f"окно клипа {prm['ss']:.2f}–{prm['ss'] + (t1 - t0):.2f}с")
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0/rate:.2f}–{t1/rate:.2f} | {(t1-t0)/rate:.2f}с | {rec} "
              f"| {desc} | {txt or '— (говорит графика)'} |")
    print(f"| — | {nf/FPS/rate:.2f}–{m['dur']:.2f} | {m['dur'] - nf/FPS/rate:.2f}с "
          "| — | **тело сданной версии кадр в кадр**, с плана `cards3` "
          "| см. `montage-plan.md` |")

    print("\nГрафика блока хука — та же, что стояла в старом начале: стоковая "
          "вставка с руками и колодой (mixkit 100377). Другой графики в старом "
          "хуке не было, менять её незачем. Окно клипа взято новое и не "
          "пересекается ни со сданной версией (2.92–4.79), ни со второй "
          "версией — иначе один и тот же кадр стока стоял бы в двух роликах "
          "подряд, и площадка честно сочла бы их дублями.")

    print("\n## Точка реза\n")
    print("Старое начало — «если ты учил в школе теорию вероятности, ты должен "
          "решить эту задачку» (0.090–3.354). Оно занимает два плана: `A1` "
          "0.000–1.800 и `stock` 1.800–3.6667. Ближайшая граница плана после "
          "конца фразы — **3.6667**, по ней и режем.\n")
    print(f"В кадрах это ceil(3.6667 × 30) = **{HK.CUT_F}**. Округление вверх, "
          "а не к ближайшему: кадр 110 стоит на 3.6667 и по `shot_at` "
          "принадлежит ещё стоковому плану старого хука — при round от него "
          "остался бы целый кадр. Проверено прямым перебором.\n")
    print("Тело начинается самостоятельным предложением «итак, перед вами три "
          "карты»: своё подлежащее, ни одного местоимения, отсылок к "
          "выброшенному тексту нет.")

    print("\n## Звук\n")
    print("Дорожка пересобрана целиком, а не склеена из готовых:")
    print(f"- голос хука (коррекция уровня под тело) + голос тела с {HK.CUT_A:.4f}с;")
    print(f"- постель (whoosh / impact / tick) со сдвигом {dt:+.4f}с;")
    print(f"- музыка `{os.path.basename(cfg['music'])}` с нуля, −19 dB от RMS "
          "голоса, фейды 0.8 / 2.0с;")
    print("- highpass 65 Гц + loudnorm + добор volume/alimiter под громкость "
          "**оригинала**, а не под абстрактные −14.\n")
    print("**J-cut в один кадр.** Первое слово тела («итак») по огибающей "
          "атакует в 3.705: 3.690 = −84 дБ, 3.700 = −68, 3.710 = −49, "
          f"3.720 = −39. Картинка тела начинается кадром {HK.CUT_F} (3.7000). "
          f"Голос тела берётся с кадра {HK.CUT_F - 1} ({HK.CUT_A:.4f}с, там "
          "−86 дБ — чистая тишина) и ложится на кадр раньше картинки. Смещение "
          "кратно кадру, поэтому синхрон не едет.")

    if key == "h1":
        print("\n**У этого дубля нет хвостовой тишины.** Слово кончается на "
              "3.150, а с 3.22 до конца файла (3.325) идёт дыхание на "
              "−27…−37 dB. Само слово целое — обрезано не оно, но если оставить "
              "хвост как есть, в паузе перед телом будет слышен вдох. Поэтому "
              "дорожка хука гасится фейдом с 3.170 за 0.080с: пауза выходит "
              "тихой, последнее слово не тронуто. У hook2 после последнего "
              "слова 0.17с настоящей тишины, там фейд не нужен.")

    print(f"\n## Уникализация — {DEFORM_RULE[key]}\n")
    print(f"- Трек: `{os.path.basename(cfg['music'])}` (версия 1 — `song1.mp3`, "
          "версия 2 — `song2.mp3`, версия 3 — `song3.mp3`, ни один не "
          "повторяется).")
    print(f"- Деформация измерена машиной: {m['deform']}.")

    print("\n## Проверки версии\n")
    print("| проверка | результат | норма |")
    print("|---|---|---|")
    print(f"| громкость | **{m['lufs']} LUFS**, пик **{m['tp']} dBTP**, "
          f"LRA {m['lra']} LU | версия 1: −14.2 LUFS, −1.5 dBTP |")
    print(f"| шов: первый кадр тела против кадра {HK.CUT_F} оригинала "
          f"| {m['seam_same']} | должны совпасть |")
    print(f"| шов против кадра {HK.CUT_F - 1} (последний кадр старого хука) "
          f"| {m['seam_diff']} | должны разойтись |")
    print(f"| последний кадр блока хука против кадра {HK.CUT_F - 1} "
          f"| {m['tail_diff']} | должны разойтись |")
    print(f"| ни одного кадра лица старого хука | min {m['old_face_min']} при "
          f"пороге {m['old_face_thr']} | больше порога |")
    print("| окна стока не пересекаются со старыми | 0 пересечений | 0 |")
    print(f"| тело кадр в кадр с версией 1 | худшая разница {m['body_worst']} "
          "| уровень шума кодека |")
    print(f"| щелчок на шве | скачок {m['click'][0]} против типичного "
          f"{m['click'][1]} (p99.9) | не выделяется |")
    print(f"| пауза хук → тело | **{m['pause']:.3f}с** | 0.10–0.20с |")
    print(f"| средний RGB в карточке A | хук {m['rgb_hook']}, тело "
          f"{m['rgb_main']} | расхождение ≤10 |")
    print("| A-roll не морожен | лицо кончается на кадре "
          f"{max(f for f in range(nf) if next((x for x in shots if x[0] <= f/FPS < x[1]), shots[-1])[2] in SB.FACE_KINDS)} "
          f"при {cfg['src_frames']} кадрах дубля | ok |")
    print("| субтитры мимо расшифровки / стиль / резы внутри слова | 0 / 0 / 0 | 0 |")
    print("| текст за карточкой · графика на тексте · наложение строк | 0 / 0 / 0 | 0 |")
    print(f"| полоса субтитров на стоковой вставке | {m['band'][0]} / p90 "
          f"{m['band'][1]} | ≤110 / ≤140 |")
    print(f"| стоковая вставка играет | покадровая разница {m['motion']} "
          "| заметно больше 0 |")

    print("\n**Почему «последний кадр блока хука против кадра "
          f"{HK.CUT_F - 1}» — не главная проверка.** В ролике 37 старое начало "
          "кончалось той же стоковой вставкой (mixkit 100377), что стоит и в "
          "новом блоке, только другим окном клипа. Пиксельная разница двух "
          "кадров одного клипа мало что значит — она меряет, «насколько клип "
          "похож сам на себя». Поэтому отсутствие старого хука проверяется "
          "двумя метриками раздельно: по планам ЛИЦА — попиксельно (другой "
          "дубль, разница обязана быть заметной), по стоку — непересечением "
          "окон клипа во времени.")

    print("\n## Дубль хука — что не правилось\n")
    print("Хук прошёл через тот же тракт A-roll, что и основной исходник: те же "
          "`FRAMINGS` (окно 630×1000 от (57, 264)), тот же безусловный `hflip`, "
          "грейда нет. Ни крупность, ни экспозиция, ни положение в кадре не "
          "подгонялись.\n")
    print("| дубль | cx | линия глаз | ширина лица |")
    print("|---|---|---|---|")
    print("| основной | 378 | 684 | 264 |")
    print(f"| **этот хук** | **{cfg['face_cx']}** | **{cfg['face_eye']}** "
          f"| **{cfg['face_d']}** |")
    print(f"\nЛицо в дубле шире основного на {cfg['face_d'] - 264}px и стоит "
          f"на {cfg['face_eye'] - 684}px ниже — снимали чуть ближе. Кропом это "
          "не правится: правило гайда — хук идёт через тот же тракт без "
          "поправок, расхождение называется числами, а решение (переснять или "
          "принять) остаётся за съёмочной стороной. Средний RGB внутри "
          f"карточки A: {m['rgb_hook']} против {m['rgb_main']} у основного "
          "дубля — расхождение ≤1 единицы по каналу при норме ~10, то есть по "
          "свету дубли сошлись.\n")
    print("Зеркальность проверена по кадру: надпись на футболке в дубле читается "
          "задом наперёд, значит штатный `hflip` подходит.")

    if key == "h1":
        print("\n## Замечание по этой версии\n")
        print("**«подвох» звучит в хуке и позже стоит крупным словом (R6).** "
              "Дубль кончается словами «но она с небольшим подвохом», а в теле "
              "на 24.93 (в этой версии — на "
              f"{24.933 + dt:.2f}с) над головой встаёт **ПОДВОХ**. Правило "
              "`brand-kit §5` запрещает повтор смысла в ОДНОМ кадре; здесь "
              "между ними 21 секунда, и R6 работает как расплата за обещание "
              "из хука, а не как дубль. Субтитр хука слово оставляет: без него "
              "фраза разваливается.")
    else:
        print("\n## Замечание по этой версии\n")
        print(f"**Самый короткий план — {m['shortest']:.2f}с при норме ≥1с.** "
              "Это план тела длиной 1.233с, ужатый обязательным ускорением "
              "×1.02. Собственные планы блока хука подобраны с запасом "
              "(хвостовой план 1.533с → 1.503с), тело не пересобирается, "
              "поэтому 2% срезаются со всех его планов — но в норму ролик "
              "укладывается целиком.")
        print("\n**«условная вероятность» в хуке — термин, которого нет в теле.** "
              "Дубль обещает задачу на условную вероятность, и ролик её ровно "
              f"и решает: условие «сверху красная» задаёт множество исходов, "
              f"ответ **{A}** против наивного **{AN}**. Термин на экран "
              "субтитром выносится (он звучит), но графикой не дублируется.")


if __name__ == "__main__":
    emit(sys.argv[1])
