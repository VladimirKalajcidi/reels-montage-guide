RU = {"R": "красная", "B": "чёрная"}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = lens[len(lens) // 2]
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «парадокс трёх карт»\n")
    print(f"Исходник: `videos/37/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/37/cards_edit.mp4` · 1080×1920 · 30 fps · "
          f"{int(round(DUR*30))} кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с — ролик объяснительный, "
          "очередь быстрых резов R3 не используется")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· графика и вставки **{100*(DUR-face)/DUR:.0f}%** "
          f"(из них сток {stock:.1f}с = {100*stock/DUR:.0f}%).")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          f"**белое число: {AN}** · **синее число одно: {A}** "
          "(лимит brand-kit — до 4)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa37.speech_sync` = 0) и дополнительно "
          "проверены по огибающей (`qa37.cut_energy` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if kind == "stock":
            desc = STOCK_NAMES[prm["clip"]].split(" — ")[0] + \
                   "; карточка B, притемнение 28%"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Один визуальный язык на весь ролик")
    print("Задача цветная («красная сторона» / «чёрная сторона»), и цвет "
          "стороны рисуется буквально: красная сторона — **красная**, чёрная — "
          "**чёрная**. Это отступление от палитры `brand-kit §4` "
          "(чёрное / белое / синее) по прямому решению автора: раз в речи "
          "звучит «красная», на картинке она должна быть красной. Масть ♥/♠ "
          "оставлена поверх заливки — она держит опознание там, где заливка "
          "приглушена по альфе, и в миниатюре. Ни один элемент не меняет "
          "смысла от плана к плану:\n")
    print("| элемент | что значит |")
    print("|---|---|")
    print("| скруглённый прямоугольник с горизонтальной чертой | карта; "
          "верхняя половина — сторона сверху, нижняя — сторона снизу |")
    print("| красная половина с белым ♥ | красная сторона |")
    print("| чёрная половина с белой рамкой и белым ♠ | чёрная сторона |")
    print("| половина со знаком «?» | сторона ещё не известна |")
    print("| отдельная плитка над картами | одна сторона, которую мы могли "
          "увидеть |")
    print("| линия плитка↔карта | из какой карты вынута эта сторона |")
    print("| стрелка вниз от плитки | что у этой же карты с другой стороны |")
    print("| **синее** | **ответ**: две плитки из трёх, их карта и число |")
    print("\nКарта в задаче лежит на столе, поэтому «сверху» и «снизу» из речи — "
          "это буквально верх и низ прямоугольника, а не условная метка. "
          "Знак «?» вместо полой половины: полая половина того же силуэта "
          "читалась бы как обычная сторона.")
