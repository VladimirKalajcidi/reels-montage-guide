    print("- **приглушение неактивных карт поднято** с 0.52 до 0.70 (и по "
          "диаграмме с 0.28–0.34 до 0.42–0.48): красный на чёрном при малой "
          "альфе уходит в бордовый и теряет масть, белый так не вёл себя.")
    print("- **масть на синей заливке осталась белой.** Иначе при подсветке "
          "ответа ♥ перекрашивался из белого в чёрный и мигал на переходе.")

    print("\n## Математика пересчитана, а не взята на веру")
    print("`qa37.logic` строит пространство **сторон** (а не карт) и считает "
          "ответ заново (0 нарушений):\n")
    print("| карта | верхняя сторона | нижняя сторона | даёт красных сторон |")
