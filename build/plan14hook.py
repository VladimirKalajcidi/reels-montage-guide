"""Монтажный лист версии ролика 14 с хуком 1."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard14 as SB
import hook14 as HK
from plan14 import NAMES

key = sys.argv[1] if len(sys.argv) > 1 else "h1"
cfg = HK.HOOKS[key]
NF, CUT = cfg["frames"], HK.CUT
HL = NF / FPS
dt = HL - CUT
DUR = HL + (SB.DUR - CUT)

shots = [(a, b, k, p, "хук") for a, b, k, p in cfg["shots"]]
# первый план тела начинается точкой реза, а не своим номинальным t0 (6.08 < 6.10)
shots += [(max(a, CUT) + dt, b + dt, k, p, "тело") for a, b, k, p in SB.SHOTS if b > CUT]
lens = sorted(b - a for a, b, _, _, _ in shots)
face = sum(b - a for a, b, k, _, _ in shots if k in SB.FACE_KINDS)

print(f"# Монтажный лист — ролик 14, версия 2 (хук 1)\n")
print(f"Хук: {cfg['title']}")
print("Тело: «гипотеза Кеплера: как плотнее всего уложить шары», кадры взяты готовыми "
      "из `assets/_video_kepler.mp4`, не пересобирались.\n")
print(f"Исходники: `videos/14/hook1.mov` (720×1280, `yuvj420p`/`pc`) + "
      f"`videos/14/source.mov` (1080×1920, `yuv420p`/`tv`)")
print(f"Готовый файл: `{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
      f"{DUR:.2f}с · {NF + int(round((SB.DUR - CUT) * FPS))} кадров\n")
print(f"**Точка реза:** кадр {HK.CUT_F} ({CUT:.3f}с). Старая хуковая фраза кончается на "
      f"6.080 по `source.srt`, там же граница плана `y400` (3.52–6.08). "
      f"Планы 1–3 старого начала и их субтитры выброшены целиком.")
print(f"**Блок хука:** {NF} кадров ({HL:.3f}с), дубль обрезан с {cfg['ss']:.3f}с "
      f"(тишина до 2.66 и после 7.52 по огибающей).")
print(f"**Планов:** {len(shots)} · средняя **{sum(lens)/len(lens):.2f}с** · "
      f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
      f"первый рез {shots[0][1]:.2f}с")
print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%**\n")
print("| # | тайминг | длит. | откуда | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|---|")
caps = [(a, b, r, s, "хук") for a, b, r, s in cfg["caps"]]
caps += [(a + dt, b + dt, r, s, "тело") for a, b, r, s in SB.CAPS if a >= CUT]
for i, (t0, t1, kind, prm, who) in enumerate(shots, 1):
    rec, desc = NAMES[kind]
    if prm.get("clip"):
        desc = SB.STOCK_NAMES[prm["clip"]]
    txt = " / ".join("".join(r[0] for r in runs).strip()
                     for (a, b, runs, _s, _w) in caps if t0 - 1e-6 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {who} | {rec} | {desc} "
          f"| {txt or '— (говорит графика)'} |")

print("\n## Приведение формата хука — сделано")
print("- `720×1280` → `1080×1920` и полный диапазон `pc` → `tv`: объективные свойства файла, "
      "приводятся всегда (START-HERE, «приведение формата»). Один проход, звук не тронут.")
print("- Цветовые теги после конверсии совпадают с основным исходником: "
      "`yuv420p` / `tv` / `bt709` / `bt709` / `bt709`.")
print("- Зеркальность сверена по кадру: надпись на футболке читается задом наперёд "
      "и в основном дубле, и в хуке — штатный `hflip` подходит обоим, отключать не нужно.")
print("- Дальше хук идёт через тот же тракт A-roll, что и тело: те же `FRAMINGS`, "
      "тот же `hflip`, тот же грейд. Ни одной поправки под дубль.")

print("\n## Расхождение дублей — измерено, не исправлено")
print("Экспозиция и посадка головы у хука заметно другие. По протоколу это решается "
      "на съёмке, а не кропом и не лутом, поэтому числа называются как есть:\n")
print("| что мерили | тело | хук | расхождение |")
print("|---|---|---|---|")
print("| средний RGB в карточке A (после тракта) | 93 / 73 / 62 | 132 / 110 / 98 | **+39 / +37 / +36** |")
print("| средний RGB самого лица | 156 / 101 / 93 | 187 / 126 / 123 | +31 / +25 / +30 |")
print("| средний RGB потолка | 123 / 114 / 104 | 195 / 189 / 180 | +72 / +76 / +76 |")
print("| линия глаз в кадре 1080×1920 | y 838 | y 965 | **+127px ниже** |")
print("| ширина лица (детектор) | 436px | 435px | −1px |")
print("| центр лица по X после `hflip` | 581 | 570 | −11px |")
print("\nНорма по `delivery-specs.md §6` — до ~10 единиц по каналу. Здесь превышено вчетверо: "
      "хук снят светлее (потолок +76 — свет включён иначе), и голова сидит на 127px ниже, "
      "из-за чего в карточку попадает больше потолка. Крупность и горизонталь совпадают. "
      "Конверсия диапазона `pc`→`tv` тут ни при чём: без неё расхождение было +45/+43/+41, "
      "то есть она сняла всего 1–5 единиц. Решение — переснять хук при том же свете и той же "
      "посадке или принять как есть — не за монтажом.")

print("\n## Стык")
print(f"- J-cut не нужен: тело после реза начинается собственной паузой, "
      f"первое слово «задача» звучит только на 6.80 (абс.).")
print("- Пауза между речью хука и первым словом тела — **0.64–0.68с**. "
      "`delivery-specs.md §6` называет 0.10–0.20с, но с оговоркой «как между предложениями "
      "в теле»; в этом дубле паузы между предложениями 0.50 / 0.72 / 0.97с, так что стык "
      "лёг в собственный ритм записи. Сжать до 0.15с можно было бы только перерезав тело, "
      "а тело обязано совпасть с версией 1 кадр в кадр.")
print("- Щелчка нет: максимальный скачок между соседними сэмплами в окне ±10мс вокруг стыка "
      "**0.011** при медиане по всей дорожке 0.003 и 99-м перцентиле 0.085.")

print("\n## Уникализация версии")
print(f"- Музыка: `{os.path.basename(cfg['music'])}` (в версии 1 — `song3.mp3`, не повторяется).")
print(f"- Деформация: `{cfg['post_v']}` — кроп ×0.98 по уже собранному немому видео.")
print("- Проверено машинно: карточка A выросла с 870×1380 до 888×1408 — "
      "**×1.0207 по ширине и ×1.0203 по высоте** при норме ×1.0204.")
print("- Тело совпадает с версией 1 кадр в кадр: корреляция кадров v1[183+k] и v2[149+k] "
      "после снятия кропа даёт максимум ровно на нулевом сдвиге на всём таймлайне.")
print("- Версия 1 не тронута: `kepler_edit.mp4` тот же файл, что сдавали "
      "(sha256 `24922993…f5d1`).")

print("\n## Автопроверки версии — все по нулям")
print("`gfx_text_overlap` · `gfx_out_of_zone` · `caption_out_of_zone` · `text_out_of_card` · "
      "`line_overlap_pairs` · `bright_outside_card`.")
print("Проверка «текст за карточкой» считает карточку в геометрии версии 2 с допуском 2px: "
      "билинейный ресемпл кропа размазывает край карточки на соседний пиксель "
      "(замер: 97…984 против расчётных 96…983). Вылет текста измеряется десятками пикселей, "
      "спрятаться в этот допуск не может.")
print(f"\nГромкость: **{-13.95:.2f} LUFS**, истинный пик **−1.60 dBTP** "
      f"(версия 1 — −13.9 LUFS / −1.7 dBTP, сходится).")
