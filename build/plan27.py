"""Генерирует монтажный лист ролика 27 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard27 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS, STEP,
                          NX, NY, OX, OY)
from geom27 import (POLY, POLY2, ROWS, D1, D2, S1, S2, DIFF, AREA,
                    shoelace, pick, boundary, interior, convex,
                    self_intersections)
import render27

# измерения сданного файла
LUFS, TP, LRA = -14.2, -1.6, 3.0
AROLL_SRC = (164, 138, 125)
AROLL_OUT = (161, 135, 121)

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "shape": ("R4+R10", "сетка: многоугольник обводится по узлам клетки "
                        "и заливается — осей ещё нет"),
    "plane": ("R4+R10", "сетка: из начала координат выезжают оси с засечками "
                        "и подписями **x** и **y**, фигура остаётся на месте"),
    "hold": ("R4+R10", "сетка: плоскость с фигурой стоит, вершины "
                       "подсвечиваются по кругу — план держит кадр до чисел"),
    "coords": ("R4+R10", "сетка: каждая вершина вспыхивает и рядом встаёт "
                         "её пара координат — ровно на своём слове; "
                         "субтитра на плане нет"),
    "table": ("R4+R10", "сетка: координаты выстраиваются в столбик — "
                        "колонка x и колонка y, по строке на вершину"),
    "repeat": ("R4+R10", "сетка: дуга от первой строки к шестой и сама "
                         "шестая строка — повторённая первая точка"),
    "lace1": ("R4+R10", "сетка: диагонали **↘** прорисовываются одна за другой, "
                        "справа встают произведения"),
    "sum1": ("R4+R5a", "сетка: таблица приглушается, под столбиком "
                       "произведений черта и **белое 70** резким попом; "
                       "субтитра на плане нет"),
    "lace2": ("R4+R10", "сетка: диагонали **↙**, произведения слева"),
    "sum2": ("R4+R5a", "сетка: черта и **белое 33**; субтитра на плане нет"),
    "diff": ("R4+R5a", "сетка: **70 − 33** выходят на своих словах, "
                       "затем скобки модуля и **37**"),
    "result": ("R4+R5b", "сетка: **37 : 2** и **синее 18,5** с набором "
                         "по разрядам; субтитра на плане нет"),
    "any": ("R4+R10", "сетка: невыпуклый многоугольник на той же плоскости — "
                      "«практически любой формы»"),
    "order": ("R4+R10", "сетка: точка обходит контур, вершины нумеруются "
                        "1…5 в порядке обхода"),
    "laces": ("R4+R10", "сетка: обе диагонали разом, прорисованные как две "
                        "сплошные нити — та самая «шнуровка»"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «формула шнуровки»\n")
    print(f"Исходник: `videos/27/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/27/lace_edit.mp4` · 1080×1920 · 30 fps · "
          "1578 кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синее число одно** (18,5) · белых чисел на экране: 70, 33, 37 "
          "и произведения по диагоналям\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa27.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]] + f" (с {prm['ss']:.2f}с клипа)"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Математика ролика — пересчитана, а не переписана из сценария")
    print("Многоугольник взят прямо из речи: **(1;1) (5;1) (6;4) (3;6) (1;4)**. "
          "Всё остальное считает `geom27`, и каждое число сверено с тем, "
          "что произносится вслух (`qa27.numbers` = 0 нарушений):\n")
    print("| шаг | на экране | пересчёт | в речи |")
    print("|---|---|---|---|")
    print(f"| произведения по диагонали ↘ | {', '.join(map(str, D1))} "
          f"| x·y следующей строки | — |")
    print(f"| их сумма | **{S1}** | {' + '.join(map(str, D1))} = {S1} | «получаем 70» ✓ |")
    print(f"| произведения по диагонали ↙ | {', '.join(map(str, D2))} "
          f"| y·x следующей строки | — |")
    print(f"| их сумма | **{S2}** | {' + '.join(map(str, D2))} = {S2} | «получаем 33» ✓ |")
    print(f"| модуль разности | **{DIFF}** | \\|{S1} − {S2}\\| = {DIFF} "
          "| «вычитаем, берём модуль» ✓ |")
    ru = lambda v: f"{v:g}".replace(".", ",")
    print(f"| площадь | **{ru(AREA)}** | {DIFF} : 2 = {ru(AREA)} | «площадь 18,5» ✓ |")
    print("\n**Независимая проверка.** Площадь по шнуровке сверена с формулой Пика "
          f"по узлам решётки: внутренних узлов {len(interior(POLY))}, граничных "
          f"{boundary(POLY)}, значит {len(interior(POLY))} + {boundary(POLY)}/2 − 1 = "
          f"**{str(pick(POLY)).replace(chr(46), chr(44))}** — то же самое. Две разные формулы дают один ответ, "
          "так что на экран выходит проверенное число, а не переписанное из сценария.")
    print(f"\nВторой многоугольник (план `any`) — **{POLY2}**: невыпуклый "
          f"(`convex` = {convex(POLY2)}), без самопересечений, "
          f"шнуровка {shoelace(POLY2):g} = Пик {pick(POLY2):g}. Он и показывает "
          "«практически любой формы».")
    print("\n**Про слово «практически».** Речь оговаривается верно: шнуровка "
          "работает для любого **простого** многоугольника (без самопересечений), "
          "и невыпуклость ей не мешает. На самопересекающемся контуре формула "
          "даёт не площадь — поэтому обе фигуры ролика проверены на "
          "самопересечения машинно (`qa27.geometry` = 0).")

    print("\n## Кто что несёт: графика и субтитр")
    print("На графике нет ни одной надписи, кроме подписей осей **x** и **y** — "
          "их в речи нет, а без них координатная схема не читается "
          "(`shot-recipes.md` R10). Всё остальное:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| точка на плоскости | вершина многоугольника |")
    print("| белая замкнутая ломаная | сам многоугольник |")
    print("| пара чисел у вершины | её координаты (x; y) |")
    print("| строка «x  y» в столбике | координаты одной вершины |")
    print("| шестая строка столбика | повторённая первая точка |")
    print("| дуга слева от столбика | «первая точка возвращается в конец» |")
    print("| диагональ ↘ | произведение в первую сумму |")
    print("| диагональ ↙ | произведение во вторую |")
    print("| две сплошные нити разом | почему метод называется шнуровкой |")
    print("| номера 1…5 у вершин | порядок обхода границы |")
    print("| синее число | ответ |")
    print("\nЧисла и координаты, которые произносятся вслух, стоят там, где "
          "субтитра нет вообще (`qa27.no_caption_on_number_shots` = 0): планы "
          "`coords`, `sum1`, `sum2`, `result` идут без текста, а на `diff` "
          "субтитр выходит только на «берём модуль», где цифр нет.")
    print("\nМашинная проверка пересечения слоёв (`qa27.gfx_text_overlap`) — 0 кадров, "
          "графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa27.gfx_in_zone`) — 0 кадров.")

    print("\n## Координатная плоскость и сетка")
    print(f"Плоскость нарисована с шагом **{STEP}px** на единицу, показаны "
          f"{NX} единиц по x и {NY} по y, начало координат в точке "
          f"({OX}; {OY}) холста.")
    print("\n**Сетка-подложка на этих планах рисуется тем же шагом и сдвинута так, "
          "что узел (0;0) попадает ровно на пересечение линий.** Это отступление "
          "от клетки 168px из `brand-kit.md` §R4, и оно сделано осознанно: "
          "координаты доходят до 6, а при клетке 168px шесть единиц — это 1008px "
          "при ширине зоны 730px, плоскость просто не помещается. Если оставить "
          "клетку 168px и рисовать плоскость своим шагом, в кадре окажутся две "
          "несовпадающие сетки, а вершины «в узлах клетки» повиснут между клетками. "
          "Кривизна линий на этих планах уменьшена до 0.30 — при полной вершина "
          "уходит от номинального узла до ~14px.")

    print("\n## Ритм")
    print(f"- {len(SHOTS)} планов, средняя **{sum(lens)/len(lens):.2f}с** "
          f"при норме 1.7–2.1, медиана **{lens[len(lens)//2]:.2f}с** при норме 1.5–2.0.")
    print(f"- Самый короткий план {lens[0]:.2f}с, самый длинный {lens[-1]:.2f}с "
          "(план `coords`: пять пар координат выходят по одной, каждая на своём слове).")
    print(f"- Первый рез на **{SHOTS[0][1]:.2f}с**.")
    print(f"- Лицо **{100*face/DUR:.0f}%** при норме 30–45; подряд лицом — "
          "не дольше 4.4с и не дольше 2.35с в одном плане.")
    print("- Все переходы — прямые резы, ни одного диссолва.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под четырьмя ревилами чисел — 70, 33, 37 и 18,5 (0.070), тики под "
          "каскадами элементов (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume 0.8 dB / alimiter.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**. Сошлось с первой итерации.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/27/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nОбе вставки буквальны: звучит «многоугольника на клетке» — в кадре "
          "рука чертит фигуру по линейке в тетради в клетку; звучит «напоминают "
          "шнурки» — в кадре затягивают шнурок на кроссовке. Оба клипа играют, "
          "статики нет.")
    print("\nУчасток каждого клипа выбран по числам, а не на глаз: объект должен "
          "быть в кадре всё время плана после обрезки до 1.385:1, и полоса "
          "субтитров в карточке B после притемнения 0.72 должна держаться "
          "в пределах «средняя ≤110, p90 ≤140». Замеры по готовому файлу: "
          "50113 — 63/102, 11584 — 60/103.")
    print("\nОтклонены по этим же числам: `50116` (та же тетрадь в клетку, "
          "но p90 143–148 в любом участке — белый текст на светлой бумаге тонет) "
          "и `15059` (шнурки, p90 183). Клип `50110` из ролика 12 не брался "
          "намеренно: ролик 12 — про ту же площадь на клетке, и одинаковая "
          "вставка склеила бы два ролика в дубли.")
    print("\nОстальные 18 планов закрыты собственной графикой: суть ролика — "
          "в самой процедуре шнуровки, а этого сток не показывает.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) окрашено **одно число — 18,5**, это ответ. "
          "Лимит `brand-kit.md` §4 — четыре, использовано одно.")
    print("- **Лайм #C3DB4E в ролике не используется вовсе.** Напрашивалось "
          "покрасить им вторую диагональ, но это не «один элемент», а десять "
          "объектов. Обе диагонали белые: они никогда не стоят в кадре "
          "одновременно, кроме финального плана `laces`, где в том и смысл, "
          "что нитей две.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt. Кегли крупных чисел "
          "подобраны по ширине зоны: 70 и 33 — 104pt, 37 — 190pt, 18,5 — 200pt.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render27). Кроп посчитан по детектору: 36 замеров "
          f"по всему дублю дали cx 347±6, линию глаз y 677±3, ширину лица 313±8 — "
          "глаза стоят на 42% высоты карточки в обеих крупностях.")
    print(f"Проверка: средний RGB внутри карточки A — **{AROLL_SRC[0]} / "
          f"{AROLL_SRC[1]} / {AROLL_SRC[2]}** у кропа исходника против "
          f"**{AROLL_OUT[0]} / {AROLL_OUT[1]} / {AROLL_OUT[2]}** в сданном файле, "
          "расхождение 2.8–4.3 единицы по каналу — это цена 4:2:0 и H.264, "
          "а не коррекция.")
    print("\n**Что назвать числами, а не чинить молча.** Дубль заметно светлее "
          f"ориентира `brand-kit.md` §6 «130 / 112 / 104»: замер даёт "
          f"{AROLL_SRC[0]} / {AROLL_SRC[1]} / {AROLL_SRC[2]}. Гамма-подтяжка "
          "до ориентира уже пробовалась на ролике 16 и дала вымытое лицо и рост "
          "шума, поэтому картинка исходника не тронута. Решение — за съёмкой.")
    print("\n**Зеркальность.** В кадре нет ни одной надписи (стена, картина, "
          "однотонная футболка), по которой можно было бы проверить ориентацию "
          "экспорта, поэтому `hflip` оставлен штатным, как во всех предыдущих "
          "роликах с этой же точки и того же телефона. Если дубль экспортирован "
          "уже незеркальным, это видно только по съёмочной стороне — скажите, "
          "и `hflip` отключается одной строкой.")
    print("\n**Футболка.** Дубль снова снят в светло-серой футболке, и субтитры "
          "на планах с лицом ложатся белым по светло-серому. Плашку под текст "
          "ставить нельзя (`brand-kit.md` §7), грейдить лицо — тоже. Тёмная "
          "футболка снимает вопрос целиком; то же было на роликах 24, 25 и 26.")

    print("\n## Автопроверки — все по нулям")
    print("| проверка | результат |")
    print("|---|---|")
    print("| текст за карточкой (каждый 3-й кадр всего ролика) | **0 кадров** |")
    print("| наложение строк внутри блока (по `font.getbbox`) | **0 пар** |")
    print("| графика пересекает субтитр (по альфе >40) | **0 кадров** |")
    print("| графика вне зоны y700…1560 / x175…905 | **0 кадров** |")
    print("| субтитр вне карточки с отступом 30px | **0 кадров** |")
    print("| рез в середине слова | **0** |")
    print("| субтитр разошёлся с речью | **0** |")
    print("| слово субтитра, которого нет в расшифровке | **0** |")
    print("| капс / пунктуация / не 2–4 слова во фразе | **0** |")
    print("| субтитр на плане, где число несёт графика | **0** |")
    print("| числа на экране расходятся с пересчётом | **0** |")
    print("| геометрия: самопересечения, вершины вне узлов и вне зоны | **0** |")


if __name__ == "__main__":
    emit()
