"""Генерирует монтажный лист ролика 36 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard36 import (SHOTS, CAPS, DUR, FACE_KINDS, OUTCOMES, STOCK_NAMES,
                          ANSWER_ATLEAST, ANSWER_ELDER, ANSWER_NAIVE, BIG_WORD)

# измерения сданного файла (заполнены после финального рендера)
LUFS, TP, LRA = -14.0, -1.6, 2.3
FACE_BAND = (164.1, 165.7)
STOCK_BAND = (61.9, 61.9)

A1 = f"{ANSWER_ATLEAST[0]}/{ANSWER_ATLEAST[1]}"
A2 = f"{ANSWER_ELDER[0]}/{ANSWER_ELDER[1]}"
AN = f"{ANSWER_NAIVE[0]}/{ANSWER_NAIVE[1]}"

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A1word": ("R1+R6", f"лицо + крупное слово «{BIG_WORD}» над головой, "
                        "внутри карточки, без маски по силуэту"),
    "stock": ("R2", "школьный класс: учительница у доски, ученик тянет руку; "
                    "карточка B, притемнение 28%"),
    "family": ("R4+R10", "сетка: отец и двое детей. Дети — знаки «?»: пол "
                         "не известен ни у одного. Кто крупнее, тот старший — "
                         "этот код держится весь ролик"),
    "atLeast": ("R4+R10", "сетка: мальчик перескакивает между старшим и "
                          "младшим — известно, что один из двоих мальчик, "
                          "но не который"),
    "ask": ("R4+R10", "сетка: над парой встаёт большой «?», оба ребёнка "
                      "проявляются мальчиками — это и есть вопрос задачи"),
    "naive1": ("R4+R10", "сетка: мальчик и «?» одного роста — в ложной "
                         "интуиции порядок детей пропадает"),
    "naive2": ("R4+R10", "сетка: «?» уходит, вместо него вилка на два "
                         "варианта — мальчик и девочка"),
    "half1": ("R4+R5a", f"сетка: два варианта складываются в две пары, "
                        f"искомая обведена жирнее; под ними белое **{AN}** "
                        "резким попом (R5a)"),
    "grid": ("R4+R10", "сетка: четыре пустые ячейки каскадом — четвёрку "
                       "несёт сама сетка, числа на экране нет"),
    "fill1": ("R4+R10", "сетка: первые две пары встают в ячейки ровно на "
                        "своих словах — «мальчик-мальчик», «мальчик-девочка»"),
    "fill2": ("R4+R10", "сетка: «девочка-мальчик» и «девочка-девочка»"),
    "dropDD": ("R4+R10", "сетка: белый крест на «девочка-девочка» — "
                         "единственном исходе, где мальчика нет вообще"),
    "three": ("R4+R10", "сетка: отпавший исход догорает до призрака, три "
                        "оставшихся разгораются — счёт несут ячейки"),
    "oneOfThree": ("R4+R10", "сетка: ячейка «оба мальчики» загорается синим, "
                             "два других исхода приглушаются"),
    "thirdNum": ("R4+R5b", f"сетка: синее **{A1}** — масштаб 0.55→1.0 с "
                           "микро-оверщутом, разряды слева направо. Ячеек в "
                           "кадре нет: число не лежит на объекте своего цвета"),
    "elder": ("R4+R10", "сетка: условие сменилось, все четыре исхода вернулись "
                        "в игру; рамка встала на левой (старшей) фигурке"),
    "elderTwo": ("R4+R10", "сетка: исходы, где старший — девочка, гаснут под "
                           "крестом. Две ячейки в кадре и есть ответ «два»"),
    "halfBlue": ("R4+R5b", f"сетка: пара ячеек уходит, затем синее **{A2}** (R5b)"),
}

RU = {"B": "мальчик", "G": "девочка"}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = lens[len(lens) // 2]
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «парадокс мальчика и девочки»\n")
    print(f"Исходник: `videos/36/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/36/kids_edit.mp4` · 1080×1920 · 30 fps · "
          f"{int(round(DUR*30))} кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с — ролик объяснительный, "
          "очередь быстрых резов R3 не используется")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· графика и вставка **{100*(DUR-face)/DUR:.0f}%** "
          f"(из них сток {stock:.1f}с = {100*stock/DUR:.0f}%).")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          f"**белое число: {AN}** · **синих чисел два: {A1} и {A2}** "
          "(лимит brand-kit — до 4)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa36.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Один визуальный язык на весь ролик")
    print("Ни один элемент не меняет смысла от плана к плану:\n")
    print("| элемент | что значит |")
    print("|---|---|")
    print("| фигурка с прямоугольным телом | мальчик |")
    print("| фигурка с треугольным телом (юбка) | девочка |")
    print("| знак «?» ростом с фигурку | пол ребёнка ещё не известен |")
    print("| фигурка крупнее / мельче | старший / младший ребёнок |")
    print("| в ячейке: левая фигурка / правая | старший / младший |")
    print("| ячейка | один равновероятный исход |")
    print("| белый крест на ячейке | исход отпал; погасшая ячейка — его больше нет |")
    print("| рамка вокруг фигурки | «вот про кого нам сказали» |")
    print("| **синее** | **ответ**: ячейка-победитель и два числа |")
    print("\nПорядок «слева старший, и он крупнее» задаётся на первом же "
          "графическом плане (отец и двое детей) и дальше не меняется — "
          "поэтому на 37.86 рамка на левой фигурке читается как «старший» "
          "без подписи. Подписи на графике нет намеренно: слово «старший» "
          "звучит в речи, а подпись, повторяющая произносимое, запрещена "
          "(`brand-kit §5`).")

    print("\n## Математика пересчитана, а не взята на веру")
    print("`qa36.logic` строит пространство исходов и считает оба ответа "
          "заново (0 нарушений):\n")
    print("| исход (старший, младший) | «хотя бы один мальчик» | «старший — мальчик» |")
    print("|---|---|---|")
    for e, y in OUTCOMES:
        a = "да" if "B" in (e, y) else "**отпадает**"
        b = "да" if e == "B" else "**отпадает**"
        print(f"| {RU[e]} — {RU[y]} | {a} | {b} |")
    print(f"| **исходов осталось** | **3** | **2** |")
    print(f"| **P(оба мальчики)** | **{A1}** | **{A2}** |")
    print("\nОба условия дают разный ответ, потому что задают разное множество "
          "исходов — это и есть содержание ролика. Ложная интуиция "
          f"(«второй либо мальчик, либо девочка») даёт {AN}: тот же ответ, "
          "но для второй задачи, а не для первой. Поэтому в ролике "
          f"{AN} появляется дважды — первый раз белым (промежуточный неверный "
          "ход), второй раз синим (верный ответ второй задачи).")

    print("\n## Вставки")
    print("Одна стоковая вставка, всё остальное — своя графика на сетке.\n")
    for cid, desc in STOCK_NAMES.items():
        print(f"- `videos/36/stock/stock_{cid}.mp4` — {desc}. "
              f"Полоса субтитров после притемнения 28%: средняя "
              f"**{STOCK_BAND[0]}**, p90 **{STOCK_BAND[1]}** при пороге ≤110 / ≤140.")
    print("\nБольше стока в ролике нет намеренно: живого видео, показывающего "
          "«четыре равновероятных исхода двух детей», не существует, а "
          "случайная перебивка в такой задаче ломает смысл "
          "(`assets-manifest §2`). Предметная графика тут точнее.")

    print("\n## Цвет")
    print(f"- Синим — только два ответа, **{A1}** и **{A2}**, и ячейка-победитель "
          "«оба мальчики», из которой первый ответ и получается.")
    print(f"- Белым — **{AN}** ложной интуиции: это промежуточный, неверный ход, "
          "а не результат, поэтому он не синий (`brand-kit §4`).")
    print("- Кресты, рамки и сами ячейки — белые: синий не размывается на "
          "служебные пометки.")
    print("- Лайм не использован: в ролике нет матричных/табличных элементов, "
          "для которых он предусмотрен.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          f"под белым ревилом {AN}, под крестом на отпавшем исходе и под двумя "
          "синими ответами (0.070), тики под каскадами элементов квадрата "
          "исходов (0.030).")
    print("- Музыка `audios/song1.mp3`: −19 dB от RMS голоса, петля с "
          "кроссфейдом 0.25с, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume / alimiter limit=0.80.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render36.py). Кроп посчитан по детектору: 29 замеров "
          "по всему дублю дали cx 372±8, линию глаз y 683±5, ширину лица "
          "264±6 — окно 630×1000 от (57, 264) ставит глаза на 42% высоты "
          "карточки, то же окно, что в роликах 22–34. Зеркальность проверена "
          "по кадру: надпись на футболке в исходнике читается задом наперёд, "
          "значит штатный `hflip` подходит.")

    print("\n## Полоса субтитров на планах с лицом — не в норме, не чинилось")
    print("Замер полосы, где лежит субтитр (карточка A, y 1260…1400, "
          "x 200…880, по всем планам с лицом):\n")
    print("| ролик | средняя | p90 | порог |")
    print("|---|---|---|---|")
    print(f"| **36 (этот)** | **{FACE_BAND[0]}** | **{FACE_BAND[1]}** | ≤110 / ≤140 |")
    print("| 34 (сдан) | 168.6 | 170.3 | ≤110 / ≤140 |")
    print("| 33 (сдан) | 171.8 | 219.4 | ≤110 / ≤140 |")
    print("\nСветлая футболка в дневном свете: полоса ярче, чем у стоковой "
          "вставки, которую этот же порог в ролик не пустил бы. Белый текст "
          "со свечением на ней читается слабее, чем на графических планах.")
    print("\nМонтажом это не чинится и не чинилось: плашка-подложка под текстом "
          "запрещена (`brand-kit §7`), грейд лица — тоже (A-roll идёт только "
          "через `hflip` + кроп). Решение — на съёмочной стороне: тёмная "
          "футболка или менее выбитый свет на груди.")

    print("\n## Расшифровка")
    print("Пословные тайминги — `videos/36/words.json`, собраны по речевым "
          "отрезкам: границы сняты `ffmpeg silencedetect` (-34dB / 0.12с), "
          "внутри каждого отрезка выдача whisper large-v3 растянута на "
          "измеренный интервал (`align36.py`). Три паузы короче 0.20с "
          "(9.905–10.058, 15.572–15.727, 45.483–45.608) считаны "
          "внутрифразовыми, отрезки слиты.")
    print("\nДроби whisper пишет цифрами: «получается 1 ,2» (14.45–17.02), "
          "«равна 1 третьей» (33.78–35.91), «ответ был бы 1 -2» (41.42–43.26). "
          "Произносятся они словами — «одна вторая», «одной третьей». "
          "На экран спорная запись не выносится ни разу: все три числа "
          "несут ревилы, и субтитр в этих местах обрывается перед числом "
          "(`qa36.captions_on_number_shots` = 0).")

    print("\n## Пересборка после сдачи первой версии")
    print("При сборке версий с другими хуками нашёлся дефект ридера стока: "
          "длинный скачок по клипу он догонял чтением кадров подряд с "
          "ограничением в 400 кадров, и до `ss` больше ~13.3с не доезжал. "
          "**Первый кадр стокового плана показывал чужой момент клипа** — "
          "13.31с вместо 16.60с, один кадр-вспышка ровно на склейке. В "
          "контакт-лист первый кадр плана обычно не попадает, глазами это не "
          "ловится.")
    print("\nРидер теперь делает seek на любой скачок больше секунды. Ролик "
          "пересобран целиком, все проверки прогнаны заново; кроме этого "
          "кадра в версии 1 ничего не менялось. Регрессия закрыта проверкой "
          "`qa36.stock_reader_seek` — она откалибрована: со старым ридером "
          "даёт 1 нарушение, с новым 0.")

    print("\n## Автопроверки")
    print("Обе обязательные — по нулям, вместе с остальными:\n")
    print("```")
    print("cuts_inside_word=0            captions_off_speech=0")
    print("captions_crossing_cut=0       caption_words_not_in_speech=0")
    print("caption_style_violations=0    digits_in_captions=0")
    print("captions_on_number_shots=0    gfx_text_overlap_frames=0")
    print("gfx_out_of_zone_frames=0      gfx_touching_mask_frames=0")
    print("text_out_of_card_frames=0     line_overlap_pairs=0")
    print("bright_outside_card_frames=0  logic_violations=0")
    print("stock_reader_off_by_frames=0")
    print("```")


if __name__ == "__main__":
    emit()
