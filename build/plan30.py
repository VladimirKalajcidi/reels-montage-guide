"""Генерирует монтажный лист ролика 30 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard30 import (SHOTS, CAPS, DUR, FACE_KINDS, TWO, HUNDRED, MULT,
                          NET_EDGES, NET_DEGREE, HUB, ORDINARY, STOCK_NAMES)
import render30

# измерения сданного файла (заполняются после финального рендера)
LUFS, TP, LRA = -14.46, -2.19, 3.00

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A1word": ("R1+R6", "лицо + крупное слово «ПАРАДОКС» над головой, "
                        "внутри карточки, без маски по силуэту"),
    "netYou": ("R4+R10", "сетка: небольшая эго-сеть — «вы» в центре и "
                         "несколько друзей вокруг, узлы и рёбра появляются "
                         "каскадом"),
    "twoFriends": ("R4+R10+R5a", "сетка: один узел с ровно двумя рёбрами, "
                                 "белое **2** резким попом после того, как "
                                 "субтитр «всего» уже погас"),
    "hundredFriends": ("R4+R10+R5a", "сетка: хаб и плотное кольцо из 16 "
                                     "узлов — условно «много»; белое **100** "
                                     "резким попом"),
    "multiplier": ("R4+R5b", "сетка: сверху маленькое 2, снизу маленькое "
                             "100, между ними синее **× 50** набором по "
                             "разрядам — то, что добавляет график поверх "
                             "сказанного (сам множитель в речи не выделен "
                             "как графический объект)"),
    "netRandomPerson": ("R4+R10", "та же сеть из 9 узлов (степень хаба 5): "
                                  "стрелка падает на рядовой узел (степень "
                                  "1) — равновероятный выбор человека"),
    "netRandomFriend": ("R4+R10", "тот же граф: стрелка падает на хаб, узел "
                                  "загорается **синим** — это и есть "
                                  "контринтуитивный результат: случайный "
                                  "друг человека чаще оказывается "
                                  "популярным"),
    "netBias": ("R4+R10", "тот же граф: несколько выборов подряд — хаб "
                          "загорается почти каждый раз и остаётся "
                          "подсвеченным синим"),
    "netSkew": ("R4+R10", "без подписей: два столбика, левый низкий "
                          "(случайный человек), правый высокий (случайный "
                          "друг) — смещение показано разницей высот"),
    "netCompareA": ("R4+R10", "справа растёт плотная эго-сеть (7 связей) — "
                              "«ваш друг»"),
    "netCompareB": ("R4+R10", "слева достраивается редкая эго-сеть (2 "
                              "связи) — «случайный человек», для контраста "
                              "с уже построенной правой"),
    "netRecall": ("R4+R10", "эхо механизма: маленький хаб с тремя узлами, "
                            "выбор снова падает на хаб"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = (lens[len(lens) // 2 - 1] + lens[len(lens) // 2]) / 2
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «парадокс дружбы»\n")
    print(f"Исходник: `videos/30/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/30/friendship_edit.mp4` · 1080×1920 · 30 fps · "
          f"{int(round(DUR*30))} кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток "
          f"{stock:.1f}с — два буквальных плана, остальное своя графика: "
          "тема абстрактная, сеть точек и рёбер показывает механику буквально, "
          "assets-manifest §2). Для доказательного ролика доля лица ближе "
          "к 30% — норма (delivery-specs §6).")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих элементов: 1 число (× 50) + подсветка хаба на 3 планах** · "
          "**белых чисел: 2, 100**\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa30.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]] + f" (с {prm['ss']:.1f}с клипа)"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Сценарий пересчитан — ошибок нет")
    print("Арифметика речи верна целиком (`qa30.numbers` = 0 нарушений).\n")
    print("| в речи | пересчёт |")
    print("|---|---|")
    print(f"| «у которого всего два друга» | {TWO} ✓ |")
    print(f"| «у которого 100 друзей» | {HUNDRED} ✓ |")
    print(f"| «в 50 раз больше возможностей» | {HUNDRED} / {TWO} = **{MULT}** ✓ |")
    deg = NET_DEGREE
    total = sum(deg.values())
    p_u = 1 / len(deg)
    p_f = deg[HUB] / total
    print(f"| «популярные люди встречаются намного чаще» | граф из 9 узлов: "
          f"хаб (степень {deg[HUB]}) при выборе случайного узла — "
          f"{p_u:.1%}, при выборе через случайное ребро (= «случайный друг») "
          f"— {p_f:.1%}, то есть в {p_f/p_u:.1f} раза чаще ✓ |")
    print("\nГраф — отдельная концептуальная иллюстрация механизма (size-biased "
          "sampling), а не пересчёт сценарных «50 раз»: с графом из 9 узлов "
          "нельзя буквально показать множитель 50× и не нужно — суть парадокса "
          "(смещение в сторону высокой степени) видна и на графе меньшего "
          "масштаба. Это отмечено в шапке `storyboard30.py`.")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи** — только цифры и цвет. "
          "Слова несёт субтитр, механику несёт граф:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| белая точка | человек |")
    print("| белая линия | дружба (ребро графа) |")
    print("| размер/степень узла (число рёбер) | число друзей |")
    print("| хаб, подсвеченный синим | узел, на который упал выбор "
          "«случайного друга» — результат, ради которого граф нарисован |")
    print("| плотное кольцо из 16 узлов вокруг хаба | условно «много» "
          "(100 несёт текст, не буквальный счёт узлов — см. шапку storyboard30) |")
    print("\nЧисла на экране стоят там, где субтитра нет вообще "
          "(`qa30.captions_on_number_shots` = 0): «два друга» и «100 друзей» "
          "несёт график, субтитр обрывается перед числом; на `multiplier` — "
          "наоборот, субтитр начинается только после того, как поп × 50 уже "
          "завершился. На `A1word` субтитр обрывается на «называется», "
          "«парадоксом дружбы» несёт крупное слово R6. "
          "Ни одной цифры в субтитрах нет вовсе (`qa30.digits_in_captions` = 0).")
    print("\nМашинная проверка пересечения слоёв (`qa30.gfx_text_overlap`) — 0 кадров, "
          "графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa30.gfx_out_of_zone`) — 0 кадров (R6 в этот периметр не входит "
          "по определению — он живёт над карточкой A, проверено отдельно) "
          "и нигде не упирается во врезку маски (`qa30.gfx_clipped`) — 0 кадров.")

    print("\n## Граф — один и тот же макет в трёх планах")
    print("`netRandomPerson`, `netRandomFriend`, `netBias` рисуют один и тот же "
          f"граф (`NET_EDGES`, {len(NET_EDGES)} рёбер, степени {deg}) — не три "
          "разных картинки, а один и тот же механизм, показанный трижды: "
          "сначала равновероятный выбор узла, потом выбор через ребро, потом "
          "несколько выборов подряд. Хаб (узел 0) — единственный узел "
          f"максимальной степени ({deg[HUB]}), это проверяется машинно "
          "(`qa30.geometry`).")
    print("\nКольцо verts() из `graph.py` центрировано на (540, 905) с радиусом "
          "292/288 — эти значения посчитаны под другую зону графики и в этом "
          "ролике вывели бы часть графа выше y700. Центр графа сдвинут на "
          "(540, 1020), радиус уменьшен до 220 (сеть) / 200 (кольцо на "
          "hundredFriends) / 130 и 90 (эго-сети на netCompareA/B) — с запасом "
          "на узел и свечение до края зоны. Пересчёт — в шапке `render30.py`.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) — множитель **× 50** и подсветка хаба в момент, "
          "когда на него падает выбор «случайного друга» (это и есть "
          "результат демонстрации, brand-kit §4: синий = результат).")
    print("- Лайм не использован: в ролике нет матричных/табличных элементов, "
          "для которых он предусмотрен.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под тремя ревилами чисел (0.070), тики под каскадами узлов графа "
          "(0.030).")
    print("- Музыка `audios/song2.mp3`: −19 dB от RMS голоса, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume 1.35 dB / alimiter limit=0.76.")
    if LUFS is not None:
        print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
              f"**LRA {LRA} LU**.")
    else:
        print("- Замер готового `.mp4` — заполняется после финального прогона "
              "(`python3 measure30.py`).")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/30/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}.")
    print("\nДва плана из 19 — оба буквальные под произносимый смысл "
          "(assets-manifest §2: сток только там, где прямо относится "
          "к смыслу, остальное — своя графика). Замер полосы субтитров "
          "после штатного притемнения 0.72: `30015` (рукопожатие) среднее "
          "**90**, p90 **115**; `46874` (вечеринка) среднее **50**, p90 **78** "
          "— оба ниже порога 110/140.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render30.py). Кроп посчитан по детектору: 29 замеров "
          "по всему дублю дали cx 402±10, линию глаз y 688±4, ширину лица "
          "288±6 — глаза стоят на 42% высоты карточки.")

    print("\n## Расшифровка")
    print("Пословные тайминги — `videos/30/words.json`, собраны по речевым "
          "отрезкам: границы сняты `ffmpeg silencedetect` (-34dB / 0.12с), "
          "внутри каждого отрезка выдача whisper large-v3 растянута "
          "на измеренный интервал (`align30.py`).")
    print("\nОдин отрезок пришлось поправить вручную: 34.511–36.497 large-v3 "
          "услышал как «математика и выбор» — грамматически не сходится "
          "(«может быть просто X» требует творительного падежа). Черновой "
          "проход medium-моделью по всему файлу дал «математикой выборки» — "
          "это и есть верный вариант; интервал переразмечен на два слова "
          "по пропорции длины (см. `align30.py`).")

    print("\n## Автопроверки")
    print("Все — по нулям (`python3 qa30.py`):\n")
    print("```")
    print("cuts_inside_word=0            captions_off_speech=0")
    print("captions_crossing_cut=0       caption_words_not_in_speech=0")
    print("caption_style_violations=0    digits_in_captions=0")
    print("captions_on_number_shots=0    gfx_text_overlap_frames=0")
    print("gfx_out_of_zone_frames=0      gfx_touching_mask_frames=0")
    print("text_out_of_card_frames=0     line_overlap_pairs=0")
    print("bright_outside_card_frames=0  number_violations=0")
    print("geometry_violations=0")
    print("```")
    print("\nСмысловая проверка графики — по контакт-листу ключевых кадров "
          "(`python3 contact30.py <папка>`): первый кадр каждого графического "
          "плана, пик анимации и полный ревил каждого числа.")


if __name__ == "__main__":
    emit()
