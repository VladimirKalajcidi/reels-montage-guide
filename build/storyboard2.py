cl = D.cl


def _svc(op_doors=0.62, op_l=0.0, op_r=0.0):
    """Служебные подписи сцены: какая дверь и какой стражник."""
    out = []
    if op_doors > 0:
        out += [D.txt("свобода", (D.LX, D.DLBL_Y), 42, "s", op=op_doors, ga=0.5),
                D.txt("смерть", (D.RX, D.DLBL_Y), 42, "s", op=op_doors, ga=0.5)]
    if op_l > 0:
        out.append(D.txt("правда", (D.LX, D.GLBL_Y), 46, "s", op=op_l))
    if op_r > 0:
        out.append(D.txt("ложь", (D.RX, D.GLBL_Y), 46, "s", op=op_r))
    return out


DOORS_BASE = dict(door_l=("blue", 1.0), door_r=("white", 1.0), dash_r=True)


def layers(kind, prm, lt, dur, t):
    """(список RGBA-слоёв, список текстовых элементов) для плана."""
    L, T = [], []

    if kind == "doors2":
        st = D.stagger(lt, 2, 0.30, 0.12)
        L.append(D.stage(door_l=("white", st[0]), door_r=("white", st[1])))
        T += D.num(t, 3.820, "2", D.NUM_XY, 155)

    elif kind == "doors_lbl":
        pl = ease_out(cl((t - 4.640) / 0.35))
        pr = ease_out(cl((t - 5.680) / 0.35))
        L.append(D.stage(door_l=("white", 1.0), door_r=("white", 1.0)))
        if pl > 0.01:
            L.append(D.stage(door_l=("blue", pl), door_r=("dim", 0.0)))
        if pr > 0.01:
            L.append(D.stage(door_l=("dim", 0.0), door_r=("white", pr), dash_r=True))
        if pl > 0:
            T.append(D.txt("свобода", (D.LX, D.DLBL_Y), 56, "s", op=pl))
        if pr > 0:
            T.append(D.txt("смерть", (D.RX, D.DLBL_Y), 56, "s", op=pr))

    elif kind == "guards2":
        st = D.stagger(lt - 0.15, 2, 0.30, 0.14)
        L.append(D.stage(guard_l=("w", st[0]), guard_r=("w", st[1]), **DOORS_BASE))
        T += _svc()

    elif kind == "g_truth":
        p = ease_out(cl(lt / 0.35))
        L.append(D.stage(guard_l=("w", 1.0), guard_r=("w", 1.0), ring_l=p, **DOORS_BASE))
        T += _svc(op_l=p)

    elif kind == "g_lie":
        p = ease_out(cl(lt / 0.35))
        L.append(D.stage(guard_l=("w", 1.0), guard_r=("w", 1.0), ring_r=p, **DOORS_BASE))
        T += _svc(op_l=0.7, op_r=p)

    elif kind == "oneq":
        ask = ease_out(cl((lt - 0.15) / 0.55))
        L.append(D.stage(guard_l=("b", 1.0), guard_r=("w", 1.0),
                         ring_l=ease_out(cl(lt / 0.4)), ask=ask, **DOORS_BASE))
        T += _svc(op_l=0.85, op_r=0.6)
        T += D.num(t, 15.440, "1", D.NUM_XY, 155)

    elif kind == "qflow1":
        p = ease_out(cl(lt / 0.40))
        L.append(D.stage(guard_l=("b", 1.0), guard_r=("w", 1.0),
                         ring_r=p, ask=1.0, **DOORS_BASE))
        T += _svc(op_l=0.7, op_r=0.5 + 0.5 * p)

    elif kind == "qflow2":
        a = ease_out(cl((lt - 0.10) / 0.60))
        L.append(D.stage(guard_l=("b", 1.0), guard_r=("w", 1.0), ring_r=1.0, ask=1.0,
                         arc=("lr", a, "white"), **DOORS_BASE))
        T += _svc(op_l=0.7, op_r=1.0)

    elif kind == "qflow3":
        u = ease_out(cl(lt / 0.45))
        dn = ease_out(cl((lt - 0.35) / 0.40))
        L.append(D.stage(guard_l=("b", 1.0), guard_r=("w", 1.0), ring_r=1.0, ask=1.0,
                         arc=("lr", 1.0, "white"), up=("r", u), **DOORS_BASE))
        if dn > 0.01:
            L.append(D.stage(door_l=("dim", 0.0), door_r=("named", dn)))
        T += _svc(op_l=0.7, op_r=1.0)

    elif kind == "flip1":
        c = cl(lt / 0.55)
        f = ease_out(cl((lt - 0.50) / 0.50))
        L.append(D.stage(door_l=("blue", 1.0), door_r=("named", 1.0),
                         guard_l=("dim", 1.0), guard_r=("dim", 1.0),
                         cross_r=c, flip=f))
        T += _svc(op_doors=0.55)

    elif kind == "caseH":
        a = ease_out(cl((lt - 0.20) / 0.60))
        L.append(D.stage(guard_l=("b", 1.0), guard_r=("w", 1.0), ring_l=1.0,
                         arc=("lr", a, "blue"), **DOORS_BASE))
        T += _svc(op_l=1.0, op_r=0.7)

    elif kind == "caseH2":
        u = ease_out(cl(lt / 0.45))
        c = cl((lt - 0.55) / 0.60)
        L.append(D.stage(door_l=("blue", 1.0), door_r=("named", 1.0),
                         guard_l=("w", 1.0), guard_r=("w", 1.0), ring_r=1.0,
                         arc=("lr", 1.0, "blue"), up=("r", u), cross_r=c))
        T += _svc(op_l=0.7, op_r=1.0)

    elif kind == "caseL":
        a = ease_out(cl((lt - 0.20) / 0.60))
        L.append(D.stage(guard_l=("w", 1.0), guard_r=("b", 1.0), ring_r=1.0,
                         arc=("rl", a, "blue"), **DOORS_BASE))
        T += _svc(op_l=0.7, op_r=1.0)

    elif kind == "caseL2":
        u = ease_out(cl(lt / 0.45))
        c = cl((lt - 0.55) / 0.60)
        L.append(D.stage(door_l=("blue", 1.0), door_r=("named", 1.0),
                         guard_l=("w", 1.0), guard_r=("b", 1.0), ring_r=1.0,
                         arc=("rl", 1.0, "blue"), up=("r", u), cross_r=c))
        T += _svc(op_l=0.7, op_r=1.0)

    elif kind == "table":
        st = D.stagger(lt - 0.15, 2, 0.35, 0.30)
        L.append(D.table([(st[0], True), (st[1], True)]))
        rows = [("спросил честного", 820), ("спросил лжеца", 1030)]
        for i, (a, y) in enumerate(rows):
            if st[i] <= 0:
                continue
            T += [D.txt(a, (355, y), 31, "r", op=st[i]),
                  D.txt("неверная дверь", (770, y), 28, "r", op=st[i])]

    elif kind == "dbl":
        a1 = ease_out(cl(lt / 0.40))
        a2 = ease_out(cl((lt - 0.22) / 0.40))
        L.append(D.stage(door_l=("blue", 1.0), door_r=("named", 1.0),
                         guard_l=("w", 1.0), guard_r=("w", 1.0),
                         arc=("lr", a1, "blue"), up=("r", 1.0), cross_r=1.0))
        if a2 > 0.01:
            L.append(D.stage(door_l=("dim", 0.0), door_r=("dim", 0.0),
                             arc=("rl", a2, "white")))
        T += _svc(op_l=0.8, op_r=0.8)

    elif kind == "burst":
        i = prm["i"]
        left = (i % 2 == 0)
        L.append(D.stage(door_l=("blue", 1.0), door_r=("named", 1.0),
                         guard_l=("b" if left else "w", 1.0),
                         guard_r=("w" if left else "b", 1.0),
                         ring_l=1.0 if left else 0.0, ring_r=0.0 if left else 1.0,
                         arc=("lr" if left else "rl", 1.0, "blue"),
                         up=("r", 1.0), cross_r=1.0))
        T += _svc(op_l=1.0 if left else 0.6, op_r=0.6 if left else 1.0)

    elif kind == "result":
        L.append(D.stage(door_l=("blue", 1.0), door_r=("named", 1.0),
                         guard_l=("dim", 1.0), guard_r=("dim", 1.0),
                         arc=("lr", 1.0, "white"), up=("r", 1.0), cross_r=1.0))
        L.append(D.stage(door_l=("dim", 0.0), door_r=("dim", 0.0),
                         arc=("rl", 1.0, "white")))
        T += _svc(op_doors=0.45, op_l=0.6, op_r=0.6)
        T += D.num(t, 54.700, "100%", (540, 1462), 150)

    elif kind == "flip3":
        f = ease_out(cl((lt - 0.25) / 0.50))
        b = ease_out(cl((lt - 0.65) / 0.50))
        L.append(D.stage(door_l=("white", 1.0), door_r=("named", 1.0),
                         cross_r=1.0, flip=f))
        if b > 0.01:
            L.append(D.stage(door_l=("blue", b), door_r=("dim", 0.0)))
        if b > 0:
            T.append(D.txt("свобода", (D.LX, D.DLBL_Y), 60, "s", op=b))

    return L, T


