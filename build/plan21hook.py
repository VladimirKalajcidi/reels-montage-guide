"""Монтажный лист версии ролика 21 с другим хуком.

    python3 plan21hook.py h1 > ../videos/21/montage-plan-hook1.md
    python3 plan21hook.py h2 > ../videos/21/montage-plan-hook2.md
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard21 as SB
import render21 as R
from hook21 import HOOKS, CUT, CUT_F
from plan21 import NAMES

VIDEO_DIR = "/Users/vladimirkalajcidi/reels_good/videos/21"

MEAS = {
    "h1": dict(band="средняя 60.6 / p90 129", lufs="-14.1", tp="-1.7",
               post="кроп ×0.98", post_measured="карточка A 888px против 870 = ×1.0207",
               music="song2.mp3 (335с)", loop="петли нет",
               face="cx 376.6 · линия глаз 693.7 · размер лица 273.9 (23 замера)",
               seam="0.0025 против 99.99-перцентиля дорожки 0.2409"),
    "h2": dict(band="средняя 77.0 / p90 133", lufs="-14.1", tp="-1.6",
               post="ускорение ×1.02 (картинка и звук вместе)",
               post_measured="1235 кадров вместо 1260, r_frame_rate 30/1 (не 30.6); "
                             "видео 41.167с, аудио 41.162с — сходятся",
               music="song1.mp3 (9.5с)", loop="петля 9.27с ×4.5 с кроссфейдом 0.25с",
               face="cx 386.7 · линия глаз 681.4 · размер лица 273.6 (22 замера)",
               seam="0.0191 против 99.99-перцентиля дорожки 0.2496"),
}


def words(cfg):
    name = os.path.basename(cfg["src"]).replace(".mov", ".json")
    out = []
    for seg in json.load(open(f"{VIDEO_DIR}/{name}"))["segments"]:
        for w in seg.get("words", []):
            out.append((w["start"], w["end"], w["word"].strip()))
    return out


def emit(key):
    cfg = HOOKS[key]
    m = MEAS[key]
    hook_len = cfg["frames"] / FPS
    dt = hook_len - CUT
    dur = hook_len + (SB.DUR - CUT)
    speed = 1.02 if cfg.get("post_a") else 1.0

    shots = [(a, b, k, p, "хук") for a, b, k, p in cfg["shots"]]
    for a, b, k, p in SB.SHOTS:
        if b <= CUT + 0.001:
            continue
        shots.append((max(a, CUT) + dt, b + dt, k, p, "тело"))
    lens = sorted(b - a for a, b, _, _, _ in shots)
    face = sum(b - a for a, b, k, _, _ in shots if k in SB.FACE_KINDS)

    print(f"# Монтажный лист — ролик 21, версия {cfg['version']} (хук {key[-1]})\n")
    print(f"Хук: `videos/21/{os.path.basename(cfg['src'])}` · "
          f"{cfg['frames']} кадров · {hook_len:.3f}с")
    print(f"Тело: кадры {CUT_F}…1201 из уже сданного `porog_edit.mp4`, "
          "не пересобиралось")
    print(f"Готовый файл: `{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{dur / speed:.2f}с\n")
    print(f"**Текст хука:** {cfg['title']}\n")
    print(f"**Планов:** {len(shots)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {shots[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {dur:.1f}с = **{100*face/dur:.0f}%**\n")

    print("## Точка реза\n")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `A2` → `calc` "
          "в исходном ролике. Кадр считается через `ceil(t·30 − 1e-6)`, "
          "а не через `round`: на дробной границе `round` отдал бы последний кадр "
          "выброшенного плана.")
    print("\nВыброшено целиком: планы `A1` (0.00–1.88), `thresh` (1.88–3.16), "
          "`A2` (3.16–5.06) и все 4 их субтитра. Машинная проверка "
          "`qa21hook.old_hook_gone()`: `shot_at(151/30)` = `A2`, "
          "`shot_at(152/30)` = `calc` — планы разные, ни одного кадра старого "
          "начала не осталось.\n")
    print("**Связность стыка.** Первая фраза тела — «**это** конкретный расчёт "
          "пользы магазина». Местоимение «это» должно опираться на слово, которое "
          "реально звучит в новом дубле:\n")
    if key == "h1":
        print("> «…откуда берётся **это число**, после которого идёт скидка.» → "
              "«**Это** конкретный расчёт пользы магазина.»\n")
    else:
        print("> «…откуда **эта сумма** конкретно берётся?» → "
              "«**Это** конкретный расчёт пользы магазина.»\n")
    print("Опора есть, хук задаёт вопрос — тело сразу отвечает.\n")
    print("Резать по 3.16 (следующая граница плана) было бы хуже: тело начало бы "
          "с «это не просто какое-то случайное число», и ролик дважды подряд сказал "
          "бы, что число не случайное — оба дубля это уже проговаривают.\n")

    print("## Раскадровка\n")
    print("| # | тайминг | длит. | блок | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    caps = cfg["caps"]
    for i, (t0, t1, kind, prm, part) in enumerate(shots, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = SB.STOCK_NAMES.get(prm["clip"],
                                      "полки продуктового с ценниками, проезд камеры "
                                      "(mixkit 6102) — «в магазине»")
        if prm.get("big"):
            desc += f" + **R6**: крупное «{prm['big']}» на стене над головой"
        src = caps if part == "хук" else [(a + dt, b + dt, r, s) for a, b, r, s in SB.CAPS
                                          if a >= CUT]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, _b, runs, _s) in src if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {part} | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Блок хука\n")
    print("Структура старого начала сохранена — **лицо → шкала с порогом → лицо**, — "
          "и добавлен сток под слово «магазин», с которого начинаются оба дубля.\n")
    print("**План `thresh` («3000 ₽») оставлен намеренно.** Это визуальная интрига "
          "ролика, и без него порог 3000 в теле появился бы ниоткуда: после реза "
          "число «3 тысячи» в речи больше не звучит ни разу, а ярлык «3000 ₽» стоит "
          "на шкале до самого конца. При этом дубль говорит о сумме расплывчато "
          f"({'«скидка от скольки-то рублей»' if key == 'h1' else '«от определённой суммы»'}), "
          "и графика ставит на это место конкретное число — расхождение работает "
          "на интригу, а не против неё.\n")
    print("Субтитра с числом на этом плане нет: сумму пишет только графика "
          "(brand-kit §5, «одно и то же не пишется дважды»).\n")

    print("## Сток хука\n")
    print("`videos/21/stock/stock_6102.mp4` — полки продуктового магазина "
          "с ценниками, проезд камеры (Mixkit, свободная лицензия). Скачан под "
          "этот ролик.\n")
    print(f"Взят вместо тележки 49137 (она уже стоит в теле на 17.84) — реюз того же "
          f"клипа дважды в одном ролике читался бы как нехватка материала.\n")
    print(f"Полоса субтитров после `STOCK_GAIN 0.72` на окне `ss={cfg['shots'][1][3]['ss']}` "
          f"длиной {cfg['shots'][1][1]-cfg['shots'][1][0]:.2f}с: **{m['band']}** "
          "при пороге ≤110 / ≤140 — с запасом.\n")

    print("## Уникализация версии\n")
    print(f"| параметр | значение |")
    print(f"|---|---|")
    print(f"| музыка | `{m['music']}`, {m['loop']} |")
    print(f"| деформация | **{m['post']}** |")
    print(f"| замер деформации | {m['post_measured']} |")
    print(f"\nДеформация наложена на **уже собранное немое видео**, кадры "
          "не перерисовывались — один проход кодека. Порядок: сначала правка кадра, "
          "потом мукс со звуком.\n")
    print("Версия №1 (`porog_edit.mp4`, song3, без деформации) не тронута — "
          "она эталон, с ней сравниваются остальные.\n")

    print("## Звук\n")
    print("Дорожка пересобрана целиком, а не склеена из готовых: голос хука + голос "
          f"тела с точки реза, постель (whoosh / impact / tick) со сдвигом "
          f"**{dt:.4f}с**, музыка с нуля, затем loudnorm.\n")
    hw = words(cfg)
    hook_end = max(w[1] for w in hw)
    print(f"- Громкость голоса хука подогнана к телу по RMS речи: "
          f"×{'1.154' if key == 'h1' else '0.973'}.")
    print(f"- **Пауза между хуком и первой фразой тела: "
          f"{(hook_len - hook_end) + (5.200 - CUT):.3f}с** "
          f"(хвост хука {hook_len - hook_end:.3f}с + голова тела {5.200 - CUT:.4f}с). "
          "Норма `delivery-specs §6` — 0.10–0.20с.")
    print(f"- **Щелчка на стыке нет:** максимальный скачок между соседними сэмплами "
          f"в окне ±5мс вокруг шва — {m['seam']}.")
    print(f"- Замер готового `.mp4`: **{m['lufs']} LUFS**, истинный пик "
          f"**{m['tp']} dBTP**. Ориентир — громкость версии №1 (-14.0 / -1.6), "
          "а не абстрактные -14.")
    print("- **LRA 2.1 LU** при норме гайда 3–5 — то же свойство дубля, что "
          "и в версии №1: речь идёт очень ровно.\n")

    print("## Дубль хука против основного\n")
    print("A-roll хука прошёл **через тот же тракт**, что и тело: те же `FRAMINGS`, "
          "тот же безусловный `hflip`, грейда нет ни там, ни там. Ни крупность, "
          "ни экспозиция под основной дубль не подгонялись.\n")
    print("| | цветовые теги | крупность (детектор, после hflip) |")
    print("|---|---|---|")
    print("| основной | `yuv420p` / `bt709` / `bt709` / `bt709`, `tv` "
          "| cx 389.4 · линия глаз 669.6 · размер лица 267.6 (121 замер) |")
    print(f"| этот хук | те же | {m['face']} |")
    d_cx = cfg["face_cx"] - 389.4
    d_eye = cfg["face_eye"] - 669.6
    d_d = cfg["face_d"] / 267.6 - 1
    print(f"\n**Расхождение:** по горизонтали {d_cx:+.1f}px, по линии глаз "
          f"{d_eye:+.1f}px, по размеру лица {100*d_d:+.1f}%. В карточке A "
          f"(масштаб ×1.30) линия глаз уезжает на ~{abs(d_eye)*1.3:.0f}px из 1380. "
          "Это решается на съёмке — точкой, дистанцией и высотой камеры, — "
          "а не кропом на монтаже.\n")
    print("**Цветовые теги сверены и совпадают полностью**, приведения HDR→SDR "
          "не требуется. Средний RGB карточки A: хук "
          f"{'(114, 101, 95)' if key == 'h1' else '(114, 103, 95)'} против "
          "(114, 100, 93) у основного дубля — расхождение до 3 единиц по каналу "
          "при допуске ~10.\n")
    print("**Зеркальность проверена:** надписей в кадре нет, но интерьер, точка "
          "съёмки и рука с петличкой совпадают с основным дублём — штатный `hflip` "
          "подходит, отключать его не нужно.\n")

    print("## Автопроверки\n")
    print(f"Все по нулям (`python3 qa21hook.py {key}`):\n")
    print("| проверка | результат |")
    print("|---|---|")
    print("| текст за карточкой (скан готового mp4 через каждые 3 кадра, порог 200) "
          "| **0 кадров** |")
    print("| наложение строк внутри блока | **0 пар** |")
    print("| графика пересекает субтитры (по альфе >40) | **0 кадров** |")
    print("| графика вне зоны y700–1560 / x175–905 | **0 кадров** |")
    print("| субтитр вне карточки с отступом 30px | **0 кадров** |")
    print("| рез в хуке попал в середину слова | **0 резов** |")
    print("| фраза хука разошлась с речью дубля | **0 фраз** |")
    print("| от старого хука остался кадр или субтитр | **нет** |")
    print("| щелчок на стыке хук→тело | **нет** |")
    print("| тело кадр в кадр совпадает с версией №1 | **да**, PSNR 44 dB "
          "(шум кодека, кадры не перерисовывались) |")


if __name__ == "__main__":
    emit(sys.argv[1])
