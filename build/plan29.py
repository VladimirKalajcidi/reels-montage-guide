"""Генерирует монтажный лист ролика 29 до сборки."""
from storyboard29 import SHOTS, CAPS, DUR, FACE_KINDS, STOCK_KINDS


NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, более крупный кроп; смена только резом"),
    "infiniteWin": ("R4+R5a", "сетка: белые монеты складываются в растущую лестницу; над последней белым вспыхивает ∞"),
    "coinLaunch": ("R4+R10", "сетка: одна монета вылетает по дуге, поворот читается сменой стороны"),
    "coinLoop": ("R4+R10", "сетка: последовательность бросков; решка уходит дальше, первый орёл останавливает цепочку"),
    "ruleHeads": ("R4+R10", "сетка: орёл фиксируется слева, справа раскрывается первая ветвь выплаты"),
    "payout2": ("R4+R5a", "один бросок → орёл → крупное белое 2 ₽; субтитра с числом нет"),
    "payout4": ("R4+R5a", "решка → орёл → крупное белое 4 ₽; число живёт только в графике"),
    "payout8": ("R4+R5a", "решка → решка → орёл → крупное белое 8 ₽"),
    "doubling": ("R4+R10", "выплаты 2 → 4 → 8 → 16 каскадом; каждое следующее значение вдвое больше"),
    "prob2": ("R4+R5b", "1 бросок: 2 ₽ и синяя вероятность 1/2"),
    "prob4": ("R4+R5b", "2 броска: 4 ₽ и синяя вероятность 1/4"),
    "prob8": ("R4+R5b", "3 броска: 8 ₽ и синяя вероятность 1/8"),
    "expectTerms": ("R4+R10", "три строки 2×1/2=1, 4×1/4=1, 8×1/8=1; единицы вспыхивают по очереди"),
    "infiniteOutcomes": ("R4+R10", "дерево продолжает ветвиться вправо за край, число исходов визуально не заканчивается"),
    "infiniteSum": ("R4+R5b", "1 + 1 + 1 + … собирается в одну строку и превращается в синее ∞"),
    "stockCoins": ("R3", "видео: руки пересчитывают реальные монеты; практическая цена противопоставлена формальному ожиданию"),
    "tinyTail": ("R4+R10", "длинная цепочка решек сжимает толщину вероятностной ветви в почти невидимую нить"),
    "tinyWin": ("R4+R10", "огромная стопка выплаты справа, к ней ведёт тончайшая ветвь вероятности; контраст размера и шанса"),
    "stockSpb": ("R3+R6", "дроновый план Петропавловской крепости и Невы; поверх — САНКТ-ПЕТЕРБУРГСКИЙ / ПАРАДОКС"),
}


def main():
    face = sum(b - a for a, b, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(b - a for a, b, k, _ in SHOTS if k in STOCK_KINDS)
    lens = sorted(b - a for a, b, _, _ in SHOTS)
    med = lens[len(lens) // 2]
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «Санкт-Петербургский парадокс»\n")
    print(f"Исходник: `videos/29/source.mov` · 720×1280 · 30 fps · {DUR:.3f}с · SDR bt709")
    print("Планируемый выход: `videos/29/st_petersburg_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо:** {face:.2f}с = **{100*face/DUR:.1f}%** · "
          f"инфографика: {100*(DUR-face-stock)/DUR:.1f}% · сток: {stock:.2f}с")
    print(f"**Субтитры:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt. "
          "Речь и длительность исходника сохраняются целиком.\n")

    print("| # | тайминг | длит. | рецепт | источник / что на экране | текст на экране | анимация и звук |")
    print("|---|---|---:|---|---|---|---|")
    for i, (t0, t1, kind, _) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for a, _, runs, _ in CAPS if t0 <= a < t1)
        motion = "прямой рез; печать 30мс/символ; low whoosh"
        if kind not in FACE_KINDS and kind not in STOCK_KINDS:
            motion = "каскад 85мс / ease-out; low whoosh; tick на элементах"
        if kind in STOCK_KINDS:
            motion = "прямой рез; видео затемнено на 30%; low whoosh"
        if kind in {"prob2", "prob4", "prob8", "infiniteSum"}:
            motion += "; impact на синем результате"
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | "
              f"{txt or '— (смысл несёт графика)'} | {motion} |")

    print("\n## Проверка математики до рендера\n")
    print("- Выплаты: при первом орле на броске n показано `2ⁿ ₽`: 2, 4, 8, 16…")
    print("- Вероятность первого орла на броске n показана как `1/2ⁿ`: 1/2, 1/4, 1/8…")
    print("- Вклад каждого исхода в ожидание: `2ⁿ × 1/2ⁿ = 1 ₽`.")
    print("- Поэтому частичные суммы равны `1 + 1 + 1 + …` и растут без границы.")
    print("- Визуальный вывод не утверждает, что типичный выигрыш велик: отдельный блок показывает, "
          "как вероятность гигантской выплаты схлопывается к нулю.")
    print("- Синих результатов ровно четыре при лимите 4: вероятности 1/2, 1/4, 1/8 и финальное ∞. "
          "Бесконечность в хуке остаётся белой.")

    print("\n## Материал\n")
    print("Используются две короткие видео-вставки Pexels: пересчёт монет и дроновый план "
          "Петропавловской крепости с Невой. Фотографии и стоп-кадры не используются; "
          "вся математическая механика остаётся проверяемой анимированной графикой.")
    print("\n- Санкт-Петербург: https://www.pexels.com/video/aerial-video-of-saint-petersburg-3753675/")
    print("- Пересчёт монет: https://www.pexels.com/video/a-person-counting-coins-8870185/")


if __name__ == "__main__":
    main()
