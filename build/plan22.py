def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «дилемма заключённых»\n")
    print(f"Исходник: `videos/22/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/22/dilemma_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих чисел: 0** (в речи не звучит ни одного числа)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa22.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи и ни одной цифры.** Слова несёт только "
          "субтитр, графика несёт то, чего в словах нет:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| фигура в скруглённой рамке | участник в своей комнате |")
    print("| чёрточка на лице | «молчит» |")
    print("| стрелка к соседу | «сдаёт его» |")
    print(f"| вертикальная полоса под фигурой | срок: короткая {TERM_SHORT}px, "
          f"средняя {TERM_MID}px, длинная {TERM_LONG}px |")
    print("| пустая засечка без полосы | срока нет — свобода |")
    print("| пунктирное продолжение полосы | срок, который был бы при другом выборе |")
    print("| пунктирный разделитель посередине | сравниваются два сценария |")
    print("\nПоэтому проверка «одно и то же не пишется дважды» здесь проходит "
          "по построению: пересечься субтитру и графике нечем. Машинная проверка "
          "пересечения слоёв (`qa22.gfx_text_overlap`) — 0 кадров, графика "
          "не выходит из зоны y700…1560 / x175…905 (`qa22.gfx_in_zone`) — 0 кадров.")

    print("\n## Цвет")
    print("- **Синих чисел ноль**, потому что в речи нет ни одного числа. "
          "Синим (#3B4BE8) окрашен **результат** — средний срок, к которому приходят "
          "оба «рационально»: планы `eqResult`, `verdict`, `together`, `couldHave`. "
          "Это одна и та же пара полос, показанная четыре раза, а не четыре разных "
          "синих объекта.")
    print("- **Лайм #C3DB4E — один элемент на весь ролик**: восстановленная связь "
          "между комнатами на плане `deal` («если бы просто договорились»). "
          "Ровно то, чего им не хватило.")
    print("- Кегли субтитров "
          f"{min(sizes)}–{max(sizes)}pt. Верх шкалы `brand-kit §3` (XL 150–200 "
          "под число-ревил) не задействован: числа-ревила в этом ролике нет, "
          "показывать XL нечего.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print("- Whoosh на каждой из 28 склеек (0.040 от пика), импакт под ревилом "
          "результата (0.070), тики под каскадами элементов (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume/alimiter.")
    print("- Замер готового `.mp4`: **-14.2 LUFS**, истинный пик **-1.5 dBTP** — в цели.")
    print("- **LRA 2.3 LU** при норме гайда 3–5. Это свойство дубля: речь идёт очень "
          "ровно, без громких и тихих мест. Лимитером и loudnorm не лечится — "
          "фиксирую замер, а не правлю.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/22/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nПолоса субтитров в карточке B замерена до скачивания 1080p: "
          "средняя 51–54 из 255, p90 82–87 при пороге ≤110 / ≤140 — "
          "клип тёмный, белый текст со свечением на нём читается.")
    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render22). Кроп посчитан по детектору: 28 замеров "
          "по всему дублю дали cx 395±10, линию глаз y 671±4, ширину лица 265 — "
          "глаза стоят на 42.0% высоты карточки у A1 и на 41.5% у A2.")
    print("Проверка: средний RGB внутри карточки A в сданном файле отличается "
          "от того же кропа исходника на **1.6–2.8 единицы** по каналу — это "
          "цена 4:2:0 и H.264, а не коррекция.")
    print("Замер самого дубля: средние по карточке A **121 / 104 / 95** против "
          "ориентира `brand-kit §6` «130 / 112 / 104». Расхождение называю "
          "числами и не правлю: гамма-подтяжка до ориентира уже пробовалась "
          "на ролике 16 и дала вымытое лицо и рост шума.")
    print("\nОстальные планы закрыты собственной графикой. Это не экономия: "
          "у дилеммы вся суть — в четырёх исходах и их сравнении, а сток такого "
          "не показывает (`assets-manifest §2`: «если сцену можно закрыть своей "
          "графикой без потери смысла — берём графику»).")


if __name__ == "__main__":
    emit()
