"""Монтажные листы версий ролика 15 с другим хуком.

    python3 plan15hook.py h1 > ../videos/15/montage-plan-hook1.md
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import storyboard15 as SB
from hook15 import HOOKS, CUT_F, CUT, BRIDGE
from style import FPS

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "проезд по авеню к Капитолию США (mixkit 11800) — «президент США»"),
    "pyth": ("R4+R10", "сетка: классический чертёж — прямоугольный треугольник "
                       "и три квадрата, построенные наружу на каждой стороне"),
}

# замеры дублей: детектор лица и средний RGB внутри карточки A (см. hook15.py)
TAKES = {
    "h1": dict(face="x=295 y=785 d=437", eyes=969, rgb="141/116/104"),
    "h2": dict(face="x=311 y=786 d=427", eyes=966, rgb="139/115/102"),
}
BODY_TAKE = dict(face="x=309 y=657 d=438", eyes=841, rgb="94/74/63")

key = sys.argv[1] if len(sys.argv) > 1 else "h1"
cfg = HOOKS[key]
tk = TAKES[key]
L = cfg["frames"] / FPS
dt = L - CUT
total = L + (SB.DUR - CUT)
speed = 1.02 if cfg.get("post_a") else 1.0

print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
print(f"Хук: {cfg['title']}\n")
print(f"Исходники: `videos/15/source.mov` (тело) + `videos/15/hook{key[-1]}.mov` (хук)")
print(f"Готовый ролик: `videos/15/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
      f"{total / speed:.2f}с\n")
print(f"**Блок хука:** {cfg['frames']} кадров = {L:.4f}с · планов {len(cfg['shots'])} · "
      f"первый рез {cfg['shots'][0][1]:.2f}с")
print(f"**Тело:** без изменений, кадры взяты готовыми из уже сданного ролика начиная "
      f"с кадра {CUT_F} ({CUT:.4f}с). Раскадровка тела — в `montage-plan.md`.\n")

print("## Точка реза\n")
print(f"Хуковая фраза оригинала — «Президент США доказал теорему Пифагора» — кончается "
      f"на 2.580с, но следующая фраза «Её доказывали больше 370 разными способами» "
      f"начинается уже на 2.880с, внутри плана 2 (`pyth`, 1.94–3.64). Рез по 2.88 дал бы "
      f"тело, начинающееся с середины анимации чертежа, и план длиной 0.76с — поэтому рез "
      f"поставлен на ближайшую границу плана после неё: 3.64с, в кадрах 109.2, то есть по "
      f"первому кадру плана `n370` — кадр {CUT_F} = {CUT:.4f}с.\n")
print(f"Планы 1–2 старого начала и их субтитры выброшены целиком: первый кадр тела в этой "
      f"версии машинно сверен с кадром {CUT_F} оригинала.\n")
print(f"Связка «её доказывали» (2.88–3.64) в новом хуке не произносится, поэтому она взята "
      f"из исходной дорожки: голос хука кончается, дальше исходник идёт сплошняком с "
      f"{BRIDGE:.2f}с и играет под последним планом блока хука, где и перерисован её "
      f"субтитр. Пауза между хуком и первой фразой тела — "
      f"{(L - (CUT - 2.88)) - (cfg['caps'][-2][1]):.2f}с.\n")

print("## Блок хука\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(cfg["shots"], 1):
    rec, desc = NAMES[kind]
    if prm.get("ss") is not None:
        desc += f", с {prm['ss']:.1f}с клипа"
    txt = " / ".join("".join(r[0] for r in runs).strip()
                     for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | {txt or '—'} |")
print()
print("Графика блока — та же, что стояла в старом начале (классический чертёж Пифагора): "
      "это визуальная интрига ролика, менять её незачем. Вставка с Капитолием взята из "
      "стока этого же ролика (`videos/15/stock/`), под произносимые слова «президент США».\n")

print("## Чем эта версия отличается от версии 1\n")
print(f"- **Музыка:** `audios/{os.path.basename(cfg['music'])}` "
      f"(у версии 1 — `song2.mp3`, у второй версии — `song1.mp3`, у третьей — `song3.mp3`; "
      f"ни один трек не повторяется).")
if cfg.get("post_v", "").startswith("crop"):
    print("- **Деформация:** кроп ×0.98 — 2% по краям обрезаны, холст возвращён к 1080×1920. "
          "Измерено машинно: ширина карточки A 870 → 888 px = **×1.0207** при норме ×1.0204.")
else:
    print("- **Деформация:** ускорение ×1.02 картинки и звука вместе (`setpts` + `atempo`), "
          "липсинк не едет. После `setpts` стоит `fps=30`: без него на выходе был бы "
          "нестандартный 30.6 fps. Кадров стало 1609 вместо 1641 — лишние 2% выброшены честно.")
print("- **Уровень:** доведён до уровня версии 1, а не до абстрактных −14: "
      "зритель сравнивает версии между собой.")
print("- Версия 1 не тронута: файл `garfield_edit.mp4` тот же, что сдавали "
      "(sha1 записан в выводе `qa15hook.py`).\n")

print("## Расхождение дублей — замерено, не подчищено\n")
print("Формат хука приведён к тракту (это делается всегда, START-HERE):\n")
print("| свойство | основной дубль | хук | что сделано |")
print("|---|---|---|---|")
print("| разрешение | 1080×1920 | 720×1280 | апскейл lanczos до холста тракта |")
print("| pix_fmt / range | `yuv420p` / `tv` | `yuvj420p` / `pc` | приведение к limited |")
print("| color_space / transfer / primaries | bt709 | bt709 | совпадают, тонмаппинг не нужен |")
print()
print("Приведение range меняет картинку на 3–4 единицы по каналу "
      "(141.2/116.5/103.8 против 144.5/121.0/107.8 до приведения).\n")
print("**Вкусовые параметры не правились** — ни крупность, ни положение головы, ни "
      "экспозиция. По цифрам расхождение такое:\n")
print("| замер | основной дубль | хук |")
print("|---|---|---|")
print(f"| лицо детектором | {BODY_TAKE['face']} | {tk['face']} |")
print(f"| линия глаз в кадре | y={BODY_TAKE['eyes']} | y={tk['eyes']} |")
print(f"| средний RGB внутри карточки A | {BODY_TAKE['rgb']} | {tk['rgb']} |")
print()
print(f"Размер головы совпадает (438 против {tk['face'].split('d=')[1]} — расхождение до 2.5%), "
      f"а вот по вертикали голова в хуке сидит на **{tk['eyes'] - BODY_TAKE['eyes']}px ниже**, "
      f"и дубль на **~{int(round((int(tk['rgb'].split('/')[0]) - 94) - 3))} единиц по каналу светлее** "
      f"основного (из них 3–4 единицы — приведение range, остальное съёмочное). "
      f"Норма из delivery-specs — до ~10 единиц по каналу, здесь заметно больше. "
      f"Это решается светом и точкой съёмки, а не кропом и лутом на монтаже: "
      f"снимать хуки тем же светом, с той же дистанции и с той же высоты камеры, "
      f"что и основной дубль. Решение — переснять или принять как есть — не за монтажом.\n")

print("## Звук\n")
print("- Дорожка пересобрана целиком: голос хука + исходник с "
      f"{BRIDGE:.2f}с, постель со сдвигом {dt:.4f}с, музыка с нуля, потом loudnorm.")
print("- Уровень голоса хука подогнан к телу по RMS речи "
      "(это микс, а не грейд: иначе версия звучала бы тише оригинала).")
print("- Whoosh на каждой склейке, включая стык хук/тело; импакты и тики каскадов тела "
      "сдвинуты вместе с телом.")
print("- Стык проверен машинно: скачок между соседними сэмплами на порядок меньше "
      "типичного по дорожке — щелчка нет.")
