"""Генерирует монтажный лист ролика 11 из раскадровки."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard11 import SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена дубля)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "pyth": ("R4+R10", "сетка: прямоугольный треугольник + квадраты на сторонах"),
    "swap": ("R4+R10", "сетка: показатели 2 меняются на n синим"),
    "zero": ("R4+R5b", "сетка: синий «0»"),
    "eqn": ("R4+R10", "сетка: xⁿ + yⁿ собирается по словам"),
    "eqn2": ("R4+R10", "сетка: дописывается «= zⁿ»"),
    "n2": ("R4+R10", "сетка: показатель n → 2, чертится треугольник"),
    "inf": ("R4+R10", "сетка: ∞ и решётка целых точек"),
    "triple345": ("R4+R5a", "сетка: треугольник 3-4-5, белые числа"),
    "ngt2": ("R4+R10", "сетка: n > 2 и ряд показателей 3 4 5 6 7"),
    "none": ("R4+R10", "сетка: пустое множество, кандидаты вычёркиваются"),
    "y1637": ("R4+R5b", "сетка: синий «1637»"),
    "margin": ("R4+R10", "сетка: страница с полем, доказательство не помещается"),
    "y358": ("R4+R5b", "сетка: синий «358» + «лет молчания»"),
    "y1994": ("R4+R5b", "сетка: синий «1994»"),
    "proof": ("R4+R10", "сетка: галка и знак конца доказательства"),
    "timeline": ("R4+R10", "сетка: шкала 1637 → 1994, разрыв заливается синим"),
}

face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

print("# Монтажный лист — «великая теорема Ферма»\n")
print(f"Исходник: `videos/11/source.mov` · 1080×1920 · 30 fps · {DUR:.2f}с · SDR bt709")
print("Готовый ролик: `videos/11/fermat_edit.mp4`\n")
print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
      f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
      f"первый рез {SHOTS[0][1]:.2f}с")
print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
      f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 4 (0 · 1637 · 358 · 1994)\n")
print("Речь не резана: резы только по картинке. Субтитры исправляют Whisper "
      "(«Пер Ферма» → пьер ферма, «опровернуть» → опровергнуть).\n")
print("Зоны на планах с графикой: субтитры y 300…600, графика y 700…1560 "
      "(`brand-kit.md §5`). Где смысл несёт графика — субтитра нет.\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
    rec, desc = NAMES[kind]
    if prm.get("clip"):
        desc = STOCK_NAMES[prm["clip"]]
    txt = " / ".join("".join(r[0] for r in runs).strip()
                     for (a, b, runs, _s) in CAPS if t0 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
          f"| {txt or '— (говорит графика)'} |")

print("\n## Звук")
print("- Речь исходника целиком, без резки.")
print("- Whoosh на каждой склейке (0.040 от пика), импакт под числом-ревилом (0.070), "
      "тики каскада (0.030).")
print("- Музыка `audios/song1.mp3`: −19 dB от RMS голоса, петля с кроссфейдом 0.25с, "
      "фейды 0.8 / 2.0с.")
print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7.")

print("\n## Сток")
print("Скачан под этот ролик в `videos/11/stock/`, источник Mixkit (свободная лицензия):\n")
for cid, name in STOCK_NAMES.items():
    print(f"- `stock_{cid}.mp4` — {name}")
