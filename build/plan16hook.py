"""Монтажные листы версий ролика 16 с другими хуками."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hook16 as HK
import storyboard16 as SB
from style import FPS
from plan16 import NAMES

HOOK_NAMES = dict(NAMES)
HOOK_NAMES["trio"] = ("R4+R10", "сетка: три листа А3/А4/А5, затем А4 и А5 наезжают на А3 "
                                "и точно ложатся в его контур")

MEAS = {
    "h1": dict(rgb="121 / 105 / 99", face=41.2, eyes=49.9, lufs=-14.05, tp=-1.29,
               pause=0.150, card="888x1408 (x1.0207 по ширине, x1.0203 по высоте)"),
    "h2": dict(rgb="113 / 101 / 96", face=38.8, eyes=49.5, lufs=-14.05, tp=-1.66,
               pause=0.153, card="870x1380 (без кропа, ускорение x1.02)"),
}


def build(key):
    cfg = HK.HOOKS[key]
    m = MEAS[key]
    hl = cfg["frames"] / FPS
    sp = 1.02 if cfg.get("post_a") else 1.0
    total = (cfg["frames"] + 1228) / FPS / sp
    out = []
    P = out.append
    P(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    P(f"Файл: `videos/16/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · {total:.2f}с")
    P(f"Дубль хука: `videos/16/hook{key[-1]}.mov`\n")
    P(f"Текст хука: {cfg['title']}\n")
    P("## Что изменилось относительно версии 1\n")
    P(f"- Перерисован только блок хука — **{cfg['frames']} кадров ({hl:.3f}с)**.")
    P("- Тело взято готовыми кадрами из `build/assets/_video_a4.mp4` начиная с кадра "
      f"**{HK.CUT_F}** ({HK.CUT:.4f}с) — это граница плана `sheet` (1.86–4.44), "
      "то есть конец старого хука. Кадров и субтитров старого начала не осталось.")
    P(f"- Тело сверено с версией 1 покадрово: худший PSNR по пяти пробам **45.5 dB** "
      "(расхождение — только шум кодека).")
    P(f"- Музыка: `{os.path.basename(cfg['music'])}` (у версии 1 — `song2.mp3`).")
    P(f"- Деформация под площадку: `{cfg['post_v']}`"
      + (f" + `{cfg['post_a']}` по звуку." if cfg.get("post_a") else "."))
    P(f"- Замер деформации: габарит карточки A **{m['card']}**.\n")
    P("## Блок хука\n")
    P("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    P("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, _p) in enumerate(cfg["shots"], 1):
        rec, desc = HOOK_NAMES[kind]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        P(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
          f"| {txt or '— (говорит графика)'} |")
    P(f"\nДалее с {hl:.3f}с — тело версии 1 без изменений "
      "(планы 3–22 монтажного листа `montage-plan.md`).\n")
    if key == "h1":
        P("Субтитра на «а3 а4 а5» (2.66–3.86) нет: ровно эти имена стоят подписями "
          "под прямоугольниками графики (`brand-kit.md §5`).\n")
    P("## Звук\n")
    P("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, "
      "постель SFX со сдвигом, музыка с нуля, потом loudnorm.")
    P(f"- Громкость **{m['lufs']} LUFS**, истинный пик **{m['tp']} dBTP** "
      "(у версии 1 — −14.0 и −1.7).")
    P(f"- Пауза между хуком и первой фразой тела **{m['pause']:.3f}с** (норма 0.10–0.20).")
    P("- На стыке щелчка нет: скачок между соседними сэмплами 0.009 против 0.32 "
      "по 99.99-перцентилю дорожки.\n")
    P("## Расхождение дубля хука с основным — измерено, НЕ исправлено\n")
    P("Приведён только формат (объективные свойства файла): **720×1280 → 1080×1920** "
      "и **color_range pc → tv**. Дальше хук идёт через тот же тракт A-roll, что и тело: "
      "тот же `hflip`, тот же кроп из `FRAMINGS`, грейда нет ни там, ни там.\n")
    P("| | основной дубль | хук |")
    P("|---|---|---|")
    P(f"| разрешение | 1080×1920 | **720×1280** (в карточку идёт с апскейлом ×1.32) |")
    P(f"| средний RGB в карточке A | 77 / 65 / 58 | **{m['rgb']}** |")
    P(f"| ширина лица, % кадра | 41.9 | {m['face']} |")
    P(f"| линия глаз, % высоты кадра | 41.8 | **{m['eyes']}** |")
    P("")
    P("Расхождение по яркости — **порядка 40 единиц по каждому каналу** при норме "
      "`delivery-specs.md §6` «до ~10». Хук снят заметно светлее. Голова в кадре стоит "
      "на 8 процентных пунктов ниже, поэтому после того же кропа лицо в карточке сидит "
      "ниже, чем в теле. Ни то, ни другое кропом и цветокоррекцией не правится — "
      "по `START-HERE.md` это съёмочная сторона: тот же свет, та же точка, та же "
      "дистанция и экспорт в том же разрешении.")
    P("")
    P("Что при этом проверено и в порядке: зеркальность (надпись на футболке читается "
      "задом наперёд, штатный `hflip` подходит), цветовые теги (`bt709` у обоих, "
      "HDR нет, тонмаппинг не нужен), субтитр не наезжает на рот — до подбородка "
      "остаётся 108px.")
    P("")
    P("## Автопроверки\n")
    P("| проверка | результат |")
    P("|---|---|")
    P("| ярче 200 вне карточки | 0 кадров |")
    P("| графика × субтитры в хуке | 0 кадров |")
    P("| графика хука вне зоны y700…1560 | 0 кадров |")
    P("| текст хука вне карточки | 0 кадров |")
    P("| тело против версии 1 | PSNR 45.5 dB |")
    if key == "h2":
        P("| фреймрейт после ускорения | ровно 30/1 |")
        P("| длительности видео / звука | 46.967с / 46.945с |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    for k in ("h1", "h2"):
        p = f"/Users/vladimirkalajcidi/reels_good/videos/16/montage-plan-hook{k[-1]}.md"
        open(p, "w", encoding="utf-8").write(build(k))
        print("записан", p)
