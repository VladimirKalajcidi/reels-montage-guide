"""Монтажные листы версий ролика 13 с другим хуком.

    python3 plan13hook.py h1 > ../videos/13/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import storyboard13 as SB
from hook13 import HOOKS, CUT_F, CUT
from plan13 import NAMES  # печать плана под main()
from style import FPS

KEY = sys.argv[1]
cfg = HOOKS[KEY]
N = cfg["frames"]
HOOK_LEN = N / FPS
DT = HOOK_LEN - CUT                      # сдвиг тела на новой таймлинии
# план 6 начинается на 8.42, то есть до точки реза 8.4333 — он попадает в тело
# частично, началом служит сам рез. Фильтр по s[1] > CUT, начало клампится.
BODY = [(max(s[0], CUT), s[1], s[2], s[3]) for s in SB.SHOTS if s[1] > CUT]
TOTAL = HOOK_LEN + (SB.DUR - CUT)
SPEED = 1.02 if cfg.get("post_a") else 1.0

# замеры дублей: детектор лица и средние по каналам внутри карточки A (крупность A1)
MEAS = {
    "h1": dict(face_pct=42, face_y=724, rgb=(131, 110, 98)),
    "h2": dict(face_pct=40, face_y=717, rgb=(133, 111, 99)),
}[KEY]
BODY_MEAS = dict(face_pct=44, face_y=608, rgb=(96, 75, 65))

print(f"# Монтажный лист — версия {cfg['version']} ({KEY}), ролик 13 «парадокс Банаха — Тарского»\n")
print(f"Хук: `videos/13/hook{cfg['version']-1}.mov` — {cfg['title']}")
print(f"Тело: готовые кадры из `build/assets/_video_banach.mp4`, с кадра **{CUT_F}** "
      f"({CUT:.4f}с). Не пересобиралось.")
print(f"Готовый файл: `videos/13/{os.path.basename(cfg['out'])}`\n")
print(f"**Точка реза.** Хуковая фраза оригинала кончается словом «исходный» на 8.420 "
      f"(`source.srt`), ближайшая граница плана — 8.42 (конец плана 5). В кадрах это 252.6, "
      f"поэтому режем по первому кадру следующего плана: кадр 253 = 8.4333с. "
      f"Планы 1–5 старого начала и их субтитры выброшены целиком.\n")
print(f"**Хронометраж:** хук {N} кадров ({HOOK_LEN:.3f}с) + тело {SB.DUR - CUT:.3f}с "
      f"= {TOTAL:.3f}с" + (f", после ускорения ×1.02 — {TOTAL/SPEED:.3f}с" if SPEED != 1 else "") + "\n")

print("## Блок хука\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, _prm) in enumerate(cfg["shots"], 1):
    rec, desc = NAMES[kind]
    txt = " / ".join("".join(r[0] for r in runs).strip()
                     for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | {txt or '— (говорит графика)'} |")

print(f"\nГрафика хука — та же, что стояла в старом начале (шар → куски → два шара → "
      f"равные линейки): это визуальная интрига ролика, менять её незачем. "
      f"Первый рез {cfg['shots'][0][1]:.2f}с (норма ≤2.0). Хвост блока закрыт графическим "
      f"планом, а не стоп-кадром лица.\n")

print("## Тело (без изменений, тайминги на новой таймлинии)\n")
print("| тайминг в версии | было в оригинале | рецепт | что на экране |")
print("|---|---|---|---|")
for t0, t1, kind, prm in BODY:
    rec, desc = NAMES[kind]
    if prm.get("clip"):
        desc = SB.STOCK_NAMES[prm["clip"]]
    print(f"| {(t0+DT)/SPEED:.2f}–{(t1+DT)/SPEED:.2f} | {t0:.2f}–{t1:.2f} | {rec} | {desc} |")

print("\n## Звук")
print("Дорожка пересобрана целиком, а не склеена из готовых:")
print(f"- голос хука (приведён к уровню речи тела ×{'0.831' if KEY=='h1' else '1.156'} по RMS речи) "
      f"+ голос тела с {CUT:.4f}с;")
print(f"- постель whoosh/impact/tick пересчитана со сдвигом {DT:+.3f}с;")
print(f"- музыка `{os.path.basename(cfg['music'])}` с нуля: −19 dB от RMS голоса, петля с "
      f"кроссфейдом 0.25с, фейды 0.8 / 2.0с;")
print("- финал: highpass 65 Гц + loudnorm + догон до уровня оригинала.")
print(f"\nЗамер готового файла: **−14.1 LUFS**, истинный пик **−1.6 dBFS** — совпадает с "
      f"оригиналом (−14.1 / −1.7). На стыке хук/тело скачок между соседними сэмплами "
      f"{'0.006' if KEY=='h1' else '0.002'} против типичного {'0.184' if KEY=='h1' else '0.191'} "
      f"по дорожке — щелчка нет.")
print(f"\nПауза между хуком и первой фразой тела — **{(HOOK_LEN - cfg['speech_end']) + (8.76 - CUT):.3f}с**. "
      f"Собственные паузы между предложениями в теле — 0.16–0.54с, медиана 0.28с, "
      f"и перед этой самой фразой в оригинале стоит 0.34с. То есть шов звучит ровно как "
      f"межфразовая пауза этого дубля.")

print(f"\n## Уникализация (версия {cfg['version']})")
print(f"- музыка: `{os.path.basename(cfg['music'])}` (версия 1 — song3, версия 2 — song1, "
      f"версия 3 — song2, ни один трек не повторяется);")
if cfg.get("post_v", "").startswith("crop"):
    print("- деформация: **кроп ×0.98** — 2% по краям срезаны, холст возвращён к 1080×1920. "
          "Замерено машиной по одному и тому же объекту (ширина карточки A на кадре 1290): "
          "**870 → 888 px, ×1.0207** при норме ×1.0204.")
else:
    print("- деформация: **ускорение ×1.02** — `setpts=PTS/1.02` и `atempo=1.02` вместе, "
          "картинка и звук. После `setpts` дописан `fps=30`: замер готового файла "
          "**r_frame_rate=30/1**, 1790 кадров вместо 1826 — лишние 2% кадров выброшены честно. "
          "Длительности видео 59.667с и аудио 59.662с сходятся.")
print("- деформация наложена на уже собранное немое видео одним проходом кодека, "
      "кадры не перерисовывались.")
print("\nВерсия 1 (`banach_edit.mp4`) не тронута — файл тот же, что сдавали "
      "(sha1 6170ca6e733932b4, 1852 кадра).")

print("\n## Расхождения дубля хука с основным исходником")
print("Правило гайда: приведение **формата** делается всегда, подгонка **вкусовых** "
      "параметров — никогда. Ниже — что приведено и что осталось как снято.\n")
print("**Приведено (однозначно выводится из тегов файла):**\n")
print("| свойство | основной дубль | хук | что сделано |")
print("|---|---|---|---|")
print("| разрешение | 1080×1920 | **720×1280** | апскейл lanczos до холста тракта |")
print("| `color_range` | `tv` (yuv420p) | **`pc`** (yuvj420p) | приведён к limited |")
print("| `color_space` / `transfer` / `primaries` | bt709 | bt709 | совпадают, конверсия не нужна |")
print("| зеркальность | надпись на толстовке читается наизнанку | так же | штатный `hflip` подходит |")
print("\nПриведение range меняет картинку на ~2 единицы по каналу "
      "(109.7/97.5/92.0 → 107.6/96.6/89.7) — декодер и так читал теги верно. "
      "HDR-тонмаппинг не понадобился: оба дубля SDR bt709.\n")
print("**НЕ правится — это к съёмочной стороне, а не к монтажу:**\n")
print("| замер внутри карточки A (крупность A1) | основной дубль | хук | расхождение |")
print("|---|---|---|---|")
print(f"| ширина лица | {BODY_MEAS['face_pct']}% ширины карточки | {MEAS['face_pct']}% "
      f"| **−{BODY_MEAS['face_pct']-MEAS['face_pct']} п.п.** (голова мельче) |")
print(f"| центр лица по вертикали | {BODY_MEAS['face_y']} из 1380 | {MEAS['face_y']} "
      f"| **+{MEAS['face_y']-BODY_MEAS['face_y']} px** (голова ниже, больше потолка) |")
print(f"| средний RGB | {'/'.join(map(str,BODY_MEAS['rgb']))} | {'/'.join(map(str,MEAS['rgb']))} "
      f"| **+{MEAS['rgb'][0]-BODY_MEAS['rgb'][0]}/+{MEAS['rgb'][1]-BODY_MEAS['rgb'][1]}"
      f"/+{MEAS['rgb'][2]-BODY_MEAS['rgb'][2]}** |")
print(f"\nНорма по чеклисту — расхождение среднего RGB до ~10 единиц по каналу. Здесь "
      f"**+{MEAS['rgb'][0]-BODY_MEAS['rgb'][0]}** — втрое больше: дубль хука снят заметно "
      f"светлее. Крупность и положение головы тоже разошлись. Ни то, ни другое кропом и лутом "
      f"не чинится — хук прошёл через тот же тракт A-roll (`FRAMINGS`, `hflip`, `GRADE`) "
      f"без единой поправки. Решение — переснять хук с тем же светом, точкой и дистанцией "
      f"или принять как есть — не за монтажом.\n")
print("Плюс апскейл 720p → 1080p: A-roll хука мягче, чем тело. Тоже съёмочное — "
      "дубли хуков стоит экспортировать в том же разрешении, что основной.")
