# ---------------------------------------------------------------- графика планов
cl = D.cl


def layers(kind, prm, lt, dur, t):
    """(список RGBA-слоёв, список текстовых элементов) для плана."""
    L, T = [], []

    if kind == "chaos":
        st = D.stagger(lt, 4, 0.60, 0.16)
        L.append(D.tangle([0, 1, 2, 3], st, blue=(2,)))

    elif kind == "two":
        st = D.stagger(lt, 2, 0.45, 0.14)
        L.append(D.orbits(t, sun=st[0], o1=ease_out(cl(lt / 0.55)), b1=st[1]))
        T += D.num(t, 5.420, "2", D.NUM_XY, 155)

    elif kind == "two_lbl":
        L.append(D.orbits(t, o1=1.0, b1=1.0))
        p = ease_out(cl(lt / 0.35))
        q = ease_out(cl((lt - 0.20) / 0.35))
        T.append(D.txt("солнце", (D.SC[0], D.SC[1] + 72), 44, "s", op=p))
        bx, by = D._body_pt(0, t)
        T.append(D.txt("земля", (bx, by + 54), 42, "s", op=q))

    elif kind == "two_pred":
        L.append(D.orbits(t, o1=1.0, b1=1.0, pred=ease_out(cl(lt / 0.65))))
        T.append(D.txt("любой момент в будущем", (540, 1462), 40, "r",
                       op=ease_out(cl((lt - 0.45) / 0.40))))

    elif kind == "three":
        st = D.stagger(lt - 0.30, 2, 0.40, 0.16)
        L.append(D.orbits(t, o1=1.0, b1=1.0, o2=st[0], b2=st[1]))
        T += D.num(t, 12.980, "3", D.NUM_XY, 155)

    elif kind == "nosol":
        L.append(D.orbits(t, o1=1.0, b1=1.0, o2=1.0, b2=1.0, jit=0.55, dim=0.55))
        p = ease_out(cl(lt / 0.35))
        L.append(D.formula_box(p, cross=cl((lt - 0.45) / 0.60)))
        if p > 0:
            T.append(D.txt("точная формула", (510, 1333), 46, "r", op=p))

    elif kind == "year":
        L.append(D.orbits(t, o1=1.0, b1=1.0, o2=1.0, b2=1.0, jit=0.5, dim=0.55))
        T += D.num(t, 21.080, "1889", D.NUM_XY, 150)

    elif kind == "stable":
        st = D.stagger(lt, 2, 0.50, 0.22)
        L.append(D.orbits(t, o1=st[0], b1=1.0, o2=st[1], b2=1.0))
        T.append(D.txt("устойчива и предсказуема", (540, 1382), 40, "r",
                       op=ease_out(cl((lt - 0.90) / 0.40))))

    elif kind == "err":
        j = ease_out(cl(lt / 1.20))
        L.append(D.orbits(t, o1=1.0, b1=1.0, o2=1.0, b2=1.0, jit=0.95 * j,
                          dim=1.0 - 0.35 * j))
        L.append(D.diverge(1, ease_out(cl((lt - 0.25) / 0.90)), dots=0.0))

    elif kind == "div1":
        L.append(D.magnifier(ease_out(cl(lt / 0.40)), gap=0.0))

    elif kind == "div2":
        L.append(D.magnifier(1.0, gap=ease_out(cl(lt / 0.55))))

    elif kind == "div3":
        L.append(D.diverge(0, ease_out(cl(lt / 1.30)),
                           dots=ease_out(cl(lt / 0.30))))

    elif kind == "burst":
        L.append(D.diverge(2 + prm["i"], 1.0, dots=1.0))

    elif kind == "det":
        L.append(D.panel([(ease_out(cl(lt / 0.45)), "ok"), (0.0, "no")]))
        T.append(D.txt("точные законы", (205, 910), 46, "r", anchor="lm",
                       op=ease_out(cl((lt - 0.10) / 0.40))))

    elif kind == "unpred":
        p = ease_out(cl((lt - 0.15) / 0.45))
        L.append(D.panel([(1.0, "ok"), (p, "no")]))
        T.append(D.txt("точные законы", (205, 910), 46, "r", anchor="lm", op=0.72))
        if p > 0:
            T.append(D.txt("прогноз надолго", (205, 1130), 46, "r", anchor="lm", op=p))

    elif kind == "tangle":
        st = D.stagger(lt, 5, 0.55, 0.14)
        L.append(D.tangle([0, 4, 5, 6, 7], st, blue=(3,)))

    elif kind == "app1":
        L.append(D.icons("butterfly", ease_out(cl(lt / 1.20)), t))

    elif kind == "app2":
        L.append(D.icons("turb", cl(lt / 1.00), t))

    elif kind == "app3":
        L.append(D.icons("asteroid", cl(lt / 1.10), t))

    return L, T


