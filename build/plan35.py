def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = lens[len(lens) // 2]
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «парадокс Рассела»\n")
    print(f"Исходник: `videos/35/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/35/russell_edit.mp4` · 1080×1920 · 30 fps · "
          f"{int(round(DUR*30))} кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с — ролик объяснительный, "
          "очередь быстрых резов R3 не используется")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· графика и вставка **{100*(DUR-face)/DUR:.0f}%** "
          f"(из них сток {stock:.1f}с = {100*stock/DUR:.0f}%).")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**чисел в ролике не звучит ни одного**, поэтому ревилов числа "
          "(R5a/R5b) нет — синим помечены выводы\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa35.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Логика парадокса пересчитана")
    print("R — множество всех множеств, которые не содержат сами себя. Условие "
          "приёма в R: «не содержит сам себя». Обе ветки пересчитаны машинно "
          "(`qa35.logic` = 0 нарушений):\n")
    print("| посылка | условие выполнено | значит R должен | что вышло |")
    print("|---|---|---|---|")
    print("| R **содержит** себя | нет ✗ | не лежать в R | противоречие с посылкой |")
    print("| R **не содержит** себя | да ✓ | лежать в R | противоречие с посылкой |")
    print("\nВывод каждой ветки — это посылка другой, поэтому цикл A → B → A "
          "замкнут. Именно он нарисован на плане `loop`, а не абстрактное кольцо.")
    print("\nБытовая версия — та же схема на людях: парикмахер бреет ровно тех, "
          "кто не бреет себя, и вопрос «бреет ли он себя» даёт то же кольцо. "
          "Поэтому на планах `barber1–3` работают те же стрелки: стрелка = "
          "«бреет его», петля = «бреется сам».")

    print("\n## Расхождение со сценарием — не чинилось монтажом")
    print("На 4.81–7.04 в речи звучит «ответ **да**, и оно называется множество "
          "Рассела». Строго говоря ответ «нет»: противоречие, которое разбирает "
          "сам ролик, и доказывает, что такого множества не существует — это и "
          "есть содержание парадокса Рассела (1901) и причина, по которой "
          "наивную схему свёртывания заменили аксиоматикой ZFC.")
    print("\nРечь не режется, поэтому фраза остаётся как риторическая подводка — "
          "и ролик сам её опровергает: 23.8с «противоречия при любом ответе», "
          "36.5с «нельзя просто объявлять множество объектов». **Графика нигде "
          "не утверждает, что R существует:** коробка R собирается как попытка "
          "построения и на плане `prop2` (38.26–40.64) получает синий крест. "
          "Единственный субтитр с этим утверждением — «ответ да» на 4.81, и он "
          "снимается на экране через 19 секунд.")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи** — только фигуры, цвет и знак "
          "вопроса. Слова несёт субтитр, механику несёт сцена:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| коробка с точками | множество и его элементы |")
    print("| коробка с копией себя внутри | множество содержит само себя |")
    print("| белый крест на такой коробке | «такие сюда не входят» — условие R |")
    print("| большая коробка с тремя коробками и пустым местом | множество Рассела |")
    print("| «?» в пустом месте | вопрос «содержит ли R сам себя» |")
    print("| стрелка от фигурки к фигурке | «бреет его» |")
    print("| петля от фигурки к себе | «бреется сам» |")
    print("| **синее** | вывод: что из посылки следует |")
    print("| два состояния и две дуги между ними | замкнутая петля |")
    print("\nОдин и тот же знак работает в обеих половинах ролика: коробка "
          "внутри коробки и петля у фигурки — это одно и то же отношение "
          "«применить к самому себе», из-за которого и ломается логика.")

    print("\nСубтитры не повторяют графику (`qa35.captions_duplicating_graphics` "
          "= 0, `qa35.digits_in_captions` = 0): слово «парикмахер» на стоковом "
          "плане не набирается — его несёт сам кадр; слово «парадокс» не "
          "набирается ни разу — его несёт крупная надпись R6 на 34.76–36.57.")
    print("\nМашинная проверка пересечения слоёв (`qa35.gfx_text_overlap`) — "
          "0 кадров; графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa35.gfx_out_of_zone`) — 0 кадров и нигде не упирается во врезку "
          "маски (`qa35.gfx_clipped`) — 0 кадров. Текст за карточку не "
          "выходит (`qa35.text_out_of_card` и `qa35.bright_outside_card`) — "
          "0 кадров; строки блоков не пересекаются "
          "(`qa35.line_overlap_pairs`) — 0 пар.")

    print("\n## Сток")
    print("Вставка одна, и она литеральная — на слове «парикмахер»:\n")
    print("| файл | что в кадре |")
    print("|---|---|")
    for cid, desc in STOCK_NAMES.items():
        print(f"| `videos/35/stock/stock_{cid}.mp4` | {desc} |")
    print(f"\nКлип скачан под этот ролик (Mixkit, свободная лицензия), лежит "
          "в его папке и не берётся из других роликов (`assets-manifest §2`). "
          "Он стоит **перед** пиктограммой парикмахера: схему из фигурок и "
          "стрелок опознают только после литерального плана с настоящим "
          "парикмахером. Полоса субтитров после притемнения на 28% — "
          f"**{STOCK_BAND[0]} / p90 {STOCK_BAND[1]}** при пороге ≤110 / ≤140. "
          f"Клип играет, а не стоит: покадровая разница **{STOCK_MOTION[0]}** "
          f"при {STOCK_MOTION[1]} плотности контуров — не ниже принятого клипа "
          "ролика 34 (4.19 / 0.006).")
    print("\nБыл рассмотрен более буквальный клип «barber shaving a man's beard» "
          "(mixkit 47843): по смыслу он точнее под слово «бреет», но полоса "
          "субтитров у него 113–123 при любом кропе и окне — белый текст на нём "
          "не читается, поэтому взят 43222 (`stock_caption_band_check`).")
    print("\nОстальные планы — своя графика. Живого видео, буквально "
          "показывающего «множество, содержащее само себя», не существует; "
          "перебивка «человек думает» или «книги» к механике задачи не "
          "относится, а `assets-manifest §2` прямо запрещает ставить сток "
          "ради ритма.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) — только выводы: крест «R нарушает своё условие», "
          "контур R как вывод «не содержит себя», галочка «подходит под "
          "условие», вынужденная копия внутри R, замкнутая петля, «?» у "
          "парикмахера, крест на коробке из произвольного свойства и галочка "
          "на множестве, стоящем на аксиомах. Один код на весь ролик: "
          "синее = вывод (brand-kit §4).")
    print("- Белых чисел нет: в речи не звучит ни одного числа, а придумывать "
          "число на экран — значит выносить то, чего в дубле нет.")
    print("- Лайм не использован: в ролике нет матричных/табличных элементов, "
          "для которых он предусмотрен.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под пятью синими выводами (0.070), тики под каскадами элементов "
          "(0.030).")
    print("- Музыка `audios/song1.mp3`: −19 dB от RMS голоса, петля с "
          "кроссфейдом 0.25с, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume / alimiter limit=0.80.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render35.py). Кроп посчитан по детектору: 29 замеров "
          "по всему дублю дали cx 374±9, линию глаз y 687±6, ширину лица "
          "271±6 — окно 630×1000 от (57, 264) ставит глаза на 42% высоты "
          "карточки, то же окно, что в роликах 22–34. Зеркальность проверена "
          "по кадру: надпись на футболке после `hflip` читается нормально "
          "(«…CA BEACH 902»), штатный `hflip` подходит.")

    print("\n## Полоса субтитров на планах с лицом — не в норме, не чинилось")
    print("Замер полосы, где лежит субтитр (карточка A, y 1260…1400, "
          "x 200…880, по всем планам с лицом):\n")
    print("| ролик | средняя | p90 | порог |")
    print("|---|---|---|---|")
    print(f"| **35 (этот)** | **{FACE_BAND[0]}** | **{FACE_BAND[1]}** | ≤110 / ≤140 |")
    print("| 34 (сдан) | 168.6 | 170.3 | ≤110 / ≤140 |")
    print("| 33 (сдан) | 171.8 | 219.4 | ≤110 / ≤140 |")
    print("\nСветлая футболка в дневном свете: полоса ярче, чем у стоковой "
          "вставки, которую этот же порог в ролик не пустил бы. Белый текст "
          "со свечением на ней читается слабее, чем на графических планах.")
    print("\nМонтажом это не чинится и не чинилось: плашка-подложка под текстом "
          "запрещена (`brand-kit §7`), грейд лица — тоже (A-roll идёт только "
          "через `hflip` + кроп). Решение — на съёмочной стороне: тёмная "
          "футболка или менее выбитый свет на груди.")

    print("\n## Расшифровка")
    print("Пословные тайминги — `videos/35/words.json`, собраны по речевым "
          "отрезкам: границы сняты `ffmpeg silencedetect` (-34dB / 0.12с), "
          "внутри каждого отрезка выдача whisper large-v3 растянута на "
          "измеренный интервал (`align35.py`). Семь пауз короче 0.18с сочтены "
          "внутрифразовыми и отрезки слиты.")
    print("\nДевять границ, по которым идёт рез, дополнительно уточнены по "
          "огибающей (`snap35.py`): линейная растяжка внутри отрезка уводит "
          "границу на десятые доли секунды, и рез попадает на атаку слова. "
          "Самая большая поправка — 15.184 → 15.105 (энергия на резе упала "
          "с 0.074 до 0.0016).")
    print("\nТри места whisper слышит неверно: 28.29 «**Барикмахер**» вместо "
          "«парикмахер» (на 33.24 то же слово распознано верно), 35.13 "
          "«**Продокс**» вместо «парадокс», 20.82–21.99 «по собственной "
          "определении» вместо «по собственному определению». Ни одно из этих "
          "мест в субтитр не вынесено: на 28.29 субтитр начинается со слова "
          "«бреет» (парикмахера несёт стоковый кадр), на 35.13 слово несёт "
          "надпись R6, на 20.82 субтитр идёт «идеально подходит» и обрывается.")


if __name__ == "__main__":
    emit()
