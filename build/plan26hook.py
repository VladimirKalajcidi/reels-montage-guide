"""Монтажный лист версии ролика 26 с другим хуком.

    python3 plan26hook.py h1 > ../videos/26/montage-plan-hook1.md
    python3 plan26hook.py h2 > ../videos/26/montage-plan-hook2.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard26 as SB
from hook26 import HOOKS, CUT, CUT_F, lts_for
from plan26 import NAMES

# замеры готовых файлов (qa26hook.py)
MEASURED = {
    "h1": dict(lufs=-14.10, tp=-1.60, lra=1.7, frames=1501, dur=50.03, pause=0.542,
               seam=(56, 1928), rgb=7, psnr=44.0, gain=1.613,
               deform="кроп ×0.98 — карточка A на одном и том же кадре тела "
                      "(49.5с, план с лицом) 870px → 888px = ×1.0207 "
                      "(целевое ×1.0204, расхождение — 1px квантования)"),
    "h2": dict(lufs=-14.10, tp=-1.50, lra=1.7, frames=1436, dur=47.87, pause=0.531,
               seam=(140, 2065), rgb=2, psnr=44.0, gain=1.055,
               deform="ускорение ×1.02 картинкой и звуком разом — 1465 кадров "
                      "исходной склейки стали 1436 (×1.0202), длительность видео "
                      "47.867с против звука 47.853с, фреймрейт ровно 30/1"),
}

RHYTHM = {
    "h1": dict(shots=25, avg=2.00, median=1.94, shortest=1.10, longest=2.87,
               first_cut=1.33, face_pct=31.7),
    "h2": dict(shots=25, avg=1.92, median=1.87, shortest=1.11, longest=2.81,
               first_cut=1.27, face_pct=32.5),
}

# межфразовые паузы самого дубля (гэпы >0.30с по videos/26/words.json)
BODY_PAUSES = dict(lo=0.320, hi=0.562, med=0.424, n=13)

OLD_HOOK = ("«есть задача, которую невозможно решить полным перебором, "
            "даже если у вас есть самый мощный в мире суперкомпьютер»")


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    r = RHYTHM[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    dt = nh - CUT
    speed = 1.02 if "setpts" in (cfg.get("post_v") or "") else 1.0

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/26/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.2f}с · {m['frames']} кадров")
    print(f"Хук: `videos/26/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с)")
    print(f"Тело: кадры {CUT_F}+ из уже сданного `tsp_edit.mp4`, не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")
    print(f"**Ритм версии целиком:** {r['shots']} планов · средняя {r['avg']:.2f}с · "
          f"медиана {r['median']:.2f}с · мин {r['shortest']:.2f}с · макс {r['longest']:.2f}с · "
          f"первый рез {r['first_cut']:.2f}с · лицо **{r['face_pct']:.1f}%**\n")

    print("## Точка реза")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `stock` → `A2` в исходном ролике, "
          f"то есть конец старого начала {OLD_HOOK}. Планы 1–3 старого хука и все 6 "
          "их субтитров выброшены целиком: от старого начала не осталось ни кадра.")
    print(f"\nКадр считается как `ceil(5.877 × 30)` = {CUT_F}, а не `round` = 176: "
          "граница плана стоит на дробном кадре 176.31, и кадр 176 — это ещё последний "
          "кадр выбрасываемого плана со стойками дата-центра. Проверка машинная: "
          f"`qa26hook.old_hook_gone` требует, чтобы кадры {CUT_F - 1} и {CUT_F} лежали "
          "в разных планах.")
    print("\n**Что именно заменил хук.** Новый дубль проговаривает то же самое первое "
          "предложение другими словами — «есть задача, которую не решить перебором даже "
          "на самом мощном компьютере». Поэтому убирается ровно одно предложение старого "
          "начала, и его конец совпадает с границей плана кадр в кадр — подбирать точку "
          "реза не пришлось.")
    print("\n**Связность стыка.** Тело начинается с «итак, курьеру нужно объехать несколько "
          "адресов и вернуться обратно» — самостоятельное предложение, без местоимений, "
          "которые отсылали бы к словам старого начала. Ни подставлять слова в дубль, "
          "ни выбрасывать фразы тела не пришлось.")
    print()

    print("## Блок хука")
    print(f"Планов: **{len(cfg['shots'])}** · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"первый рез **{lens[0]:.2f}с** · мин {min(lens):.2f}с · макс {max(lens):.2f}с\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = SB.STOCK_NAMES[prm["clip"]] + f" (с {prm.get('ss', 0):.1f}с клипа)"
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")
    print(f"\nДалее без изменений идёт тело сданного ролика — планы 4–25 из "
          f"`montage-plan.md`, со сдвигом **{dt:+.4f}с** на новой таймлинии"
          + (f" и общим ускорением ×{speed:.2f}.\n" if speed != 1.0 else ".\n"))

    print("## Графика хука")
    print("Взято ровно то, что стояло в старом начале: план `bruteFlash` (шесть адресов, "
          "старт кольцом, поверх них один за другим вспыхивают варианты маршрута) "
          "и стоковые серверные стойки. Это визуальная интрига ролика, менять её незачем; "
          "ни одного нового плана не нарисовано.")
    print(f"\nНа слова дубля план ложится буквально: перебор вариантов идёт под "
          f"«{'не подвластные решению' if key == 'h1' else 'может решить'}», а стойки "
          f"дата-центра — под «{'на самых мощных на сегодняшний день компьютерах' if key == 'h1' else 'мощный суперкомпьютер'}». "
          f"Длина плана перебора {lens[1]:.2f}с против 1.35с в теле; масштаб времени "
          "анимации **×1.00** — анимация циклическая (вспышки вариантов идут одна за "
          "другой), ей нечего «доигрывать», и ускорять её не нужно.")

    print("\n## Сток в хуке")
    print("Тот же клип, что стоял в старом начале, и с той же точки входа — "
          f"`stock_7887.mp4` с {cfg['shots'][2][3]['ss']:.1f}с. План "
          f"{'длиннее' if lens[2] > 2.816 else 'короче'} "
          f"({lens[2]:.2f}с против 2.82с в теле), клип 11.04с это выдерживает без петли. "
          "Хвост блока хука закрыт им, а не стоп-кадром лица.")

    print("\n## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, и основной "
          "исходник — 720×1280, `yuv420p`, `color_range=tv`, `bt709`/`bt709`/`bt709`, 30 fps. "
          "Кадры читаются прямо из `.mov` и идут в штатный тракт A-roll **без единого "
          "промежуточного кодека**.")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip, медиана по всему дублю): основной дубль "
          f"cx 402 / линия глаз 643 / ширина лица 283; этот хук cx {cfg['face_cx']} / "
          f"{cfg['face_eye']} / {cfg['face_d']}.")
    print(f"  Расхождение: **{cfg['face_cx']-402:+d}px по горизонтали, "
          f"{cfg['face_eye']-643:+d}px по линии глаз, "
          f"{100*(cfg['face_d']/283-1):+.1f}% по размеру лица** — то есть дубли сняты "
          "практически с одной точки, разница на уровне разброса самого детектора "
          "на основном дубле (±7px по центру, ±4px по линии глаз). "
          "Править нечего и ничего не правилось.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуках, "
          "проверить по тексту не на чем. Штатный `hflip` оставлен: петличка в руке "
          "во всех трёх дублях с одной стороны кадра.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука против кадров тела расходятся "
          f"на **{m['rgb']} единиц** по каналу (норма — до ~10).")

    print("\n## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек; "
          "у версии №1 `song2.mp3`, у другой версии — третий. Ни один не повторяется.")
    if key == "h1":
        print("  Трек 110с длиннее ролика, поэтому идёт без петли — шва не существует.")
    else:
        print("  Трек 9.53с короче ролика, поэтому идёт петлёй 9.27с ×5.3 "
              "с кроссфейдом 0.25с на шве — это единственный доступный третий трек "
              "в `audios/`.")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались.")
    if key == "h1":
        print("  Ресайз bilinear, а не lanczos: у lanczos отрицательные лепестки дают "
              "на границе карточки светлый ореол в 1px, и автопроверка «текст "
              "за карточкой» краснеет.")
    else:
        print("  Ускорение прошло и по картинке (`setpts`), и по звуку (`atempo`) — "
              "разъехавшийся на 2% липсинк виден на губах. После `setpts` стоит `fps=30`: "
              "без него на выходе получается 30.6 fps, нестандартный фреймрейт, "
              "который площадка пережмёт по-своему.")

    print("\n## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, постель "
          f"(whoosh / impact / tick) со сдвигом **{dt:+.4f}с**, музыка с нуля, потом loudnorm.")
    print("- Whoosh стоит и на резах внутри хука, и на самом шве «хук → тело».")
    print(f"- Голос хука приведён к громкости тела по RMS речи (×{m['gain']:.3f})"
          + (": дубль записан заметно тише основного." if m["gain"] > 1.2
             else ": дубли записаны на одном уровне."))
    print(f"- Пауза между последним словом хука и первым словом тела: **{m['pause']:.3f}с**. "
          "Чеклист `delivery-specs §6` называет 0.10–0.20с, но там же оговорка «как между "
          f"предложениями в теле» — в этом дубле межфразовые паузы идут "
          f"{BODY_PAUSES['lo']:.2f}–{BODY_PAUSES['hi']:.2f}с "
          f"(медиана {BODY_PAUSES['med']:.2f}с по {BODY_PAUSES['n']} паузам), "
          f"так что {m['pause']:.2f}с — ровно уровень тела. Укоротить её нечем: "
          "0.539с из этой паузы — это тишина в голове тела перед словом «итак», "
          "а тело идёт готовыми кадрами, и сдвигать под него звук значит развалить синхрон.")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами на шве "
          f"**{m['seam'][0]}** против **{m['seam'][1]}** на 99.9-м процентиле всей дорожки.")
    print(f"- Громкость **{m['lufs']:.2f} LUFS**, истинный пик **{m['tp']:.2f} dBFS**, "
          f"LRA {m['lra']:.1f} LU — сведено к уровню уже сданного `tsp_edit.mp4` "
          "(−14.10 / −1.70 / 1.9), а не к абстрактным −14.")

    print("\n## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa26hook.py {key}")
    print("```")
    print("Все по нулям: `text_out_of_card=0`, `gfx_text_overlap=0`, `gfx_out_of_zone=0`, "
          "`line_overlaps=0` по блоку хука, `bright_outside` = 0 кадров по всему файлу версии "
          "(включая деформацию), нарушений стиля субтитров 0, слов не из речи 0.")
    print(f"- Рез по границе плана: кадры {CUT_F - 1} и {CUT_F} лежат в разных планах "
          "(`stock` → `A2`) — от старого хука не осталось ни кадра, ни субтитра.")
    print(f"- Тело против сданной версии — худший PSNR **{m['psnr']:.1f} dB** "
          "на 14 контрольных кадрах (это второе прохождение того же кодека, картинка та же).")
    print("- Версия №1 не тронута: `tsp_edit.mp4` не открывался на запись — "
          "хук читает из него только готовые кадры тела.")


if __name__ == "__main__":
    emit(sys.argv[1])
