"""Генерирует монтажный лист ролика 17 из раскадровки."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard17 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS, CARD,
                          CARD_SWAPPED, CARD_SUM, CARD_SUM_BAD)

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "scan": ("R4+R10", "сетка: по номеру карты идёт луч, берёт одну цифру в рамку, под ней крест"),
    "card16": ("R4+R10", "сетка: номер набирается группами по четыре, под группами подчёркивания"),
    "check": ("R4+R10", "сетка: от каждой цифры линия сходится в один пульсирующий узел"),
    "every2": ("R4+R10", "сетка: стрелка справа налево, подчёркнута каждая вторая цифра, под ними удвоенные значения"),
    "gt9": ("R4+R10", "сетка: удвоенные значения, три из них (16, 12, 12) подчёркнуты и пульсируют"),
    "minus9": ("R4+R10", "сетка: «12 − 9 = 3», строка удвоенных перещёлкивается на 7, 3, 3"),
    "sumrow": ("R4+R10", "сетка: строка итоговых значений, из неё сыплются 80 точек в компактный блок"),
    "sum80": ("R4+R5b", "сетка: блок из 80 точек + синее «80»"),
    "div10": ("R4+R10", "сетка: точки разъезжаются в восемь полных десятков, лишнего нет, галка"),
    "swap": ("R4+R10", "сетка: две первые цифры меняются местами по дуге, пара берётся в рамку"),
    "nodiv": ("R4+R5b", "сетка: синее «72», семь десятков и две лишние лаймовые точки, крест"),
    "barcode": ("R4+R10", "сетка: штрих-код со своим рядом цифр, по нему проходит луч"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    print("# Монтажный лист — «алгоритм Луна»\n")
    print(f"Исходник: `videos/17/source.mov` · 1080×1920 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (теги сверены, конверсия не нужна)")
    print("Готовый ролик: `videos/17/luhn_edit.mp4`\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 2 ({CARD_SUM} · {CARD_SUM_BAD})\n")
    print("Речь не резана: резы только по картинке, все — на границах фраз "
          "по пословным таймингам whisper.\n")
    print(f"Номер на экране — публичный тестовый Visa-номер `{CARD}`, он проходит "
          f"проверку Луна: сумма **{CARD_SUM}**, делится на 10. После перестановки двух первых "
          f"цифр (`{CARD_SWAPPED}`) сумма **{CARD_SUM_BAD}**, остаток 2. Арифметика пересчитана кодом.\n")
    print("Зоны на планах с графикой: субтитры y 300…600, графика y 700…1560 "
          "(`brand-kit.md §5`). Числа, которые звучат в речи (16, 9, 10), графика не пишет; "
          "числа на графике (номер карты, удвоенные значения, 80, 72) в речи не звучат.\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print("- Whoosh на каждой склейке (0.040 от пика), импакт под синим числом (0.070), "
          "тики каскада (0.030).")
    print("- Музыка `audios/song2.mp3`: −19 dB от RMS голоса, трек длиннее ролика — "
          "идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор volume/alimiter.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/17/stock/`, источник Mixkit (свободная лицензия):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")

    print("\n## Решения по этому дублю")
    print("- **A-roll не грейдится** — только `hflip` и кроп. Дубль снят вечером при тёплом "
          "искусственном свете, он уже тёплый (R>G>B по средним). Подтяжка гаммы к "
          "«эталонным» 130/112/104 делает кадр вымытым.")
    print("- **`hflip` включён**: надпись на футболке в исходнике читается зеркально — "
          "проверено по кадру.")
    print("- **Кадры идут в кодек одним проходом** — сырой поток в ffmpeg вместо "
          "промежуточного `cv2.VideoWriter(mp4v)`.")

    print("\n## Чего в ролике сознательно нет")
    print("- **R6 (крупное слово в карточке)** — полоса над головой это подсвеченный "
          "потолок с диагональной световой лентой (средняя яркость 100, p90 188). "
          "Белое слово на 62% там разрывается светом, а опустить его нельзя — сядет на голову.")
    print("- **R3 (очередь быстрых резов)** — материал предметный, очередь пришлось бы "
          "набивать нерелевантным стоком. `assets-manifest.md §2`: лучше своя графика.")
    print("- **R8 (пруф-вставка)** и **R9 (предметный PNG)** — в речи нет ни ссылки "
          "на источник, ни предмета, который стоило бы вклеить отдельным PNG.")
    print("- **Сток под «штрих-коды»** — на Mixkit нет ни одного клипа со сканированием "
          "штрих-кода. По правилу «лучше своя графика, чем случайная перебивка» "
          "план закрыт нарисованным штрих-кодом на сетке.")



if __name__ == "__main__":
    emit()
