"""Монтажный лист версии ролика 31 с другим хуком.

    python3 plan31hook.py h1 > ../videos/31/montage-plan-hook1.md
    python3 plan31hook.py h2 > ../videos/31/montage-plan-hook2.md
"""
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import hook31 as HK
import storyboard31 as SB
from plan31 import NAMES

VIDEO_DIR = "/Users/vladimirkalajcidi/reels_good/videos/31"

# измерения сданных файлов
MEAS = {
    "h1": dict(lufs=-14.07, tp=-1.76, lra=2.9, frames=1479, dur=49.30,
               voice_gain=1.310, rgb_hook=(123, 111, 103), rgb_src=(122, 110, 103),
               pause=0.154, seam_jump=0.00034, seam_ref=0.05246,
               deform="ширина карточки A на одном и том же кадре тела — 864px "
                      "в версии №1 и 882px в этой → **×1.0208** при ожидаемых "
                      "×1.0204 для кропа 0.98 (метод — bbox не-чёрных пикселей, "
                      "не детектор лица: тот слишком шумный для измерения 2%)"),
    "h2": dict(lufs=-14.08, tp=-1.92, lra=2.7, frames=1485, dur=49.50,
               voice_gain=1.113, rgb_hook=(123, 111, 105), rgb_src=(122, 110, 103),
               pause=0.157, seam_jump=0.00108, seam_ref=0.05296,
               deform="кадров до ускорения 1515, после — 1485 → **×1.0202** "
                      "при номинальных ×1.02; `r_frame_rate` ровно `30/1` "
                      "(без `fps=30` вышло бы 30.6); длительности видео и звука "
                      "совпадают до миллисекунды — ускорение прошло и по "
                      "картинке, и по звуку"),
}

HOOK_NAMES = {
    "schedPlain": ("R4+R10", "линия времени с равными промежутками — расписание; "
                             "чисел нет, потому что чисел нет и в речи"),
    "schedTen": ("R4+R10+R5a", "та же линия расписания, один промежуток "
                               "подсвечен, под ним белое **10** на слове «10»"),
    "waitPlain": ("R4+R10", "один промежуток на весь кадр: метка прихода "
                            "пассажира и полоса ожидания; числа нет"),
    "waitFive": ("R4+R10+R5a", "тот же промежуток, метка прихода посередине "
                               "и полоса ожидания — белое **5** на слове «5»"),
    "A1": ("R1", "лицо, базовая крупность"),
}


def words(key):
    return json.load(open(f"{VIDEO_DIR}/words_hook{key[-1]}.json"))


def emit(key):
    cfg = HK.HOOKS[key]
    m = MEAS[key]
    seam = cfg["frames"] / FPS
    dt = seam - HK.CUT_V
    speech_end = max(w["end"] for w in words(key))

    print(f"# Монтажный лист — «парадокс инспекции», версия хука {key[-1]}\n")
    print(f"**Хук:** {cfg['title']}")
    print(f"**Готовый файл:** `videos/31/{os.path.basename(cfg['out'])}` · "
          f"1080×1920 · 30 fps · {m['frames']} кадров · {m['dur']:.2f}с")
    dfm = ("кроп ×0.98 (обрезка 2% по краям, холст возвращён к 1080×1920)"
           if cfg["version"] == 2 else
           "ускорение ×1.02 (картинка и звук вместе, затем `fps=30`)")
    print(f"**Деформация версии:** {dfm}")
    print(f"**Музыка:** `audios/{os.path.basename(cfg['music'])}`\n")

    print("## Точка реза")
    print("Старое начало ролика — «если автобусы ходят в среднем раз в 10 минут, "
          "это ещё не значит, что вы будете ждать в среднем 5 минут» (0.00–5.16) "
          "— занимало три плана: `A1` 0.00–1.12, `schedTicks` 1.12–2.44, "
          "`naiveWait` 2.44–5.67. Граница плана **5.669с** (`naiveWait` → `A1` "
          "«итак допустим интервалы между автобусами разные») — точка реза: "
          f"`CUT_F = ceil(5.669·30) = {HK.CUT_F}`. Все три старых плана и все "
          "пять их субтитров выброшены целиком; от старого хука не осталось "
          "ни кадра и ни субтитра (проверено машинно: первый кадр тела в версии "
          "совпадает с кадром 171 версии №1 и расходится с кадрами 169–170 "
          "на 61 уровень серого).\n")
    print("**Звук тела берётся с 5.669, а картинка — с 5.700, и это не описка.** "
          "Границы планов в этом ролике поставлены по началам слов, поэтому "
          "граница 5.669 совпадает не с тишиной, а с атакой слова «Итак». "
          "Огибающая `source.mov` с шагом 10мс: 5.62 −82 дБ, 5.63 −57, 5.66 −38, "
          "5.67 −33, 5.70 −25 при пике слова −9 дБ. То есть кадр 171 стоит уже "
          "на 35% амплитуды слова — обрезав по нему звук, мы срезали бы атаку "
          "«И» и получили бы «...так допустим».\n")
    print("Поэтому картинка тела идёт с кадра 171 (иначе в версию попал бы кадр "
          "старого хука), а голос — с 5.669, с настоящей атаки слова. Разница "
          "ровно один кадр, **31мс**, и знак у неё безопасный: картинка идёт "
          "впереди звука. Порог заметности для задержки звука ~125мс против "
          "~45мс для опережения — 31мс лежит вчетверо ниже порога. Смещение "
          "постоянное на всё тело, склеек внутри дорожки нет. SFX при этом "
          "считаются от картинки, чтобы whoosh падал ровно на кадр реза.\n")
    print("Тело начинается самостоятельным предложением со своим подлежащим — "
          "«итак, допустим, интервалы между автобусами разные». Отсылок "
          "к выброшенному тексту в нём нет, а про автобусы и ожидание говорит "
          "и новый хук — дефицита антецедента нет.\n")

    print("## Блок хука")
    print("| план | тайминг | рецепт | что на экране | текст |")
    print("|---|---|---|---|---|")
    for t0, t1, kind, _ in cfg["shots"]:
        rec, desc = HOOK_NAMES[kind]
        txt = " / ".join("«" + "".join(r[0] for r in runs).strip() + "»"
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| `{kind}` | {t0:.2f}–{t1:.2f} | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")
    face = sum(t1 - t0 for t0, t1, k, _ in cfg["shots"] if k in SB.FACE_KINDS)
    print(f"\nПланов в блоке {len(cfg['shots'])}, лицо {face:.2f}с из "
          f"{seam:.2f}с = {100*face/seam:.0f}%, первый рез "
          f"{cfg['shots'][0][1]:.2f}с (≤2.0с).\n")
    print("Графика хука — те же два плана, что стояли на этом месте в исходном "
          "начале ролика: линия расписания с равными промежутками (`schedTicks`) "
          "и один промежуток с меткой прихода и полосой ожидания (`naiveWait`). "
          "Ни одного нового графического объекта не нарисовано — это визуальная "
          "интрига ролика, её незачем менять. Изменено только расписание стадий, "
          "чтобы ревилы падали на слова нового дубля.\n")
    if cfg["num_reveals"]:
        print("Числа показаны там же, где звучат: **10** на «раз в 10 минут», "
              "**5** на «больше 5 минут» — те же два числа, что несла графика "
              "в старом начале. Субтитр на этих планах обрывается перед попом "
              "числа (`qa31hook.captions_on_number_shots` = 0), цифр "
              "в субтитрах нет.\n")
    else:
        print("**Чисел в блоке нет** — их нет и в речи этого дубля. Графика идёт "
              "без ревилов и без подсветки размеченного промежутка: показывать "
              "«10» и «5», которых зритель не слышит, значило бы утверждать "
              "графикой то, чего не говорит автор.\n")
    b0 = SB.SHOTS[3]
    print("Блок кончается **графикой, а не лицом**: первый план тела "
          f"(`{b0[2]}` {b0[0]:.2f}–{b0[1]:.2f}) — говорящая голова, и стык "
          "«лицо чужого дубля → лицо» читался бы как джамп-кат.\n")

    print("## A-roll хука")
    print(f"Дубль `{os.path.basename(cfg['src'])}` идёт через тот же тракт "
          "A-roll, что и основной исходник: тот же `hflip`, тот же кроп "
          "(`FRAMINGS[\"A1\"]`), без грейда и без поправок под дубль.\n")
    print("Цветовые теги совпадают с основным исходником: `yuv420p` / `tv` / "
          "`bt709` / `bt709` / `bt709`, 720×1280, 30 fps — конверсия HDR→SDR "
          "не требовалась ни для одного из хуков.\n")
    print("Крупность дубля (детектор, после hflip, среднее по дублю): основной "
          "cx 401 / линия глаз 701 / ширина лица 273; "
          f"{os.path.basename(cfg['src']).split('.')[0]} cx {cfg['face_cx']} / "
          f"линия глаз {cfg['face_eye']} / ширина лица {cfg['face_d']}.")
    dx = cfg["face_cx"] - 401
    if abs(dx) >= 10:
        print(f"Голова стоит на {abs(dx)}px {'левее' if dx < 0 else 'правее'}, "
              f"чем в основном дубле ({abs(dx)/273:.0%} ширины лица). Кропом это "
              "не правится: расхождение измерено и называется, а не подчищено — "
              "решается на съёмке.")
    else:
        print("Расхождение с основным дублем в пределах разброса самого дубля — "
              "правки не требуется и не сделано.")
    print(f"\nСредний RGB внутри карточки A: хук "
          f"({' / '.join(map(str, m['rgb_hook']))}) против основного дубля "
          f"({' / '.join(map(str, m['rgb_src']))}) — расхождение "
          f"{max(abs(a-b) for a, b in zip(m['rgb_hook'], m['rgb_src']))} единицы "
          "по каналу при норме ~10, свет между дублями не разошёлся.\n")

    print("## Звук")
    print("Дорожка пересобрана целиком: голос хука приведён к громкости тела "
          f"по RMS речи (×{m['voice_gain']:.3f}), постель (whoosh / impact / "
          f"tick) сдвинута на {dt:.3f}с, музыка с нуля, затем loudnorm.\n")
    print(f"- Пауза между хвостом хука и первым звуком тела: **{m['pause']:.3f}с** "
          f"(речь дубля кончается на {speech_end:.3f}, шов на {seam:.3f}) — "
          "в диапазоне 0.10–0.20с из delivery-specs §6. Хвостовой тишины "
          "в дубле нет, поэтому пауза набрана кадрами блока хука, а лишние "
          "кадры добиты графическим планом, а не стоп-кадром лица.")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами "
          f"на шве — {m['seam_jump']}, против {m['seam_ref']} на 99.9-м "
          "процентиле всей дорожки.")
    print(f"- Громкость сведена к уровню основного ролика: **{m['lufs']} LUFS**, "
          f"истинный пик **{m['tp']} dBTP**, LRA {m['lra']} LU "
          f"(версия №1: {HK.TARGET_LUFS} LUFS / −1.8 dBTP / 2.8 LU).")
    print(f"- Свой трек: `{os.path.basename(cfg['music'])}` — у каждой из трёх "
          "версий он свой, ни один не повторяется.\n")

    print("## Автопроверки")
    print("Все — по нулям (`python3 qa31hook.py " + key + "`):\n")
    print("```")
    print("cuts_inside_word=0            captions_off_speech=0")
    print("captions_crossing_cut=0       caption_words_not_in_speech=0")
    print("caption_style_violations=0    captions_on_number_shots=0")
    print("line_overlap_pairs=0          gfx_text_overlap_frames=0")
    print("gfx_out_of_zone_frames=0      gfx_touching_mask_frames=0")
    print("text_out_of_card_frames=0     bright_outside_card_frames=0")
    print("old_hook_captions_alive_at_cut=0")
    print("```")
    print(f"\n- **Деформация измерена машинно:** {m['deform']}.")
    print("- **Тело кадр в кадр совпадает с версией №1:** сверены кадры 171, "
          "300, 700, 1100, 1410 — средняя |Δ| по кадру 0.08–1.0 уровня серого "
          "из 255, то есть шум одного прохода кодека, а не другая картинка. "
          "Оба файла читают один и тот же немой рендер "
          f"`assets/_video_{SB.TAG}.mp4`.")
    print("- **Версия №1 не тронута:** `inspection_edit.mp4` на запись "
          "не открывался, md5 `a555553011804d0b05653f4f861040e2`.")
    print("- Смысловая проверка блока хука — по контакт-листу "
          f"`build/test/hook31_{key}_sheet.jpg`.")


if __name__ == "__main__":
    emit(sys.argv[1])
