# --- построение Морли ------------------------------------------------------
def _ang(P, Q, R):
    """Угол при вершине Q в треугольнике PQR."""
    a = (P[0] - Q[0], P[1] - Q[1])
    b = (R[0] - Q[0], R[1] - Q[1])
    ca = (a[0] * b[0] + a[1] * b[1]) / (math.hypot(*a) * math.hypot(*b))
    return math.acos(max(-1.0, min(1.0, ca)))


def _rot(v, t):
    return (v[0] * math.cos(t) - v[1] * math.sin(t),
            v[0] * math.sin(t) + v[1] * math.cos(t))


def _unit(a, b):
    d = (b[0] - a[0], b[1] - a[1])
    L = math.hypot(*d)
    return (d[0] / L, d[1] / L)


def _ray_int(P, u, Q, v):
    """Пересечение прямых P+s*u и Q+t*v."""
    det = u[0] * (-v[1]) - (-v[0]) * u[1]
    if abs(det) < 1e-12:
        return None
    dx, dy = Q[0] - P[0], Q[1] - P[1]
    s = (dx * (-v[1]) - (-v[0]) * dy) / det
    return (P[0] + s * u[0], P[1] + s * u[1])


def _trisectors(V, U, Wp):
    """Две трисектрисы угла при V. Первая ближе к лучу VU, вторая — к VW."""
    a = _unit(V, U)
    b = _unit(V, Wp)
    th = _ang(U, V, Wp)
    sgn = 1.0 if a[0] * b[1] - a[1] * b[0] > 0 else -1.0
    return [_rot(a, sgn * th / 3.0), _rot(a, sgn * 2.0 * th / 3.0)]


def scene(A, B, C):
    """Полное построение по трём вершинам.

    tri   — вершины,
    tris  — по две трисектрисы из каждой вершины (направления),
    feet  — точки, где трисектриса упирается в противоположную сторону,
    M     — три точки Морли: MA против A, MB против B, MC против C.
    """
    tA = _trisectors(A, B, C)      # tA[0] ближе к AB, tA[1] ближе к AC
    tB = _trisectors(B, C, A)      # tB[0] ближе к BC, tB[1] ближе к BA
    tC = _trisectors(C, A, B)      # tC[0] ближе к CA, tC[1] ближе к CB
    MA = _ray_int(B, tB[0], C, tC[1])
    MB = _ray_int(C, tC[0], A, tA[1])
    MC = _ray_int(A, tA[0], B, tB[1])
    feet = {}
    for key, (V, ts, P, Q) in {"A": (A, tA, B, C),
                               "B": (B, tB, C, A),
                               "C": (C, tC, A, B)}.items():
        feet[key] = [_ray_int(V, u, P, _unit(P, Q)) for u in ts]
    return dict(tri=(A, B, C), tris={"A": tA, "B": tB, "C": tC}, feet=feet,
                M=(MA, MB, MC),
                # пары соседних трисектрис, каждая даёт свою точку Морли
                pairs=[((B, tB[0]), (C, tC[1]), MA),
                       ((C, tC[0]), (A, tA[1]), MB),
                       ((A, tA[0]), (B, tB[1]), MC)])


