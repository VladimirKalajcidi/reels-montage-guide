"""Монтажный лист версии ролика 22 с другим хуком.

    python3 plan22hook.py h1 > ../videos/22/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard22 as SB
from hook22 import HOOKS, CUT, CUT_F, lts_for
from plan22 import NAMES

# замеры готовых файлов (qa22hook.py)
MEASURED = {
    "h1": dict(lufs=-14.30, tp=-1.60, frames=1693, dur=56.43, pause=0.442,
               seam=(141, 2210), rgb=1,
               deform="кроп ×0.98 — карточка A на одном и том же кадре тела "
                      "870px → 888px = ×1.0207 (целевое ×1.0204, расхождение — "
                      "1px квантования)"),
    "h2": dict(lufs=-14.20, tp=-1.70, frames=1546, dur=51.53, pause=0.446,
               seam=(128, 2158), rgb=2,
               deform="ускорение ×1.02 — 1577 кадров → 1546, `r_frame_rate` ровно "
                      "30/1, звук ускорен вместе с картинкой (видео 51.533с, "
                      "аудио 51.529с), геометрия карточки не тронута (870px → 870px)"),
}

RHYTHM = {
    "h1": dict(shots=30, avg=1.88, median=1.89, shortest=1.19, longest=2.64,
               first_cut=1.40, face_pct=33.8),
    "h2": dict(shots=28, avg=1.84, median=1.80, shortest=1.17, longest=2.59,
               first_cut=1.54, face_pct=29.9),
}


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    r = RHYTHM[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    dt = nh - CUT
    lts = lts_for(cfg)

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/22/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.2f}с · {m['frames']} кадров")
    print(f"Хук: `videos/22/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с)")
    print(f"Тело: кадры {CUT_F}+ из уже сданного `dilemma_edit.mp4`, не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")
    print(f"**Ритм версии целиком:** {r['shots']} планов · средняя {r['avg']:.2f}с · "
          f"медиана {r['median']:.2f}с · мин {r['shortest']:.2f}с · макс {r['longest']:.2f}с · "
          f"первый рез {r['first_cut']:.2f}с · лицо **{r['face_pct']:.1f}%**\n")

    print("## Точка реза")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `A2` → `stock` в исходном ролике, "
          "то есть конец старого начала «иногда действовать логично для себя — это самый "
          "нелогичный выбор для двоих людей сразу. и вот очень известный пример». "
          "Планы 1–3 старого хука и все 7 их субтитров выброшены целиком: от старого начала "
          "не осталось ни кадра.")
    print(f"\nКадр считается как `ceil(5.98 × 30)` = {CUT_F}, а не `round` = {CUT_F - 1}: "
          "граница плана стоит на дробном кадре 179.4, и кадр 179 — это ещё последний кадр "
          "выбрасываемого плана с лицом. Проверка машинная: `qa22hook.old_hook_gone` "
          "требует, чтобы кадры 179 и 180 лежали в разных планах.")
    print("\n**Связность стыка.** Тело начинается новым предложением с новым подлежащим — "
          "«двух подозреваемых допрашивают в разных комнатах». Ни одного местоимения "
          "и ни одной отсылки к словам старого хука в первых фразах тела нет, поэтому "
          "обе версии режутся по одной и той же точке и ни одну фразу тела выбрасывать "
          "не пришлось.")
    if key == "h1":
        print("\nПередача эстафеты: хук кончается на «это математическая и социальная задачка "
              "как раз на это» — та же функция, что у старого «и вот очень известный пример»: "
              "обещание примера, который тело и разворачивает.")
    else:
        print("\nПередача эстафеты: хук кончается на «называется дилеммой заключённого» — "
              "названием задачи, после которого «двух подозреваемых допрашивают в разных "
              "комнатах» читается как её условие.")
    print()

    print("## Блок хука")
    print(f"{len(cfg['shots'])} планов · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"первый рез **{lens[0]:.2f}с** · мин {min(lens):.2f}с · макс {max(lens):.2f}с\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    for i, (t0, t1, kind, _p) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")
    print(f"\nДалее без изменений идёт тело сданного ролика — планы 4–29 из "
          f"`montage-plan.md`, со сдвигом **{dt:+.4f}с** на новой таймлинии"
          + (" и с последующим ускорением ×1.02." if cfg.get("post_a") else "."))

    print("\n## Графика хука")
    print("Взят тот же план, что стоял в старом начале, — `selfboth`: две фигуры, под каждой "
          "галка «его выбор логичен», скобка сводит обе и общий итог перечёркнут. Это "
          "визуальная интрига ролика, менять её незачем; ни одного нового плана "
          "не нарисовано.")
    if key == "h1":
        print("\nНа слова дубля он ложится буквально: галки появляются под «что вы хотите "
              "как лучше», крест — под «а получается как обычно». Длина плана 2.27с, "
              "анимация идёт в штатном темпе, без масштабирования времени.")
    else:
        s = lts.get("selfboth", 1.0)
        print(f"\nПлан хука короче, чем в теле (1.73с против 2.41с), поэтому анимация "
              f"ускорена в **×{s:.2f}** — иначе крест обрывался бы на половине движения. "
              "Ускорять можно, замедлять нельзя: тот же план в теле идёт своим темпом.")

    print("\n## Сток в хуке")
    print("Стока в хуке нет — в старом начале его тоже не было. Первая вставка "
          "(допрос, mixkit 49251) стоит уже в теле, первым же планом после реза.")

    print("\n## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, и основной "
          "исходник — 720×1280, `yuv420p`, `color_range=tv`, `bt709`/`bt709`/`bt709`, 30 fps. "
          "Кадры читаются прямо из `.mov` и идут в штатный тракт A-roll **без единого "
          "промежуточного кодека**.")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip, медиана по всему дублю): основной дубль "
          f"cx 396 / линия глаз 671 / ширина лица 264; этот хук cx {cfg['face_cx']} / "
          f"{cfg['face_eye']} / {cfg['face_d']}.")
    if key == "h1":
        print("  Расхождение: 1px по горизонтали, **+7px по линии глаз**, **+7.2% по размеру "
              "лица** — голова в дубле чуть крупнее и чуть выше. Кропом не правилось.")
    else:
        print("  Расхождение: 3px по горизонтали, **−16px по линии глаз**, **+5.7% по размеру "
              "лица** — голова в дубле крупнее и заметно ниже в кадре. Кропом не правилось: "
              "это к съёмочной стороне (та же точка, та же дистанция), а не к монтажу.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуках, проверить "
          "по тексту не на чем. Штатный `hflip` оставлен: рука с петличкой во всех трёх "
          "дублях с одной стороны кадра.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука против кадров тела расходятся "
          f"на **{m['rgb']} единицу** по каналу (норма — до ~10).")

    print("\n## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек, у остальных версий "
          "другие (v1 `song3.mp3`, v2 `song2.mp3`, v3 `song1.mp3`).")
    if "song1" in cfg["music"]:
        print("  Трек 9.53с короче ролика, поэтому идёт петлёй с кроссфейдом 0.25с на шве "
              "(5.7 повтора). У двух других версий треки длиннее ролика и петли не требуют.")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались.")

    print("\n## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, постель "
          f"(whoosh / impact / tick) со сдвигом **{dt:+.4f}с**, музыка с нуля, потом loudnorm.")
    print("- Whoosh стоит и на резах внутри хука, и на самом шве «хук → тело».")
    print(f"- Голос хука приведён к громкости тела по RMS речи (×"
          f"{'1.425' if key == 'h1' else '1.658'}): дубли записаны тише основного.")
    print(f"- Пауза между последним словом хука и первым словом тела: **{m['pause']:.3f}с**. "
          "Чеклист `delivery-specs §6` называет 0.10–0.20с, но там же оговорка «как между "
          "предложениями в теле» — в этом дубле межфразовые паузы идут 0.24–0.59с "
          "(медиана 0.41с), так что 0.44с — ровно медиана тела. Укоротить её нечем: "
          "0.36с из этой паузы — это тишина в голове тела перед словом «двух», а тело "
          "идёт готовыми кадрами и сдвигать под него звук значит развалить синхрон.")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами на шве "
          f"**{m['seam'][0]}** против **{m['seam'][1]}** на 99.9-м процентиле всей дорожки.")
    print(f"- Громкость **{m['lufs']:.2f} LUFS**, истинный пик **{m['tp']:.2f} dBFS** — "
          "сведено к уровню уже сданного `dilemma_edit.mp4` (−14.20 / −1.50), "
          "а не к абстрактным −14.")

    print("\n## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa22hook.py {key}")
    print("```")
    print("Все по нулям: `text_out_of_card=0`, `gfx_text_overlap=0`, `gfx_out_of_zone=0`, "
          "`line_overlaps=0` по блоку хука, `bright_outside` = 0 кадров по всему файлу версии "
          "(включая деформацию), нарушений стиля субтитров 0, слов не из речи 0.")
    print("- Рез по границе плана: кадры 179 и 180 лежат в разных планах "
          "(`A2` → `stock`) — от старого хука не осталось ни кадра, ни субтитра.")
    print("- Тело против сданной версии — худший PSNR **43.8 dB** на 14 контрольных кадрах "
          "(это второе прохождение того же кодека, картинка та же).")
    print("- Версия №1 не тронута: `dilemma_edit.mp4` не открывался на запись — "
          "хуки читают из него только готовые кадры тела.")


if __name__ == "__main__":
    emit(sys.argv[1])
