"""Генерирует монтажный лист ролика 8 из раскадровки."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard8 import SHOTS, CAPS, DUR

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена дубля)"),
    "nonsense": ("R4+R5a", "сетка: √−1 и перечёркивание — «бессмыслица»"),
    "no_such": ("R4+R10", "сетка: числовая прямая, √−1 не помещается"),
    "sq_pos": ("R10", "сетка: карточка 2² = +4"),
    "sq_neg": ("R10", "сетка: вторая карточка (−2)² = +4 каскадом"),
    "crossed": ("R4+R10", "сетка: √−1 перечёркнуто крест-накрест"),
    "mockery": ("R4+R5a", "сетка: «мнимое» в кавычках — насмешка"),
    "letter_i": ("R4+R5a", "сетка: белый ревил буквы i"),
    "assume": ("R4+R10", "сетка: синяя точка вне числовой прямой — «допустим, оно есть»"),
    "new_field": ("R4+R10", "сетка: числовая прямая обычных чисел"),
    "plane": ("R10+R5b", "сетка: синяя мнимая ось достраивает плоскость, ревил i"),
    "formula": ("R4+R5b", "сетка: формула a + bi, i — синим"),
    "three_uses": ("R10+R5b", "сетка: ток / сигнал / квантовая → синее i"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
}
STOCK = {
    "14669": "рука печатает на телефоне ночью, боке (Mixkit 14669)",
    "45366": "нить накала лампы разгорается на чёрном (Mixkit 45366)",
    "15189": "стрелки VU-индикаторов дрожат — сигнал (Mixkit 15189)",
    "4407": "белые частицы плывут на тёмном фоне (Mixkit 4407)",
}

face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in ("A1", "A2"))
lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

print("# Монтажный лист — «мнимая единица i»\n")
print(f"Исходник: `videos/8/source.mov` · 1080×1920 · 30 fps · {DUR:.2f}с")
print("Готовый ролик: `videos/8/imaginary_edit.mp4`\n")
print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
      f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с")
print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%**")
print(f"**Первый рез:** {SHOTS[1][0]:.2f}с")
print(f"**Субтитров:** {len(CAPS)} фраз · в среднем {DUR/len(CAPS):.2f}с на фразу\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
    rec, desc = NAMES[kind]
    if prm.get("topword"):
        desc += f" · крупное слово наверху «{prm['topword']}»"
    if prm.get("clip"):
        desc = STOCK[prm["clip"]]
    txt = " / ".join("".join(r[0] for r in runs).strip()
                     for (a, b, runs, _) in CAPS if t0 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | {txt} |")
