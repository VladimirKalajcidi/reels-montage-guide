"""Монтажный лист версии ролика 34 с другим хуком.

    python3 plan34hook.py h1 > ../videos/34/montage-plan-hook1.md
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import math

import storyboard34 as SB
import hook34 as HK
from plan34 import NAMES
from style import FPS


def _first_frame_t(a):
    """Момент первого кадра, на котором субтитр реально появляется."""
    return math.ceil(a * FPS - 1e-9) / FPS

VD = "/Users/vladimirkalajcidi/reels_good/videos/34"

# измерения сданных файлов (заполняются после рендера версий)
MEASURED = {
    "h1": dict(lufs=-14.0, tp=-1.6, lra=1.8, frames=1126, dur=37.53,
               panels_v1=675, panels_ver=689, scale=1.0207),
    "h2": dict(lufs=-14.0, tp=-1.6, lra=1.5, frames=1096, dur=36.53,
               panels_v1=675, panels_ver=675, scale=1.0),
}


def emit(key):
    cfg = HK.HOOKS[key]
    m = MEASURED[key]
    ver = cfg["version"]
    rate = 1.02 if cfg.get("post_a") else 1.0
    shots = HK.shots_of(cfg)
    hook_n = cfg["frames"]
    dt = hook_n / FPS - HK.CUT_V
    hw = json.load(open(f"{VD}/words_hook{ver - 1}.json"))
    speech_end = max(w["end"] for w in hw)

    print(f"# Монтажный лист — «парадокс крокодила», версия {ver} (хук {ver - 1})\n")
    print(f"Новый хук: `videos/34/hook{ver - 1}.mov` — {cfg['title']}")
    print(f"Тело: кадры {HK.CUT_F}+ из `assets/_video_{SB.TAG}.mp4`, "
          "не пересобиралось — склеено готовыми кадрами за новым хуком.")
    print(f"Готовый ролик: `{os.path.relpath(cfg['out'], os.path.dirname(VD) + '/..')}` · "
          f"1080×1920 · 30 fps · {m['frames']} кадров · {m['dur']:.2f}с\n")

    print("## Точка реза")
    print("Старое начало — «эта логическая задача существует больше 2000 лет» "
          "(0.000–2.804). Оно занимает план `A1` 0.000–1.891 и хвостом заходит "
          "в план `ages` 1.891–3.283, где на сетке выстраиваются двадцать "
          "засечек-веков и всплывает белое **2000**. Эта графика иллюстрирует "
          "ровно ту фразу, которую мы выбрасываем, и **ни один из новых дублей "
          "возраст задачи не называет** — поэтому план `ages` уходит из версии "
          "целиком вместе с хуком.")
    print(f"\nРез — по границе плана `ages` → `stock`, то есть по **3.283**. "
          f"В кадрах это ceil(3.283 × 30) = **{HK.CUT_F}** — округление вверх, "
          "а не к ближайшему: кадр 98 показывает ещё сетку с числом 2000, и при "
          "round в версии остался бы целый кадр старой графики.")
    print("\nОт старого хука не осталось ни кадра и ни одного его субтитра "
          "(`qa34hooks.no_old_hook`, `qa34hooks.old_hook_gone`).")

    print("\n## Шов внутри плана, а не на резе")
    print("Тело начинается стоковой вставкой с крокодилом (3.283–5.330). Блок "
          "хука кончается **тем же планом**: последние кадры блока — тот же "
          "клип, отмотанный назад по времени от шва "
          "(`rel = 0.017 − (N − f)/30`). На шве не меняются ни карточка, ни "
          "кадр — планов два, а рез между ними один. Whoosh на шве не ставится: "
          "визуального реза там нет.")
    print(f"\nЕдинственный рез блока хука — `A1` → `stock` на "
          f"{cfg['a1_frames'] / FPS:.4f} (кадр {cfg['a1_frames']}).")

    print("\n## Раскадровка версии\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    i = 0
    for t0, t1, kind, _p in shots:
        i += 1
        rec, desc = NAMES[kind]
        if kind == "stock":
            desc += " — тот же план, что открывает тело; шов внутри плана"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"]
                         if t0 <= _first_frame_t(a) < t1)
        print(f"| {i} | {t0/rate:.2f}–{t1/rate:.2f} | {(t1-t0)/rate:.2f}с | {rec} "
              f"| {desc} | {txt or '— (говорит графика)'} |")
    for t0, t1, kind, _p in SB.SHOTS:
        if t1 <= HK.CUT_V:
            continue
        a0 = max(t0, HK.CUT_V) + dt
        a1 = t1 + dt
        rec, desc = NAMES[kind]
        if t0 < HK.CUT_V:                      # продолжение плана из блока хука
            desc += " (продолжение того же плана)"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in SB.CAPS if t0 <= a < t1)
        i += 1
        print(f"| {i} | {a0/rate:.2f}–{a1/rate:.2f} | {(a1-a0)/rate:.2f}с | {rec} "
              f"| {desc} | {txt or '— (говорит графика)'} |")

    print("\n## Передача эстафеты")
    print("Тело начинается самостоятельным предложением «крокодил похищает "
          "ребёнка и говорит отцу»: своё подлежащее, ни одного местоимения, "
          "отсылок к выброшенному тексту нет. Новый дубль кончается словом "
          f"«{cfg['caps'][-1][2][-1][0].strip()}» и ведёт ровно туда же, куда "
          "вело старое начало.")

    print("\n## Голос на шве — J-cut в один кадр")
    print("Слово «крокодил» в основном дубле начинается в 3.283, то есть "
          "**раньше** кадра 99 (3.300): по огибающей 3.260 = −67 дБ, "
          "3.270 = −50, 3.280 = −28, 3.300 = −21. Рез голоса ровно по картинке "
          "срезал бы 17мс уже звучащего слова. Поэтому голос тела берётся с "
          "кадра 98 (3.2667, там −55 дБ — тишина) и кладётся в новую дорожку "
          "на кадр N−1, на один кадр раньше картинки тела. Смещение кратно "
          "кадру, поэтому синхрон не едет: каждый кадр тела стоит против "
          "своего звука, а на последнем кадре блока хука звучат 33мс тишины "
          "из тела.")
    print(f"\nПауза «конец речи хука → первое слово тела»: речь дубля кончается "
          f"на {speech_end:.3f}, слово «крокодил» звучит на "
          f"{(hook_n - 1) / FPS + (3.283 - HK.CUT_A):.3f} → пауза "
          f"**{((hook_n - 1) / FPS + (3.283 - HK.CUT_A) - speech_end) / rate:.3f}с**, "
          "в диапазоне 0.10–0.20с из `delivery-specs §6`. Хвостовая тишина в "
          "дубле есть, последнее слово записью не обрезано.")

    print("\n## A-roll хука")
    print("Дубль идёт через тот же тракт, что и основной исходник: те же "
          "`FRAMINGS` (окно 630×1000 от (57, 264)), тот же безусловный `hflip`, "
          "грейда нет. Ни крупность, ни экспозиция, ни баланс белого под "
          "основной дубль не подгонялись.")
    print("\nЗеркальность проверена по кадру: надпись на футболке после `hflip` "
          "читается нормально — штатный `hflip` этому дублю подходит.")
    print("\nЦветовые теги сверены с основным исходником: `yuv420p` / `tv` / "
          "`bt709` / `bt709` / `bt709` — совпадают, HDR нет, конверсия "
          "цветового пространства не требуется.")
    print("\n| | cx | линия глаз | ширина лица |")
    print("|---|---|---|---|")
    print("| основной дубль | 377 | 684 | 269 |")
    print(f"| hook{ver - 1} | {cfg['face_cx']} | {cfg['face_eye']} | {cfg['face_d']} |")
    print("\nРасхождение крупности — на съёмочной стороне, монтажом не "
          "правится. Средний RGB внутри карточки A на кадрах хука и тела "
          "сходится (`qa34hooks.face_rgb`), то есть по свету дубли совпадают.")

    print(f"\n## Уникализация версии {ver}")
    if cfg.get("post_a"):
        print("- **Ускорение ×1.02** — `setpts=PTS/1.02` **и** `atempo=1.02` "
              "вместе, картинка и звук; `fps=30` обязателен, иначе на выходе "
              "30.6 fps. Проверено: на выходе `r_frame_rate=30/1`, "
              f"{m['frames']} кадров вместо 1118, длительности видео и звука "
              "расходятся на 0.006с. Геометрия кадра не тронута: та же пара "
              f"панелей на плане `loop` — {m['panels_ver']}px против "
              f"{m['panels_v1']}px в версии 1, ×{m['scale']}.")
    else:
        print("- **Кроп ×0.98** — обрезаем 2% по краям и возвращаем холст "
              "1080×1920. Измерено по объекту в кадре: пара панелей на плане "
              f"`loop` — {m['panels_v1']}px в версии 1 против "
              f"{m['panels_ver']}px здесь, то есть ×{m['scale']} при "
              "ожидаемых ×1.0204.")
    print(f"- **Свой трек**: `audios/{os.path.basename(cfg['music'])}` "
          "(версия 1 — `song3.mp3`, ни один трек не повторяется).")
    print("- Деформация наложена на уже собранное немое видео, кадры не "
          "перерисовывались; мукс со звуком — после правки кадра.")
    print("- Версия 1 (`croc_edit.mp4`) не тронута.")

    print("\n## Звук")
    print("Дорожка пересобрана целиком, а не склеена из готовых: голос хука + "
          "голос тела с 3.2667, постель (whoosh / импакт / тики) со сдвигом "
          f"{dt:+.3f}с, музыка с нуля, потом loudnorm.")
    print("- Голос хука приведён по RMS речи к уровню тела.")
    print(f"- Whoosh на каждом резе (0.040 от пика), импакт под тремя синими "
          "выводами (0.070), тики под каскадами элементов сцены (0.030). "
          "Ревил белого 2000 ушёл вместе с хуком, импакта под ним больше нет.")
    print(f"- Музыка: −19 dB от RMS голоса, петля с кроссфейдом 0.25с, "
          "фейды 0.8 / 2.0с.")
    print(f"- Замер готового `.mp4`: **{m['lufs']} LUFS**, истинный пик "
          f"**{m['tp']} dBTP**, LRA {m['lra']} LU — против −14.1 LUFS у версии 1.")

    print("\n## Что не менялось")
    print("Тело кадр в кадр совпадает с версией 1 "
          "(`qa34hooks.body_identical`), раскадровка ролика не трогалась, "
          "стоковая вставка и вся графика те же. Перерисован только блок хука.")


if __name__ == "__main__":
    emit(sys.argv[1])
