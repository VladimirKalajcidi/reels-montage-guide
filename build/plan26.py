"""Генерирует монтажный лист ролика 26 из раскадровки."""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard26 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS,
                          ADDR6, ADDR10, TOURS5, OPT6, LONG6, NN10, GOOD10,
                          CROSS10, tour_len, crossings)
import render26

# измерения сданного файла (см. блоки «Звук» и «A-roll»)
LUFS, TP, LRA = -14.1, -1.7, 1.9
AROLL_SRC = (114, 100, 92)
AROLL_OUT_DELTA = (0.9, 3.0)

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "bruteFlash": ("R4+R10", "сетка: шесть адресов, старт кольцом; поверх них "
                             "один за другим вспыхивают варианты маршрута — "
                             "это и есть «полный перебор»"),
    "route1": ("R4+R10", "сетка: сначала прорисовывается длинный вариант, "
                         "потом поверх — **синий** кратчайший (точный оптимум "
                         "перебором всех 60 маршрутов)"),
    "five": ("R4+R10", "сетка: двенадцать миниатюр — **все** различные маршруты "
                       "по пяти адресам; цифры на экране нет, её роль играет "
                       "сам пересчёт"),
    "ten": ("R4+R10", "сетка: десять адресов, варианты мелькают уже быстрее, "
                      "чем их можно разглядеть"),
    "tenNum": ("R4+R5a", "сетка: облако адресов уходит вверх и гаснет, под ним "
                         "**белое 181 440** резким попом и черта; субтитр "
                         "обрывается до появления числа"),
    "twenty": ("R4+R10", "сетка: двадцать адресов, варианты сливаются "
                         "в мельтешение"),
    "factorial": ("R4+R5b", "сетка: **синее 19!** с набором по разрядам и под ним "
                            "белым — то же число целиком; субтитра на плане нет"),
    "fifty": ("R4+R10", "сетка: пятьдесят адресов и все связи между ними — "
                        "клубок, в котором маршрут уже не разглядеть"),
    "huge": ("R4+R5b", "сетка: **синее 3 · 10⁶²** с набором по разрядам; "
                       "субтитра на плане нет"),
    "heuristic": ("R4+R10", "сетка: жадный маршрут строится ребро за ребром "
                            "и остаётся с самопересечением — эти два ребра "
                            "подсвечиваются **лаймом**"),
    "goodRoute": ("R4+R10", "сетка: пересечение развязано (2-opt), маршрут "
                            "короче на 11.9% и становится **синим** результатом"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «задача коммивояжёра»\n")
    print(f"Исходник: `videos/26/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/26/tsp_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих чисел: 2** (19! и 3 · 10⁶²) · "
          "**белых чисел: 2** (181 440 и 121 645 100 408 832 000)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa26.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]] + f" (с {prm['ss']:.1f}с клипа)"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Что не так со сценарием: число атомов")
    print("В речи: «а для 50 адресов количество возможных маршрутов **превышает "
          "число атомов видимой Вселенной**». Это неверно, и вот числа:\n")
    print("| величина | значение |")
    print("|---|---|")
    print("| маршрутов для 50 адресов (49!/2) | **3.04 · 10⁶²** |")
    print("| атомов в наблюдаемой Вселенной | ~10⁸⁰ |")
    print("| разница | **18 порядков** |")
    print("| с какого числа адресов утверждение станет верным | **61** "
          "(60!/2 = 4.2 · 10⁸¹) |")
    print("\nРечь не режется и не переписывается — это правило гайда. Поэтому "
          "на плане `huge` стоит честное **3 · 10⁶²** и **нет ни субтитра, "
          "ни сравнения с атомами**: экран не повторяет и не подтверждает ошибку. "
          "Само по себе 3 · 10⁶² звучит достаточно: это больше, чем секунд "
          "с Большого взрыва, в 10⁴⁴ раз.")
    print("\nЕсли переписать одну фразу и переснять её как альтернативный дубль "
          "(«превышает число секунд, прошедших с Большого взрыва» или «для "
          "шестидесяти адресов — больше, чем атомов во Вселенной»), ролик "
          "пересобирается по протоколу хука: меняется только этот блок.")
    print("\nОстальные числа сценария пересчитаны и верны "
          "(`qa26.numbers` = 0 нарушений):\n")
    print("| в речи | на экране | пересчёт |")
    print("|---|---|---|")
    print("| «для пяти адресов вариантов всего 12» | 12 миниатюр | 4!/2 = 12 ✓ |")
    print("| «для 10 адресов больше 180 тысяч» | 181 440 | 9!/2 = 181 440 ✓ |")
    print("| «для 20 адресов это 19 факториал» | 19! и 121 645 100 408 832 000 "
          "| 19! = 121 645 100 408 832 000 ✓ |")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи.** Слова несёт только субтитр, "
          "графика несёт то, чего в словах нет:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| белая точка | адрес |")
    print("| кольцо вокруг точки | старт: откуда курьер выезжает и куда вернётся |")
    print("| белая замкнутая ломаная | один вариант маршрута |")
    print("| ломаные, сменяющие друг друга | перебор вариантов |")
    print("| двенадцать миниатюр | ровно двенадцать вариантов для пяти адресов |")
    print("| все связи между точками | почему перебор растёт быстрее, чем железо |")
    print("| лаймовая пара рёбер | самопересечение жадного маршрута — «не идеально» |")
    print("| синяя ломаная | найденный маршрут: результат |")
    print("| крупная цифра | сколько вариантов бывает |")
    print("\nЧисла на экране стоят там, где субтитра нет вообще "
          "(`qa26.no_caption_on_number_shots` = 0): на планах `factorial` и `huge` "
          "субтитров нет, на `tenNum` субтитр обрывается на «вариантов уже больше» "
          "и число 181 440 выходит уже в тишине текста.")
    print("\nМашинная проверка пересечения слоёв (`qa26.gfx_text_overlap`) — 0 кадров, "
          "графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa26.gfx_in_zone`) — 0 кадров.")

    print("\n## Маршруты — посчитаны, а не нарисованы на глаз")
    print("`qa26.geometry()` пересчитывает каждый маршрут, который попал на экран:\n")
    print("| маршрут | длина | пересечений | чем является |")
    print("|---|---|---|---|")
    print(f"| длинный вариант (план `route1`) | {tour_len(ADDR6, LONG6):.0f}px | "
          f"{len(crossings(ADDR6, LONG6))} | вариант ×"
          f"{tour_len(ADDR6, LONG6)/tour_len(ADDR6, OPT6):.2f} от оптимума |")
    print(f"| синий маршрут (план `route1`) | {tour_len(ADDR6, OPT6):.0f}px | "
          f"{len(crossings(ADDR6, OPT6))} | **точный оптимум** перебором всех 60 |")
    print(f"| жадный маршрут (план `heuristic`) | {tour_len(ADDR10, NN10):.0f}px | "
          f"{len(CROSS10)} | nearest neighbour от старта |")
    print(f"| после 2-opt (план `goodRoute`) | {tour_len(ADDR10, GOOD10):.0f}px | "
          f"{len(crossings(ADDR10, GOOD10))} | короче жадного на "
          f"{100*(1-tour_len(ADDR10, GOOD10)/tour_len(ADDR10, NN10)):.1f}% |")
    print(f"\nМиниатюры плана `five` — {len(TOURS5)} различных маршрутов, "
          "проверено на повторы и на то, что каждый обходит все пять адресов "
          "ровно по разу. Маршрут и он же задом наперёд считается одним — "
          "поэтому 12, а не 24.")
    print("\nПересечение жадного маршрута выбрано не случайным: угол между "
          "рёбрами 84°, обе стороны длинные — крест виден на паузе, "
          "а не «где-то там». Ровно это и есть «не идеальный маршрут», "
          "и ровно его развязывает следующий план.")
    print("\nЧего на графике намеренно НЕТ: подписей к точкам, названий городов, "
          "километров. В речи их нет, а кадр они засоряют.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) окрашены **результаты**: кратчайший маршрут, "
          "маршрут после 2-opt и два числа — **19!** и **3 · 10⁶²**.")
    print("- **Синих чисел два** при лимите 4 (`brand-kit §4`).")
    print("- **Лайм #C3DB4E — один элемент на весь ролик**: пара "
          "самопересекающихся рёбер жадного маршрута. Она живёт на двух "
          "соседних планах (`heuristic` → `goodRoute`), но это один и тот же "
          "элемент: на втором плане его развязывают.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt. Кегль крупных чисел "
          "подобран по ширине зоны, а не по шкале XL из `brand-kit §3`: цифра "
          "SF Pro занимает ~0.75em, «181 440» на кегле 150 дало бы строку 730px "
          "— ровно всю зону, без места под свечение. Рабочие кегли: 181 440 — "
          "120pt (579px), 19! — 205pt, 3 · 10⁶² — 140pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под тремя ревилами чисел (0.070), тики под каскадами элементов (0.030).")
    print("- Музыка `audios/song2.mp3`: −19 dB от RMS голоса, трек 335с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume 0.8 dB / alimiter.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**.")
    print(f"- **LRA {LRA} LU** при норме гайда 3–5. Это свойство дубля: речь идёт "
          "очень ровно, без громких и тихих мест. Лимитером и loudnorm не лечится — "
          "фиксирую замер, а не правлю. Тот же эффект был на роликах 22 и 25.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/26/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nВставки буквальны: звучит «суперкомпьютер» — в кадре стойки "
          "дата-центра; звучит «курьеру нужно объехать адреса» — в кадре курьер "
          "с коробкой смотрит адрес в телефоне; звучит «доставки» — курьер "
          "с коробками у двери; «логистики» — ночной контейнерный порт. "
          "Все клипы играют, статики нет.")
    print("\nУчасток каждого клипа (`ss` в раскадровке) выбран по двум числам, "
          "а не на глаз: объект должен быть в кадре **всё** время плана после "
          "обрезки до 1.385:1, и полоса субтитров в карточке B после штатного "
          "притемнения 0.72 должна держаться в пределах «средняя ≤110, p90 ≤140». "
          "Замеры по итоговым окнам: 7887 — 15/35, 31136 — 76/131, 20822 — 63/147, "
          "31346 — 92/128, 31094 — 29/47, 13089 — 83/113.")
    print("\nОдин клип пришлось заменить по этим числам: у плана «логистики» "
          "сначала стояла фура с рабочим (`23852`), но небо между фурами "
          "держало p90 на 149–153 в любом участке клипа. Ночной порт даёт 47.")
    print("\nОстальные 11 планов закрыты собственной графикой: суть ролика — "
          "в том, как растёт число маршрутов, а этого сток не показывает "
          "(`assets-manifest §2`: «если сцену можно закрыть своей графикой "
          "без потери смысла — берём графику»).")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render26). Кроп посчитан по детектору: 33 замера "
          "по всему дублю дали cx 402±7, линию глаз y 642±4, ширину лица 283±6 — "
          "глаза стоят на 42% высоты карточки в обоих вариантах крупности.")
    print(f"Проверка: средний RGB внутри карточки A в сданном файле отличается "
          f"от того же кропа исходника на **{AROLL_OUT_DELTA[0]:.1f}–"
          f"{AROLL_OUT_DELTA[1]:.1f} единицы** по каналу — это цена 4:2:0 и H.264, "
          "а не коррекция.")
    print(f"Замер самого дубля: средние по карточке A **{AROLL_SRC[0]} / "
          f"{AROLL_SRC[1]} / {AROLL_SRC[2]}** против ориентира `brand-kit §6` "
          "«130 / 112 / 104». Расхождение называю числами и не правлю: "
          "гамма-подтяжка до ориентира уже пробовалась на ролике 16 и дала "
          "вымытое лицо и рост шума.")
    print("\n**Что стоит поправить на съёмке, а не на монтаже:** дубль снят "
          "в светло-серой футболке, и субтитры на планах с лицом ложатся белым "
          "по светло-серому — контраст низкий, хотя свечение на месте. "
          "Плашку под текст ставить нельзя (`brand-kit §7`), грейдить лицо — "
          "тоже. Тёмная футболка снимает вопрос целиком; это же было "
          "на роликах 24 и 25.")


if __name__ == "__main__":
    emit()
