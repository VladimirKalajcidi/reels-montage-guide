"""Генерирует монтажный лист ролика 34 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard34 import (SHOTS, CAPS, DUR, FACE_KINDS, CENTURIES, YEARS,
                          BRANCH_A, BRANCH_B, STOCK_NAMES)

# измерения сданного файла (заполняются после финального рендера)
LUFS, TP, LRA = -14.1, -1.6, 1.5
FACE_BAND = (168.6, 170.3)
STOCK_BAND = (74.0, 74.6)

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A1word": ("R1+R6", "лицо + крупное слово «ПАРАДОКС» над головой, "
                        "внутри карточки, без маски по силуэту"),
    "ages": ("R4+R5a", "сетка: двадцать засечек-веков выстраиваются каскадом, "
                       "под ними белое **2000** резким попом (R5a)"),
    "stock": ("R2", "крокодил с раскрытой пастью крупным планом, карточка B, "
                    "притемнение 28%"),
    "rule": ("R4+R10", "сетка: собирается сцена — пасть с ребёнком, отец, "
                       "над отцом облачко с вопросом; затем галочка и дуга "
                       "возврата: вот условие обещания"),
    "promise": ("R4+R10", "сетка: фигурка ребёнка едет по дуге из пасти к отцу — "
                          "«верну»"),
    "predict": ("R4+R10", "сетка: в облачке проявляется тот же символ возврата "
                          "и перечёркивается — это предсказание отца"),
    "caseA1": ("R4+R10", "сетка: дуга возврата появляется и перечёркивается, "
                         "ребёнок остаётся в пасти"),
    "caseA2": ("R4+R10", "сетка: перечёркнутый возврат в облачке и в сцене — "
                         "одна и та же картинка, оба креста синие, синяя галочка"),
    "mustReturn": ("R4+R10", "сетка: крест с дуги снимается, дуга синяя, "
                             "ребёнок едет к отцу — вынужденный вывод"),
    "caseB1": ("R4+R10", "сетка: белая посылка второй ветки — ребёнок едет "
                         "к отцу по несиней дуге"),
    "caseB2": ("R4+R10", "сетка: синий крест у облачка — предсказание ложно"),
    "caseB3": ("R4+R10", "сетка: синий крест ложится на дугу, ребёнок "
                         "возвращается в пасть"),
    "loop": ("R4+R10", "сетка: две панели состояний и две дуги между ними — "
                       "замкнутый цикл, по нему бежит синяя точка"),
    "loopSpin": ("R4+R10", "сетка: содержимое панелей гаснет, остаются два узла "
                           "и бесконечно бегущая по кольцу точка"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = lens[len(lens) // 2]
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «парадокс крокодила»\n")
    print(f"Исходник: `videos/34/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/34/croc_edit.mp4` · 1080×1920 · 30 fps · "
          f"{int(round(DUR*30))} кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с — ролик объяснительный, "
          "очередь быстрых резов R3 не используется")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· графика и вставка **{100*(DUR-face)/DUR:.0f}%** "
          f"(из них сток {stock:.1f}с = {100*stock/DUR:.0f}%).")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**белое число: 2000** · синих чисел нет — синим помечены выводы\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa34.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Логика парадокса пересчитана")
    print("Предсказание отца — «ты его не вернёшь», то есть оно истинно ровно "
          "тогда, когда крокодил **не** возвращает. Обещание крокодила — "
          "вернуть ребёнка тогда и только тогда, когда отец угадал. Обе ветки "
          "пересчитаны машинно (`qa34.logic` = 0 нарушений):\n")
    print("| посылка | предсказание | обещание требует | что вышло |")
    print("|---|---|---|---|")
    print("| крокодил **не возвращает** | истинно ✓ | вернуть | "
          "противоречие с посылкой |")
    print("| крокодил **возвращает** | ложно ✗ | не возвращать | "
          "противоречие с посылкой |")
    print("\nВывод каждой ветки — это посылка другой, поэтому цикл A → B → A "
          "замкнут. Это и есть «логическая петля» из речи, и именно она "
          "нарисована на планах `loop` / `loopSpin`, а не абстрактное кольцо.")
    print(f"\n«Больше {YEARS} лет» — на экране {CENTURIES} засечек по сто лет. "
          "Парадокс восходит к античной школе (Коракс, V век до н. э.), так что "
          "число на экране — заведомо нижняя оценка, а не округление вверх.")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи-пояснения** — только фигуры, цвет "
          "и одно число. Слова несёт субтитр, механику несёт сцена:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| пасть с зубами слева | крокодил |")
    print("| маленькая фигурка внутри пасти | ребёнок у него |")
    print("| большая фигурка справа | отец |")
    print("| дуга со стрелкой и фигуркой на ней | «вернуть ребёнка» |")
    print("| крест на дуге | «не вернуть» |")
    print("| облачко над отцом | предсказание отца; внутри — тот же символ "
          "возврата, что и в сцене |")
    print("| галочка / крест у облачка | предсказание оказалось верным / неверным |")
    print("| **синее** | вывод: что из посылки следует |")
    print("| две панели и две дуги между ними | два состояния и переходы "
          "между ними — замкнутая петля |")
    print("\nОдинаковая картинка в облачке и в сцене — не украшение: именно по "
          "ней видно, что предсказание совпало с реальностью, без единой "
          "подписи «предсказание верно».")

    print("\nЧисло и ключевые слова стоят там, где субтитр их не повторяет "
          "(`qa34.digits_in_captions` = 0, `qa34.captions_on_number_shots` = 0): "
          f"во время ревила белого {YEARS} субтитра на экране нет — блок "
          "«существует больше» срезан на 1.89, следующая строка появляется "
          "только на 3.28. Кусок «верну ли я тебе ребёнка или нет / я его "
          "верну» идёт вообще без субтитра — обещание несёт дуга возврата и "
          "едущая по ней фигурка. На плане `A1word` субтитр обрывается на "
          "«это и называют», слово ПАРАДОКС несёт крупная надпись R6. Слово "
          "«петля» в субтитрах не набирается ни разу — его несёт цикл.")
    print("\nМашинная проверка пересечения слоёв (`qa34.gfx_text_overlap`) — "
          "0 кадров; графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa34.gfx_out_of_zone`) — 0 кадров и нигде не упирается во врезку "
          "маски (`qa34.gfx_clipped`) — 0 кадров. Текст за карточку не "
          "выходит (`qa34.text_out_of_card` и `qa34.bright_outside_card`) — "
          "0 кадров; строки блоков не пересекаются "
          "(`qa34.line_overlap_pairs`) — 0 пар.")

    print("\n## Сток")
    print("Вставка одна, и она литеральная — на слове «крокодил»:\n")
    print("| файл | что в кадре |")
    print("|---|---|")
    for cid, desc in STOCK_NAMES.items():
        print(f"| `videos/34/stock/stock_{cid}.mp4` | {desc} |")
    print(f"\nКлип скачан под этот ролик (Mixkit, свободная лицензия), лежит "
          "в его папке и не берётся из других роликов (`assets-manifest §2`). "
          "Окно 7.04–9.09с выбрано по движению в кадре: у этого отрезка самая "
          "высокая покадровая разница из всего клипа, стоп-кадром он не "
          f"читается. Полоса субтитров после притемнения на 28% — "
          f"**{STOCK_BAND[0]} / p90 {STOCK_BAND[1]}** при пороге ≤110 / ≤140, "
          "белый текст читается.")
    print("\nОстальные планы — своя графика. Живого видео, буквально "
          "показывающего «предсказание отца делает обещание невыполнимым», "
          "не существует; перебивка «человек думает» или «суд» к механике "
          "задачи не относится, а `assets-manifest §2` прямо запрещает ставить "
          "сток ради ритма.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) — только выводы: галочка «отец угадал», "
          "вынужденный возврат, крест «предсказание ложно», перечёркнутый "
          "возврат и замкнутая петля. Один код на весь ролик: синее = вывод "
          "(brand-kit §4).")
    print(f"- Белым — единственное число ролика, **{YEARS}**.")
    print("- Лайм не использован: в ролике нет матричных/табличных элементов, "
          "для которых он предусмотрен.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под белым ревилом 2000 и под тремя синими выводами (0.070), тики "
          "под каскадами элементов сцены (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, петля с "
          "кроссфейдом 0.25с, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume / alimiter limit=0.80.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render34.py). Кроп посчитан по детектору: 29 замеров "
          "по всему дублю дали cx 377±8, линию глаз y 684±6, ширину лица "
          "269±7 — окно 630×1000 от (57, 264) ставит глаза на 42% высоты "
          "карточки. Зеркальность проверена по кадру: надпись на футболке "
          "после `hflip` читается нормально, штатный `hflip` подходит.")

    print("\n## Полоса субтитров на планах с лицом — не в норме, не чинилось")
    print("Замер полосы, где лежит субтитр (карточка A, y 1260…1400, "
          "x 200…880, по всем планам с лицом):\n")
    print("| ролик | средняя | p90 | порог |")
    print("|---|---|---|---|")
    print(f"| **34 (этот)** | **{FACE_BAND[0]}** | **{FACE_BAND[1]}** | ≤110 / ≤140 |")
    print("| 33 (сдан) | 171.8 | 219.4 | ≤110 / ≤140 |")
    print("| 32 (сдан) | 125.2 | 191.6 | ≤110 / ≤140 |")
    print("\nСветлая футболка в дневном свете: полоса ярче, чем у стоковой "
          "вставки, которую этот же порог в ролик не пустил бы. Белый текст "
          "со свечением на ней читается слабее, чем на графических планах.")
    print("\nМонтажом это не чинится и не чинилось: плашка-подложка под текстом "
          "запрещена (`brand-kit §7`), грейд лица — тоже (A-roll идёт только "
          "через `hflip` + кроп). Решение — на съёмочной стороне: тёмная "
          "футболка или менее выбитый свет на груди.")

    print("\n## Расшифровка")
    print("Пословные тайминги — `videos/34/words.json`, собраны по речевым "
          "отрезкам: границы сняты `ffmpeg silencedetect` (-34dB / 0.12с), "
          "внутри каждого отрезка выдача whisper large-v3 растянута на "
          "измеренный интервал (`align34.py`). Пауза 37.517–37.639 (0.122с) — "
          "внутри фразы, отрезки слиты.")
    print("\nОдно место спорное. На 8.66–9.44 whisper читает «я его **вернул**», "
          "хотя по смыслу это часть обещания — «я его **верну**». Решать по "
          "звуку не пришлось: этот кусок идёт **без субтитра**, обещание несёт "
          "дуга возврата, так что на экран спорное слово не выносится. То же "
          "на 10.96–11.83: в расшифровке «его не вернёшь» без «ты» — в субтитр "
          "взята ровно та часть, которая слышна однозначно.")


if __name__ == "__main__":
    emit()
