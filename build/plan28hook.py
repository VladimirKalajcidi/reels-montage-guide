"""Монтажный лист версии ролика 28 с другим хуком.

    python3 plan28hook.py h1 > ../videos/28/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard28 as SB
from hook28 import HOOKS, CUT, CUT_T, CUT_F, cut_of, cut_f_of, lts_for
from plan28 import NAMES

# замеры готовых файлов (qa28hook.py)
MEASURED = {
    "h1": dict(lufs=-13.9, tp=-2.1, lra=2.6, frames=1341, dur=44.70, pause=0.161,
               seam=(35, 1431), rgb=3, gain=0.939, psnr=43.9,
               hook_tail=0.125, body_head=0.036,
               deform="кроп ×0.98 — карточка A на одном и том же кадре тела "
                      "870px → 888px = ×1.0207 (целевое ×1.0204, расхождение — "
                      "1px квантования)"),
    "h2": dict(lufs=-13.9, tp=-2.2, lra=2.5, frames=1269, dur=42.30, pause=0.136,
               seam=(45, 1276), rgb=3, gain=0.659, psnr=43.9,
               hook_tail=0.103, body_head=0.036,
               deform="ускорение ×1.02 — 1294 кадра → 1269, `r_frame_rate` ровно "
                      "30/1, звук ускорен вместе с картинкой (видео 42.300с, "
                      "аудио 42.293с), геометрия карточки не тронута (870px → 870px)"),
}

RHYTHM = {
    "h1": dict(shots=21, avg=2.13, median=2.06, shortest=1.16, longest=3.62,
               first_cut=1.82, face_pct=32.7),
    "h2": dict(shots=21, avg=2.01, median=2.00, shortest=1.13, longest=3.55,
               first_cut=1.55, face_pct=33.4),
}

HOOK_SPEECH = {"h1": "0.00–4.21", "h2": "0.15–2.66"}


def plural_frames(n):
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return "кадр"
    if n10 in (2, 3, 4) and n100 not in (12, 13, 14):
        return "кадра"
    return "кадров"


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    r = RHYTHM[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    cut, cut_f = cut_of(cfg), cut_f_of(cfg)
    trim = cfg.get("head_trim_f", 0)
    dt = nh - cut
    lts = lts_for(cfg)

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/28/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.2f}с · {m['frames']} кадров")
    print(f"Хук: `videos/28/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с)")
    print(f"Тело: кадры {cut_f}+ из уже сданного `envelopes_edit.mp4`, "
          "не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")
    print(f"**Ритм версии целиком:** {r['shots']} плана · средняя {r['avg']:.2f}с · "
          f"медиана {r['median']:.2f}с · мин {r['shortest']:.2f}с · макс {r['longest']:.2f}с · "
          f"первый рез {r['first_cut']:.2f}с · лицо **{r['face_pct']:.1f}%**\n")

    print("## Точка реза")
    print(f"Базовая точка — кадр **{CUT_F}** (`ceil({CUT_T} × 30)`, {CUT:.4f}с): "
          "граница планов `A2` → `twoEnv` в исходном ролике, первая граница после конца "
          "старого начала «вот парадокс, который математическое ожидание заставляет вас "
          "бесконечно менять своё решение» (0.17–4.79). "
          "Планы 1–3 старого хука и все 5 их субтитров выброшены целиком: "
          "от старого начала не осталось ни кадра.")
    print(f"\nПроверка машинная: `qa28hook.old_hook_gone` требует, чтобы кадры "
          f"{CUT_F - 1} и {CUT_F} лежали в разных планах.")

    print(f"\n### Плюс срез головы тела: {trim} {plural_frames(trim)} "
          f"({trim / FPS:.3f}с) — и это тот случай, когда whisper врёт")
    print(f"Тело берётся не с кадра {CUT_F}, а с **{cut_f}** ({cut:.4f}с).")
    print("\nПо пословным таймингам на границе 5.418 начинается слово «перед», "
          "то есть резать можно было бы прямо там. **По звуку это не так.** "
          "Огибающая исходника в точке 5.418 держится на **0.43** — там ещё звучит "
          "«так» из выбрасываемого «итак». Провал между словами идёт "
          "**5.484–5.534**, и первый кадр внутри него — **165** (5.5000с), "
          "огибающая в нём **0.006** при шумовом поле 0.0001.")
    print("\n| точка | кадр | огибающая | что там на самом деле |")
    print("|---|---|---|---|")
    print("| граница плана 5.418 | 162.5 | **0.43** | середина «так» |")
    print("| ceil → 163 | 163 | 0.19 | хвост «так» |")
    print("| 164 | 164 | 0.036 | затухание «так» |")
    print("| **165** | **165** | **0.006** | тишина между словами |")
    print("| первый звук тела | 166.1 | 0.02+ | начало «перед» (5.536с) |")
    print("\nСрезаются только кадры **выбрасываемого** слова «итак» — ни одно слово "
          "тела не задето, «перед» приходит целым и с 0.036с тишины перед ним "
          "(`qa28hook.head_trim`: `cut_in_silence=True`, "
          "`body_sound_after_cut=True`). Первый план тела `twoEnv` стал "
          f"{SB.shot_at(cut)[1] - cut:.2f}с вместо 1.75с, порог 1.0с не нарушен.")
    print("\n**Побочный результат, который стоит записать.** В сданной версии №1 "
          "рез 5.418 стоит внутри слова «так». `qa28.speech_sync` этого не увидел, "
          "потому что сверялся с теми же таймингами whisper, которые и промахнулись. "
          "Там это только картинка — дорожка не резана, щелчка нет, — но в следующем "
          "ролике границу плана надо проверять по огибающей, а не по расшифровке. "
          "Версию №1 не переделываю: она эталон, с ней сравнивают остальные.")

    print("\n### Почему не раньше и не позже")
    print("**Не раньше.** Ближайшая предыдущая граница — 3.727с (`swapLoop` → `A2`), "
          "и резать по ней нельзя: тело начиналось бы с «менять своё решение», "
          "а что именно менять — звучало только в выброшенном хуке.")
    print("\n**Не позже.** Следующая граница — 7.163с (`twoEnv` → `double`), "
          "и по ней пропадает «перед вами два закрытых конверта», то есть вся "
          "постановка задачи. В новых хуках конвертов нет ни в одном, "
          "и восстановить её нечем.")
    print("\n**Связность стыка.** Тело начинается самостоятельным предложением "
          "с собственным подлежащим — «перед вами два закрытых конверта». Ни одного "
          "местоимения и ни одной отсылки к словам старого хука в первых фразах тела "
          "нет, поэтому обе версии режутся по одной и той же точке и ни одной фразы "
          "тела выбрасывать не пришлось.")
    if key == "h1":
        print("\nПередача эстафеты: хук кончается на «в этом парадоксе подвоха» — "
              "зритель ждёт, в чём подвох, и получает «перед вами два конверта».")
    else:
        print("\nПередача эстафеты: хук кончается на «известный парадокс теории "
              "вероятностей» — названо, что будет парадокс, и тело сразу его "
              "выкладывает: «перед вами два закрытых конверта».")
    print()

    print("## Блок хука")
    print(f"{len(cfg['shots'])} плана · первый рез **{lens[0]:.2f}с** "
          f"(норма — не позже 2.0с) · графика держит хвост\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    HOOK_DESC = {
        "swapLoop": "сетка: два закрытых конверта и стрелка обмена, которая "
                    "перекидывается с одного на другой и не останавливается — "
                    "та же графика, что стояла в старом начале",
    }
    for i, (t0, t1, kind, _p) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        desc = HOOK_DESC.get(kind, desc)
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")
    held = cfg["frames"] - {"h1": 129, "h2": 83}[key]
    if held > 0:
        print(f"\nВ дубле {cfg['frames'] - held} {plural_frames(cfg['frames'] - held)}, "
              f"в блоке — {cfg['frames']}: последние **{held} {plural_frames(held)}** "
              "A-roll уже кончился, и хвост добит **графическим планом**, "
              "а не стоп-кадром лица (`START-HERE`: «хвост добивать графическим "
              f"планом»). Эти кадры и дают паузу до тела {m['pause']:.3f}с.")
    else:
        print(f"\nA-roll дубля хватило на весь блок целиком ({cfg['frames']} "
              f"{plural_frames(cfg['frames'])}), добивать хвост графикой "
              "не потребовалось: собственного хвоста тишины в дубле "
              f"({m['hook_tail']:.3f}с) хватило на паузу {m['pause']:.3f}с.")
    print(f"\nДалее без изменений идёт тело сданного ролика — планы 4–22 из "
          f"`montage-plan.md`, со сдвигом **{dt:+.4f}с** на новой таймлинии"
          + (" и с последующим ускорением ×1.02." if cfg.get("post_a") else "."))
    print(f"\nРечь дубля: {HOOK_SPEECH[key]} по огибающей. Правая граница речевого "
          "отрезка для whisper бралась по ней же, а не по длине файла: в обоих дублях "
          "после последнего слова остаётся хвост тишины, и растяжка выдачи на весь "
          "файл уводила тайминги на 1.3% — к концу хука это полтора кадра "
          "(`align28hooks.py`).")

    print("\n## Графика хука")
    print("Взят тот же план, что стоял в старом начале, — `swapLoop`: два закрытых "
          "конверта и стрелка обмена, которая перекидывается с одного на другой "
          "и не останавливается. Это визуальная интрига ролика, менять её незачем; "
          "ни одного нового плана не нарисовано.")
    for kind, s in lts.items():
        ln = next(t1 - t0 for t0, t1, k, _ in cfg["shots"] if k == kind)
        body_ln = next(t1 - t0 for t0, t1, k, _ in SB.SHOTS if k == kind)
        if s > 1.001:
            print(f"\n`{kind}` идёт {ln:.2f}с против {body_ln:.2f}с в теле, поэтому "
                  f"анимация ускорена в **×{s:.2f}**.")
        else:
            print(f"\n`{kind}` идёт {ln:.2f}с при {body_ln:.2f}с в теле — анимация "
                  "в штатном темпе, без масштабирования времени.")
    print("\nУскорять анимацию можно, замедлять нельзя: тот же план в теле идёт "
          "своим темпом, и разойтись они не должны.")
    if key == "h1":
        print("\nНа слова дубля графика ложится буквально: конверты и мечущаяся "
              "стрелка выходят под «скорее всего не заметите в этом парадоксе "
              "подвоха» — подвох как раз в том, что стрелка не останавливается.")
    else:
        print("\nНа слова дубля графика ложится буквально: конверты и мечущаяся "
              "стрелка выходят под «теории вероятностей» — то, о чём парадокс, "
              "и то, чем он кончится.")
    print("\nПосле реза сразу идёт `twoEnv` — те же два конверта, но выше, крупнее "
          "и без стрелки. Композиция меняется за один кадр, поэтому стык читается "
          "как рез, а не как продолжение того же плана.")

    print("\n## Сток в хуке")
    print("Стока в хуке нет — в старом начале его тоже не было. Обе стоковые вставки "
          "ролика (руки с деньгами, mixkit 23725 и 24582) стоят в теле и идут "
          "без изменений.")

    print("\n## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, "
          "и основной исходник — 720×1280, `yuv420p`, `color_range=tv`, "
          "`bt709`/`bt709`/`bt709`, 30 fps. Кадры читаются прямо из `.mov` и идут "
          "в штатный тракт A-roll **без единого промежуточного кодека**.")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip, медиана по всему дублю): "
          f"основной дубль cx 388 / линия глаз 690 / ширина лица 292; "
          f"этот хук cx {cfg['face_cx']} / {cfg['face_eye']} / {cfg['face_d']}.")
    if key == "h1":
        print("  Расхождение: **+14px по горизонтали**, **+13px по линии глаз**, "
              "**+2.1% по размеру лица**. Кропом не правилось.")
    else:
        print("  Расхождение: **+32px по горизонтали** (4.4% ширины кадра), "
              "**+10px по линии глаз**, **+1.4% по размеру лица**. Голова в этом дубле "
              "заметно правее, чем в остальных двух; кропом это не правится — "
              "вопрос к точке съёмки, а не к монтажу.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуках, "
          "проверить по тексту не на чем. Штатный `hflip` оставлен: интерьер "
          "и рука с петличкой во всех трёх дублях с одной стороны кадра.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука (120 / 109 / 102) против "
          f"кадров тела (123 / 111 / 103) — расхождение **{m['rgb']} единицы** "
          "по каналу при норме до ~10. Свет между дублями не уехал.")

    print("\n## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек, у остальных "
          "версий другие (v1 `song3.mp3`, v2 `song2.mp3`, v3 `song1.mp3`).")
    if "song1" in cfg["music"]:
        print("  Трек 9.53с короче ролика, поэтому идёт петлёй с кроссфейдом 0.25с "
              "на шве (4.7 повтора). У двух других версий треки длиннее ролика "
              "и петли не требуют.")
    else:
        print("  Трек 335с длиннее ролика — идёт без петли, шва не существует.")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались. Порядок: сначала правка кадра, потом мукс "
          "со звуком.")

    print("\n## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, "
          f"постель (whoosh / impact / tick) со сдвигом **{dt:+.4f}с**, музыка с нуля, "
          "потом loudnorm.")
    print("- Whoosh стоит и на резе внутри хука, и на самом шве «хук → тело».")
    print(f"- Голос хука приведён к громкости тела по RMS речи (×{m['gain']:.3f}): "
          + ("дубль записан заметно **громче** основного — почти в полтора раза."
             if m["gain"] < 0.9 else "дубль записан чуть громче основного."))
    print(f"- Пауза между последним звуком хука и первым звуком тела: "
          f"**{m['pause']:.3f}с** при норме 0.10–0.20с. Складывается из хвоста хука "
          f"({m['hook_tail']:.3f}с) и тишины в голове тела ({m['body_head']:.3f}с). "
          "Меряется по огибающей, а не по словам whisper — на этом стыке он "
          "промахивается (см. «Точка реза»).")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами на шве "
          f"**{m['seam'][0]}** против **{m['seam'][1]}** на 99.9-м процентиле "
          "всей дорожки.")
    print(f"- Громкость **{m['lufs']:.1f} LUFS**, истинный пик **{m['tp']:.1f} dBFS**, "
          f"LRA **{m['lra']:.1f} LU** — сведено к уровню уже сданного "
          "`envelopes_edit.mp4` (−13.9 / −2.0 / 2.6), а не к абстрактным −14. "
          "Потолок лимитера 0.76, как в основном ролике.")

    print("\n## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa28hook.py {key}")
    print("```")
    print("Все по нулям: `text_out_of_card=0`, `gfx_text_overlap=0`, "
          "`gfx_out_of_zone=0`, `line_overlaps=0` по блоку хука, `bright_outside` = "
          "0 кадров по всему файлу версии (включая деформацию), нарушений стиля "
          "субтитров 0, слов не из речи 0.")
    print(f"- Рез по границе плана: кадры {CUT_F - 1} и {CUT_F} лежат в разных планах "
          "(`A2` → `twoEnv`) — от старого хука не осталось ни кадра, ни субтитра.")
    print(f"- Тело против сданной версии — худший PSNR **{m['psnr']:.1f} dB** "
          "на 14 контрольных кадрах (это второе прохождение того же кодека, "
          "картинка та же).")
    print("- Версия №1 не тронута: `envelopes_edit.mp4` не открывался на запись — "
          "хуки читают из него только готовые кадры тела.")


if __name__ == "__main__":
    emit(sys.argv[1])
