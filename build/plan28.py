"""Генерирует монтажный лист ролика 28 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard28 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS,
                          FOUND, LOW, HIGH, EV, MULT, ANY_SUMS, BILL_UNIT, ru)
import render28

# измерения сданного файла (см. блоки «Звук», «A-roll», «Сток»)
LUFS, TP, LRA = -13.99, -1.97, 2.90
AROLL_SRC = (124, 111, 102)
AROLL_OUT = (121, 110, 100)
AROLL_DELTA = (0.7, 2.9)
CAPBAND_FACE = (135, 184)          # средняя / p90 в полосе субтитров на лице
STOCK_MEASURED = {"23725": (83, 130, 0.80), "24582": (58, 134, 0.34)}

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "swapLoop": ("R4+R10", "сетка: два закрытых конверта, стрелка обмена "
                           "перекидывается с одного на другой и не "
                           "останавливается — это и есть «бесконечно менять "
                           "решение»"),
    "twoEnv": ("R4+R10", "сетка: два закрытых конверта появляются каскадом — "
                         "ровно два, ровно закрытых"),
    "double": ("R4+R10", "сетка: оба конверта открыты, в левом **две** купюры, "
                         "в правом **четыре** — «вдвое больше» показано счётом, "
                         "а не подписью"),
    "open1000": ("R4+R5a", "сетка: выбранный конверт открывается, из него "
                           "поднимаются две купюры, над ним резким попом — "
                           "**белое 1 000 ₽**; субтитр обрывается до числа"),
    "branch": ("R4+R10", "сетка: второй конверт наверху и две ветви вниз "
                         "к двум таким же закрытым конвертам — двум вариантам "
                         "того, что в нём лежит"),
    "branchNums": ("R4+R10", "сетка: оба варианта открыты — конверт с **одной** "
                             "купюрой и конверт с **четырьмя**, над ними "
                             "**500** и **2 000**; субтитра на плане нет"),
    "ev1250": ("R4+R5b", "сетка: 500 и 2 000 стоят метками на оси, синяя метка "
                         "едет ровно на середину между ними, под ней "
                         "**синее 1 250 ₽** набором по разрядам; субтитра нет"),
    "swapGood": ("R4+R10", "сетка: в своём конверте **1 000 ₽**, во втором — "
                           "**синие 1 250 ₽**, и синяя дуговая стрелка ведёт "
                           "туда"),
    "anySum": ("R4+R5b", "сетка: сумма наверху меняется (400 → 1 000 → 6 800 → "
                         "20 000 ₽), результат внизу меняется вместе с ней, "
                         "а **синее × 1,25** между ними не меняется никогда"),
    "loopAlways": ("R4+R10", "сетка: та же пара конвертов, но период броска "
                             "стрелки сокращается с 0.46 до 0.17с — обмен "
                             "не кончается"),
    "flaw": ("R4+R10", "сетка: от 1 000 ₽ две ветви к 500 и 2 000, под каждой "
                       "полоса веса; полосы приходят равными, потом "
                       "разъезжаются **лаймом** и продолжают ходить"),
    "prior": ("R4+R10", "сетка: две пары, при которых в руках могла оказаться "
                        "1 000 — «одна купюра и две» и «две и четыре»; конверт "
                        "с двумя купюрами обведён рамкой в обеих парах, "
                        "подсветка ходит между парами"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = (lens[len(lens) // 2 - 1] + lens[len(lens) // 2]) / 2
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «парадокс двух конвертов»\n")
    print(f"Исходник: `videos/28/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/28/envelopes_edit.mp4` · 1080×1920 · 30 fps · "
          "1376 кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих чисел: 2** (1 250 ₽ и × 1,25) · "
          "**белых чисел: 1 000 ₽, 500, 2 000** и пары сумм на `anySum`\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa28.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]] + f" (с {prm['ss']:.1f}с клипа)"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Сценарий пересчитан — ошибок нет")
    print("В отличие от ролика 26, здесь править нечего: арифметика речи верна "
          "целиком (`qa28.numbers` = 0 нарушений).\n")
    print("| в речи | пересчёт |")
    print("|---|---|")
    print(f"| «в одном в два раза денег больше» | пара (S, 2S) ✓ |")
    print(f"| «находите там например {ru(FOUND)} рублей» | S = {ru(FOUND)} ✓ |")
    print(f"| «во втором либо {ru(LOW)}, либо {ru(HIGH)}» | S/2 = {ru(LOW)}, "
          f"2S = {ru(HIGH)} ✓ |")
    print(f"| «средняя ожидаемая сумма — {ru(EV)}» | ({ru(LOW)} + {ru(HIGH)}) / 2 "
          f"= **{ru(EV)}** ✓ |")
    print(f"| «то же рассуждение при любой увиденной сумме» | (S/2 + 2S)/2 = "
          f"**{MULT} · S** при любом S ✓ |")
    print("| «считаем две суммы равновероятными без основания» | это и есть "
          "стандартное разрешение парадокса ✓ |")
    print(f"\nПары для плана `anySum` подобраны так, чтобы результат был целым "
          f"и делился на масштаб купюры: "
          + ", ".join(f"{ru(s)} → {ru(int(s*MULT))}" for s in ANY_SUMS) + ".")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи** — только цифры сумм. "
          "Слова несёт субтитр, механику несёт графика:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| прямоугольник с «галкой» | закрытый конверт |")
    print("| прямоугольник с треугольником вверх | открытый конверт |")
    print(f"| одна купюра внутри | **{ru(BILL_UNIT)} ₽** — масштаб один "
          "на весь ролик |")
    print("| дуговая стрелка между конвертами | обмен |")
    print("| стрелка, перекидывающаяся туда-сюда | «менять решение» без конца |")
    print("| ветвление вниз | «во втором либо …, либо …» |")
    print("| ось с двумя метками | две суммы на числовой прямой |")
    print("| метка посередине оси | их среднее |")
    print("| полоса под ветвью | вес (вероятность) этой ветви |")
    print("| рамка вокруг конверта | тот конверт, который уже в руках |")
    print("| синее | результат: 1 250 ₽, × 1,25, стрелка обмена, метка среднего |")
    print("| лайм | единственное место ролика, где рассуждение ломается |")
    print("\nЧисла на экране стоят там, где субтитра нет вообще "
          "(`qa28.no_caption_on_number_shots` = 0): на планах `branchNums` "
          "и `ev1250` субтитров нет, на `open1000` субтитр «там например» "
          "гаснет на 12.76, а 1 000 ₽ выходит на 12.84 — уже в тишине текста. "
          "Ни одной цифры в субтитрах нет вовсе "
          "(`qa28.digits_in_captions` = 0).")
    print("\nМашинная проверка пересечения слоёв (`qa28.gfx_text_overlap`) — 0 кадров, "
          "графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa28.gfx_in_zone`) — 0 кадров и нигде не упирается во врезку "
          "маски (`qa28.gfx_clipped`) — 0 кадров.")

    print("\n## Масштаб купюры — почему картинка не врёт")
    print(f"Одна купюра = **{ru(BILL_UNIT)} ₽** на всех планах сразу, поэтому "
          "счёт купюр всегда сходится с числом рядом:\n")
    print("| план | конверты | купюр | проверка |")
    print("|---|---|---|---|")
    print(f"| `double` | S и 2S | {FOUND//BILL_UNIT} и {HIGH//BILL_UNIT} "
          f"| ровно вдвое ✓ |")
    print(f"| `open1000` | {ru(FOUND)} ₽ | {FOUND//BILL_UNIT} "
          f"| {FOUND//BILL_UNIT} × {ru(BILL_UNIT)} = {ru(FOUND)} ✓ |")
    print(f"| `branchNums` | {ru(LOW)} и {ru(HIGH)} | {LOW//BILL_UNIT} и "
          f"{HIGH//BILL_UNIT} | 1:4, как {ru(LOW)}:{ru(HIGH)} ✓ |")
    print(f"| `swapGood` | {ru(FOUND)} ₽ | {FOUND//BILL_UNIT} | ✓ |")
    print(f"| `prior` | пары ({ru(LOW)}, {ru(FOUND)}) и ({ru(FOUND)}, {ru(HIGH)}) "
          f"| 1|2 и 2|4 | обведён один и тот же конверт ✓ |")
    print("\nМетка среднего на оси `ev1250` стоит не «примерно посередине»: "
          f"ось {render28.AX_X0}…{render28.AX_X1}px, середина "
          f"{(render28.AX_X0+render28.AX_X1)/2:.0f}px, и туда же поставлено "
          "число 1 250 ₽ (`qa28.geometry` пересчитывает это).")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) окрашены **результаты**: число **1 250 ₽**, "
          "множитель **× 1,25**, метка среднего на оси и стрелка обмена "
          "на `swapGood`.")
    print("- **Синих чисел два** при лимите 4 (`brand-kit §4`).")
    print("- **Лайм #C3DB4E — один элемент на весь ролик**: разъезжающиеся "
          "полосы веса на плане `flaw`. Ровно то место, где рассуждение "
          "и ломается.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt. Кегль крупных чисел "
          "подобран под ширину зоны графики (730px), а не по шкале XL "
          "из `brand-kit §3`: цифра SF Pro занимает ~0.75em, и «1 000 ₽» "
          "на кегле 175 дало бы строку 700px — всю зону, без места под "
          "свечение. Рабочие кегли: 1 000 ₽ — 126pt (593px), 1 250 ₽ — 132pt, "
          "× 1,25 — 116pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под тремя ревилами чисел (0.070), тики под каскадами элементов (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume 1.35 dB / alimiter limit=0.76.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**.")
    print(f"- **LRA {LRA} LU** при норме гайда 3–5 — на нижней границе. Это "
          "свойство дубля: речь идёт очень ровно. Лимитером и loudnorm "
          "не лечится, фиксирую замер. Тот же эффект был на роликах 22, 25 и 26.")
    print("- Потолок лимитера пришлось опустить с 0.80 до 0.76: на 0.80 файл "
          "выходил на −1.04 dBTP — формально в норме, но с запасом 0.04 dB "
          "до потолка площадки. На 0.76 получилось −1.97 dBTP при тех же "
          "−14 LUFS.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/28/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        m, p, f = STOCK_MEASURED[cid]
        print(f"- `stock_{cid}.mp4` — {name}. Замер окна: полоса субтитров "
              f"средняя **{m}**, p90 **{p}** (порог 110 / 140), объект в кадре "
              f"на **{f:.0%}** площади карточки всё время плана.")
    print("\nВсего два стоковых плана из 22 — и это осознанно: смысл ролика "
          "держится на конвертах, ветвлении и среднем, а этого сток не "
          "показывает (`assets-manifest §2`: «если сцену можно закрыть своей "
          "графикой без потери смысла — берём графику»). Сток стоит ровно "
          "там, где в речи звучит буквальное «деньги»/«суммы денег».")
    print("\nОдин клип пришлось заменить по числам: на «чем в другом» сначала "
          "стояли падающие купюры (`18305`) — красивый чёрный кадр, но в окне "
          "плана в кадре оказывалась одна купюра на краю, объект занимал 10–15% "
          "карточки, и план читался чёрной вспышкой. Клип 23725 даёт 80%.")
    print("\nКроп стоковых кадров перестал быть жёстко центральным: `fit_bgr` "
          "получил смещение окна `cx/cy` (`brand-kit §2`: «композицию клипа "
          "кадрируем сами»). Обоим клипам подошёл центр, но параметр теперь "
          "есть и измеряется, а не подбирается пересъёмкой раскадровки.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render28). Кроп посчитан по детектору: 35 замеров "
          "по всему дублю дали cx 387±7, линию глаз y 690±3, ширину лица 291±7 — "
          "глаза стоят на 42% высоты карточки в обоих вариантах крупности.")
    print(f"Замер дубля: средние по карточке A **{AROLL_SRC[0]} / {AROLL_SRC[1]} "
          f"/ {AROLL_SRC[2]}** против ориентира `brand-kit §6` «130 / 112 / 104» "
          "— расхождение в пределах разброса между дублями, править нечего.")
    print(f"Проверка тракта: средний RGB внутри карточки A в сданном файле "
          f"**{AROLL_OUT[0]} / {AROLL_OUT[1]} / {AROLL_OUT[2]}**, то есть "
          f"отличается от того же кропа исходника на "
          f"**{AROLL_DELTA[0]:.1f}–{AROLL_DELTA[1]:.1f} единицы** по каналу — "
          "это цена 4:2:0 и H.264, а не коррекция.")
    print("\n**Что стоит поправить на съёмке, а не на монтаже:** дубль снят "
          "в светло-серой футболке, и субтитры на планах с лицом ложатся белым "
          "по светло-серому. Числа: полоса субтитров на планах с лицом даёт "
          f"среднюю **{CAPBAND_FACE[0]}** и p90 **{CAPBAND_FACE[1]}** — при том, "
          "что стоковую вставку я не пропускаю в ролик, если у неё в той же "
          "полосе средняя выше 110 или p90 выше 140. То есть собственный кадр "
          "проходит по контрасту хуже любой принятой вставки.")
    print("Плашку под текст ставить нельзя (`brand-kit §7`), грейдить лицо — "
          "тоже (`editing-taste`, проверено на ролике 16). Тёмная футболка "
          "снимает вопрос целиком; это же было на роликах 24, 25 и 26.")

    print("\n## Расшифровка")
    print("Пословные тайминги — `videos/28/words.json`, собраны по речевым "
          "отрезкам: границы сняты `ffmpeg silencedetect` (-34dB / 0.12с), "
          "внутри каждого отрезка выдача whisper large-v3 растянута "
          "на измеренный интервал (`align28.py`).")
    print("\nДва отрезка пришлось слить и перетранскрибировать: на коротком "
          "куске модель добивает фразу мусором. По отдельности 9.96–11.71 "
          "и 11.89–13.31 дали «…находите **один**» и «там например **тысячи** "
          "рублей», слитые — верное «…находите там например 1000 рублей». "
          "То же с хвостом: 43.66–45.44 обрывался на «у меня…», а 45.57–45.87 "
          "декодировался как «**профит**» вместо «в профиле». Оба слияния "
          "записаны в `align28.py` (`MERGED`), пересборка воспроизводит "
          "исправленный вариант.")
    print("\nОдно место осталось спорным и в субтитр не вынесено: на 26.48–27.36 "
          "whisper устойчиво слышит «рассуждение **может** провести», хотя "
          "по смыслу там «**можно** провести». Субтитр этого куска — "
          "«точно такое же рассуждение» и «при любой увиденной сумме», "
          "спорное слово в кадр не попадает.")

    print("\n## Автопроверки")
    print("Все — по нулям (`python3 qa28.py`):\n")
    print("```")
    print("cuts_inside_word=0            captions_off_speech=0")
    print("captions_crossing_cut=0       caption_words_not_in_speech=0")
    print("caption_style_violations=0    digits_in_captions=0")
    print("captions_on_number_shots=0    gfx_text_overlap_frames=0")
    print("gfx_out_of_zone_frames=0      gfx_touching_mask_frames=0")
    print("text_out_of_card_frames=0     line_overlap_pairs=0")
    print("bright_outside_card_frames=0  number_violations=0")
    print("geometry_violations=0")
    print("```")
    print("\nСмысловая проверка графики — по контакт-листу ключевых кадров "
          "(`python3 contact28.py <папка>`): первый кадр каждого графического "
          "плана, пик анимации и полный ревил каждого числа.")


if __name__ == "__main__":
    emit()
