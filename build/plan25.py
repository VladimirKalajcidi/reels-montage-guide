"""Генерирует монтажный лист ролика 25 из раскадровки."""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard25 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS,
                          MAIN, ALT1, ALT2, _ang)
import render25

# измерения сданного файла (см. блоки «Звук» и «A-roll»)
LUFS, TP, LRA = -14.0, -1.6, 2.3
AROLL_SRC = (115, 102, 94)
AROLL_OUT_DELTA = (0.2, 3.6)

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "anyTri": ("R4+R10", "сетка: тремя штрихами рисуется разносторонний "
                         "треугольник — «любой, даже самый кривой»"),
    "teaser": ("R4+R10", "сетка: весь приём целиком — шесть трисектрис, три точки, "
                         "**синий** равносторонний треугольник; обещание ролика"),
    "trisect": ("R4+R10", "сетка: дуги отмечают все три угла, затем угол при "
                          "нижней вершине делится двумя **лаймовыми** линиями "
                          "на три равные дуги"),
    "trisectAll": ("R4+R10", "сетка: шесть трисектрис каскадом — по две "
                             "из каждой вершины до противоположной стороны"),
    "adjacent": ("R4+R10", "сетка: три пары соседних трисектрис загораются "
                           "по очереди, каждая рождает свою точку"),
    "points": ("R4+R10", "сетка: трисектрисы гаснут, остаются три точки"),
    "connect": ("R4+R10", "сетка: три отрезка между точками прорисовываются подряд"),
    "equilateral": ("R4+R10", "сетка: контур обводится и заливается **синим** — "
                              "результат"),
    "equalMarks": ("R4+R10", "сетка: засечки на трёх сторонах, дуги в трёх углах "
                             "и **синее 60°** с выноской к углу (R5b)"),
    "anyStart1": ("R4+R10", "сетка: другой исходный треугольник — тупоугольный; "
                            "тот же приём, тот же равносторонний результат"),
    "anyStart2": ("R4+R10", "сетка: третий исходный треугольник, другая "
                            "ориентация; результат снова равносторонний"),
    "year": ("R4+R5a", "сетка: **белое 1899** резким попом, под ним черта; "
                       "субтитра на плане нет"),
    "recap": ("R4+R10", "сетка: весь приём одним быстрым проходом"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «теорема Морли»\n")
    print(f"Исходник: `videos/25/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/25/morley_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих чисел: 1** (60° на плане `equalMarks`) · "
          "**белых чисел: 1** (1899 на плане `year`)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa25.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи.** Слова несёт только субтитр, "
          "графика несёт то, чего в словах нет:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| три белых отрезка | исходный треугольник — «любой» |")
    print("| дуга у вершины | сам угол |")
    print("| три дуги с зазорами + две лаймовые линии | «на три равные части» |")
    print("| тонкая линия от вершины до противоположной стороны | трисектриса |")
    print("| яркая пара линий | «соседние линии соседних углов» |")
    print("| точка | пересечение соседней пары |")
    print("| синий залитый треугольник | результат — равносторонний |")
    print("| засечка поперёк стороны | «эта сторона равна тем» |")
    print("| дуга в углу синего треугольника | «этот угол равен тем» |")
    print("\nДве цифры на экране поставлены так, чтобы не спорить с речью:")
    print("- **60°** — в речи звучит «все углы абсолютно одинаковые», а не "
          "«шестьдесят»: графика добавляет то, чего в словах нет (`brand-kit §5` "
          "разрешает подпись ровно в этом случае);")
    print("- **1899** — год произносится вслух, поэтому на плане `year` "
          "**субтитра нет вообще**: число несёт графика "
          "(`qa25.no_caption_on_number_shot` = 0).")
    print("\nМашинная проверка пересечения слоёв (`qa25.gfx_text_overlap`) — 0 кадров, "
          "графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa25.gfx_in_zone`) — 0 кадров.")

    print("\n## Геометрия — построена, а не нарисована на глаз")
    print("Трисектрисы считаются поворотом направления на θ/3 и 2θ/3, точки Морли — "
          "пересечением соседних трисектрис соседних углов. `qa25.geometry()` "
          "пересчитывает это для **всех трёх** исходных треугольников:\n")
    print("| треугольник | углы исходного | сторона результата | разброс сторон | углы результата |")
    print("|---|---|---|---|---|")
    for name, sc in (("основной", MAIN), ("ALT1 (тупоугольный)", ALT1),
                     ("ALT2 (другая ориентация)", ALT2)):
        A, B, C = sc["tri"]
        MA, MB, MC = sc["M"]
        s = [math.dist(MA, MB), math.dist(MB, MC), math.dist(MC, MA)]
        an = [math.degrees(_ang(MB, MA, MC)), math.degrees(_ang(MC, MB, MA)),
              math.degrees(_ang(MA, MC, MB))]
        ta = [math.degrees(_ang(B, A, C)), math.degrees(_ang(C, B, A)),
              math.degrees(_ang(A, C, B))]
        print(f"| {name} | {ta[0]:.1f}° / {ta[1]:.1f}° / {ta[2]:.1f}° | "
              f"{s[0]:.1f}px | {max(s)-min(s):.1e}px | "
              f"{an[0]:.4f}° / {an[1]:.4f}° / {an[2]:.4f}° |")
    print("\nПроверяется ещё три вещи, и все три дают ноль нарушений:")
    print("- каждая трисектриса делит свой угол ровно на три равные части "
          "(до 1e-6 градуса);")
    print("- каждая точка Морли лежит **ровно** на обеих своих трисектрисах "
          "(расстояние до прямой < 1e-6 px), а не «примерно рядом»;")
    print("- всё построение — вершины, ноги трисектрис, точки — помещается "
          "в зону графики целиком, ни одна линия не обрезана краем.")
    print("\nТри исходных треугольника намеренно разные (разносторонний, "
          "тупоугольный, повёрнутый): «независимо от того, с какого треугольника "
          "вы начали» — это утверждение, и его показывают три разных построения, "
          "а не одно и то же дважды.")
    print("\nЧего на графике намеренно НЕТ: подписей к вершинам и сторонам. "
          "Буквы A/B/C ничего не добавляют — в речи их нет, а кадр они засоряют.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) окрашен **результат** — равносторонний треугольник "
          "Морли и его угол **60°**. Больше синего в ролике нет.")
    print("- **Синих чисел одно** при лимите 4 (`brand-kit §4`).")
    print("- **Лайм #C3DB4E — один элемент на весь ролик**: деление угла при "
          "нижней вершине на плане `trisect` (две линии и три дуги). Это ровно "
          "та операция, на которой держится вся теорема.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt; крупные числа "
          "60° (118pt) и 1899 (176pt) идут графикой, а не субтитром.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под четырьмя ревилами (0.070), тики под каскадами элементов (0.030).")
    print("- Музыка `audios/song2.mp3`: −19 dB от RMS голоса, трек 335с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume/alimiter.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**.")
    print(f"- **LRA {LRA} LU** при норме гайда 3–5. Это свойство дубля: речь идёт "
          "очень ровно, без громких и тихих мест. Лимитером и loudnorm не лечится — "
          "фиксирую замер, а не правлю. Тот же эффект был на ролике 22 (2.3 LU).")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/25/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nВставка буквальна: звучит «открыть ещё в древности» — в кадре "
          "аллея сфинксов Карнака, то есть сама древность, а не «что-то старое». "
          "Клип панорамирует, статики нет.")
    print("\nПолоса субтитров в карточке B замерена **до** постановки в план: "
          "средняя 52–62 из 255 и p95 126–139 на выбранном участке при пороге "
          "≤140 — белый текст со свечением читается. Два других скачанных "
          "кандидата (`32893` коридор с колоннами, `21612` старинная карта) "
          "отброшены по смыслу: первый — компьютерная графика в духе фэнтези, "
          "второй — карта, а не древность.")
    print("\nОстальные планы закрыты собственной графикой. Вся суть ролика — "
          "в построении, которого сток не показывает (`assets-manifest §2`: "
          "«если сцену можно закрыть своей графикой без потери смысла — берём графику»).")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render25). Кроп посчитан по детектору: 30 замеров "
          "по всему дублю дали cx 392±9, линию глаз y 641±4, ширину лица 286±8 — "
          "глаза стоят на 42.2% высоты карточки у A1 и на 42.3% у A2.")
    print(f"Проверка: средний RGB внутри карточки A в сданном файле отличается "
          f"от того же кропа исходника на **{AROLL_OUT_DELTA[0]:.1f}–"
          f"{AROLL_OUT_DELTA[1]:.1f} единицы** по каналу — это цена 4:2:0 и H.264, "
          "а не коррекция.")
    print(f"Замер самого дубля: средние по карточке A **{AROLL_SRC[0]} / "
          f"{AROLL_SRC[1]} / {AROLL_SRC[2]}** против ориентира `brand-kit §6` "
          "«130 / 112 / 104». Расхождение называю числами и не правлю: "
          "гамма-подтяжка до ориентира уже пробовалась на ролике 16 и дала "
          "вымытое лицо и рост шума.")
    print("Ориентация: дубль снят тем же трактом, что ролик 23 (тёмная стена слева, "
          "проём справа в исходнике), поэтому штатный `hflip` остаётся включённым.")


if __name__ == "__main__":
    emit()
