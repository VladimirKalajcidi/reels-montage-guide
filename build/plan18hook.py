"""Монтажный лист версии ролика 18 с другим хуком.

    python3 plan18hook.py h1 > ../videos/18/montage-plan-hook1.md
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import storyboard18 as SB
import hook18 as H
from plan18 import NAMES

FPS = 30
BODY_FRAMES = 1431                      # длина _video_leap.mp4 = длина исходника

# результаты qa18hook.py, снятые с готовых файлов
QA = {
    "h1": dict(bright=0, gfx=0, textcard=0, lines=0,
               body="расхождение по пикселям не более 2.15% (ресемпл кропа)",
               seam="2691 против p99.99 = 6378 — щелчка нет",
               deform="ширина карточки A 870px → 888px = ×1.0207 при ожидаемых ×1.0204",
               loud="-14.1 LUFS · LRA 2.5 · истинный пик -1.6 dBTP"),
    "h2": dict(bright=0, gfx=0, textcard=0, lines=0,
               body="покадровое сравнение неприменимо — версия ускорена ×1.02",
               seam="81 против p99.99 = 6467 — щелчка нет",
               deform="fps ровно 30/1 (не 30.6), видео 46.967с и аудио 46.956с сходятся",
               loud="-14.1 LUFS · LRA 2.3 · истинный пик -1.6 dBTP"),
}

key = sys.argv[1]
cfg = H.HOOKS[key]
qa = QA[key]
cut_f = cfg["cut_f"]
cut = cut_f / FPS
nf_hook = cfg["frames"]
hook_len = nf_hook / FPS
# cut_f — первый кадр СОХРАНЁННОГО плана; граница плана может стоять
# на дробном кадре, поэтому считаем по индексу плана, а не по времени
first_kept = SB.SHOTS.index(SB.shot_at(cut))
edge_t = SB.SHOTS[first_kept][0]
dropped_shots = first_kept
dropped_caps = sum(1 for c in SB.CAPS if c[0] < edge_t)
edge_pair = f"`{SB.SHOTS[first_kept - 1][2]}` → `{SB.SHOTS[first_kept][2]}`"

dt = hook_len - edge_t
body = SB.SHOTS[first_kept:]
total = (nf_hook + BODY_FRAMES - cut_f) / FPS
post = "кроп ×0.98" if cfg.get("post_v", "").startswith("crop") else "ускорение ×1.02"
if cfg.get("post_a"):
    total /= 1.02

# у ускоренной версии тайминги приводим к сданному файлу, иначе лист
# разойдётся с ним на 2% и по нему нельзя будет ничего найти
tsc = 1.02 if cfg.get("post_a") else 1.0
shots = [(a, b, k, p) for a, b, k, p in cfg["shots"]] + \
        [(a + dt, b + dt, k, p) for a, b, k, p in body]
shots = [(a / tsc, b / tsc, k, p) for a, b, k, p in shots]
lens = sorted(b - a for a, b, _, _ in shots)
face = sum(b - a for a, b, k, _ in shots if k in SB.FACE_KINDS)
n_hook_shots = len(cfg["shots"])

print(f"# Монтажный лист — «правило високосного года», версия {cfg['version']} (hook{key[-1]})\n")
print(f"Хук: `videos/18/hook{key[-1]}.mov` — {cfg['title']}")
print(f"Тело: кадры {cut_f}+ из `assets/_video_leap.mp4`, не пересобиралось.")
print(f"Готовый ролик: `{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · {total:.2f}с\n")
print(f"**Точка реза в старом ролике:** кадр {cut_f} = **{cut:.4f}с** "
      f"(граница плана {edge_t:.2f}с), стык планов "
      f"{edge_pair}. От старого начала (планы 1–{dropped_shots}, 0.00–{cut:.2f}с, "
      f"{dropped_caps} фраз) не осталось ни кадра, ни субтитра.\n")
print(f"**Блок хука:** {nf_hook} кадров = {hook_len:.4f}с · {n_hook_shots} плана · "
      f"первый рез {cfg['shots'][0][1]:.2f}с")
print(f"**Всего планов:** {len(shots)} · средняя {sum(lens)/len(lens):.2f}с · "
      f"мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · лицо {100*face/total:.0f}%")
print(f"**Уникализация:** трек `{os.path.basename(cfg['music'])}` + {post}\n")

print("## Почему режем именно здесь\n")
if key == "h1":
    print("Дубль пересказывает не только старое начало, но и два следующих бита тела: "
          "«всем же говорили, что год високосный, если он делится на 4» повторяет "
          "бит 2.98–6.60, а «оказывается, это не совсем так» — бит 6.60–8.08 "
          "(«но это правило не полное»). Оставить их значило бы сказать «не совсем так» "
          "и сразу «не полное» — заикание в первые же секунды.\n")
    print("**Но и рез по 8.08 не годится.** Тело тогда начинается с «и если бы **им** "
          "пользовались без исключений», а слова «правило» в этом дубле нет вообще — "
          "местоимению не на что опереться, и фраза повисает: чем пользовались? "
          "Поэтому выброшено всё это предложение целиком, вместе с «календарь со временем "
          "начал бы немного съезжать», то есть планы `noexc` и `drift` (8.08–12.84). "
          "Режем по **12.84**, тело начинается с «дело в том, что год длится неровно».\n")
    print("Слово «правило» дальше звучит само на 24.02 («правило каждый четвёртый год "
          "слегка перебарщивает с поправкой») — там контекст уже набран, и опереться "
          "на него есть на что.\n")
    print("**Звук тела взят на 0.087с раньше кадра реза.** Слово «дело» начинается "
          "на 12.825, то есть ДО кадра реза 12.8667: взять звук ровно с реза значило бы "
          "срезать взрыв «д». Сдвиг компенсирован укорочением тишины в хвосте хука "
          "ровно на ту же величину, поэтому A/V-синхрон не уехал ни на кадр. "
          "Форма атаки слова в сданном файле совпадает с оригиналом "
          "(0.12 → 0.22 → 0.49 → 0.73 по огибающей).\n")
else:
    print("Дубль доходит ровно до конца бита «…если он делится на 4» и не трогает "
          "бит «но это правило не полное». Поэтому режем по 6.60 — граница планов "
          "`div4` → `A1`, и тело начинается с «но это правило не полное», что прямо "
          "продолжает хук.\n")
    print("Рез по границе плана, а не по слову: план `div4` кончается на 6.60, "
          "первое слово тела («но») стоит ровно в кадре реза.\n")
PAUSE = {"h1": (6.48, 6.625, 0.145, ""),
         "h2": (6.64, 6.875, 0.235, " (в сданном файле 0.23с — версия ускорена ×1.02)")}
sp_end, body_on, pause, note = PAUSE[key]
print(f"**Пауза между хуком и телом.** В дубле речь идёт до самого конца файла, "
      f"поэтому длина блока хука задана кадрами: {nf_hook} кадров = {hook_len:.3f}с. "
      f"Последнее слово хука кончается на {sp_end:.2f}с, первое слово тела начинается "
      f"на {body_on:.3f}с — пауза **{pause:.2f}с**{note}. Хвост добит графическим планом "
      "`div4`, а не стоп-кадром лица: A-roll там уже кончился, но сетку рисует движок.\n")

print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(shots, 1):
    rec, desc = NAMES[kind]
    if prm.get("clip"):
        desc = SB.STOCK_NAMES[prm["clip"]]
    src_caps = [(a / tsc, b / tsc, r, s) for a, b, r, s in
                (cfg["caps"] if i <= n_hook_shots else
                 [(x + dt, y + dt, r, s) for x, y, r, s in SB.CAPS])]
    txt = " / ".join("".join(r[0] for r in runs).strip()
                     for (a, b, runs, _s) in src_caps if t0 - 1e-6 <= a < t1)
    if not txt:
        txt = "— (пауза в речи)" if kind in SB.FACE_KINDS else "— (говорит графика)"
    mark = " **(хук)**" if i <= n_hook_shots else ""
    print(f"| {i}{mark} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | {txt} |")

print("\n## Что сделано с хуком")
print("- **Приведение формата не понадобилось.** Дубль 720×1280 `yuv420p` / "
      "`color_range=tv` / `bt709` — байт в байт те же теги, что у основного исходника. "
      "Сверено `ffprobe` до сборки.")
print("- **Тракт A-roll штатный:** те же `FRAMINGS`, тот же безусловный `hflip`, "
      "грейда нет — как и в основном ролике. Ни одной поправки под дубль.")
print("- **Зеркальность проверена по кадру:** рука с петличкой входит в сырой кадр "
      "справа во всех трёх файлах, штатный `hflip` подходит всем.")
print("- **Тишину в голове не срезали** — речь в дубле начинается с первых кадров.")
print("- **Графика хука — та же**, что стояла в старом начале: `div4` (шкала лет, "
      "каждый четвёртый год получает день) плюс та же стоковая вставка с классом "
      "(mixkit 6636). Менять визуальную интригу незачем.")
print("- **Скорость анимации подогнана под длину плана** (`lts`), чтобы движение "
      "доигрывало ровно к резу, а не обрывалось и не замирало.")

print("\n## Расхождение дублей — измерено, не исправлено")
print("Хук снят отдельным дублем. По правилу START-HERE это НЕ правится кропом "
      "и лутом — расхождение называется цифрами, решение за съёмочной стороной.\n")
print("| что | основной дубль | хук | норма |")
print("|---|---|---|---|")
print("| формат | 720×1280 `tv` `bt709` | тот же | — |")
print(f"| ширина лица (детектор) | 302px | {cfg['face_d']}px | "
      f"разница {abs(cfg['face_d']-302)/302*100:.1f}% |")
print(f"| линия глаз по кадру | y=640 | y={cfg['face_y']} | "
      f"разница {abs(cfg['face_y']-640)}px |")
print(f"| средний RGB в карточке A | 124.6/112.0/105.9 | {cfg['rgb']} | до ~10 единиц |")
print("\n**Дубли сошлись.** Крупность отличается на "
      f"{abs(cfg['face_d']-302)/302*100:.1f}%, линия глаз — на {abs(cfg['face_y']-640)}px, "
      "экспозиция — в пределах 3 единиц по каналу при норме ~10. Свет, точка и "
      "дистанция на съёмке те же, что в основном дубле. Править нечего.")

print("\n## Звук")
print(f"- Дорожка пересобрана целиком: голос хука + голос тела с {cut:.2f}с, "
      "постель (whoosh / impact / tick) со сдвигом, музыка с нуля, потом loudnorm.")
print("- Голос хука приведён по RMS к голосу тела "
      f"(×{0.959 if key == 'h1' else 1.074:.3f}).")
if key == "h2":
    print("- Музыка `song1.mp3` — 9.5с, короче ролика, поэтому идёт петлёй "
          "с кроссфейдом 0.25с (5.2 круга). Это единственный трек в `audios/`, "
          "который остался незанятым: `song3` стоит в версии 1, `song2` — в версии 2. "
          "Если петля мешает — нужен четвёртый трек длиннее 47с.")
else:
    print("- Музыка `song2.mp3` (335с) — своя на эту версию, длиннее ролика, "
          "петли нет.")
print("- Уровень −19 dB от RMS голоса, фейды 0.8 / 2.0с, без дакинга.")
print(f"- Целевая громкость — как у оригинала ролика ({H.TARGET_LUFS} LUFS), "
      "а не абстрактные −14.")

print("\n## Результаты проверок на сданном файле")
print("| проверка | результат | норма |")
print("|---|---|---|")
print(f"| текст ярче 200 вне карточки | **{qa['bright']} кадров** | 0 |")
print(f"| графика × субтитры блока хука | **{qa['gfx']} кадров** | 0 |")
print(f"| субтитры хука вне карточки | **{qa['textcard']} кадров** | 0 |")
print(f"| пересечение строк в блоке хука | **{qa['lines']} пар** | 0 |")
print(f"| от старого хука не осталось кадров | планы 1–{dropped_shots} и "
      f"{dropped_caps} фраз выброшены целиком | 0 |")
print(f"| тело совпадает с версией 1 | {qa['body']} | кадр в кадр |")
print(f"| щелчок на стыке | {qa['seam']} | нет |")
print(f"| деформация версии измерена | {qa['deform']} | ×1.0204 / fps 30 |")
print(f"| громкость | {qa['loud']} | как у оригинала (-14.1 LUFS, -1.6 dBTP) |")
print("\nВерсия 1 (`leap_edit.mp4`) не тронута — файл тот же, что сдавали.")
