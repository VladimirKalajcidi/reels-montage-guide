"""Генерирует монтажный лист ролика 24 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard24 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS, MEAN_Y,
                          DEV_TALL, SEG_GENE, SEG_LUCK, CHILD_LUCK, DEV_CHILD)
import render24

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "tallPair": ("R4+R10", "сетка: линия среднего, точка родителя высоко над ней, "
                           "точка ребёнка заметно ниже; пунктир на родительском "
                           "уровне показывает, насколько ниже"),
    "statCloud": ("R4+R10", "сетка: результаты каскадом рассыпаются вокруг линии "
                            "среднего"),
    "spread": ("R4+R10", "сетка: то же облако приглушено, четыре крайние точки "
                         "подсвечены, от каждой пунктир до линии среднего"),
    "pullMean": ("R4+R10", "сетка: от крайних точек растут стрелки к линии среднего, "
                           "на их концах появляются **синие** точки — следующее "
                           "поколение приходит ближе к среднему"),
    "sumBar": ("R4+R10", "сетка: столбик от линии среднего — сначала сплошной "
                         "сегмент, затем пунктирный поверх него"),
    "tallBar": ("R4+R10", "сетка: весь столбик целиком, пунктир по обе стороны "
                          "отмечает уровень его вершины"),
    "genesLit": ("R4+R10", "сетка: подсвечен нижний, сплошной сегмент, скобка слева "
                           "берёт только его"),
    "randomLit": ("R4+R10", "сетка: подсвечен верхний, пунктирный сегмент, затем "
                            "скобка раскрывается на весь столбик — сложились оба"),
    "inherit": ("R4+R10", "сетка: два столбика; от сплошного сегмента родителя "
                          "стрелка к ребёнку, у ребёнка вырастает такой же сплошной "
                          "сегмент; вторая стрелка, от пунктирного сегмента, "
                          "перечёркнута"),
    "childRes": ("R4+R10", "сетка: пунктирный сегмент ребёнка вырастает коротким, "
                           "его вершина — **синяя** и стоит ниже родительской; "
                           "пунктир и стрелка показывают разницу"),
    "topDown": ("R4+R10", "сетка: точка высоко над линией, стрелка вниз-вправо "
                          "к **синей** точке ближе к линии"),
    "bottomUp": ("R4+R10", "сетка: точка низко под линией, стрелка вверх-вправо "
                           "к **синей** точке ближе к линии"),
    "wobble": ("R4+R10", "сетка: ряд попыток одного человека — ломаная скачет "
                         "вокруг линии среднего"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «регрессия к среднему»\n")
    print(f"Исходник: `videos/24/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/24/regress_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих чисел: 0** (в речи не звучит ни одного числа)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa24.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]] + f" (с {prm.get('ss', 0):.1f}с клипа)"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи и ни одной цифры.** Слова несёт только "
          "субтитр, графика несёт то, чего в словах нет:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print(f"| горизонтальный пунктир поперёк кадра (y {MEAN_Y}) | среднее |")
    print("| точка | один человек / один результат; её высота над линией = отклонение |")
    print(f"| сплошной сегмент столбика ({SEG_GENE}px) | наследуемая часть отклонения |")
    print(f"| пунктирный сегмент столбика ({SEG_LUCK}px у родителя, "
          f"{CHILD_LUCK}px у ребёнка) | случайная часть отклонения |")
    print(f"| полная высота столбика | {DEV_TALL}px у родителя, {DEV_CHILD}px "
          "у ребёнка — «в среднем чуть ниже» |")
    print("| стрелка к линии среднего | движение к среднему |")
    print("| крест на стрелке | эта часть не передаётся |")
    print("| скобка слева от столбика | какой кусок отклонения сейчас обсуждается |")
    print("\nПоэтому проверка «одно и то же не пишется дважды» здесь проходит "
          "по построению: пересечься субтитру и графике нечем. Машинная проверка "
          "пересечения слоёв (`qa24.gfx_text_overlap`) — 0 кадров, графика "
          "не выходит из зоны y700…1560 / x175…905 (`qa24.gfx_in_zone`) — 0 кадров.")

    print("\n## Цвет")
    print("- **Синих чисел ноль**, потому что в речи нет ни одного числа. "
          "Синим (#3B4BE8) окрашен **результат** — то, что получилось в следующем "
          "поколении или в следующей попытке: планы `pullMean`, `childRes`, "
          "`topDown`, `bottomUp`. Это один и тот же смысл, показанный четыре раза, "
          "а не четыре разных синих объекта.")
    print("- **Лайм #C3DB4E не используется.** В гайде он «максимум один элемент "
          "на ролик», то есть верхняя граница, а не обязательство: осмысленного "
          "одиночного применения в этой схеме нет, и третий цвет здесь только "
          "спорил бы с синим результатом.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt. Верх шкалы `brand-kit §3` "
          "(XL 150–200 под число-ревил) не задействован: числа-ревила в этом ролике "
          "нет, показывать XL нечего.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт под "
          "четырьмя ревилами синего результата (0.070), тики под каскадами "
          "элементов (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume/alimiter.")
    print("- Замер готового `.mp4`: **-14.1 LUFS**, истинный пик **-1.6 dBTP** — в цели.")
    print("- **LRA 2.5 LU** при норме гайда 3–5. Это свойство дубля: речь идёт очень "
          "ровно, без громких и тихих мест (у ролика 22 было 2.3 LU на том же "
          "тракте). Лимитером и loudnorm не лечится — фиксирую замер, а не правлю.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/24/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nПолоса субтитров в карточке B замерена до сборки, на притемнённом "
          "кадре (`brand-kit §6`, gain 0.72): 47005 — средняя 76 / p90 118, "
          "46749 — 37 / 67, 20468 — 46 / 120 при пороге ≤110 / ≤140. "
          "Все три проходят: белый текст со свечением на них читается.")
    print("\nПервым кандидатом на «богатых» стоял mixkit 18305 (купюры падают "
          "на чёрном фоне): по яркости он лучше всех (25 / 68), но на собранном "
          "кадре карточка B оказалась почти пустой — в 2.3с окне купюр в кадре "
          "занято 24–29% площади, и вставка читалась как чёрный провал, "
          "а не как деньги. Заменён на 47005, где кадр заполнен на 74%.")
    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render24). Кроп посчитан по детектору: 35 замеров "
          "по всему дублю дали cx 398±7, линию глаз y 640±6, ширину лица 282±5 — "
          "глаза стоят на 42.0% высоты карточки у A1 и на 41.5% у A2.")
    print("Ширину A1 ограничивает сам кадр: лицо стоит правее центра (cx 398 "
          "из 720), поэтому симметричный кроп шире 644px из исходника "
          "не вырезается.")
    print("\nПолоса субтитров на лице (y1270…1420 внутри карточки A) замерена: "
          "A1 — средняя **124**, p85 **170**; A2 — **133** / **178**. "
          "У сданного ролика 22 на том же тракте было 122 / 165 и 128 / 168, "
          "то есть это штатный уровень канала, а не просадка этого дубля. "
          "Рука с петличкой в этом дубле поднята выше обычного и часть строк "
          "ложится на неё; гамму и грейд не трогаю — `brand-kit §6` держит "
          "лицо без коррекции, а плашек под текст в стиле нет.")
    print("\nЗеркальность: в кадре нет ни одной надписи, по которой её можно "
          "проверить (голая стена и однотонная футболка), поэтому `hflip` стоит "
          "штатно — как во всех предыдущих роликах этого канала.")


if __name__ == "__main__":
    emit()
