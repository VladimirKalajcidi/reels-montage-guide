"""Монтажный лист версии ролика 19 с другим хуком.

    python3 plan19hook.py h1 > ../videos/19/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard19 as SB
from hook19 import HOOKS, CUT, CUT_F
from plan19 import NAMES

HOOK_STOCK = {
    "49137": "женщина с тележкой выбирает продукты в торговом зале (mixkit 49137)",
    "15914": "оплата картой на терминале, рядом пакет с покупками (mixkit 15914)",
}

MEASURED = {
    "h1": dict(lufs=-13.90, tp=-1.80, deform="кроп ×0.98 — панель QR 558px → 570px = ×1.0215 "
                                              "(целевое ×1.0204, расхождение — 1px квантования)",
               frames=1719, dur=57.30, pause=0.155, seam=(0.00354, 0.24790)),
    "h2": dict(lufs=-13.90, tp=-1.50, deform="ускорение ×1.02 — 1657 кадров → 1625, "
                                              "r_frame_rate ровно 30/1, звук ускорен вместе "
                                              "с картинкой (видео 54.167с, аудио 54.156с)",
               frames=1625, dur=54.167, pause=0.156, seam=(0.00580, 0.24857)),
}


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    dt = nh - CUT

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/19/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.2f}с · {m['frames']} кадров")
    print(f"Хук: `videos/19/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с)")
    print(f"Тело: кадры {CUT_F}+ из уже сданного `qr_edit.mp4`, не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")

    print("## Точка реза")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `A2` → `qrbuild` в исходном ролике. "
          "Это конец старой хуковой фразы «и вот почему это так работает» (слово кончается "
          "на 7.26, план — на 7.5667). Планы 1–5 старого начала и все их субтитры выброшены "
          "целиком: от старого хука не осталось ни кадра.")
    print("\nРезать по границе плана, а не по слову, здесь ничего не стоило: оба новых дубля "
          "кончаются на «и вот как это работает» — той же передачей эстафеты, что была в "
          "старом начале. Фразу тела трогать не пришлось, тело начинается с «QR-код выглядит "
          "как случайный узор из чёрных квадратиков».")
    print("\nJ-cut не нужен: предыдущая фраза реально смолкает на 7.138с, первое слово тела "
          "реально начинается на 7.590с (замерено по огибающей, не по whisper). "
          "Рез по 7.5667 попадает в паузу и ничего не срезает.\n")

    print("## Блок хука")
    print(f"{len(cfg['shots'])} планов · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"первый рез **{lens[0]:.2f}с** · мин {min(lens):.2f}с · макс {max(lens):.2f}с\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    for i, (t0, t1, kind, _p) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        if _p.get("clip"):
            desc = HOOK_STOCK[_p["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")

    print(f"\nДалее без изменений идёт тело сданного ролика — планы 6–26, "
          f"со сдвигом **+{dt:.4f}с** на новой таймлинии.\n")

    print("## Графика хука")
    print("Гайд велит брать ту же графику, что стояла в старом хуке (`qrlogo` — символ под "
          "логотипом, `qrok` — луч и галка). **Здесь взяты `qrworn` и `qrok2`** — потрёпанный "
          "символ и луч с галкой по нему.")
    print("\nПричина: оба новых дубля говорят «порван или помят», а старая графика показывает "
          "символ, закрытый логотипом. Логотип под словами «порван или помят» — ровно тот "
          "дефект, который запрещает `anti-patterns.md` («графика должна быть похожа на то, "
          "что произносится»). Ни одного нового плана при этом не нарисовано: `qrworn` и "
          "`qrok2` уже есть в ролике и стоят на вердикте в конце — начало и финал стали рамкой. "
          "Если хочется вернуть логотип — это правка двух строк в `hook19.py`.")
    print("\n## Сток в хуке")
    print("Под слова про магазин и кассу стоят две буквальные вставки:\n")
    print("- `stock_49137.mp4` — женщина с тележкой выбирает продукты в торговом зале "
          "(mixkit 49137, «young woman looking for discounts at the supermarket»);")
    print("- `stock_15914.mp4` — оплата картой на терминале, рядом пакет с покупками "
          "(mixkit 15914, «woman pays cashier with credit card in shop»).")
    print("\n**Оговорка по второму клипу:** это касса с терминалом, а не касса "
          "самообслуживания. Клипов с самообслуживанием на Mixkit нет вообще "
          "(`self-checkout`, `checkout` — пусто), а это ближайшее буквальное попадание "
          "в слово «касса». Для хука 2 («пробьёте на кассе») совпадает точно.")
    print("\n**Исправление к первой сборке версий.** В прошлой сдаче я написал, что "
          "релевантного стока под супермаркет на Mixkit нет. Это было неверно — виноват мой "
          "парсер выдачи: он брал id из списка mp4-ссылок соседних блоков страницы и "
          "сопоставлял их с чужими подписями. Реальный id клипа лежит в слаге "
          "(`...-supermarket-49137/#video`). По исправленному поиску `supermarket` даёт пять "
          "клипов, `cashier` — ещё пять. Перепроверил заодно и основной ролик: `coffee` → 236 "
          "и `puzzle` → 42185 совпали с тем, что уже стояло, а `qr-code` / `scanner` / "
          "`barcode` действительно пусты — там графика остаётся единственным вариантом.\n")

    print("## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, и основной "
          "исходник — 720×1280, `yuv420p`, `color_range=tv`, `bt709`/`bt709`/`bt709`, 30 fps. "
          "Поэтому кадры читаются прямо из `.mov` и идут в штатный тракт A-roll "
          "**без единого промежуточного кодека** (в ролике 17 хуки приходили в полном "
          "диапазоне и требовали отдельного прохода).")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip): основной дубль cx 377 / линия глаз 650 / "
          f"размер лица 289; этот хук cx {cfg['face_cx']} / {cfg['face_eye']} / {cfg['face_d']}. "
          "Расхождение до 16px по горизонтали, 10px по линии глаз и 3% по размеру лица. "
          "Кропом не правилось — это к съёмочной стороне, но расхождение мелкое.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуках, проверить "
          "по тексту не на чем. Штатный `hflip` оставлен: рука с петличкой во всех трёх дублях "
          "с одной стороны кадра.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука против кадров тела расходятся "
          f"не больше чем на 2 единицы по каналу (норма — до ~10).\n")

    print("## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек, у остальных версий другие "
          "(v1 `song3.mp3`, v2 `song2.mp3`, v3 `song1.mp3`).")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались.\n")

    print("## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, постель "
          f"(whoosh / impact / tick) со сдвигом **+{dt:.4f}с**, музыка с нуля, потом loudnorm.")
    print("- Whoosh стоит и на резах внутри хука, и на самом шве «хук → тело».")
    print(f"- Пауза между последним словом хука и первым словом тела: **{m['pause']:.3f}с** "
          "(норма 0.10–0.20).")
    print(f"- Стык без щелчка: скачок между соседними сэмплами на шве {m['seam'][0]:.5f} "
          f"против {m['seam'][1]:.5f} на 99.99-м процентиле всей дорожки.")
    print(f"- Громкость **{m['lufs']:.2f} LUFS**, истинный пик **{m['tp']:.2f} dBFS** — "
          "сведено к уровню уже сданного `qr_edit.mp4` (−13.80 / −1.70), а не к абстрактным −14.\n")

    print("## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa19hook.py {key}")
    print("```")
    print("Все по нулям: `gfx_text_overlap_frames=0`, `gfx_out_of_zone_frames=0`, "
          "`text_out_of_card_frames=0`, `bright_outside_card_frames=0`.")
    print("- Тело против сданной версии — худший PSNR 43.8 dB на 10 контрольных кадрах "
          "(это второе прохождение того же кодека, картинка та же).")
    print("- QR на плане `qrok2` в хуке читается декодером **3 кадра из 3** даже после "
          "деформации версии: галка не врёт.")
    print("- Версия №1 не тронута: `qr_edit.mp4` тот же файл, "
          "sha256[:16] = `af6b6d7ff0a8a500`, 26 177 296 байт.")


if __name__ == "__main__":
    emit(sys.argv[1])
