"""Монтажные листы версий ролика 33 с другими хуками.

    python3 plan33hook.py h1 > ../videos/33/montage-plan-hook1.md
    python3 plan33hook.py h2 > ../videos/33/montage-plan-hook2.md
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import storyboard33 as SB
from style import FPS
from hook33 import HOOKS, CUT_F, CUT_V, CUT_A, shots_of
from plan33 import NAMES as BASE_NAMES

# в блоке хука план `people` идёт без числа: белое «100» всплывает на lt=1.60,
# то есть уже в теле
NAMES = dict(BASE_NAMES)
NAMES["people"] = ("R4+R10", "сетка: сто фигурок занимают узлы решётки 10×10; "
                             "числа в блоке хука нет — белое **100** всплывает "
                             "уже в теле")

# замеры сданных файлов
MEAS = {
    "h1": dict(lufs=-13.97, tp=-1.58, frames=1640, dur=54.667,
               card_w=888, card_h=1409, rgb=(123, 110, 103),
               speech_end=3.0006, tail_db=-21.7),
    "h2": dict(lufs=-14.14, tp=-1.61, frames=1600, dur=53.333,
               card_w=870, card_h=1380, rgb=(121, 108, 100),
               speech_end=2.7177, tail_db=-30.2),
}
MAIN_RGB = (125, 111, 104)
MAIN = dict(lufs=-13.9, tp=-1.6, frames=1631, card_w=870, card_h=1380)


def emit(key):
    cfg = HOOKS[key]
    m = MEAS[key]
    shots = shots_of(cfg)
    seam = cfg["frames"] / FPS
    dt = seam - CUT_V
    a1 = cfg["a1_frames"] / FPS
    words = json.load(open(f"/Users/vladimirkalajcidi/reels_good/videos/33/"
                           f"words_{os.path.basename(cfg['src']).split('.')[0]}.json"))
    text = " ".join(w["word"] for w in words)
    pause = seam + (2.8424 - CUT_A) - m["speech_end"]
    n = int(key[1])

    print(f"# Монтажный лист — версия {cfg['version']}, хук {n}\n")
    print(f"Готовый ролик: `videos/33/{os.path.basename(cfg['out'])}` · 1080×1920 · "
          f"30 fps · {m['frames']} кадров · {m['dur']:.2f}с")
    print(f"Исходный ролик: `videos/33/boxes_edit.mp4` (версия 1) — **не тронут**, "
          f"файл тот же, что сдавали.")
    print(f"Дубль хука: `videos/33/hook{n}.mov` · 720×1280 · 30 fps · "
          f"{cfg['src_frames']/FPS:.4f}с · SDR bt709, теги совпадают с основным "
          "исходником, конверсия не нужна\n")
    print(f"**Новое начало:** {cfg['title']}\n")

    print("## Что поменялось")
    print(f"Меняется только начало. Тело ролика — кадры с {CUT_F}-го из "
          "`assets/_video_boxes.mp4`, склеены за новым хуком одним проходом "
          "кодека; заново нарисован только блок хука. Сверка тела с версией 1 "
          "по шести контрольным кадрам: средняя разница 0.19–0.94 из 255, "
          "пикселей с расхождением >16 — **0.001%**. Это шум кодека, "
          "не пересборка.\n")

    print("## Точка реза")
    print("Старое начало — «это одна из самых безумных задач по вероятности» "
          "(0.000–2.449). Оно занимает план `A1` 0.000–1.746 **и хвостом "
          "заходит** в план `people` 1.746–3.873: решётка из ста фигурок "
          "начинает собираться ещё под словами «по вероятности». Тело "
          "начинается внутри того же плана — «итак есть 100 заключённых», 2.842.")
    print("\nПоэтому «резать по границе плана» здесь буквально нельзя, "
          "и оба соседних варианта плохи:")
    print("- рез по **1.746** оставил бы в версии повисший хвост старой фразы "
          "«по вероятности» — без начала предложения;")
    print("- рез по **3.873** выбросил бы вместе с хвостом и «итак есть 100 "
          "заключённых», то есть саму постановку задачи: ни один из новых "
          "дублей сотню не вводит.")
    print(f"\nРез поставлен по речевой границе **{CUT_A:.3f}** (кадр {CUT_F}) — "
          "в тишине 2.449–2.842, за 9мс до атаки слова «Итак». Огибающая "
          "исходника (шаг 10мс): 2.80 −73 дБ, 2.81 −61, 2.82 −49, 2.83 −42, "
          "2.84 −28 дБ. Голос и картинка тела берутся с одной и той же точки, "
          "смещения между ними нет.")
    print("\nОт старого хука не осталось ни кадра лица, ни одного его субтитра: "
          "блок «по вероятности» срезан на 2.449, следующий стартует только "
          "на 2.842 — на кадре реза `caption_layer` пуст.")

    print("\n## Шов не читается")
    print(f"Блок хука **кончается тем же планом `people`**, что идёт в теле: "
          f"последние {cfg['frames'] - cfg['a1_frames']} кадров блока — та же "
          "решётка, отрисованная той же функцией `render33.g_people`. Каскад "
          "фигурок кончается на lt≈0.77, а в теле план подхватывается на "
          "lt=1.087 — по обе стороны шва решётка уже собрана и неподвижна.")
    print("Фон-сетка на этих кадрах считается обратным отсчётом от шва "
          "(`t_grid = CUT_A − (N − f)/30`), иначе на шве прыгнула бы фаза "
          "её дрейфа.")
    print(f"Замер: средняя |разница| соседних кадров в зоне графики на шве "
          f"(кадры {cfg['frames']-1}→{cfg['frames']}) — **1.11**, ровно та же, "
          "что у обычных соседних кадров внутри плана (1.13). "
          "Визуального реза на шве нет, поэтому **whoosh туда не ставится**.")
    print(f"Белое «100» всплывает на lt=1.60, то есть уже в теле; в блоке хука "
          "чисел нет.")

    print("\n## Блок хука\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, _p) in enumerate(shots, 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.3f}–{t1:.3f} | {t1-t0:.3f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")
    print(f"| — | {seam:.3f}–{m['dur']:.2f} | — | тело | кадры {CUT_F}+ из версии 1, "
          f"без изменений | как в версии 1 |")

    print(f"\nРечь дубля: «{text}»")
    print(f"\nОба дубля — сплошная речь без единой паузы (`silencedetect` "
          "-34dB/0.12с не нашёл ничего), поэтому единственный рез блока "
          f"поставлен на ближайшую границу слов: **{a1:.4f}** против "
          f"{'1.953 («вероятности»/«совсем»), промах 14мс' if key=='h1' else '1.956 («теории»/«вероятностей»), промах 11мс'}. "
          "Меньше 20мс — в середину слова рез не попал.")
    if key == "h2":
        print("\nНа графическом плане блока субтитра нет: после реза в дубле "
              "остаётся одно слово «вероятностей», на фразу из 2–4 слов оно не "
              "бьётся, а вести его в предыдущий блок нельзя — субтитр обогнал "
              "бы речь. План несёт графика (`brand-kit §5`).")

    print("\n## Передача эстафеты")
    print("Тело начинается самостоятельным предложением «итак, есть 100 "
          "заключённых и 100 закрытых коробок»: своё подлежащее, ни одного "
          "местоимения, отсылок к выброшенному тексту нет. Новый дубль кончается "
          "на «задач(к)е по теории вероятности» и ведёт ровно туда же, куда "
          "вело старое начало.")

    print("\n## Пауза хук → тело")
    print(f"Речь дубля кончается на {m['speech_end']:.4f} (это же конец файла), "
          f"блок хука длится {cfg['frames']} кадров = {seam:.4f}с, слово «Итак» "
          f"в версии приходится на {seam + (2.8424 - CUT_A):.4f}. "
          f"Пауза **{pause:.3f}с**"
          + (f" (после ускорения ×1.02 — {pause/1.02:.3f}с)" if key == "h2" else "")
          + " — в диапазоне 0.10–0.20с из `delivery-specs §6`.")
    print(f"Кадры сверх дубля ({cfg['frames'] - cfg['src_frames']} шт.) добиты "
          "графическим планом, лицо не морожено.")
    print(f"\nСкачок между соседними сэмплами на стыке — "
          f"{'0.00156' if key == 'h1' else '0.00015'} при p99.9 внутри дорожки "
          f"{'0.056' if key == 'h1' else '0.066'}: щелчка нет.")

    print("\n## A-roll хука — штатный тракт, без поправок")
    print("Дубль идёт через те же `FRAMINGS` (окно 630×1000 от 57, 264), тот же "
          "`hflip`, без грейда — ровно как основной исходник.\n")
    print("| | cx | линия глаз | ширина лица | средний RGB в карточке A |")
    print("|---|---|---|---|---|")
    print(f"| основной дубль | 372 | 684 | 273 | {MAIN_RGB[0]} / {MAIN_RGB[1]} / {MAIN_RGB[2]} |")
    print(f"| **hook{n}** | {cfg['face_cx']} | {cfg['face_eye']} | {cfg['face_d']} "
          f"| {m['rgb'][0]} / {m['rgb'][1]} / {m['rgb'][2]} |")
    d = max(abs(a - b) for a, b in zip(m["rgb"], MAIN_RGB))
    print(f"\nРасхождение по среднему RGB карточки A — **{d} единицы** при норме "
          "до ~10: дубли сняты в одной сцене при том же свете. Крупность "
          f"расходится на {abs(cfg['face_cx']-372)}px по центру и "
          f"{abs(cfg['face_eye']-684)}px по линии глаз — это уровень разброса "
          "между дублями, кропом не правится (`START-HERE`).")
    print("Зеркальность проверена по кадру: надпись на футболке после штатного "
          "`hflip` читается нормально.")

    print("\n## Уникализация версии")
    print(f"- **Музыка:** `audios/{os.path.basename(cfg['music'])}` — свой трек, "
          "у версии 1 `song2.mp3`, у другой версии — третий. Ни один не повторяется.")
    if key == "h1":
        print("- **Деформация:** кроп ×0.98 (`crop=iw*0.98:ih*0.98` + возврат "
              "холста 1080×1920).")
        print(f"  Замер: карточка A в версии 1 — **{MAIN['card_w']}×{MAIN['card_h']}px**, "
              f"в этой версии — **{m['card_w']}×{m['card_h']}px**, то есть "
              f"×{m['card_w']/MAIN['card_w']:.4f} и ×{m['card_h']/MAIN['card_h']:.4f} "
              "при ожидаемых ×1.0204. Деформация применена и измерена.")
    else:
        print("- **Деформация:** ускорение ×1.02 — `setpts=PTS/1.02,fps=30` "
              "по картинке и `atempo=1.02` по звуку **вместе**, липсинк не едет.")
        print(f"  Замер: {cfg['frames']} + 1546 = 1632 кадра до ускорения, "
              f"после — **{m['frames']}** (1632/1.02 = 1600.0). "
              f"`r_frame_rate` = **30/1**, не 30.6. Длительности сходятся: "
              f"видео {m['dur']:.3f}с, звук 53.322с.")
        print("  Геометрия не тронута: карточка A по-прежнему "
              f"{m['card_w']}×{m['card_h']}px, как в версии 1.")

    print("\n## Звук")
    print("Дорожка пересобрана целиком, а не склеена из готовых: голос хука + "
          f"голос тела с {CUT_A:.3f}, постель (whoosh/impact/tick) со сдвигом "
          f"{dt:.4f}с, музыка с нуля, потом loudnorm.")
    print(f"- Громкость голоса дубля выровнена по телу: ×"
          f"{'1.067' if key == 'h1' else '1.007'} по RMS речевых участков.")
    print(f"- Whoosh на резе блока хука ({a1:.3f}) и на каждом резе тела "
          f"со сдвигом; на шве whoosh не ставится — реза там нет.")
    print("- Тики под каскадом решётки в блоке хука и под каскадами тела; "
          "импакты под четырьмя ревилами чисел тела.")
    print(f"- Замер готового `.mp4`: **{m['lufs']} LUFS**, истинный пик "
          f"**{m['tp']} dBTP**. Ориентир — громкость версии 1 "
          f"({MAIN['lufs']} LUFS), а не абстрактные −14.")
    if key == "h2":
        print("  Итерация +1.02 dB дала −13.97 LUFS, но выбила истинный пик "
              "до **+1.14 dBTP** (и +1.09 dB → +1.59 dBTP); такая версия не "
              "отдаётся, вернулись к предыдущей, прошедшей по пику.")

    print("\n## Что осталось от дубля и не чинится монтажом")
    print(f"Речь в `hook{n}.mov` идёт до последнего сэмпла файла: последние 10мс "
          f"на уровне **{m['tail_db']} дБ** при пике дубля около −9 дБ. "
          + ("То есть последний гласный слова «очевидно» обрезан самой записью — "
             "на 25 дБ ниже пика звук просто кончается. "
             if key == "h1" else
             "Хвост слова «вероятностей» затухает, но тоже упирается в конец файла. ")
          + "Монтаж этого не восстановит: подложен штатный фейд 8мс, щелчка нет, "
          "но слово звучит подрезанным. Решение — переписать дубль с запасом "
          "0.3–0.5с тишины в хвосте.")
    print("\nПолоса субтитров на планах с лицом в этой версии та же, что "
          "в версии 1 (белая футболка, дневной свет): средняя ~172, p90 ~219 "
          "при пороге ≤110 / ≤140. Подробности и почему это не чинится "
          "монтажом — в `montage-plan.md`.")


if __name__ == "__main__":
    emit(sys.argv[1])
