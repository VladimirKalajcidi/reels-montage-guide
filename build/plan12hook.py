"""Монтажные листы версий ролика 12 с другими хуками.

    python3 plan12hook.py h1 > ../videos/12/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import storyboard12 as SB
import hook12 as HK
import qa12hook as QA
from style import FPS

# NAMES не импортируется из plan12: тот модуль печатает весь монтажный лист
# на уровне модуля, и его вывод попал бы в начало этого файла
NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена дубля)"),
    "shape": ("R4+R10", "сетка: многоугольник обводится и заливается площадью"),
    "formulas": ("R4+R10", "сетка: три школьные формулы площади зачёркиваются"),
}

# замеры, сделанные при сборке (hook12.card_rgb / детектор лица / ebur128)
MEASURED = {
    "h1": dict(rgb_hook=(119, 100, 90), rgb_raw=(117, 99, 90), face=351,
               lufs=-14.19, tp=-1.73, pause=0.170, speech_end=5.030),
    "h2": dict(rgb_hook=(136, 115, 104), rgb_raw=(133, 115, 103), face=367,
               lufs=-14.19, tp=-1.77, pause=0.165, speech_end=7.500),
}
RGB_BODY = (101, 80, 69)
FACE_BODY = 404

key = sys.argv[1]
cfg = HK.HOOKS[key]
m = MEASURED[key]
nf = cfg["frames"]
hook_dur = nf / FPS
dt = hook_dur - HK.CUT
r = QA.rhythm(key)

print(f"# Монтажный лист — «формула Пика», версия {cfg['version']} (хук {key[-1]})\n")
print(f"Хук: `videos/12/hook{key[-1]}.mov` · {cfg['title']}")
print(f"Тело: готовые кадры из `assets/_video_pick.mp4` с кадра {HK.CUT_F}")
print(f"Готовый ролик: `videos/12/{os.path.basename(cfg['out'])}`\n")
print(f"**Длительность:** {r['dur']:.2f}с (блок хука {hook_dur:.2f}с + тело {SB.DUR - HK.CUT:.2f}с)")
print(f"**Планов:** {r['shots']} · средняя **{r['avg']}с** · медиана {r['median']}с · "
      f"мин {r['shortest']}с · макс {r['longest']}с · первый рез {r['first_cut']:.2f}с")
print(f"**Лицо в кадре:** {r['face_pct']}%\n")

print("## Точка реза\n")
print(f"Кадр **{HK.CUT_F}** ({HK.CUT:.4f}с) — граница плана `shape` (1.62–3.16), "
      "то есть конец старого хука «эта формула ищет площадь любой фигуры на клетке». "
      "Планы 1–2 старого начала и их субтитры выброшены целиком, ни одного кадра "
      "от них не осталось.\n")
print("**J-cut на стыке.** Резать звук ровно по границе плана нельзя: в теле слово "
      "«нарисуйте» начинается по энергии на 3.115с, и рез по 3.1667с срубил бы 50мс "
      "атаки — это слышный щелчок. Звук тела берётся с 3.100с и кладётся на 2 кадра "
      "раньше картинки: речь заходит под последние кадры хука (`editing-taste.md §2`), "
      "синхрон тела остаётся кадр в кадр.\n")

print("## Блок хука\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(cfg["shots"], 1):
    rec, desc = NAMES[kind]
    if prm.get("lts"):
        desc += f" (анимация x{prm['lts']} — план короче, чем в теле)"
    txt = " / ".join("".join(run[0] for run in runs).strip()
                     for (a, _b, runs, _s) in cfg["caps"] if t0 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | {txt or '—'} |")
print(f"\nГрафика хука — та же, что стояла в старом хуке (`shape`, многоугольник на "
      f"сетке, чью площадь ролик и ищет), плюс `formulas` там, где речь про отдельные "
      f"школьные формулы. Хвост блока добит графическим планом, а не стоп-кадром лица.\n")
print(f"Дальше идёт тело уже сданного ролика без изменений — раскадровка в "
      f"`montage-plan.md`, все тайминги там сдвигаются на **+{dt:.4f}с**.\n")

print("## Уникализация версии\n")
print(f"- Музыка: `{os.path.basename(cfg['music'])}` — свой трек, ни с одной другой "
      "версией не повторяется (версия 1 — `song3.mp3`).")
if cfg.get("post_a"):
    print(f"- Деформация: ускорение **x1.02** — `{cfg['post_v']}` по картинке и "
          f"`{cfg['post_a']}` по звуку. Замер готового файла: `r_frame_rate=30/1` "
          "(не 30.6), длительности видео и звука сходятся, геометрия кадра не тронута.")
else:
    print(f"- Деформация: кроп **x0.98** — `{cfg['post_v']}`. Замер по готовым файлам: "
          "нижнее ребро фигуры 678px в версии 1 против 692px здесь, то есть **x1.0206** "
          "при требуемых x1.0204.")
print("- Деформация наложена на уже собранное немое видео, кадры не перерисовывались.")
print("- Версия 1 (`pick_edit.mp4`) не тронута.\n")

print("## Звук\n")
print("Дорожка пересобрана целиком, а не склеена из готовых: голос хука + голос тела "
      "с точки реза, постель (whoosh / импакт / тики) со сдвигом, музыка с нуля, "
      "потом loudnorm.\n")
print(f"- Замер готового mp4: **{m['lufs']} LUFS**, истинный пик **{m['tp']} dBFS** "
      "(версия 1 — -14.1 LUFS).")
print(f"- Пауза между концом речи хука ({m['speech_end']:.2f}с) и первым словом тела — "
      f"**{m['pause']:.3f}с** (норма 0.10–0.20).")
print("- На стыке щелчка нет: скачок между соседними сэмплами 0.0017 против 0.098 "
      "в 99.99-м перцентиле по всей дорожке.")

print("\n## Расхождение дублей — измерено, не подчищено\n")
print("Хук снят в другом формате и с другой точки. Формат приведён (это свойство файла), "
      "крупность и экспозиция — нет: это решается на съёмке, а не кропом на монтаже "
      "(`START-HERE.md`).\n")
print("| | основной дубль | хук |")
print("|---|---|---|")
print(f"| разрешение / range | 1080×1920 `tv` | **720×1280 `pc`** → приведено к 1080×1920 `tv` |")
print(f"| средний RGB в карточке A | {RGB_BODY[0]}/{RGB_BODY[1]}/{RGB_BODY[2]} | "
      f"**{m['rgb_hook'][0]}/{m['rgb_hook'][1]}/{m['rgb_hook'][2]}** |")
print(f"| ширина лица в карточке A | {FACE_BODY}px | **{m['face']}px** |")
d = [m['rgb_hook'][i] - RGB_BODY[i] for i in range(3)]
print(f"\n- По цвету расхождение **+{d[0]}/+{d[1]}/+{d[2]}** при норме до ~10 единиц на канал: "
      "хук заметно светлее и площе. Приведение `pc`→`tv` на это почти не влияет "
      f"(замер: {m['rgb_raw'][0]}/{m['rgb_raw'][1]}/{m['rgb_raw'][2]} до приведения против "
      f"{m['rgb_hook'][0]}/{m['rgb_hook'][1]}/{m['rgb_hook'][2]} после) — разница именно в съёмке.")
print(f"- По крупности лицо в хуке на **{100*(1 - m['face']/FACE_BODY):.0f}% мельче**: "
      "снято дальше от камеры.")
print("- Ни то, ни другое не правилось: хук прошёл через тот же тракт A-roll "
      "(`FRAMINGS`, `hflip`, `GRADE`) без единой поправки под дубль. Решение — "
      "переснять или принять как есть — за съёмочной стороной.")
print("- Зеркальность проверена по кадру: надпись на толстовке читается задом наперёд "
      "и в основном дубле, и в обоих хуках — штатный `hflip` подходит всем трём.")

print("\n## Автопроверки\n")
print("Все по нулям: текст за карточкой, наложение строк, графика вне зоны, "
      "пересечение графики с субтитрами, текст за карточкой по габаритам глифов "
      "(`qa12hook.py`). Тело сверено с версией 1 покадрово — расхождение только "
      "шум кодека (<0.007% пикселей отличается больше чем на 12).")
