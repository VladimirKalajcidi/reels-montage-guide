"""Генерирует монтажный лист ролика 12 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard12 import SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS
import render12 as r

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена дубля)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "shape": ("R4+R10", "сетка: многоугольник обводится и заливается площадью"),
    "nodes": ("R4+R10", "сетка: вершины садятся точно в пересечения сетки, затем рёбра"),
    "tri": ("R4+R10", "сетка: замкнутый треугольник по узлам"),
    "star": ("R4+R10", "сетка: звезда из 10 вершин по узлам"),
    "formulas": ("R4+R10", "сетка: три школьные формулы площади зачёркиваются"),
    "inner": ("R4+R10", "сетка: узлы строго внутри фигуры — заполненные точки"),
    "inner_n": ("R4+R5a", "сетка: белое число внутренних точек"),
    "border": ("R4+R10", "сетка: узлы на границе — кольца"),
    "border_n": ("R4+R5a", "сетка: белое число граничных точек"),
    "f1": ("R4+R10", "сетка: собирается «S = ●»"),
    "f2": ("R4+R10", "сетка: дописывается «+ ○/2»"),
    "f3": ("R4+R10", "сетка: дописывается «− 1»"),
    "result": ("R4+R5b", "сетка: подстановка чисел и синий итог"),
    "any": ("R4+R10", "сетка: невыпуклый многоугольник, его узлы подсвечены"),
    "weird": ("R4+R10", "сетка: кривой многоугольник с диагональю, дробная площадь"),
}

face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

print("# Монтажный лист — «формула Пика»\n")
print(f"Исходник: `videos/12/source.mov` · 1080×1920 · 30 fps · {DUR:.2f}с · SDR bt709 · зеркальный дубль")
print("Готовый ролик: `videos/12/pick_edit.mp4`\n")
print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
      f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
      f"первый рез {SHOTS[0][1]:.2f}с")
print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
      f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 1 (итог {r.MAIN_AREA:.0f})\n")
print("Речь не резана: резы только по картинке, границы взяты по пословным таймингам "
      "whisper (`videos/12/source.json`).\n")
print("Зоны на планах с графикой: субтитры y 300…600, графика y 700…1560 "
      "(`brand-kit.md §5`). Где смысл несёт графика — субтитра нет.\n")

print("## Математика ролика\n")
print("Все фигуры лежат вершинами в пересечениях сетки-подложки, а числа не вписаны "
      "руками: `render12.lattice_interior` / `lattice_boundary` считают их из самого "
      "многоугольника, площадь — по формуле Гаусса. Проверка `qa12.pick_math` требует, "
      "чтобы `i + b/2 − 1` совпало с площадью на каждой фигуре.\n")
print("| фигура | где | площадь | внутри `i` | на границе `b` | `i + b/2 − 1` |")
print("|---|---|---|---|---|---|")
WHERE = {"MAIN": "основная (планы 2, 4, 10–13)", "TRI": "«хоть треугольник»",
         "STAR": "«хоть сложную звезду»", "ANY": "«любого многоугольника»",
         "WEIRD": "«каким бы кривым он не был»"}
for name in ("MAIN", "TRI", "STAR", "ANY", "WEIRD"):
    p = getattr(r, name)
    a = r.poly_area(p)
    i = len(r.lattice_interior(p))
    b = len(r.lattice_boundary(p))
    fmt = (lambda v: f"{v:.0f}" if float(v).is_integer() else f"{v:.1f}".replace(".", ","))
    print(f"| {name} | {WHERE[name]} | {fmt(a)} | {i} | {b} | {fmt(i + b/2 - 1)} |")

print("\n## Раскадровка\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
    rec, desc = NAMES[kind]
    if prm.get("clip"):
        desc = STOCK_NAMES[prm["clip"]]
    txt = " / ".join("".join(rr[0] for rr in runs).strip()
                     for (a, b, runs, _s) in CAPS if t0 <= a < t1)
    print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
          f"| {txt or '— (говорит графика)'} |")

print("\n## Звук")
print("- Речь исходника целиком, без резки.")
print("- Whoosh на каждой склейке (0.040 от пика), импакт под числом-ревилом (0.070), "
      "тики каскада (0.030).")
print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, петля с кроссфейдом 0.25с, "
      "фейды 0.8 / 2.0с.")
print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + `volume=0.7dB` + "
      "`alimiter=limit=0.80:level=disabled`.")
print("- Замер готового mp4: **-14.1 LUFS**, истинный пик **-1.7 dBFS**, LRA 1.8 LU.")

print("\n## Сток")
print("Скачан под этот ролик в `videos/12/stock/`, источник Mixkit (свободная лицензия):\n")
for cid, name in STOCK_NAMES.items():
    print(f"- `stock_{cid}.mp4` — {name}")
print("\nОстальные планы закрыты собственной графикой: тема держится на предметной "
      "механике решётки, и сток здесь был бы перебивкой ради ритма "
      "(`assets-manifest.md §2`).")

print("\n## Отступления от гайда — назвать, а не спрятать")
print("- Кривизна сетки на графических планах уменьшена (`grid_canvas(wobble=0.35)`). "
      "При штатной кривизне линия уходит от номинального пересечения до ~14px, "
      "и «вершина стоит точно в узле» перестаёт быть правдой — а весь ролик про это.")
print("- Субтитр на стоковом плане идёт от x=145, а не от базовых x=136 "
      "(`brand-kit.md §5`): жёсткое правило «отступ 30px внутрь от края карточки» "
      "даёт для карточки B границу 140, и на 136 текст за неё вылезал.")
print(f"- Лицо в кадре {100*face/DUR:.0f}% при норме «30–45%, для доказательных ближе к 30%». "
      "Ролик доказательный и короткий: любой дополнительный план с лицом пришлось бы "
      "резать не по границе фразы.")
print("- LRA 1.8 LU при ориентире 3–5 LU. Это свойство дубля, а не микса: голос ровный, "
      "без динамических перепадов, loudnorm диапазон не растягивает. Для сравнения "
      "у ролика 11 на том же тракте вышло 2.6 LU.")
