import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hook36 as HK
import storyboard36 as SB
from plan36 import NAMES, A1, A2, AN
from style import FPS

# замеры сданных файлов (qa36hooks.log)
MEAS = {
    "h1": dict(lufs=-13.9, tp=-1.7, lra=2.2, frames=1371, dur=45.70,
               shots=23, avg=1.99, median=1.90, shortest=1.01, longest=4.12,
               first_cut=1.90, face_pct=30.2,
               seam_same=0.92, seam_diff=66.25, tail_diff=63.29,
               old_face_min=9.70, old_face_thr=4.54,
               body_worst=2.6, click=(0.00171, 0.15350),
               pause=0.176, rgb_hook=(123, 111, 103), rgb_main=(124, 112, 103),
               deform="кроп ×0.98: 672.68px → 687.48px = **×1.0220** "
                      "(ожидалось ×1.0208 — ffmpeg режет кроп до целых: "
                      "1080×0.98 = 1058.4 → 1058, отсюда 1080/1058)",
               band=59.9),
    "h2": dict(lufs=-13.9, tp=-1.5, lra=2.4, frames=1385, dur=46.17,
               shots=25, avg=1.85, median=1.64, shortest=0.99, longest=4.04,
               first_cut=1.47, face_pct=30.7,
               seam_same=0.04, seam_diff=63.73, tail_diff=60.63,
               old_face_min=5.77, old_face_thr=2.00,
               body_worst=0.99, click=(0.00146, 0.15452),
               pause=0.148, rgb_hook=(124, 112, 104), rgb_main=(124, 112, 103),
               deform="ускорение ×1.02: ширина квадрата исходов 672.68px → "
                      "672.63px = **×0.9999** (кадр не деформирован, и не должен), "
                      "fps на выходе **30/1**, длительность 46.167с при "
                      "расчётных 46.176с, расхождение видео/звук 0.017с",
               band=61.8),
}

DEFORM_RULE = {
    "h1": "версия 2 — кроп ×0.98",
    "h2": "версия 3 — ускорение ×1.02 (картинка и звук вместе)",
}


def emit(key):
    cfg = HK.HOOKS[key]
    m = MEAS[key]
    v = cfg["version"]
    rate = 1.02 if cfg.get("post_a") else 1.0
    shots = HK.shots_of(cfg)
    nf = cfg["frames"]
    dt = nf / FPS - HK.CUT_V

    print(f"# Монтажный лист — версия {v}, хук {key[-1]}\n")
    print(f"Новое начало: {cfg['title']}\n")
    print(f"Исходник хука: `videos/36/{os.path.basename(cfg['src'])}` · 720×1280 · "
          f"30 fps · {cfg['src_frames']/FPS:.3f}с · SDR bt709 "
          "(`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print(f"Тело: готовые кадры из `assets/_video_{SB.TAG}.mp4` с кадра "
          f"{HK.CUT_F}, без пересборки")
    print(f"Готовый файл: `videos/36/{os.path.basename(cfg['out'])}` · 1080×1920 · "
          f"30 fps · {m['frames']} кадров · {m['dur']:.2f}с\n")

    print(f"**Планов:** {m['shots']} · средняя **{m['avg']:.2f}с** · медиана "
          f"{m['median']:.2f}с · мин {m['shortest']:.2f}с · макс {m['longest']:.2f}с · "
          f"первый рез {m['first_cut']:.2f}с · **лицо {m['face_pct']}%**\n")

    print("## Блок хука — единственное, что перерисовано\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(shots, 1):
        rec, desc = NAMES[kind]
        if kind == "stock":
            desc += f" · окно клипа {prm['ss']:.1f}–{prm['ss'] + (t1 - t0):.1f}с"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0/rate:.2f}–{t1/rate:.2f} | {(t1-t0)/rate:.2f}с | {rec} "
              f"| {desc} | {txt or '— (говорит графика)'} |")
    print(f"| — | {nf/FPS/rate:.2f}–{m['dur']:.2f} | {m['dur'] - nf/FPS/rate:.2f}с "
          "| — | **тело сданной версии кадр в кадр**, с плана `family` "
          "| см. `montage-plan.md` |")

    print("\nГрафика блока хука — та же, что стояла в старом начале: стоковая "
          "вставка со школьным классом (mixkit 35954). Другой графики в старом "
          "хуке не было, менять её незачем. Окно клипа взято новое и не "
          "пересекается ни со сданной версией, ни со второй версией — иначе "
          "один и тот же кадр стока стоял бы в двух роликах подряд.")

    print("\n## Точка реза\n")
    print("Старое начало — «если ты учил в школе теорию вероятности, ты должен "
          "решить эту задачку» (0.000–3.621). Оно занимает три плана: `A1` "
          "0.000–1.413, `stock` 1.413–2.446 и `A1` 2.446–4.110. Ближайшая "
          "граница плана после конца фразы — **4.110**, по ней и режем.\n")
    print(f"В кадрах это ceil(4.110 × 30) = **{HK.CUT_F}**. Округление вверх, "
          "а не к ближайшему: кадр 123 стоит на 4.100 и показывает ещё лицо "
          "старого хука — при round от него остался бы целый кадр.\n")
    print("Шов совпадает с настоящим резом: блок хука кончается стоковой "
          "вставкой (карточка B), тело начинается сеткой (карточка A). "
          "Поэтому whoosh на шве ставится как на любой склейке.\n")
    print("Тело начинается самостоятельным предложением «у мужчины двое детей»: "
          "своё подлежащее, ни одного местоимения, отсылок к выброшенному "
          "тексту нет.")

    print("\n## Звук\n")
    print("Дорожка пересобрана целиком, а не склеена из готовых:")
    print(f"- голос хука (коррекция уровня под тело) + голос тела с {HK.CUT_A:.4f}с;")
    print(f"- постель (whoosh / impact / tick) со сдвигом {dt:+.4f}с;")
    print(f"- музыка `{os.path.basename(cfg['music'])}` с нуля, −19 dB от RMS "
          "голоса, фейды 0.8 / 2.0с;")
    print("- highpass 65 Гц + loudnorm + добор volume/alimiter под громкость "
          "**оригинала**, а не под абстрактные −14.\n")
    print(f"**J-cut в два кадра.** Первое слово тела («у мужчины») по огибающей "
          f"атакует в 4.095: 4.080 = −80 дБ, 4.090 = −61, 4.100 = −43, "
          f"4.110 = −31. Картинка тела начинается кадром {HK.CUT_F} (4.1333) — "
          f"рез голоса ровно по картинке срезал бы 38мс уже звучащего слова. "
          f"Голос тела берётся с кадра {HK.CUT_F - 2} ({HK.CUT_A:.4f}с, там "
          "тишина) и ложится на два кадра раньше картинки. Смещение кратно "
          "кадру, поэтому синхрон не едет.")

    print(f"\n## Уникализация — {DEFORM_RULE[key]}\n")
    print(f"- Трек: `{os.path.basename(cfg['music'])}` (версия 1 — `song1.mp3`, "
          "версия 2 — `song2.mp3`, версия 3 — `song3.mp3`, ни один не "
          "повторяется).")
    print(f"- Деформация измерена машиной: {m['deform']}.")

    print("\n## Проверки версии\n")
    print("| проверка | результат | норма |")
    print("|---|---|---|")
    print(f"| громкость | **{m['lufs']} LUFS**, пик **{m['tp']} dBTP**, "
          f"LRA {m['lra']} LU | версия 1: −14.0 LUFS, −1.6 dBTP |")
    print(f"| шов: первый кадр тела против кадра {HK.CUT_F} оригинала "
          f"| {m['seam_same']} | должны совпасть |")
    print(f"| шов против кадра {HK.CUT_F - 1} (последний кадр старого хука) "
          f"| {m['seam_diff']} | должны разойтись |")
    print(f"| последний кадр блока хука против кадра {HK.CUT_F - 1} "
          f"| {m['tail_diff']} | должны разойтись |")
    print(f"| ни одного кадра лица старого хука | min {m['old_face_min']} при "
          f"пороге {m['old_face_thr']} | больше порога |")
    print("| окна стока не пересекаются со старыми | 0 пересечений | 0 |")
    print(f"| тело кадр в кадр с версией 1 | худшая разница {m['body_worst']} "
          "| уровень шума кодека |")
    print(f"| щелчок на шве | скачок {m['click'][0]} против типичного "
          f"{m['click'][1]} (p99.9) | не выделяется |")
    print(f"| пауза хук → тело | **{m['pause']:.3f}с** | 0.10–0.20с |")
    print(f"| средний RGB в карточке A | хук {m['rgb_hook']}, тело "
          f"{m['rgb_main']} | расхождение ≤10 |")
    print("| A-roll не морожен | хвост блока — стоковый план, лицо кончается "
          f"на кадре {max(f for f in range(nf) if HK.shots_of(cfg) and next((x for x in shots if x[0] <= f/FPS < x[1]), shots[-1])[2] in SB.FACE_KINDS)} "
          f"при {cfg['src_frames']} кадрах дубля | ok |")
    print("| субтитры мимо расшифровки / стиль / резы внутри слова | 0 / 0 / 0 | 0 |")
    print("| текст за карточкой · графика на тексте · наложение строк | 0 / 0 / 0 | 0 |")
    print(f"| полоса субтитров на стоковой вставке | {m['band']} | ≤110 / ≤140 |")

    print("\n## Дубль хука — что не правилось\n")
    print("Хук прошёл через тот же тракт A-roll, что и основной исходник: те же "
          "`FRAMINGS` (окно 630×1000 от (57, 264)), тот же безусловный `hflip`, "
          "грейда нет. Ни крупность, ни экспозиция, ни положение в кадре не "
          "подгонялись.\n")
    print("| дубль | cx | линия глаз | ширина лица |")
    print("|---|---|---|---|")
    print("| основной | 372 | 683 | 264 |")
    print(f"| **этот хук** | **{cfg['face_cx']}** | **{cfg['face_eye']}** "
          f"| **{cfg['face_d']}** |")
    print("\nРасхождение — единицы пикселей, на кадре не читается. Средний RGB "
          f"внутри карточки A: {m['rgb_hook']} против {m['rgb_main']} у "
          "основного дубля — расхождение ≤1 единицы по каналу при норме ~10.\n")
    print("Зеркальность проверена по кадру: надпись на футболке в дубле читается "
          "задом наперёд, значит штатный `hflip` подходит.")

    if key == "h2":
        print("\n## Два замечания по этой версии\n")
        print("**«90%» на экран не вынесено.** Дубль говорит «но 90% людей дают "
              "на неё неправильный ответ». Это риторическая оценка без "
              "источника. В ролике синее число = посчитанный результат "
              f"({A1} и {A2}), и оформить ею неподтверждённую цифру значило бы "
              "выдать её за такой же результат. В речи фраза остаётся как есть "
              "— речь не режем. Субтитра в этом месте тоже нет: цифры в "
              "субтитрах запрещены, а числительное словами дублировало бы "
              "произносимое.\n")
        print(f"**Самый короткий план — {m['shortest']:.2f}с при норме ≥1с.** Это "
              "план `thirdNum` тела (1.009с), ужатый обязательным ускорением "
              "×1.02 до 0.989с. Собственные планы блока хука подобраны с "
              "запасом (хвост 1.200с → 1.176с), но тело не пересобирается, "
              "поэтому 2% срезаются со всех его планов. Правило «≥1с» и "
              "обязательная деформация версии здесь расходятся на эти самые 2%.")


if __name__ == "__main__":
    emit(sys.argv[1])
