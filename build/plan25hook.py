"""Монтажный лист версии ролика 25 с другим хуком.

    python3 plan25hook.py h1 > ../videos/25/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard25 as SB
from hook25 import HOOKS, CUT, CUT_F, cut_of, cut_f_of, lts_for
from plan25 import NAMES

# замеры готовых файлов (qa25hook.py)
MEASURED = {
    "h1": dict(lufs=-14.0, tp=-1.7, lra=2.4, frames=1276, dur=42.53, pause=0.495,
               seam=(73, 1884), rgb=1, gain=1.259, psnr=44.1,
               deform="кроп ×0.98 — карточка A на одном и том же кадре тела "
                      "870px → 888px = ×1.0207 (целевое ×1.0204, расхождение — "
                      "1px квантования)"),
    "h2": dict(lufs=-14.0, tp=-1.6, lra=2.5, frames=1198, dur=39.93, pause=0.653,
               seam=(144, 1844), rgb=2, gain=1.229, psnr=44.1,
               deform="ускорение ×1.02 — 1222 кадра → 1198, `r_frame_rate` ровно "
                      "30/1, звук ускорен вместе с картинкой (видео 39.933с, "
                      "аудио 39.924с), геометрия карточки не тронута (870px → 870px)"),
}

def plural_frames(n):
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return "кадр"
    if n10 in (2, 3, 4) and n100 not in (12, 13, 14):
        return "кадра"
    return "кадров"


RHYTHM = {
    "h1": dict(shots=24, avg=1.77, median=1.81, shortest=1.06, longest=2.84,
               first_cut=1.74, face_pct=40.9),
    "h2": dict(shots=23, avg=1.74, median=1.77, shortest=1.04, longest=2.78,
               first_cut=1.30, face_pct=38.6),
}


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    r = RHYTHM[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    cut, cut_f = cut_of(cfg), cut_f_of(cfg)
    trim = cfg.get("head_trim_f", 0)
    dt = nh - cut
    lts = lts_for(cfg)

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/25/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.2f}с · {m['frames']} кадров")
    print(f"Хук: `videos/25/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с)")
    print(f"Тело: кадры {cut_f}+ из уже сданного `morley_edit.mp4`, не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")
    if key == "h1":
        print("Дубль пересобран по **новому файлу** `hook1.mov`: первый присланный был "
              "обрезан на 5.877с прямо на последнем слове. Новый идёт 188 кадров (6.258с), "
              "речь кончается на 6.082 по огибающей. В версию берём 183 кадра (6.100с) — "
              "до конца слова плюс 0.02с, хвост тишины в ролик не тащим. Версия 3 "
              "(`morley_hook2.mp4`) при этой пересборке не трогалась.\n")
    print(f"**Ритм версии целиком:** {r['shots']} планов · средняя {r['avg']:.2f}с · "
          f"медиана {r['median']:.2f}с · мин {r['shortest']:.2f}с · макс {r['longest']:.2f}с · "
          f"первый рез {r['first_cut']:.2f}с · лицо **{r['face_pct']:.1f}%**\n")

    print("## Точка реза")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `teaser` → `A2` в исходном ролике, "
          "то есть конец старого начала «возьмите абсолютно любой треугольник, даже самый "
          "кривой. один приём всегда превращает его в идеальный». "
          "Планы 1–3 старого хука и все 5 их субтитров выброшены целиком: от старого начала "
          "не осталось ни кадра.")
    print(f"\nКадр считается как `ceil(5.52 × 30)` = {CUT_F}: граница плана стоит "
          "на дробном кадре 165.6, и кадр 165 — это ещё последний кадр выбрасываемого "
          "плана `teaser`. Проверка машинная: `qa25hook.old_hook_gone` требует, чтобы "
          f"кадры {CUT_F - 1} и {CUT_F} лежали в разных планах.")
    if trim:
        print(f"\n**Плюс срез головы тела: {trim} {plural_frames(trim)} ({trim / FPS:.3f}с).** "
              f"Тело берётся не с кадра {CUT_F}, а с **{cut_f}** ({cut:.4f}с). "
              "Это не про старый хук — он и так весь выброшен, — а про паузу: "
              "собственный межфразовый разрыв дубля перед словом «итак» составляет "
              "0.655с, и на стыке с новым хуком он читался длинновато. "
              "**Речь не резана**: между границей плана (5.520с) и первым словом тела "
              f"(6.180с) в дубле сплошная тишина, и весь срез лежит внутри неё — "
              "`qa25hook.head_trim` даёт `speech_in_trim=[]`. Первый план тела `A2` "
              f"стал {SB.shot_at(cut)[1] - cut:.2f}с вместо 2.01с, порог 1.0с "
              "не нарушен.")
    print("\n**Почему не раньше.** Ближайшая предыдущая граница — 3.19с (`anyTri` → "
          "`teaser`), и резать по ней нельзя: тело начиналось бы с «один приём всегда "
          "превращает **его** в идеальный», а «его» осталось бы без антецедента — "
          "«треугольник» звучал только в выброшенном хуке.")
    print("\n**Связность стыка.** Тело начинается новым предложением с собственным "
          "подлежащим — «итак разделите каждый из трёх углов треугольника». Ни одного "
          "местоимения и ни одной отсылки к словам старого хука в первых фразах тела нет, "
          "поэтому обе версии режутся по одной и той же точке и ни одной фразы тела "
          "выбрасывать не пришлось.")
    if key == "h1":
        print("\nПередача эстафеты: хук кончается на «получить идеально равносторонний» — "
              "то же обещание, что несло старое «превращает его в идеальный», после него "
              "«итак разделите» читается как переход к способу.")
    else:
        print("\nПередача эстафеты: хук кончается вопросом «...равносторонний?», "
              "и «итак разделите» читается прямым ответом на него.")
    print()

    print("## Блок хука")
    print(f"{len(cfg['shots'])} планов · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"первый рез **{lens[0]:.2f}с** · мин {min(lens):.2f}с · макс {max(lens):.2f}с\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    for i, (t0, t1, kind, _p) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")
    print(f"\nДалее без изменений идёт тело сданного ролика — планы 4–23 из "
          f"`montage-plan.md`, со сдвигом **{dt:+.4f}с** на новой таймлинии"
          + (" и с последующим ускорением ×1.02." if cfg.get("post_a") else "."))

    print("\n## Графика хука")
    print("Взяты те же два плана, что стояли в старом начале, — `anyTri` (кривой "
          "треугольник тремя штрихами) и `teaser` (шесть трисектрис, три точки и "
          "**синий** равносторонний результат). Это визуальная интрига ролика, менять её "
          "незачем; ни одного нового плана не нарисовано.")
    parts = []
    for kind in ("anyTri", "teaser"):
        s = lts.get(kind)
        if s is None:
            continue
        ln = next(t1 - t0 for t0, t1, k, _ in cfg["shots"] if k == kind)
        body_ln = next(t1 - t0 for t0, t1, k, _ in SB.SHOTS if k == kind)
        if s > 1.001:
            parts.append(f"`{kind}` идёт {ln:.2f}с против {body_ln:.2f}с в теле, поэтому "
                         f"анимация ускорена в **×{s:.2f}**")
        else:
            parts.append(f"`{kind}` идёт {ln:.2f}с при {body_ln:.2f}с в теле — "
                         "анимация в штатном темпе, без масштабирования времени")
    print("\n" + "; ".join(parts) + ".")
    print("\nУскорять анимацию можно, замедлять нельзя: тот же план в теле идёт своим "
          "темпом, и разойтись они не должны.")
    if key == "h1":
        print("\nНа слова дубля графика ложится буквально: треугольник рисуется под "
              "«помогает из любого», трисектрисы и синий результат — под «получить "
              "идеально равносторонний».")
    else:
        print("\nНа слова дубля графика ложится буквально: треугольник рисуется под "
              "«любого даже самого кривого», синий равносторонний результат выходит "
              "ровно на слове «равносторонний».")

    print("\n## Сток в хуке")
    print("Стока в хуке нет — в старом начале его тоже не было. Единственная стоковая "
          "вставка ролика (аллея сфинксов Карнака, mixkit 45401) стоит в теле, "
          "под «открыть ещё в древности».")

    print("\n## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, и основной "
          "исходник — 720×1280, `yuv420p`, `color_range=tv`, `bt709`/`bt709`/`bt709`, 30 fps. "
          "Кадры читаются прямо из `.mov` и идут в штатный тракт A-roll **без единого "
          "промежуточного кодека**.")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip, медиана по всему дублю): основной дубль "
          f"cx 392 / линия глаз 642 / ширина лица 286; этот хук cx {cfg['face_cx']} / "
          f"{cfg['face_eye']} / {cfg['face_d']}.")
    if key == "h1":
        print("  Расхождение: **−10px по горизонтали**, **+10px по линии глаз**, "
              "**+2.4% по размеру лица**. Кропом не правилось.")
    else:
        print("  Расхождение: **+10px по горизонтали**, **+6px по линии глаз**, "
              "**+1.7% по размеру лица**. Кропом не правилось: это к съёмочной стороне, "
              "а не к монтажу.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуках, "
          "проверить по тексту не на чем. Штатный `hflip` оставлен: интерьер и рука "
          "с петличкой во всех трёх дублях с одной стороны кадра.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука против кадров тела расходятся "
          f"на **{m['rgb']} единицу** по каналу (норма — до ~10). Свет между дублями "
          "не уехал.")
    if cfg.get("asr_endings"):
        for good, heard in cfg["asr_endings"].items():
            print(f"- **Окончание слова.** whisper слышит последнее слово хука как "
                  f"«{heard}» — одинаково на обоих дублях. В кадре написано «{good}»: "
                  "слово согласуется с «треугольника» в мужском роде, среднему роду "
                  "здесь не к чему привязаться. Расхождение объявлено в конфиге версии, "
                  "`qa25hook.hook_captions` считает такие случаи отдельным полем "
                  "`ending_overrides`, а не прячет.")

    print("\n## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек, у остальных версий "
          "другие (v1 `song2.mp3`, v2 `song3.mp3`, v3 `song1.mp3`).")
    if "song1" in cfg["music"]:
        print("  Трек 9.53с короче ролика, поэтому идёт петлёй с кроссфейдом 0.25с на шве "
              "(4.4 повтора). У двух других версий треки длиннее ролика и петли не требуют.")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались. Порядок: сначала правка кадра, потом мукс со звуком.")

    print("\n## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, постель "
          f"(whoosh / impact / tick) со сдвигом **{dt:+.4f}с**, музыка с нуля, потом loudnorm.")
    print("- Whoosh стоит и на резах внутри хука, и на самом шве «хук → тело».")
    print(f"- Голос хука приведён к громкости тела по RMS речи (×{m['gain']:.3f}): "
          "дубль записан тише основного.")
    if trim:
        print(f"- Пауза между последним словом хука и первым словом тела: "
              f"**{m['pause']:.3f}с** (было 0.662с до среза головы тела). "
              "Собственный межфразовый разрыв дубля перед «итак» — 0.655с по "
              "`silencedetect`, самый длинный в ролике при медиане 0.42с; на стыке "
              f"с новым хуком он читался длинновато, поэтому {trim} {plural_frames(trim)} "
              "срезаны по тишине. Дальше укорачивать нечем: остаток паузы — "
              "это уже дыхание перед словом, а тело идёт готовыми кадрами.")
    else:
        print(f"- Пауза между последним словом хука и первым словом тела: "
              f"**{m['pause']:.3f}с**. Чеклист `delivery-specs §6` называет 0.10–0.20с, "
              "но там же оговорка «как между предложениями в теле». Эта пауза целиком "
              "принадлежит телу: она и есть собственный межфразовый разрыв дубля перед "
              "словом «итак» — 0.655с по `silencedetect`, самый длинный в ролике при "
              "медиане 0.42с. Хвост самого хука в ней — 0.02с.")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами на шве "
          f"**{m['seam'][0]}** против **{m['seam'][1]}** на 99.9-м процентиле всей дорожки.")
    print(f"- Громкость **{m['lufs']:.1f} LUFS**, истинный пик **{m['tp']:.1f} dBFS**, "
          f"LRA **{m['lra']:.1f} LU** — сведено к уровню уже сданного `morley_edit.mp4` "
          "(−13.9 / −1.5 / 2.2), а не к абстрактным −14.")

    print("\n## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa25hook.py {key}")
    print("```")
    print("Все по нулям: `text_out_of_card=0`, `gfx_text_overlap=0`, `gfx_out_of_zone=0`, "
          "`line_overlaps=0` по блоку хука, `bright_outside` = 0 кадров по всему файлу версии "
          "(включая деформацию), нарушений стиля субтитров 0, слов не из речи 0.")
    print(f"- Рез по границе плана: кадры {CUT_F - 1} и {CUT_F} лежат в разных планах "
          "(`teaser` → `A2`) — от старого хука не осталось ни кадра, ни субтитра.")
    print(f"- Тело против сданной версии — худший PSNR **{m['psnr']:.1f} dB** "
          "на 14 контрольных кадрах (это второе прохождение того же кодека, картинка та же).")
    print("- Версия №1 не тронута: `morley_edit.mp4` не открывался на запись — "
          "хуки читают из него только готовые кадры тела.")


if __name__ == "__main__":
    emit(sys.argv[1])
