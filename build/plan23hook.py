"""Монтажный лист версии ролика 23 с другим хуком.

    python3 plan23hook.py h1 > ../videos/23/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard23 as SB
from hook23 import HOOKS, CUT, CUT_F, lts_for
from plan23 import NAMES

# замеры готовых файлов (qa23hook.py)
MEASURED = {
    "h1": dict(lufs=-14.20, tp=-1.50, frames=1368, dur=45.60, pause=0.434,
               seam=(320, 1951), rgb=2, gain=1.727,
               deform="кроп ×0.98 — карточка A на одном и том же кадре тела "
                      "870px → 888px = ×1.0207 (целевое ×1.0204, расхождение — "
                      "1px квантования)"),
    "h2": dict(lufs=-14.20, tp=-1.70, frames=1322, dur=44.07, pause=0.508,
               seam=(73, 1917), rgb=1, gain=1.375,
               deform="ускорение ×1.02 — 1348 кадров → 1322, `r_frame_rate` ровно "
                      "30/1, звук ускорен вместе с картинкой (видео 44.067с, "
                      "аудио 44.053с), геометрия карточки не тронута (870px → 870px)"),
}

RHYTHM = {
    "h1": dict(shots=26, avg=1.75, median=1.62, shortest=1.01, longest=2.99,
               first_cut=1.40, face_pct=31.7),
    "h2": dict(shots=26, avg=1.69, median=1.59, shortest=0.99, longest=2.93,
               first_cut=1.31, face_pct=32.1),
}

FACE = {"main": (390, 636, 291), "h1": (395, 639, 291), "h2": (394, 641, 292)}


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    r = RHYTHM[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    dt = nh - CUT
    lts = lts_for(cfg)
    fh = FACE[key]
    fm = FACE["main"]

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/23/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.2f}с · {m['frames']} кадров")
    print(f"Хук: `videos/23/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с)")
    print(f"Тело: кадры {CUT_F}+ из уже сданного `gps_edit.mp4`, не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")
    print(f"**Ритм версии целиком:** {r['shots']} планов · средняя {r['avg']:.2f}с · "
          f"медиана {r['median']:.2f}с · мин {r['shortest']:.2f}с · макс {r['longest']:.2f}с · "
          f"первый рез {r['first_cut']:.2f}с · лицо **{r['face_pct']:.1f}%**\n")

    print("## Точка реза")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `teaser` → `A2` в исходном ролике, "
          "то есть конец старого начала «ваш телефон узнаёт точное место расположения, "
          "просто решая систему уравнений в реальном времени». Планы 1–3 старого хука "
          "(лицо, сток с телефоном, `teaser`) и все 5 их субтитров выброшены целиком: "
          "от старого начала не осталось ни кадра.")
    print(f"\nКадр считается как `ceil(4.92 × 30)` = {CUT_F}, а не `round`: граница плана "
          "стоит на дробном кадре 147.6, и кадр 147 — это ещё последний кадр выбрасываемого "
          "`teaser`. Проверка машинная: `qa23hook.old_hook_gone` требует, чтобы кадры 147 "
          "и 148 лежали в разных планах.")
    print("\nРез попадает в тишину: речь старого хука смолкает на 4.9238 "
          "(`silencedetect`), рез стоит на 4.9333 — после конца фразы остаётся 0.0095с, "
          "ни звука не срезано.")
    print("\n**Связность стыка.** Тело начинается фразой «и да, GPS-спутники "
          "не фотографируют вас сверху и не отслеживают телефон напрямую». Проверено "
          "на антецеденты: «GPS-спутники» — существительное, оно вводит себя само, "
          "местоимений без опоры в первых фразах тела нет. Поэтому обе версии режутся "
          "по одной и той же точке и ни одну фразу тела выбрасывать не пришлось.")
    if key == "h1":
        print("\nПередача эстафеты: хук кончается на «основана на точных математических "
              "расчётах» — заявление, которое тело тут же подтверждает и уточняет: "
              "«и да, GPS-спутники не фотографируют вас сверху».")
    else:
        print("\nПередача эстафеты: хук кончается вопросом «как работает отслеживание вас "
              "по вашему же телефону?» — и тело отвечает на него первой же фразой: "
              "«и да… не отслеживают телефон напрямую». Связка вышла плотнее оригинальной.")
    print()

    print("## Блок хука")
    print(f"{len(cfg['shots'])} планов · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"первый рез **{lens[0]:.2f}с** · мин {min(lens):.2f}с · макс {max(lens):.2f}с\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = SB.STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")
    print(f"\nДалее без изменений идёт тело сданного ролика — планы 4–26 из "
          f"`montage-plan.md`, со сдвигом **{dt:+.4f}с** на новой таймлинии"
          + (" и с последующим ускорением ×1.02." if cfg.get("post_a") else "."))

    print("\n## Графика хука")
    print("Взят тот же план, что стоял в старом начале, — `teaser`: три сферы вокруг трёх "
          "спутников сходятся в одну точку. Это визуальная интрига ролика, менять её "
          "незачем; ни одного нового плана не нарисовано.")
    s = lts.get("teaser", 1.0)
    print(f"\nНа слова дубля он ложится буквально: "
          + ("«точных математических расчётах» — и на экране ровно расчёт, три сферы "
             "сводятся в одну точку."
             if key == "h1" else
             "«по вашему же телефону» — и на экране то, чем телефон себя и находит.")
          + f" План хука короче, чем в теле ({lens[-1]:.2f}с против 2.01с), поэтому анимация "
            f"ускорена в **×{s:.2f}** — иначе точка-итог не успевала бы проявиться до реза. "
            "Ускорять можно, замедлять нельзя: тот же план в теле идёт своим темпом.")

    print("\n## Сток в хуке")
    clip = next(p["clip"] for _a, _b, k, p in cfg["shots"] if k == "stock")
    print(f"В старом начале сток был (телефон с картой), поэтому он оставлен и здесь — "
          f"но выбран **по словам самого дубля**: `stock_{clip}.mp4`, "
          f"{SB.STOCK_NAMES[clip]}.")
    if key == "h1":
        print("\nhook1 говорит «работа GPS», а не «телефон», — поэтому вместо телефона "
              "стоит спутник над Землёй. Оба клипа уже скачаны под этот ролик, "
              "ничего нового не добавлялось.")
    else:
        print("\nhook2 говорит «по вашему же телефону» — телефон с картой навигации "
              "остаётся ровно тем же клипом, что стоял в старом начале.")

    print("\n## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, и основной "
          "исходник — 720×1280, `yuv420p`, `color_range=tv`, `bt709`/`bt709`/`bt709`, 30 fps. "
          "Кадры читаются прямо из `.mov` и идут в штатный тракт A-roll **без единого "
          "промежуточного кодека**.")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip, среднее по дублю): основной дубль "
          f"cx {fm[0]} / линия глаз {fm[1]} / ширина лица {fm[2]}; этот хук "
          f"cx {fh[0]} / {fh[1]} / {fh[2]}.")
    print(f"  Расхождение: {abs(fh[0]-fm[0])}px по горизонтали, {abs(fh[1]-fm[1])}px "
          f"по линии глаз, {abs(fh[2]-fm[2])}px по ширине лица "
          f"({100*abs(fh[2]-fm[2])/fm[2]:.1f}%). Это самое малое расхождение "
          "из всех роликов — дубли сняты одной постановкой. Кропом всё равно не правилось.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуках, проверить "
          "по тексту не на чем. Штатный `hflip` оставлен: во всех трёх дублях после него "
          "лицо стоит на одном и том же месте кадра (cx 390 / 395 / 394), то есть "
          "ориентация экспорта у них общая.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука против кадров тела расходятся "
          f"на **{m['rgb']} единицы** по каналу (норма — до ~10).")

    print("\n## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек, у остальных версий "
          "другие (v1 `song3.mp3`, v2 `song2.mp3`, v3 `song1.mp3`).")
    if "song1" in cfg["music"]:
        print("  Трек 9.53с короче ролика, поэтому идёт петлёй с кроссфейдом 0.25с на шве "
              "(4.8 повтора). У двух других версий треки длиннее ролика и петли не требуют. "
              "Это последний свободный трек в `audios/` — на четвёртую версию музыки уже нет.")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались.")
    if key == "h2":
        print("- Побочный эффект ускорения, называю числом: самый короткий план версии "
              "**0.99с** вместо 1.01с — это план тела `A1` (31.63–32.64), укоротившийся "
              "на ×1.02. Формально на 0.01с ниже порога «не короче 1с»; лечится только "
              "отказом от ускорения, то есть отказом от уникализации версии.")

    print("\n## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, постель "
          f"(whoosh / impact / tick) со сдвигом **{dt:+.4f}с**, музыка с нуля, потом loudnorm.")
    print("- Whoosh стоит и на резах внутри хука, и на самом шве «хук → тело».")
    print(f"- Голос хука приведён к громкости тела по RMS речи (×{m['gain']:.3f}): "
          "дубли записаны тише основного.")
    print(f"- Пауза между последним словом хука и первым словом тела: **{m['pause']:.3f}с**. "
          "Чеклист `delivery-specs §6` называет 0.10–0.20с, но там же оговорка «как между "
          "предложениями в теле» — в этом дубле межфразовые паузы идут 0.29–0.57с "
          "(медиана 0.42с), так что замеренная пауза попадает ровно в разброс тела. "
          "Укоротить её нечем: 0.407с из неё — это тишина в голове тела перед словом «и», "
          "а тело идёт готовыми кадрами, и сдвигать под него звук значит развалить синхрон.")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами на шве "
          f"**{m['seam'][0]}** против **{m['seam'][1]}** на 99.9-м процентиле всей дорожки.")
    print(f"- Громкость **{m['lufs']:.2f} LUFS**, истинный пик **{m['tp']:.2f} dBFS** — "
          "сведено к уровню уже сданного `gps_edit.mp4` (−14.20 / −1.50), "
          "а не к абстрактным −14.")

    print("\n## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa23hook.py {key}")
    print("```")
    print("Все по нулям: `text_out_of_card=0`, `gfx_text_overlap=0`, `gfx_out_of_zone=0`, "
          "`line_overlaps=0` по блоку хука, `bright_outside` = 0 кадров по всему файлу версии "
          "(включая деформацию), нарушений стиля субтитров 0, слов не из речи 0.")
    print(f"- Рез по границе плана: кадры {CUT_F-1} и {CUT_F} лежат в разных планах "
          "(`teaser` → `A2`) — от старого хука не осталось ни кадра, ни субтитра.")
    print("- Тело против сданной версии — худший PSNR **43.8 dB** на 14 контрольных кадрах "
          "(это второе прохождение того же кодека, картинка та же).")
    print("- Версия №1 не тронута: `gps_edit.mp4` не открывался на запись — "
          "хуки читают из него только готовые кадры тела.")


if __name__ == "__main__":
    emit(sys.argv[1])
