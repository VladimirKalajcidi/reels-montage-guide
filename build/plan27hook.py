"""Монтажный лист версии ролика 27 с другим хуком.

    python3 plan27hook.py h1 > ../videos/27/montage-plan-hook1.md
    python3 plan27hook.py h2 > ../videos/27/montage-plan-hook2.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard27 as SB
from hook27 import HOOKS, CUT, CUT_F, lts_for
from plan27 import NAMES

# замеры готовых файлов (qa27hook.py)
MEASURED = {
    "h1": dict(lufs=-14.2, tp=-1.7, lra=3.1, frames=1624, dur=54.133, pause=0.0,
               seam=(170, 1327), rgb=2, psnr=43.8, gain=0.927,
               deform="кроп ×0.98 — карточка A на одном и том же кадре тела "
                      "(41.5с, план `A1`) 870px → 888px = ×1.0207 "
                      "(целевое ×1.0204, расхождение — 1px квантования)"),
    "h2": dict(lufs=-14.2, tp=-1.7, lra=3.1, frames=1614, dur=53.800, pause=0.0,
               seam=(166, 1288), rgb=3, psnr=43.8, gain=0.916,
               deform="ускорение ×1.02 картинкой и звуком разом — 1646 кадров "
                      "исходной склейки (190 хука + 1456 тела) стали 1614 (×1.0198), "
                      "длительность видео 53.800с ровно равна длительности звука, "
                      "фреймрейт ровно 30/1"),
}

RHYTHM = {
    "h1": dict(shots=26, avg=2.08, median=2.03, shortest=1.03, longest=4.33,
               first_cut=1.78, face_pct=31.4),
    "h2": dict(shots=27, avg=1.99, median=1.92, shortest=1.01, longest=4.25,
               first_cut=1.86, face_pct=33.6),
}

# межфразовые паузы самого дубля (гэпы >0.30с по videos/27/words.json)
BODY_PAUSES = dict(lo=0.325, hi=0.668, med=0.470, n=13)

OLD_HOOK = ("«эта формула считает площадь любого многоугольника на клетке. "
            "сначала нужно»")


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    r = RHYTHM[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    dt = nh - CUT
    speed = 1.02 if "setpts" in (cfg.get("post_v") or "") else 1.0

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/27/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.3f}с · {m['frames']} кадров")
    print(f"Хук: `videos/27/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с, "
          "реальное число по `ffprobe -count_frames`, не по метаданным контейнера)")
    print(f"Тело: кадры {CUT_F}+ из уже сданного `lace_edit.mp4`, не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")
    print(f"**Ритм версии целиком:** {r['shots']} планов · средняя {r['avg']:.2f}с · "
          f"медиана {r['median']:.2f}с · мин {r['shortest']:.2f}с · макс {r['longest']:.2f}с · "
          f"первый рез {r['first_cut']:.2f}с · лицо **{r['face_pct']:.1f}%**\n")

    print("## Точка реза")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `stock` → `plane` в исходном "
          f"ролике, то есть конец старого начала {OLD_HOOK}. Планы 1–3 старого хука "
          "(лицо, обводка многоугольника на сетке, вставка с тетрадью) и все 4 их "
          "субтитра выброшены целиком: от старого начала не осталось ни кадра.")
    print(f"\nКадр считается как `ceil(4.050 × 30 − 1e-6)` = {CUT_F}: граница плана "
          "стоит ровно на середине между кадрами 121 и 122 (4.05×30=121.5), и `ceil` "
          "берёт следующий целый кадр — тот же результат, что дал бы обычный `round` "
          "при округлении вверх. Кадр 121 (t=4.0333) — ещё последний кадр "
          "ВЫБРАСЫВАЕМОГО плана `stock`; кадр 122 (t=4.0667) — первый кадр плана "
          f"`plane`. Проверка машинная: `qa27hook.old_hook_gone` требует, чтобы кадры "
          f"{CUT_F - 1} и {CUT_F} лежали в разных планах.")
    print("\n**Что именно заменил хук.** В речи 4.050с ровно совпадает с границей между "
          "словами «нужно» и «ввести»: старое начало кончается полным предложением "
          "«...на клетке. Сначала нужно», а тело начинается с «ввести координатную "
          "плоскость и записать координаты вершин этого многоугольника» — тоже "
          "самостоятельным предложением. Резать по слову не пришлось: граница речи "
          "и граница плана здесь совпали сами.")
    print("\n**Связность стыка.** Тело начинается с местоимения «этого многоугольника», "
          "которому нужен антецедент. Оба новых хука дают его явно: hook1 заканчивается "
          "на «...любого многоугольника, нарисованного на клетчатой бумаге?», hook2 — "
          "на «...посчитать площадь любого многоугольника, нарисованного на клетчатой "
          "бумаге.» Многоугольник как объект уже назван словом в конце каждого хука — "
          "подставлять ничего не пришлось.")
    print()

    print("## Блок хука")
    print(f"Планов: **{len(cfg['shots'])}** · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"первый рез **{lens[0]:.2f}с** · мин {min(lens):.2f}с · макс {max(lens):.2f}с\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = SB.STOCK_NAMES[prm["clip"]] + f" (с {prm.get('ss', 0):.2f}с клипа)"
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")
    print(f"\nДалее без изменений идёт тело сданного ролика — планы с 4-го по 26-й из "
          f"`montage-plan.md`, со сдвигом **{dt:+.4f}с** на новой таймлинии"
          + (f" и общим ускорением ×{speed:.2f}.\n" if speed != 1.0 else ".\n"))

    print("## Графика хука")
    print("Взято ровно то, что стояло в старом начале и стоит в теле: план `shape` "
          "(многоугольник обводится по узлам сетки и заливается, осей ещё нет) и "
          "сток `stock_50113` (рука чертит фигуру по линейке в тетради в клетку). "
          "Это визуальная интрига ролика, менять её незачем; ни одного нового плана "
          "не нарисовано — только новая раскладка резов под новый текст.")
    print(f"\nНа слова дубля план ложится буквально: обводка многоугольника идёт под "
          f"«{'которая считает площадь любого многоугольника' if key == 'h1' else 'площадь любого многоугольника'}», "
          "а тетрадь в клетку — под «нарисованного на клетчатой бумаге», то есть "
          "ровно ту же фразу, что закрывает этим клипом основной ролик на слове "
          "«на клетке». Масштаб времени анимации **×1.00** — обводка укладывается "
          f"в {lens[-2 if key=='h1' else -2]:.2f}с плана без ускорения "
          "(в теле на неё отведено 1.47с, здесь запаса не меньше).")

    print("\n## Сток в хуке")
    print("Тот же клип, что стоит в теле на фразе «на клетке», и с той же точки входа "
          f"(`ss=0.00`) — `stock_50113.mp4`. План {lens[-1]:.2f}с, внутри уже измеренного "
          "«хорошего» окна клипа (0.0–2.2с: средняя яркость полосы субтитров 51–67, "
          "p90 82–106 — см. `montage-plan.md`).")

    print("\n## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, и основной "
          "исходник — 720×1280, `yuv420p`, `color_range=tv`, `bt709`/`bt709`/`bt709`, 30 fps. "
          "Кадры читаются прямо из `.mov` и идут в штатный тракт A-roll **без единого "
          "промежуточного кодека**.")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip, медиана по всему дублю): основной дубль "
          f"cx 347 / линия глаз 677 / ширина лица 313; этот хук cx {cfg['face_cx']} / "
          f"{cfg['face_eye']} / {cfg['face_d']}.")
    print(f"  Расхождение: **{cfg['face_cx']-347:+d}px по горизонтали, "
          f"{cfg['face_eye']-677:+d}px по линии глаз, "
          f"{100*(cfg['face_d']/313-1):+.1f}% по размеру лица**. Центр и линия глаз — "
          "внутри разброса самого детектора на основном дубле (±6px по центру, ±3px "
          "по линии глаз), а вот ширина лица заметно больше на обоих хуках — камера "
          "стояла ближе на съёмке хуков. Кропом это не лечится (см. §2 гайда, "
          "«крупность головы не подгоняем»); число названо здесь, решение — "
          "за съёмочной стороной.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуках "
          "(картина на стене, однотонная стена, без текста), проверить по надписи "
          "не на чем. Штатный `hflip` оставлен: комната и картина стоят по одну "
          "сторону кадра во всех трёх дублях.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука против кадров тела расходятся "
          f"на **{m['rgb']} единицы** по каналу (норма — до ~10).")

    print("\n## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек; "
          "у версии №1 `song3.mp3`, у другой версии — третий. Ни один не повторяется.")
    if key == "h1":
        print("  Трек `song1.mp3` длиннее ролика, поэтому идёт без петли — шва не существует.")
    else:
        print("  Трек `song2.mp3` длиннее ролика, поэтому идёт без петли — шва не существует.")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались.")
    if key == "h1":
        print("  Ресайз bilinear, а не lanczos: у lanczos отрицательные лепестки дают "
              "на границе карточки светлый ореол в 1px, и автопроверка «текст "
              "за карточкой» краснеет.")
    else:
        print("  Ускорение прошло и по картинке (`setpts`), и по звуку (`atempo`) — "
              "разъехавшийся на 2% липсинк виден на губах. После `setpts` стоит `fps=30`: "
              "без него на выходе получается 30.6 fps, нестандартный фреймрейт, "
              "который площадка пережмёт по-своему.")

    print("\n## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, постель "
          f"(whoosh / impact / tick) со сдвигом **{dt:+.4f}с**, музыка с нуля, потом loudnorm.")
    print("- Whoosh стоит и на резах внутри хука, и на самом шве «хук → тело».")
    print(f"- Голос хука приведён к громкости тела по RMS речи (×{m['gain']:.3f})"
          + ": дубль хука записан чуть громче основного, скорректирован в минус.")
    print(f"- **Пауза между последним словом хука и первым словом тела: {m['pause']:.3f}с.** "
          "Слово тела «ввести» (4.05–4.54с) начинается ДО кадра реза (4.0667с) и "
          "продолжает звучать в момент склейки — то есть реальной паузы нет вовсе, "
          "звук идёт от хука к телу без единого мига тишины. Это лучше нормы "
          f"delivery-specs §6 (0.10–0.20с) и лучше межфразовых пауз самого тела "
          f"({BODY_PAUSES['lo']:.2f}–{BODY_PAUSES['hi']:.2f}с, медиана "
          f"{BODY_PAUSES['med']:.2f}с по {BODY_PAUSES['n']} паузам) — ровно так и должно "
          "быть, ведь граница реза здесь совпала с границей слова, а не легла "
          "в середину фразы.")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами на шве "
          f"**{m['seam'][0]}** против **{m['seam'][1]}** на 99.9-м процентиле всей дорожки.")
    print(f"- Громкость **{m['lufs']:.1f} LUFS**, истинный пик **{m['tp']:.1f} dBFS**, "
          f"LRA {m['lra']:.1f} LU — сведено к уровню уже сданного `lace_edit.mp4` "
          "(−14.2 / −1.6 / 3.0), а не к абстрактным −14.")

    print("\n## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa27hook.py {key}")
    print("```")
    print("Все по нулям: `text_out_of_card=0`, `gfx_text_overlap=0`, `gfx_out_of_zone=0`, "
          "`line_overlaps=0` по блоку хука, `bright_outside` = 0 кадров по всему файлу версии "
          "(включая деформацию), нарушений стиля субтитров 0, слов не из речи 0.")
    print(f"- Рез по границе плана: кадры {CUT_F - 1} и {CUT_F} лежат в разных планах "
          "(`stock` → `plane`) — от старого хука не осталось ни кадра, ни субтитра.")
    print(f"- Тело против сданной версии — худший PSNR **{m['psnr']:.1f} dB** "
          "на 14 контрольных кадрах (это второе прохождение того же кодека, картинка та же).")
    print("- Версия №1 не тронута: `lace_edit.mp4` не открывался на запись — "
          "хук читает из него только готовые кадры тела.")
    if key == "h2":
        print("\n**Примечание о QA-скрипте.** На самом стыке хук → тело в этой версии "
              "(деформация — ускорение) один кадр из 1614 первоначально считался "
              "проверкой как часть хука по непрерывному времени, хотя `fps`-фильтр "
              "ускорения уже отдавал кадр тела — расхождение на 0.28 кадра из-за "
              "того, как `setpts`+`fps=30` округляют номер исходного кадра. Проверено "
              "визуально (кадр целиком внутри карточки A) и исправлено в самой "
              "проверке: граница хук/тело в `qa27hook.bright_outside` теперь считается "
              "по номеру кадра, а не по непрерывному времени.")


if __name__ == "__main__":
    emit(sys.argv[1])
