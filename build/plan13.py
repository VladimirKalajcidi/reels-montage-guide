"""Генерирует монтажный лист ролика 13 из раскадровки."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard13 import SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "ball": ("R4+R10", "сетка: шар вычерчивается с меридианом и экватором"),
    "split": ("R4+R10", "сетка: шар распадается на 5 секторов"),
    "two": ("R4+R10", "сетка: исходный шар -> вилка стрелок -> два шара"),
    "equal": ("R4+R10", "сетка: два шара, у каждого мерная линейка диаметра — линейки равны"),
    "pieces": ("R4+R5b", "сетка: разбиение шара на части + синее «5»"),
    "points": ("R4+R10", "сетка: шар осыпается в облако точек"),
    "rule": ("R4+R10", "сетка: одна точка (лайм) и её образы под поворотами"),
    "rot": ("R4+R10", "сетка: шар и два кольца вращения вокруг разных осей"),
    "move": ("R4+R10", "сетка: четыре группы точек переезжают на новые места"),
    "nostretch": ("R4+R10", "сетка: шар и его растянутая копия, перечёркнута только копия"),
    "nonew": ("R4+R10", "сетка: шар + лишний кусок, знак «плюс» перечёркнут"),
    "assemble": ("R4+R10", "сетка: секторы слетаются в две сферы"),
    "measure": ("R4+R10", "сетка: исходный шар и два новых, три равные линейки"),
    "physics": ("R4+R10", "сетка: один шар ≠ два шара"),
    "theorem": ("R4+R10", "сетка: галка и знак конца доказательства"),
    "y1924": ("R4+R5b", "сетка: синий «1924» + «год теоремы»"),
    "infset": ("R4+R10", "сетка: точки внутри шара всё не кончаются"),
    "finite": ("R4+R10", "сетка: пять кусков со штриховкой, пронумерованы 1–5"),
    "infeq": ("R4+R5b", "сетка: три элемента вычёркиваются, перенумерация, «=» и синяя «∞»"),
    "hotel": ("R4+R10", "сетка: шесть номеров, гости сдвигаются, в первый входит новый"),
}

def main():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    print("# Монтажный лист — «парадокс Банаха — Тарского»\n")
    print(f"Исходник: `videos/13/source.mov` · 1080×1920 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (теги сверены, конверсия не нужна)")
    print("Готовый ролик: `videos/13/banach_edit.mp4`\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 3 (5 · 1924 · ∞)\n")
    print("Речь не резана: резы только по картинке. Субтитры правят Whisper "
          "(«банаха Иторского» → банаха и тарского, «два такие же шара» → два таких же шара, "
          "«закон от физики» → закона физики).\n")
    print("Зоны на планах с графикой: субтитры y 300…600, графика y 700…1560 "
          "(`brand-kit.md §5`). Числа на графике (5 кусков, 1924, номера комнат) в речи "
          "не звучат — это добавление, а не дубль субтитра.\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print("- Whoosh на каждой склейке (0.040 от пика), импакт под числом-ревилом (0.070), "
          "тики каскада (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, петля с кроссфейдом 0.25с, "
          "фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/13/stock/`, источник Mixkit (свободная лицензия):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")

    print("\n## Чего в ролике сознательно нет")
    print("- **R6 (крупное слово в карточке)** — над головой в этом дубле светлый потолок "
          "с точечными светильниками; белое слово на 62% там не читается, а опустить его ниже "
          "нельзя — сядет на голову. `anti-patterns.md`: не ставить R6 туда, где он ломается.")
    print("- **R3 (очередь быстрых резов)** — материал ролика предметный, очередь пришлось бы "
          "набивать нерелевантным стоком. `assets-manifest.md §2`: лучше своя графика, чем "
          "перебивка ради ритма.")
    print("- **R8 (пруф-вставка)** и **R9 (предметный PNG)** — в речи нет ни ссылки на источник, "
          "ни названного предмета.")


if __name__ == "__main__":
    main()
