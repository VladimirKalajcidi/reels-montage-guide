"""Генерирует монтажный лист ролика 14 из раскадровки."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard14 import SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "y400": ("R4+R5b", "сетка: синее «400» + мерная линейка под ним"),
    "balls": ("R4+R10", "сетка: девять одинаковых шаров вразброс"),
    "dense": ("R4+R10", "сетка: те же шары съезжаются в плотный гексагональный слой"),
    "gaps": ("R4+R10", "сетка: подсвечиваются сами пустоты — криволинейные треугольники "
                       "между тремя касающимися шарами"),
    "pyramid": ("R4+R10", "сетка: пирамидка 4-3-2-1, слои ложатся снизу вверх"),
    "layers": ("R4+R10", "сетка: вид сбоку, верхний шар опускается в ложбину и касается "
                         "обоих нижних (расстояние до каждого ровно 2R)"),
    "y1611": ("R4+R5b", "сетка: синее «1611» + подпись «гипотеза»"),
    "densest": ("R4+R10", "сетка: плотный гексагональный слой целиком, 28 шаров"),
    "pct": ("R4+R5b", "сетка: мелкая плотная укладка + синее «74,05 %»"),
    "quick": ("R4+R10", "сетка: пирамидка складывается мгновенно, рядом крупная галка"),
    "other": ("R4+R10", "сетка: квадратная укладка — те же шары, пустоты крупнее"),
    "tricky": ("R4+R10", "сетка: беспорядочная («хитрая») упаковка, шары не пересекаются"),
    "denser": ("R4+R10", "сетка: два бокса — гексагональная против хитрой — и полосы "
                         "плотности под ними, правая короче"),
    "proof": ("R4+R10", "сетка: стопка из шести страниц, знак конца доказательства "
                        "в конце последней строки"),
    "timeline": ("R4+R10", "сетка: ось времени, шар слева, дуга через весь кадр, галка справа"),
    "check4": ("R4+R10", "сетка: страницы доказательства, шкала из четырёх отрезков "
                         "и четыре галки под ними"),
}

def main():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    print("# Монтажный лист — «гипотеза Кеплера: как плотнее всего уложить шары»\n")
    print(f"Исходник: `videos/14/source.mov` · 1080×1920 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (теги сверены, конверсия не нужна)")
    print("Готовый ролик: `videos/14/kepler_edit.mp4`\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 3 (400 · 1611 · 74,05 %)\n")
    print("Речь не резана: резы только по картинке. Субтитры — расшифровка Whisper "
          "строчными и без пунктуации; слова не менялись.\n")
    print("Зоны на планах с графикой: субтитры y 300…600, графика y 700…1560 "
          "(`brand-kit.md §5`). Числа 400 и 1611 в речи звучат — поэтому они живут "
          "**только в графике**, в субтитрах их нет. 74,05 % в речи не звучит: это "
          "плотность гексагональной укладки π/(3·√2), добавление к сказанному.\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Геометрия графики — что именно проверено")
    print("- Шаг между центрами касающихся шаров ровно **2R**, вертикальный шаг слоя **R·√3**. "
          "Поэтому шар верхнего слоя на плане 11 действительно лежит в ложбине: расстояние "
          "до каждого из двух нижних = 2R, то есть он касается обоих.")
    print("- Пустоты на плане 7 — не декоративные пятна, а настоящие криволинейные треугольники: "
          "треугольник по центрам трёх шаров минус три диска.")
    print("- Квадратная укладка (план 19) построена с тем же радиусом шара, что и "
          "гексагональная, — крупные пустоты в ней видны сравнением, а не подрисованы.")
    print("- «Хитрая» укладка (планы 20–21) — детерминированная случайная упаковка с "
          "проверкой непересечения; полоса плотности под ней короче ровно во столько, "
          "во сколько случайная плотная упаковка (~64 %) уступает 74,05 %.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print("- Whoosh на каждой склейке (0.040 от пика), импакт под числом-ревилом (0.070), "
          "тики каскада (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, петля с кроссфейдом 0.25с, "
          "фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/14/stock/`, источник Mixkit (свободная лицензия):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")

    print("\n## Чего в ролике сознательно нет")
    print("- **R6 (крупное слово в карточке)** — над головой в этом дубле светлый потолок "
          "с точечными светильниками; белое слово на 62% там не читается, а опустить его ниже "
          "нельзя — сядет на голову. Та же причина, что и в ролике 13.")
    print("- **R3 (очередь быстрых резов)** — ролик предметный, очередь пришлось бы набивать "
          "нерелевантным стоком. `assets-manifest.md §2`: лучше своя графика, чем перебивка "
          "ради ритма.")
    print("- **R8 (пруф-вставка)** — в речи нет ссылки на публикацию, только «доказательство "
          "появилось в начале двухтысячных».")
    print("- **R9 (предметный PNG)** — назван апельсин, но он уже отработан живым стоком "
          "(план 8), а статика поверх карточки дублировала бы его.")
    print("- **Четвёртое синее число** — «четыре года» показаны четырьмя отрезками шкалы и "
          "четырьмя галками (план 27). Цифра «4» рядом дублировала бы то же самое в одном кадре.")


if __name__ == "__main__":
    main()
