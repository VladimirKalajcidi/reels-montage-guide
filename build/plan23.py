"""Генерирует монтажный лист ролика 23 из раскадровки."""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard23 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS,
                          SAT, RAD, P_TRUE, P_ALT, ELL_A, ELL_B, ell_point)
import render23

# измерения сданного файла (см. блоки «Звук» и «A-roll»)
LUFS, TP, LRA = -14.2, -1.5, 1.8
AROLL_SRC = (119, 104, 96)
AROLL_OUT_DELTA = (1.0, 3.2)

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "teaser": ("R4+R10", "сетка: три сферы вокруг трёх спутников сходятся "
                         "в одну точку — обещание всего ролика"),
    "notTrack": ("R4+R10", "сетка: спутник сверху, телефон снизу, стрелка "
                           "от спутника к телефону перечёркнута"),
    "broadcast": ("R4+R10", "сетка: от спутника расходятся кольца во все стороны — "
                            "передаёт всем, а не кому-то"),
    "timestamp": ("R4+R10", "сетка: кольцо сигнала и идущий циферблат у спутника"),
    "delay": ("R4+R10", "сетка: фронт волны идёт от спутника вниз к телефону, "
                        "пройденный путь остаётся светлым"),
    "distance": ("R4+R10", "сетка: тот же путь как отрезок с засечками на концах"),
    "sphereStart": ("R4+R10", "сетка: спутник и один радиус от него"),
    "sphere1": ("R4+R10", "сетка: радиус разворачивается в окружность, кандидаты "
                          "мерцают по всей её длине"),
    "twoSats": ("R4+R10", "сетка: приходит вторая сфера, окружности накладываются"),
    "twoSpheres": ("R4+R10", "сетка: обе сферы стоят, проступает их пересечение"),
    "circlePos": ("R4+R10", "сетка: сферы приглушены, ярко прорисована окружность "
                            "пересечения — тонкий эллипс, видимый почти с ребра"),
    "threeSats": ("R4+R10", "сетка: третья сфера приходит и режет эту окружность"),
    "twoPoints": ("R4+R10", "сетка: окружность гаснет, остаются ровно две точки"),
    "fourthClock": ("R4+R10", "сетка: четвёртый спутник и циферблат; пунктирные "
                              "сферы стоят со сдвигом — это ошибка часов — "
                              "и **лаймовый** импульс сажает их на место"),
    "pickTwo": ("R4+R10", "сетка: два кандидата пульсируют по очереди, "
                          "они пока равноправны"),
    "pickOne": ("R4+R10", "сетка: лишняя точка гаснет с крестом, верная "
                          "разгорается **синим** — это итог"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «как телефон находит себя»\n")
    print(f"Исходник: `videos/23/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/23/gps_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих чисел: 0** (счётные «2 / три / четвёртый спутник» уже показаны "
          "самими спутниками на экране)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa23.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи и ни одной цифры.** Слова несёт только "
          "субтитр, графика несёт то, чего в словах нет:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| иконка спутника | спутник |")
    print("| иконка телефона | приёмник |")
    print("| расходящиеся кольца | сигнал во все стороны, без адресата |")
    print("| циферблат | время: отправки — у спутника, с ошибкой — у телефона |")
    print("| отрезок с засечками | расстояние |")
    print("| окружность вокруг спутника | «вы где-то на этой сфере» |")
    print("| тонкий эллипс | окружность пересечения двух сфер, видимая почти с ребра |")
    print("| точка | кандидат на положение |")
    print("| синяя точка | единственный верный итог |")
    print("| лаймовый импульс | поправка часов |")
    print("\nПоэтому проверка «одно и то же не пишется дважды» здесь проходит "
          "по построению: пересечься субтитру и графике нечем. Машинная проверка "
          "пересечения слоёв (`qa23.gfx_text_overlap`) — 0 кадров, графика "
          "не выходит из зоны y700…1560 / x175…905 (`qa23.gfx_in_zone`) — 0 кадров.")

    print("\n## Геометрия сцены — построена, а не нарисована на глаз")
    print("Конфигурация спутников подобрана численным поиском под четыре условия "
          "сразу; всё это проверяет `qa23.geometry()`:\n")
    print(f"- **P лежит ровно на всех трёх сферах** — |S−P| минус радиус равно 0 "
          f"с точностью до 1e-6 (радиусы {RAD['S1']:.0f} / {RAD['S2']:.0f} / "
          f"{RAD['S3']:.0f} px).")
    print("- **Каждая окружность целиком помещается в зону графики.** Это и было "
          "главным ограничением: обрезанная краем окружность читается как случайная "
          "дуга, а не как сфера. Первый вариант компоновки пришлось выбросить "
          "именно поэтому.")
    hits = math.dist(P_ALT, P_TRUE)
    print(f"- **Третья сфера режет окружность пересечения ровно в двух точках** — "
          f"P и Q, разнесённых на {hits:.0f}px. Ровно то, что говорит речь: "
          "три спутника сужают круг до двух точек.")
    print("- **Q лежит строго внутри первых двух сфер** "
          f"(|S1−Q| = {math.dist(P_ALT, SAT['S1']):.0f} при радиусе {RAD['S1']:.0f}). "
          "Так и должно быть в проекции: у точки на окружности пересечения есть "
          "ненулевая z-составляющая, поэтому на плоскости она уходит внутрь диска.")
    print(f"\nОкружность пересечения нарисована эллипсом {2*ELL_A:.0f}×{2*ELL_B:.0f}px: "
          "ортогональная проекция такой окружности вырождается в отрезок, поэтому "
          "она показана «почти с ребра» — стандартная условность чертежа. Концы "
          "большой оси совпадают с точками пересечения окружностей S1 и S2 точно.")
    print("\nЧего на графике намеренно НЕТ: точек на плане `twoSats`/`twoSpheres`. "
          "Двух сфер мало — кандидатом остаётся целая окружность, и она приходит "
          "следующим планом. Поставить там две точки значило бы соврать на кадр "
          "раньше, чем это скажет речь.")

    print("\n## Цвет")
    print("- **Синих чисел ноль.** Числа в речи есть, но все они счётные — "
          "«2 спутника», «три спутника», «четвёртый спутник», — и это количество "
          "уже показано на экране самими спутниками. Написать его ещё и цифрой — "
          "ровно то дублирование, которое запрещает `brand-kit §5`.")
    print("- Синим (#3B4BE8) окрашен **результат** — единственная верная точка "
          "на плане `pickOne`. Один синий объект на весь ролик.")
    print("- **Лайм #C3DB4E — один элемент на весь ролик**: импульс поправки часов "
          "на плане `fourthClock`. Ровно то, чего не хватало для точности.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt. Верх шкалы `brand-kit §3` "
          "(XL 150–200 под число-ревил) не задействован: числа-ревила в этом ролике "
          "нет, показывать XL нечего.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под ревилами (0.070), тики под каскадами элементов (0.030).")
    print("- Музыка `audios/song3.mp3`: −19 dB от RMS голоса, трек 110с длиннее "
          "ролика — идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume/alimiter.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP** — в цели.")
    print(f"- **LRA {LRA} LU** при норме гайда 3–5. Это свойство дубля: речь идёт "
          "очень ровно, без громких и тихих мест. Лимитером и loudnorm не лечится — "
          "фиксирую замер, а не правлю. Тот же эффект был на ролике 22 (2.3 LU).")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/23/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nОба клипа буквальны: звучит «телефон» — в кадре телефон с картой, "
          "звучит «спутники … сверху» — в кадре спутник над Землёй.")
    print("\nПолоса субтитров в карточке B замерена **до** постановки в план: "
          "у `22149` средняя 80–88 из 255 и p90 134–136, у `47401` средняя 18–40 "
          "и p90 65–121 при порогах ≤110 / ≤140 — белый текст со свечением читается "
          "на обоих. Третий скачанный клип (`47399`, МКС на светлом лимбе Земли) "
          "**забракован по этому же замеру**: p90 149–175, текст поверх поплыл бы.")
    print("\nОстальные планы закрыты собственной графикой. Это не экономия: "
          "вся суть ролика — в пересечении сфер и в том, как круг кандидатов "
          "сужается до точки, а сток такого не показывает (`assets-manifest §2`: "
          "«если сцену можно закрыть своей графикой без потери смысла — берём графику»).")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render23). Кроп посчитан по детектору: 30 замеров "
          "по всему дублю дали cx 387±6, линию глаз y 634±4, ширину лица 286±7 — "
          "глаза стоят на 42.0% высоты карточки у A1 и на 41.5% у A2.")
    print(f"Проверка: средний RGB внутри карточки A в сданном файле отличается "
          f"от того же кропа исходника на **{AROLL_OUT_DELTA[0]:.1f}–"
          f"{AROLL_OUT_DELTA[1]:.1f} единицы** по каналу — это цена 4:2:0 и H.264, "
          "а не коррекция.")
    print(f"Замер самого дубля: средние по карточке A **{AROLL_SRC[0]} / "
          f"{AROLL_SRC[1]} / {AROLL_SRC[2]}** против ориентира `brand-kit §6` "
          "«130 / 112 / 104». Расхождение называю числами и не правлю: "
          "гамма-подтяжка до ориентира уже пробовалась на ролике 16 и дала "
          "вымытое лицо и рост шума.")


if __name__ == "__main__":
    emit()
