def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = (lens[len(lens) // 2 - 1] + lens[len(lens) // 2]) / 2
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]
    q = P_SHORT_DEN - P_SHORT_NUM

    print("# Монтажный лист — «парадокс инспекции»\n")
    print(f"Исходник: `videos/31/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/31/inspection_edit.mp4` · 1080×1920 · 30 fps · "
          f"{int(round(DUR*30))} кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    n_stock = sum(1 for _, _, k, _ in SHOTS if k == "stock")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток "
          f"{stock:.1f}с, {n_stock} плана — все буквальные под произносимый "
          "объект; механику несёт своя графика: линия времени показывает её "
          "буквально, assets-manifest §2). "
          "Для доказательного ролика доля лица ближе к 30% — норма "
          "(delivery-specs §6).")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синих чисел: 2 (× 10 и 18)** · **белых чисел: 10, 5, 2, 20, 10** · "
          "**цифр в субтитрах: ни одной**\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa31.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]] + f" (с {prm['ss']:.1f}с клипа)"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Сценарий пересчитан — ошибок нет")
    print("Арифметика речи сходится целиком (`qa31.numbers` = 0 нарушений). "
          "Модель ролика: интервал между автобусами равен "
          f"{SHORT_MIN} или {LONG_MIN} минутам, доля коротких "
          f"{P_SHORT_NUM}/{P_SHORT_DEN}.\n")
    print("| в речи | пересчёт |")
    print("|---|---|")
    print(f"| «автобусы ходят в среднем раз в 10 минут» | "
          f"({P_SHORT_NUM}·{SHORT_MIN} + {q}·{LONG_MIN}) / {P_SHORT_DEN} = "
          f"**{SCHED_MEAN}** минут ✓ |")
    print(f"| «иногда через 2 минуты» / «а иногда через 20 минут» | "
          f"{SHORT_MIN} и {LONG_MIN} — обе величины линия времени рисует "
          f"в масштабе {render31.PPM_P} px/мин ✓ |")
    print(f"| «он занимает в 10 раз больше времени» | {LONG_MIN} / {SHORT_MIN} = "
          f"**{RATIO}** ✓, и длинный промежуток на экране физически делится "
          f"на {RATIO} коротких |")
    el2 = P_SHORT_NUM * SHORT_MIN ** 2 + q * LONG_MIN ** 2
    el = P_SHORT_NUM * SHORT_MIN + q * LONG_MIN
    print(f"| «средний интервал, который видит случайный пассажир, "
          f"оказывается длиннее» | E[L²]/E[L] = ({el2}/{P_SHORT_DEN}) ÷ "
          f"({el}/{P_SHORT_DEN}) = **{SEEN_MEAN}** минут против {SCHED_MEAN} "
          "по расписанию ✓ |")
    print(f"| «это ещё не значит, что вы будете ждать в среднем 5 минут» | "
          f"верно: {SCHED_MEAN}/2 = {NAIVE_WAIT} — это и есть ошибка, которую "
          f"речь называет; настоящее среднее ожидание — {SEEN_MEAN}/2 = "
          f"**{REAL_WAIT}** минут |")

    print(f"\n**Число {REAL_WAIT} на экран не вынесено.** Речь до него не "
          "доходит — она останавливается на «интервал длиннее», а не на "
          "«ждать дольше». Ставить на экран число, которого нет в сценарии, "
          "и на котором держится весь хук, — это дописывать за автора; "
          f"поэтому {REAL_WAIT} остаётся в этом листе как проверка, а зритель "
          f"видит пару {SCHED_MEAN} против {SEEN_MEAN}, из которой ответ "
          "выводится сам.")

    print("\n## Кто что несёт: графика и субтитр")
    print("**Ни одной цифры в субтитрах** (`qa31.digits_in_captions` = 0) — "
          "все числа несёт графика:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| горизонтальная линия | время |")
    print("| вертикальная засечка на линии | приход автобуса |")
    print("| ширина промежутка | его длительность в минутах, всегда в масштабе |")
    print("| стрелка сверху | момент, когда пассажир пришёл на остановку |")
    print("| синяя заливка промежутка | тот промежуток, в который пассажир "
          "попадает чаще — результат |")
    print("| синее число | результат: множитель × 10 и наблюдаемый интервал 18 |")
    print("\nГрафика на трёх крупностях одного и того же объекта, крупность "
          "меняется только резом (brand-kit §2): вся линия целиком "
          f"({render31.PPM_L:.2f} px/мин), два промежутка рядом "
          f"({render31.PPM_P} px/мин), один промежуток на весь кадр "
          "(50 px/мин).")
    print("\nЧисла стоят там, где субтитра нет "
          "(`qa31.captions_on_number_shots` = 0): на `schedTicks`, `naiveWait` "
          "и `gapLong` субтитр обрывается перед попом числа; `gapShortNum` "
          "и `pairBoth` идут вообще без субтитров; на `ratioNum`, наоборот, "
          "субтитр начинается только после того, как × 10 полностью "
          "проявилось. На `A1word` субтитр обрывается на «называют», "
          "«парадоксом инспекции» несёт крупное слово R6.")
    print("\nМашинная проверка пересечения слоёв (`qa31.gfx_text_overlap`) — "
          "0 кадров; графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa31.gfx_out_of_zone`) — 0 кадров (R6 в этот периметр не входит "
          "по определению — он живёт над карточкой A) и нигде не упирается "
          "во врезку маски (`qa31.gfx_clipped`) — 0 кадров.")

    print("\n## Линия времени — честная, а не иллюстративная")
    n_short = sum(1 for v in INTERVALS if v == SHORT_MIN)
    n_long = sum(1 for v in INTERVALS if v == LONG_MIN)
    share = n_long * LONG_MIN / SPAN_MIN
    hit = sum(1 for m in DROP_MIN if render31._in_long(m))
    print(f"Линия набрана из {n_short} коротких и {n_long} длинных промежутков "
          f"— ровно доля {P_SHORT_NUM}/{P_SHORT_DEN}, из которой считается "
          f"и средний интервал {SCHED_MEAN}, и наблюдаемый {SEEN_MEAN}. "
          f"Длинные занимают {n_long}·{LONG_MIN} = {n_long*LONG_MIN} минут "
          f"из {SPAN_MIN}, то есть **{share:.1%}** длины линии — поэтому "
          f"из девяти меток прихода в них попадает **{hit}**, а не «примерно "
          "большинство». Соответствие доли времени и доли попаданий "
          "проверяется машинно (`qa31.numbers`).")
    print(f"\nМасштаб проверяется отдельно (`qa31.geometry` = 0): длинный "
          f"промежуток ровно в {RATIO} раз шире короткого "
          f"({render31.P_LONG_X1-render31.P_LONG_X0}px против "
          f"{render31.P_SHORT_X1-render31.P_SHORT_X0}px), полосы «средних "
          f"интервалов» относятся как {SCHED_MEAN}:{SEEN_MEAN} "
          f"({render31.BAR_SCHED_X1-render31.BAR_X0}px против "
          f"{render31.BAR_SEEN_X1-render31.BAR_X0}px), и каждый промежуток "
          "линии нарисован своей длительностью.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) — множитель **× 10**, наблюдаемый интервал **18** "
          "и заливка того промежутка, в который пассажир попадает чаще "
          "(brand-kit §4: синий = число и результат). Синих чисел два.")
    print("- Лайм не использован: матричных и табличных элементов в ролике нет.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под семью ревилами чисел (0.070), тики под каскадами элементов "
          "(0.030).")
    print("- Музыка `audios/song1.mp3`: −19 dB от RMS голоса, петля "
          "с кроссфейдом, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume / alimiter.")
    if LUFS is not None:
        print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
              f"**LRA {LRA} LU**.")
    else:
        print("- Замер готового `.mp4` — заполняется после финального прогона.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/31/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}.")
    print(f"\nЧетыре плана из {len(SHOTS)} — все буквальные под произносимый "
          "объект: автобус в потоке, автобус на улице, ожидание на остановке, "
          "поезд у станции. Под «очереди» и «срок службы вещей» на Mixkit нет "
          "клипа, который читался бы за полсекунды и не тащил в кадр мелкий "
          "текст, — этот бит закрыт лицом и графикой, а не случайной "
          "перебивкой (assets-manifest §2).\n")
    print("Замер полосы субтитров после штатного притемнения 0.72 "
          "(порог 110 / 140):\n")
    print("| клип | среднее | p90 |")
    print("|---|---|---|")
    print("| `4000` перекрёсток с автобусом | 55–57 | 96–100 |")
    print("| `4263` двухэтажный автобус | 107–109 | 132–133 |")
    print("| `22452` ожидание на платформе | 33 | 56 |")
    print("| `1622` поезд у станции | 27 | 71 |")
    print("\n`4263` — самая светлая вставка ролика: небо занимает верхнюю треть "
          "карточки, ровно там, где идут субтитры. По порогу проходит "
          "с запасом в 3 и 7 единиц, кроп сдвинут вправо (`cx=0.65`) — так "
          "автобус остаётся в кадре весь план и в полосу субтитров попадает "
          "меньше неба.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render31.py). Кроп посчитан по детектору: 28 замеров "
          "по всему дублю дали cx 401±9, линию глаз y 701±5, ширину лица "
          "273±7 — глаза стоят на 42% высоты карточки.")

    print("\n## Расшифровка")
    print("Пословные тайминги — `videos/31/words.json`, собраны по речевым "
          "отрезкам: границы сняты `ffmpeg silencedetect` (-34dB / 0.12с), "
          "внутри каждого отрезка выдача whisper large-v3 растянута "
          "на измеренный интервал (`align31.py`).")

    print("\n## Автопроверки")
    print("Все — по нулям (`python3 qa31.py`):\n")
    print("```")
    print("cuts_inside_word=0            captions_off_speech=0")
    print("captions_crossing_cut=0       caption_words_not_in_speech=0")
    print("caption_style_violations=0    digits_in_captions=0")
    print("captions_on_number_shots=0    gfx_text_overlap_frames=0")
    print("gfx_out_of_zone_frames=0      gfx_touching_mask_frames=0")
    print("text_out_of_card_frames=0     line_overlap_pairs=0")
    print("bright_outside_card_frames=0  number_violations=0")
    print("geometry_violations=0")
    print("```")
    print("\nСмысловая проверка графики — по контакт-листу ключевых кадров "
          "(`python3 contact31.py <папка>`): первый кадр каждого графического "
          "плана, пик анимации и полный ревил каждого числа.")


if __name__ == "__main__":
    emit()
