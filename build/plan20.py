"""Генерирует монтажный лист ролика 20 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard20 import (SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS,
                          PRICE_S, PRICE_M, PRICE_L, DELTA)
import render20

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (смена крупности)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "cups3": ("R4+R10", "сетка: три стакана попкорна набираются зёрнами один за другим"),
    "cupspick": ("R4+R10", "сетка: подсветка идёт по стаканам вслед за речью"),
    "priceS": ("R4+R5a", f"сетка: маленький подсвечен, под ним всплывает ценник {PRICE_S} ₽"),
    "priceM": ("R4+R5a", f"сетка: средний подсвечен, ценник {PRICE_M} ₽"),
    "priceL": ("R4+R5a", f"сетка: большой подсвечен, ценник {PRICE_L} ₽"),
    "delta": ("R4+R5b", f"сетка: ряд из трёх цен, скобка охватывает {PRICE_M} и {PRICE_L}, "
                        f"под ней синее «+{DELTA} ₽»"),
    "volume": ("R4+R10", "сетка: средний и большой рядом, уровень среднего перенесён "
                         "пунктиром на большой — лишний объём подсвечен лаймом"),
    "decoyM": ("R4+R10", "сетка: средний гаснет и перечёркнут крестом"),
    "decoyWhy": ("R4+R10", "сетка: средний обведён пунктиром как точка отсчёта, "
                           "от него уходит стрелка к большому"),
    "dealL": ("R4+R5b", f"сетка: большой подсвечен, его цена загорается синим ({PRICE_L} ₽), "
                        "сверху проявляется галка"),
    "noM": ("R4+R10", "сетка: средний исчезает, остаются только маленький и большой"),
    "pickS": ("R4+R10", "сетка: галка встаёт над маленьким"),
    "backM": ("R4+R10", "сетка: средний возвращается на место, обведён пунктиром"),
    "pickL": ("R4+R10", "сетка: стрелка уводит выбор вправо, галка встаёт над большим"),
    "baitframe": ("R4+R10", "сетка: механизм целиком — обведённый средний и стрелка "
                            "от него к большому"),
}


def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    print("# Монтажный лист — «эффект приманки: почему в кино берут самый большой попкорн»\n")
    print(f"Исходник: `videos/20/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/20/popcorn_edit.mp4` · 1080×1920 · 30 fps\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· вставки и графика **{100*(DUR-face)/DUR:.0f}%** (из них сток {stock:.1f}с)")
    print(f"**Субтитров:** {len(CAPS)} фраз · **синих чисел:** 2 "
          f"(«+{DELTA} ₽» и «{PRICE_L} ₽»)\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам whisper (`qa20.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = STOCK_NAMES[prm["clip"]]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Числа: кто их пишет")
    print("В речи звучат четыре числа. Каждое пишет **только графика**, "
          "субтитра с этим числом нигде нет (brand-kit §5):\n")
    print("| число | когда звучит | где появляется |")
    print("|---|---|---|")
    print(f"| {PRICE_S} рублей | 10.34–11.12 | ценник под маленьким стаканом |")
    print(f"| {PRICE_M} | 11.52–12.10 | ценник под средним |")
    print(f"| {PRICE_L} рублей | 13.00–13.84 | ценник под большим |")
    print(f"| {DELTA} рублей | 17.76–18.62 | синее «+{DELTA} ₽» под скобкой |")
    print(f"\nСиних чисел два, оба — результат, а не просто цифра: «+{DELTA} ₽» "
          f"(разница между средним и большим) и «{PRICE_L} ₽» на плане `dealL` "
          "(цена, которая за счёт приманки начинает выглядеть выгодной). "
          "Остальные ценники белые — это подписи объектов, а не результаты.")

    print("\n## Предметная графика")
    print("- Стакан — трапеция-обводка, заполненная зёрнами попкорна; упаковка зёрен "
          "детерминированная, считается один раз на каждый размер.")
    s, m, l = (render20.CUPS[k] for k in ("S", "M", "L"))
    def area(c):
        return (c["tw"] + c["bw"]) / 2 * c["h"]
    print(f"- Пропорции на экране: маленький {s['tw']}×{s['h']}, средний "
          f"{m['tw']}×{m['h']}, большой {l['tw']}×{l['h']} — по площади "
          f"**1 : {area(m)/area(s):.2f} : {area(l)/area(s):.2f}**. Ряд читается "
          "как «маленький / средний / большой» без подписей, поэтому названия "
          "размеров несёт только субтитр.")
    print("- Все стаканы стоят на одной базовой линии и не двигаются внутри плана: "
          "меняется только подсветка, ценник и пометка.")
    print("- **Лайм `#C3DB4E` — один смысловой элемент на весь ролик**: на плане "
          "`volume` уровень среднего перенесён пунктиром на большой, и всё, что выше "
          "этого уровня, залито лаймом. Это и есть «заметно больше попкорна».")
    print("- На плане `delta` стаканов нет: сравниваются цены, а не объёмы, "
          "и крупному синему числу нужна пустая зона под ним "
          "(brand-kit §4 — результат не кладём на объект).")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print("- Whoosh на каждой склейке (0.040 от пика), импакт под синими числами (0.070), "
          "тики под каскадами элементов (0.030).")
    print("- Музыка `audios/song2.mp3`: −19 dB от RMS голоса, трек 335с длиннее ролика — "
          "идёт без петли, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор volume/alimiter.")
    print("- Замер готового `.mp4`: **-14.0 LUFS**, истинный пик **-1.7 dBTP** — в цели. "
          "Первая итерация со штатным `volume=0.6dB` дала -13.6 LUFS, добор снижен до 0.2 dB.")
    print("- **LRA 2.0 LU** при норме гайда 3–5. Это свойство дубля: речь идёт "
          "очень ровно, без громких и тихих мест. Лимитером и loudnorm не лечится "
          "и на звук не влияет — фиксирую замер, а не правлю.")

    print("\n## Сток")
    print("Скачан под этот ролик в `videos/20/stock/`, источник Mixkit "
          "(свободная лицензия, коммерческое использование без атрибуции):\n")
    for cid, name in STOCK_NAMES.items():
        print(f"- `stock_{cid}.mp4` — {name}")
    print("\nКлипы идут 24 / 25 / 29.97 fps и **конформятся к 30 fps проекта по времени**, "
          "а не читаются кадр-в-кадр: последовательное чтение играло бы замедленно.")

    print("\n## Решения по этому дублю")
    print("- **A-roll не грейдится** — только `hflip` и кроп.")
    print("- **Самый длинный план — 3.12с лица** (21.00–24.12, «но это не ошибка "
          "ценообразования, а осознанный расчёт»). Это тезис ролика, его незачем "
          "разбивать вставкой, а два лицевых плана подряд дали бы джамп-кат на "
          "непрерывном дубле. В эталоне 1 такой же приём: R1 на 5.93–9.53 = 3.60с.")
    print("- **`hflip` включён**: дубль снят фронталкой. Надписей в кадре нет, "
          "но кадр покадрово совпадает с роликом 19 — та же комната, та же точка, "
          "рука с петличкой с той же стороны, — поэтому тракт тот же.")
    print("- **Исходник 720×1280**, карточка A — 870×1380: кадр апскейлится "
          "в 1.30 раза (A1) и 1.45 (A2), `INTER_CUBIC`. Как и в ролике 19, "
          "это цена съёмки не в полном разрешении, а не пережатие.")
    print("- **Кадры идут в кодек одним проходом** — сырой поток в ffmpeg вместо "
          "промежуточного `cv2.VideoWriter(mp4v)`.")
    print("- **Грейда на лице нет — проверено числами.** Средний RGB карточки A "
          "в готовом файле против того же кропа из исходника расходится на "
          "**0.2–3.6 единицы** по каналу на шести замерах (1.0 / 4.5 / 15.0 / 22.5 / "
          "38.5 / 45.5с). Это цена round-trip RGB → yuv420p, а не коррекция: "
          "у сданного ролика 19 разброс тот же (2.4–3.4). Кадр и без грейда тёплый — "
          "R 115 > G 102 > B 94.")

    print("\n## Автопроверки")
    print("Обе обязательные из `START-HERE.md` и все дополнительные — по нулям "
          "(`python3 qa20.py`):\n")
    print("| проверка | результат |")
    print("|---|---|")
    print("| текст за карточкой (скан через каждые 3 кадра, порог 200) | **0 кадров** |")
    print("| наложение строк внутри блока (по `font.getbbox`) | **0 пар** |")
    print("| графика пересекает субтитры (по альфе >40) | **0 кадров** |")
    print("| графика вне зоны y700–1560 / x175–905 | **0 кадров** |")
    print("| субтитр вне карточки с отступом 30px | **0 кадров** |")
    print("| рез попал в середину слова | **0 резов** |")
    print("| фраза разошлась с речью по пословным таймингам | **0 фраз** |")

    print("\n## Чего в ролике сознательно нет")
    print("- **R6 (крупное слово в карточке)** — над головой потолок с точечными "
          "светильниками; белое слово на 62% садится прямо на светящиеся пятна "
          "и рвётся (та же причина, что в ролике 19).")
    print("- **R3 (очередь быстрых резов)** — материал предметный, очередь пришлось бы "
          "набивать нерелевантным стоком.")
    print("- **R8 (пруф-вставка)** — в речи нет ссылки на источник.")
    print("- **R9 (предметный PNG)** — назван попкорн, но он и так нарисован "
          "предметной графикой во весь кадр; PNG поверх лица был бы третьим "
          "изображением того же объекта.")
    print("- **R7 (счётная вставка)** — в речи нет ряда количеств.")
    print("- **Сток под сами стаканы и ценники кинотеатра** — на Mixkit нет ни одного "
          "клипа со стойкой попкорна и ценами (поиск по `popcorn`, `cinema`, "
          "`concession`, `price` — только зал, миски и супермаркет). По правилу "
          "«лучше своя графика, чем случайная перебивка» весь предметный слой "
          "нарисован на сетке, а сток взят под три буквальных существительных "
          "из речи: кинотеатр, порция попкорна, ценники вне кино.")


if __name__ == "__main__":
    emit()
