"""Генерирует монтажный лист ролика 7 из раскадровки."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from storyboard7 import SHOTS, CAPS, DUR, STOCK_NAMES, FACE_KINDS

NAMES = {
    "A1": ("R1", "лицо, базовая крупность"),
    "A2": ("R1", "лицо, крупнее (второй кроп)"),
    "stock": ("R2", "стоковая видео-вставка в карточке B"),
    "row_scan": ("R4+R10", "сетка: варианты появляются один за другим, пройденный гаснет"),
    "noreturn": ("R4+R10", "сетка: каждый пройденный вариант закрыт крестом, стрелка только вперёд"),
    "split37": ("R4+R10+R5b", "сетка: отметка отсекает первые 37%, синее «37%»"),
    "bestfirst": ("R4+R10", "сетка: лучший из пропущенных подсвечен, от него тянется планка"),
    "pick": ("R4+R10+R5b", "сетка: скан после отметки, первый выше планки загорается синим"),
    "tooearly": ("R4+R10", "сетка: отметка почти в начале — берём слабый вариант"),
    "missed": ("R4+R10", "сетка: настоящий лучший оказался дальше по ряду"),
    "toolate": ("R4+R10", "сетка: отметка уехала вправо, лучший остался в зоне наблюдения"),
    "observed": ("R4+R10", "сетка: скобка зоны наблюдения, лучший внутри неё перечёркнут"),
    "stats": ("R4+R10", "сетка: отсечки по каждому пройденному варианту"),
    "n37_100": ("R4+R5b", "сетка: синее «37%», ниже белое «100%» перечёркнуто"),
    "curve": ("R4+R10", "сетка: кривая P = −x·ln x, максимум ровно на 1/e ≈ 37%"),
}

if __name__ == "__main__":
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    stock = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k == "stock")
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)

    print("# Монтажный лист — «правило 37%» (задача оптимальной остановки)\n")
    print(f"Исходник: `videos/7/source.mp4` · 1080×1920 · 30 fps · {DUR:.2f}с · речь не резана")
    print("Готовый ролик: `videos/7/secretary_edit.mp4`\n")
    print(f"**Планов:** {len(SHOTS)} · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {lens[len(lens)//2]:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез **{SHOTS[0][1]:.2f}с**")
    print(f"**Лицо в кадре:** {face:.1f}с = **{100*face/DUR:.0f}%** · "
          f"сток {stock:.1f}с = {100*stock/DUR:.0f}% · "
          f"своя графика {DUR-face-stock:.1f}с = {100*(DUR-face-stock)/DUR:.0f}%")
    print(f"**Субтитров:** {len(CAPS)} фраз\n")

    print("## Вставки, скачанные под этот ролик\n")
    print("Все лежат в `videos/7/stock/`, лицензия Mixkit (free, коммерческое использование).\n")
    print("| файл | что на кадре | под какую фразу |")
    print("|---|---|---|")
    USED = {
        "5660":  "«лучшего кандидата на работу»",
        "3110":  "«лучшую квартиру»",
        "4530":  "«или даже партнёра»",
        "4919":  "«смотришь варианты один за другим» и реприза на «именно лучшего из них»",
        "29302": "«хватайте первого кто хоть немного понравился»",
    }
    for cid, why in USED.items():
        print(f"| `stock_{cid}.mp4` | {STOCK_NAMES[cid]} | {why} |")

    print("\n## Раскадровка\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        if kind == "stock":
            desc = STOCK_NAMES[prm["clip"]]
        if prm.get("topword"):
            rec += "+R6"
            desc += f" · крупное слово в карточке «{prm['topword']}»"
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} | {txt or '—'} |")

    print("\n> Планы 10 (13.94–16.70) и 26 (48.30–50.90) идут без субтитров: "
          "число несёт графика, дублировать его текстом нельзя (`brand-kit.md §5`).")
