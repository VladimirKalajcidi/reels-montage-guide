"""Монтажный лист версии ролика 24 с другим хуком.

    python3 plan24hook.py h1 > ../videos/24/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard24 as SB
from hook24 import HOOKS, CUT, CUT_F, lts_for
from plan24 import NAMES

# замеры готовых файлов (qa24hook.py)
MEASURED = {
    "h1": dict(lufs=-14.10, tp=-1.60, lra=2.6, frames=1629, dur=54.30, pause=0.394,
               seam=(58, 2289), rgb=2, psnr=43.9, gain=1.270,
               deform="кроп ×0.98 — карточка A на одном и том же кадре тела "
                      "(50.4с, план с лицом) 870px → 888px = ×1.0207 "
                      "(целевое ×1.0204, расхождение — 1px квантования)"),
}

RHYTHM = {
    "h1": dict(shots=27, avg=2.01, median=1.85, shortest=1.47, longest=2.91,
               first_cut=1.47, face_pct=40.0),
}

# межфразовые паузы самого дубля (гэпы >0.30с по videos/24/words.json)
BODY_PAUSES = dict(lo=0.339, hi=0.559, med=0.441, n=13)


def emit(key):
    cfg = HOOKS[key]
    m = MEASURED[key]
    r = RHYTHM[key]
    lens = [t1 - t0 for t0, t1, _, _ in cfg["shots"]]
    nh = cfg["frames"] / FPS
    dt = nh - CUT
    lts = lts_for(cfg)

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Готовый файл: `videos/24/{os.path.basename(cfg['out'])}` · 1080×1920 · 30 fps · "
          f"{m['dur']:.2f}с · {m['frames']} кадров")
    print(f"Хук: `videos/24/hook{key[-1]}.mov` · {cfg['frames']} кадров ({nh:.4f}с)")
    print(f"Тело: кадры {CUT_F}+ из уже сданного `regress_edit.mp4`, не пересобиралось\n")
    print(f"**Новый хук:** {cfg['title']}\n")
    print(f"**Ритм версии целиком:** {r['shots']} планов · средняя {r['avg']:.2f}с · "
          f"медиана {r['median']:.2f}с · мин {r['shortest']:.2f}с · макс {r['longest']:.2f}с · "
          f"первый рез {r['first_cut']:.2f}с · лицо **{r['face_pct']:.1f}%**\n")

    print("## Точка реза")
    print(f"Кадр **{CUT_F}** ({CUT:.4f}с) — граница планов `stock` → `A2` в исходном ролике, "
          "то есть конец старого начала «у очень высоких родителей дети в среднем чуть ниже, "
          "а у очень богатых в среднем не такие успешные». Планы 1–3 старого хука и все 5 "
          "их субтитров выброшены целиком: от старого начала не осталось ни кадра.")
    print(f"\nКадр считается как `ceil(4.797 × 30)` = {CUT_F}: граница плана стоит "
          "на дробном кадре 143.91, и кадр 143 — это ещё последний кадр выбрасываемого "
          "плана со стоком. Проверка машинная: `qa24hook.old_hook_gone` требует, чтобы "
          f"кадры {CUT_F - 1} и {CUT_F} лежали в разных планах.")
    print("\n**Что именно заменил хук.** Новый дубль проговаривает ровно то же первое "
          "предложение другими словами и добавляет заход «я думаю, вы точно замечали, "
          "что…». Поэтому убирается ровно одно предложение старого начала, и его конец "
          "совпадает с границей плана кадр в кадр — подбирать точку реза не пришлось.")
    print("\n**Связность стыка.** Тело начинается с «и дело тут не в слабых генах, "
          "а в чистой статистике». Указательное «тут» отсылает к самому явлению, "
          "а новый хук это явление проговаривает целиком — антецедент на месте, "
          "подставлять слова в дубль и выбрасывать фразы тела не пришлось.")
    print()

    print("## Блок хука")
    print(f"Планов: **{len(cfg['shots'])}** · средняя **{sum(lens)/len(lens):.2f}с** · "
          f"первый рез **{lens[0]:.2f}с** · мин {min(lens):.2f}с · макс {max(lens):.2f}с\n")
    print("| # | тайминг | кадры | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(cfg["shots"], 1):
        rec, desc = NAMES[kind]
        if prm.get("clip"):
            desc = SB.STOCK_NAMES[prm["clip"]] + f" (с {prm.get('ss', 0):.1f}с клипа)"
        txt = " / ".join("".join(x[0] for x in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {round(t0*FPS)}–{round(t1*FPS)} | {t1-t0:.2f}с "
              f"| {rec} | {desc} | {txt or '— (говорит графика)'} |")
    print(f"\nДалее без изменений идёт тело сданного ролика — планы 4–27 из "
          f"`montage-plan.md`, со сдвигом **{dt:+.4f}с** на новой таймлинии.")

    print("\n## Графика хука")
    print("Взято ровно то, что стояло в старом начале: план `tallPair` (линия среднего, "
          "точка родителя высоко над ней, точка ребёнка заметно ниже, пунктир "
          "на родительском уровне) и стоковая гора купюр. Это визуальная интрига ролика, "
          "менять её незачем; ни одного нового плана не нарисовано.")
    s = lts.get("tallPair", 1.0)
    print(f"\nНа слова дубля план ложится буквально: точка родителя появляется под "
          f"«у очень высоких родителей», точка ребёнка и пунктир — под «в среднем» / "
          f"«дети чуть ниже». Длина плана {lens[1]:.2f}с против 1.07с в теле, "
          f"масштаб времени анимации **×{s:.2f}** — то есть анимация идёт в штатном темпе "
          "тела и заканчивается на 0.92с, дальше схема стоит собранной, пока на неё "
          "ложатся оставшиеся две фразы. Ускорять анимацию можно, замедлять нельзя: "
          "тот же план в теле идёт своим темпом.")

    print("\n## Сток в хуке")
    print("Тот же клип, что стоял в старом начале, и с той же точки входа — "
          f"`stock_47005.mp4` с {cfg['shots'][2][3]['ss']:.1f}с. План длиннее "
          f"({lens[2]:.2f}с против 2.32с в теле), клип 10.07с это выдерживает без петли. "
          "Хвост блока хука закрыт им, а не стоп-кадром лица.")

    print("\n## Дубль хука — что сверено, что не правилось")
    print("- **Формат совпадает полностью**, приведения не потребовалось: и хук, и основной "
          "исходник — 720×1280, `yuv420p`, `color_range=tv`, `bt709`/`bt709`/`bt709`, 30 fps. "
          "Кадры читаются прямо из `.mov` и идут в штатный тракт A-roll **без единого "
          "промежуточного кодека**.")
    print("- **A-roll хука собран штатным трактом**: те же `FRAMINGS`, тот же `hflip`, "
          "грейда нет — ровно как у основного дубля, без поправок под хук.")
    print(f"- **Крупность** (детектор, после hflip, медиана по всему дублю): основной дубль "
          f"cx 398 / линия глаз 639 / ширина лица 283; этот хук cx {cfg['face_cx']} / "
          f"{cfg['face_eye']} / {cfg['face_d']}.")
    print("  Расхождение: **−8px по горизонтали, −1px по линии глаз, −1.4% по размеру "
          "лица** — то есть дубли сняты с одной точки и практически совпадают; "
          "разница внутри разброса самого детектора. Править нечего и ничего не правилось.")
    print("- **Зеркальность:** надписи в кадре нет ни в основном дубле, ни в хуке, "
          "проверить по тексту не на чем. Штатный `hflip` оставлен: рука с петличкой "
          "в обоих дублях с одной стороны кадра.")
    print(f"- **Средний RGB внутри карточки A**: кадры хука против кадров тела расходятся "
          f"на **{m['rgb']} единицы** по каналу (норма — до ~10).")

    print("\n## Уникализация версии")
    print(f"- Музыка: **`{os.path.basename(cfg['music'])}`** — свой трек, "
          "у версии №1 `song3.mp3`. Ни один не повторяется.")
    print("  Трек 335с длиннее ролика, поэтому идёт без петли — шва не существует.")
    print(f"- Деформация: **{m['deform']}**.")
    print("- Деформация наложена на уже собранное немое видео одним проходом кодека, "
          "кадры не перерисовывались. Ресайз bilinear, а не lanczos: у lanczos "
          "отрицательные лепестки дают на границе карточки светлый ореол в 1px, "
          "и автопроверка «текст за карточкой» краснеет.")

    print("\n## Звук")
    print("- Дорожка пересобрана целиком: голос хука + голос тела с точки реза, постель "
          f"(whoosh / impact / tick) со сдвигом **{dt:+.4f}с**, музыка с нуля, потом loudnorm.")
    print("- Whoosh стоит и на резах внутри хука, и на самом шве «хук → тело».")
    print(f"- Голос хука приведён к громкости тела по RMS речи (×{m['gain']:.3f}): "
          "дубль записан тише основного.")
    print(f"- Пауза между последним словом хука и первым словом тела: **{m['pause']:.3f}с**. "
          "Чеклист `delivery-specs §6` называет 0.10–0.20с, но там же оговорка «как между "
          f"предложениями в теле» — в этом дубле межфразовые паузы идут "
          f"{BODY_PAUSES['lo']:.2f}–{BODY_PAUSES['hi']:.2f}с "
          f"(медиана {BODY_PAUSES['med']:.2f}с по {BODY_PAUSES['n']} паузам), "
          f"так что {m['pause']:.2f}с — ровно уровень тела. Укоротить её нечем: "
          "0.384с из этой паузы — это тишина в голове тела перед словом «и», "
          "а тело идёт готовыми кадрами, и сдвигать под него звук значит развалить синхрон.")
    print(f"- Стык без щелчка: максимальный скачок между соседними сэмплами на шве "
          f"**{m['seam'][0]}** против **{m['seam'][1]}** на 99.9-м процентиле всей дорожки.")
    print(f"- Громкость **{m['lufs']:.2f} LUFS**, истинный пик **{m['tp']:.2f} dBFS**, "
          f"LRA {m['lra']:.1f} LU — сведено к уровню уже сданного `regress_edit.mp4` "
          "(−14.10 / −1.60 / 2.5), а не к абстрактным −14.")

    print("\n## Автопроверки")
    print("```bash")
    print(f"cd build && python3 qa24hook.py {key}")
    print("```")
    print("Все по нулям: `text_out_of_card=0`, `gfx_text_overlap=0`, `gfx_out_of_zone=0`, "
          "`line_overlaps=0` по блоку хука, `bright_outside` = 0 кадров по всему файлу версии "
          "(включая деформацию), нарушений стиля субтитров 0, слов не из речи 0.")
    print(f"- Рез по границе плана: кадры {CUT_F - 1} и {CUT_F} лежат в разных планах "
          "(`stock` → `A2`) — от старого хука не осталось ни кадра, ни субтитра.")
    print(f"- Тело против сданной версии — худший PSNR **{m['psnr']:.1f} dB** "
          "на 14 контрольных кадрах (это второе прохождение того же кодека, картинка та же).")
    print("- Версия №1 не тронута: `regress_edit.mp4` не открывался на запись — "
          "хук читает из него только готовые кадры тела.")


if __name__ == "__main__":
    emit(sys.argv[1])
