"""Монтажные листы версий с другим хуком (ролик 32)."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import storyboard32 as SB
import hook32 as HK
import qa32hooks as Q
from style import FPS
import plan32

VD = "/Users/vladimirkalajcidi/reels_good/videos/32"

MEAS = {   # замеры сданных файлов
    "h1": dict(lufs=-14.0, tp=-1.6, lra=2.0, row_v1=579, row_ver=592, scale=1.0225,
               seam=3.56, start=16.48, tail=5.84, body_worst=8.29,
               click=0.00067, typical=0.15103),
    "h2": dict(lufs=-14.0, tp=-1.6, lra=1.7, row_v1=579, row_ver=579, scale=1.0,
               seam=0.15, start=14.37, tail=3.61, body_worst=2.28,
               click=0.0011, typical=0.1506),
}

HOOK_NAMES = {
    "rowBuild": ("R4+R10", "сетка: шеренга из 9 фигур собирается слева направо; "
                           "числа ещё нет — оно придёт, когда его произнесут"),
    "rowNum": ("R4+R5a", "сетка: шеренга уже стоит, всплывает белое **100** "
                         "резким попом сразу после произнесённого «100»"),
}


def names(kind):
    return HOOK_NAMES.get(kind) or plan32.NAMES[kind]


def emit(key):
    cfg = HK.HOOKS[key]
    n = cfg["version"] - 1
    m = MEAS[key]
    rate = 1.02 if cfg.get("post_a") else 1.0
    pr = Q.probe(cfg["out"])
    rh = Q.rhythm(key, cfg["out"])
    hw = json.load(open(f"{VD}/words_hook{n}.json"))
    hook_dur = cfg["frames"] / FPS

    print(f"# Монтажный лист — версия {cfg['version']}, хук {n}\n")
    print(f"Хук: `videos/32/hook{n}.mov` · 720×1280 · 30 fps · "
          f"{hook_dur:.3f}с ({cfg['frames']} кадров) · SDR bt709")
    print(f"Готовый ролик: `videos/32/{os.path.basename(cfg['out'])}` · "
          f"{pr['w']}×{pr['h']} · {pr['fps']} · {pr['frames']} кадров · "
          f"{pr['v_dur']:.2f}с\n")
    print(f"Текст хука: {cfg['title']}\n")
    print(f"**Планов:** {rh['shots']} · средняя длина **{rh['avg']}с** · "
          f"медиана {rh['median']}с · мин {rh['shortest']}с · макс {rh['longest']}с · "
          f"первый рез {rh['first_cut']}с")
    print(f"**Лицо в кадре:** **{rh['face_pct']}%**\n")

    print("## Блок хука — перерисован целиком\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, _p) in enumerate(cfg["shots"], 1):
        rec, desc = names(kind)
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")
    if rate != 1.0:
        print(f"\nТайминги блока даны до ускорения ×1.02; на экране они короче "
              f"в 1.02 раза (весь ролик, включая хук, проходит через `setpts`).")

    print(f"\nГрафика хука — та же, что стояла в старом начале: `row` "
          f"(шеренга + белое 100) и `hats` (шляпы падают на головы). Ни одного "
          f"нового рисунка не добавлено. Служебные состояния `rowBuild` / "
          f"`rowNum` — тот же план `row`, разложенный на «ряд собирается» и "
          f"«всплывает число»: между ними в этом дубле вклинивается план "
          f"с лицом. Хук длиннее старого начала, поэтому анимации замедлены "
          + ", ".join(f"`{k}` ×{v}" for k, v in cfg.get("gfx_scale", {}).items())
          + " — иначе `hats` отыгрывает за 0.99с и стоит неподвижно ещё "
            "две секунды.")

    print("\n## Точка реза\n")
    print("Оба новых дубля перекрывают не одну первую фразу, а две — "
          "«представьте 100 заключённых, стоящих в ряд» **и** «каждому "
          "надевают случайно чёрную или белую шляпу». Поэтому выброшено всё "
          f"до конца плана `hats`: планы 1–4 версии 1 (0.00–5.499) и шесть "
          f"их субтитров. Рез по границе плана: `CUT_F = ceil(5.499 × 30) = "
          f"{HK.CUT_F}`, то есть **{HK.CUT:.3f}с**.")
    print("\nГраница проверена по огибающей, а не только по whisper: "
          "`silencedetect` на source.mov даёт тишину ровно 5.4993–5.9003 — "
          "слово «шляпу» кончается там же, где кончается звук, и рез попадает "
          "в тишину, а не в атаку слова.")
    print(f"\nОт старого хука не осталось ни кадра (`qa32hooks.no_old_hook`): "
          f"первый кадр тела версии совпадает с кадром {HK.CUT_F} версии 1 "
          f"(средняя разница {m['seam']} по пикселю — уровень шума кодека"
          + (" и пересжатия после кропа" if key == "h1" else "") + "), "
          f"а кадр 10 и последний кадр блока хука с версией 1 расходятся "
          f"({m['start']} и {m['tail']}) — там другой дубль.")

    print("\n## Передача эстафеты\n")
    print("Тело начинается с «каждый видит шляпы людей перед собой». "
          "«Каждый» и «шляпы» опираются на заключённых и на шляпы — и то "
          "и другое заново проговорено в этом хуке, дефицита антецедента нет.")
    tot, tail, body = Q.pause_at_seam(key)
    print(f"\nПауза «хук → тело» — **{tot}с** (хвост тишины хука {tail}с + "
          f"собственная пауза тела {body}с). Это не растянутый шов: ровно "
          "столько же длится пауза между этими двумя предложениями в самом "
          "исходнике, и она целиком приходит из тела. У этого дубля "
          "межфразовые паузы вообще 0.26–0.46с, так что 0.40 — его норма. "
          "Спецификация просит 0.10–0.20с; короче здесь не сделать, "
          "не подрезав речь тела.")
    print(f"\nЩелчка на стыке нет: скачок между соседними сэмплами на шве "
          f"{m['click']} против типичного внутри дорожки {m['typical']} "
          f"(99.9-й перцентиль) — на два порядка тише.")

    print("\n## Тело — кадр в кадр\n")
    print(f"Тело не пересобиралось: {1531 - HK.CUT_F} кадров взяты готовыми из "
          f"`assets/_video_{SB.TAG}.mp4` и склеены за новым хуком одним "
          f"проходом кодека. Сверка с версией 1 по 81 кадру: худшая средняя "
          f"разница **{m['body_worst']}** по пикселю"
          + (" — это пересжатие после кропа ×0.98 и обратного масштабирования "
             "при сравнении, а не расхождение картинки" if key == "h1"
             else " — уровень шума кодека") + ".")

    print("\n## Уникализация версии\n")
    if key == "h1":
        print(f"- Трек: `audios/{os.path.basename(cfg['music'])}` "
              "(у версии 1 — song2.mp3, у версии 3 — song3.mp3, ни один "
              "не повторяется). Трек короче ролика — петля с кроссфейдом "
              "0.25с, фейды 0.8 / 2.0с.")
        print(f"- Деформация: **кроп ×0.98** — обрезано 2% по краям и возвращён "
              f"холст 1080×1920. Измерено по объекту в кадре: ширина ряда фигур "
              f"на плане `parityB` {m['row_v1']}px в версии 1 → {m['row_ver']}px "
              f"в версии 2, то есть **×{m['scale']}** при ожидаемых ×1.0204 "
              f"(разница — гранулярность в 1px на 579).")
    else:
        print(f"- Трек: `audios/{os.path.basename(cfg['music'])}` "
              "(у версии 1 — song2.mp3, у версии 2 — song1.mp3, ни один "
              "не повторяется). Трек длиннее ролика — петли нет.")
        print(f"- Деформация: **ускорение ×1.02**, картинка и звук вместе "
              f"(`setpts=PTS/1.02` + `atempo=1.02`) — 2% рассинхрона на губах "
              f"видно сразу. После `setpts` дописан `fps=30`: на выходе "
              f"**{pr['fps']}**, а не 30.6. Длительности сходятся: видео "
              f"{pr['v_dur']:.3f}с, звук {pr['a_dur']:.3f}с, расхождение "
              f"{abs(pr['v_dur']-pr['a_dur']):.3f}с. Ширина ряда фигур не "
              f"изменилась ({m['row_v1']} → {m['row_ver']}px) — и не должна: "
              f"эта версия деформируется по времени, а не по кадру.")
    print("- Версия 1 не тронута: файл `hats_edit.mp4` тот же, что сдавали "
          "(sha1 8a304aa7eba03d871b61efa2a615f60d3663f96e).")

    print("\n## A-roll хука\n")
    print("Дубль прошёл через тот же тракт, что и основной исходник: те же "
          "`FRAMINGS` (окно 630×1000 от 75, 228), тот же безусловный `hflip`, "
          "грейда нет. Ни одной поправки под дубль не сделано.")
    print("\nЦветовые теги сверены: `yuv420p` / `tv` / `bt709` / `bt709` / "
          "`bt709` — совпадают с основным исходником, приведение HDR→SDR "
          "не требуется.")
    rgb_h = HK.card_rgb(cfg["src"], 1.0)
    rgb_m = HK.card_rgb(SB.SRC, 1.0)
    dmax = max(abs(a - b) for a, b in zip(rgb_h, rgb_m))
    print(f"\nСредний RGB внутри карточки A: хук {rgb_h} · основной дубль "
          f"{rgb_m} — расхождение до {dmax} единиц по каналу при норме ~10.")
    print(f"\n**Расхождение крупности названо, а не подчищено кропом.** "
          f"Детектор (после hflip, среднее по дублю):\n")
    print("| дубль | центр лица x | линия глаз y | ширина лица |")
    print("|---|---|---|---|")
    print("| основной | 390 | 648 | 283 |")
    print(f"| hook{n} | {cfg['face_cx']} | {cfg['face_eye']} | {cfg['face_d']} |")
    print(f"\nШирина лица сходится в пределах 2%, но голова стоит на "
          f"{cfg['face_eye'] - 648}px ниже: при штатном кропе линия глаз "
          f"садится на {(cfg['face_eye'] - 228) / 10:.0f}% высоты карточки "
          f"вместо 42%. Это решается на съёмке (та же точка и дистанция), "
          f"а не кропом на монтаже.")
    print("\nЗеркальность проверена по кадру: сцена та же, что у основного "
          "дубля (тёмная стена слева, светлая справа) — штатный `hflip` "
          "подходит, отключать его не нужно.")

    print("\n## Звук\n")
    print("Дорожка пересобрана целиком, а не склеена из готовых: голос хука "
          "(с коррекцией уровня по RMS речи под тело) + голос тела от точки "
          f"реза, постель со сдвигом {cfg['frames']/FPS - HK.CUT:.3f}с, музыка "
          "с нуля, потом loudnorm.")
    print(f"\n- Whoosh на каждой склейке блока хука, на шве «хук → тело» "
          f"и на всех склейках тела со сдвигом (0.040 от пика).")
    print(f"- Импакт под белым 100 в хуке и под синим 99 в теле (0.070).")
    print(f"- Тики под каскадами (0.030).")
    print(f"- Замер готового `.mp4`: **{m['lufs']} LUFS**, истинный пик "
          f"**{m['tp']} dBTP**, LRA {m['lra']} LU. Ориентир — громкость "
          f"версии 1 (**{plan32.LUFS} LUFS**), а не абстрактные −14: "
          f"зритель сравнивает версии между собой.")

    print("\n## Расшифровка хука\n")
    print(f"Пословные тайминги — `videos/32/words_hook{n}.json`, собраны по "
          "речевым отрезкам (`align32hooks.py`): границы сняты "
          "`silencedetect` (-34dB / 0.12с), внутри отрезка выдача whisper "
          "large-v3 растянута на измеренный интервал.\n")
    print("| # | слово | старт | конец |")
    print("|---|---|---|---|")
    for i, w in enumerate(hw, 1):
        print(f"| {i} | {w['word']} | {w['start']:.3f} | {w['end']:.3f} |")

    print("\n## Автопроверки версии\n")
    px, _ = Q.pixel_checks(key)
    print("| проверка | результат |")
    print("|---|---|")
    print(f"| резы внутри слова | {Q.cuts_inside_word(key)[0]} |")
    print(f"| субтитры мимо расшифровки хука | {Q.caption_words_match(key)[0]} |")
    print(f"| субтитры: стиль, тайминг, переход через рез | {Q.caption_checks(key)[0]} |")
    print(f"| текст за карточкой (блок хука) | {px['text_out_of_card']} |")
    print(f"| графика на тексте (блок хука) | {px['gfx_text_overlap']} |")
    print(f"| графика вне зоны (блок хука) | {px['gfx_out_of_zone']} |")
    print(f"| наложение строк блока | {px['line_overlap_pairs']} |")
    print("\nТело версии проверять заново не нужно: это те же кадры, что "
          "в версии 1, где все проверки уже дали ноль (`videos/32/qa-report.md`).")


if __name__ == "__main__":
    emit(sys.argv[1])
