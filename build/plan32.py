def emit():
    face = sum(t1 - t0 for t0, t1, k, _ in SHOTS if k in FACE_KINDS)
    lens = sorted(t1 - t0 for t0, t1, _, _ in SHOTS)
    med = lens[len(lens) // 2]
    sizes = [sz for _, _, runs, _ in CAPS for _, _, sz in runs]

    print("# Монтажный лист — «100 заключённых и шляпы»\n")
    print(f"Исходник: `videos/32/source.mov` · 720×1280 · 30 fps · {DUR:.2f}с · "
          "SDR bt709 (`yuv420p` / `bt709` / `bt709`, конверсия не нужна)")
    print("Готовый ролик: `videos/32/hats_edit.mp4` · 1080×1920 · 30 fps · "
          f"{int(round(DUR*30))} кадров\n")
    print(f"**Планов:** {len(SHOTS)} · средняя длина **{sum(lens)/len(lens):.2f}с** · "
          f"медиана {med:.2f}с · мин {lens[0]:.2f}с · макс {lens[-1]:.2f}с · "
          f"первый рез {SHOTS[0][1]:.2f}с — медиана на 0.03с выше эталонной "
          "вилки 1.5–2.0с: ролик почти целиком объяснительный, коротких "
          "планов-вспышек в нём быть не должно, очередь R3 не используется")
    print(f"**Лицо в кадре:** {face:.1f}с из {DUR:.1f}с = **{100*face/DUR:.0f}%** "
          f"· графика **{100*(DUR-face)/DUR:.0f}%** — вся своя, стока нет "
          "(обоснование ниже). Для доказательного ролика доля лица ближе "
          "к 30% — норма (delivery-specs §6).")
    print(f"**Субтитров:** {len(CAPS)} фраз · кегли {min(sizes)}–{max(sizes)}pt · "
          "**синее число: 1 (99)** · **белое число: 1 (100)**\n")
    print("Речь не резана: резы только по картинке, все — на границах слов "
          "по пословным таймингам (`qa32.speech_sync` = 0).\n")

    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, prm) in enumerate(SHOTS, 1):
        rec, desc = NAMES[kind]
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in CAPS if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")

    print("\n## Ошибка в сценарии — не исправлена монтажом, вынесена сюда")
    print("Отрезок **14.92–17.20** whisper large-v3 читает как «но заранее "
          "**не** могут договориться о стратегии» (вероятность слова «не» "
          "0.95; medium-модель даёт то же самое). Но следующая фраза — «и она "
          "должна быть такой» — и вся дальнейшая механика (последний передаёт "
          "заранее условленный бит чётности) требуют обратного: **без "
          "предварительного сговора стратегии не существует**, и задача не "
          "решается вообще. Изолированный прогон куска 15.35–16.00 даёт "
          "вариант «они могут», то есть место акустически спорное.")
    print("\nРечь не режем (`editing-taste §5`), но спорные слова на экран не "
          "выносим: субтитр на этом плане несёт только однозначную часть — "
          "«но заранее» / «договориться о стратегии». Решение — переписать "
          "фразу и переснять этот кусок — не за монтажом.")

    print("\n## Сценарий пересчитан — остальная арифметика верна")
    print("Вся цепочка вывода перебрана машинно (`qa32.deduction` = 0 "
          "нарушений), а не взята на веру.\n")
    print("| в речи | пересчёт |")
    print("|---|---|")
    print(f"| «представьте {PRISONERS} заключённых» | {PRISONERS} ✓ |")
    print("| «последний использует свой ответ, чтобы передать один бит» | "
          "чётность числа чёрных шляп впереди — ровно 1 бит, двух цветов "
          "хватает ✓ |")
    print(f"| «остальные {SAVED} точно определяют свои цвета» | "
          f"{PRISONERS} − 1 = **{SAVED}** ✓ — каждый k от {LAST-1} до 0 "
          "получает свой цвет однозначно: объявленная чётность минус то, что "
          "он видит впереди, минус уже названные сзади |")
    print(f"| «первый отвечающий может ошибиться» | у него нет ни одного "
          "источника про свою шляпу — 50/50 ✓ |")
    lay = " ".join(("чёрная" if h else "белая") for h in HATS)
    print(f"\nРасклад шляп на экране зафиксирован и просчитан: "
          f"{lay} — по индексам 0..{LAST} "
          f"(0 — первый в ряду, {LAST} — крайний справа, он же отвечает первым). "
          f"Чёрных впереди последнего — {len(BLACKS_AHEAD)} (индексы "
          f"{BLACKS_AHEAD}), это нечётно, поэтому план `parityB` рисует ровно "
          f"{len(BLACKS_AHEAD)//2} пару и один остаток. Человек {NEXT} видит те же "
          f"{len(BLACKS_AHEAD)} чёрных — значит его шляпа белая, и именно белую "
          "рисует план `deduceB`.")

    print("\n## Кто что несёт: графика и субтитр")
    print("**На графике нет ни одной надписи** — только фигуры, цвет и два "
          "числа. Слова несёт субтитр, механику несёт ряд:\n")
    print("| элемент графики | что кодирует |")
    print("|---|---|")
    print("| белый кружок с плечами | человек; ряд идёт слева направо, "
          "«впереди» — это левее, крайний справа отвечает первым |")
    print("| шляпа с белой заливкой / с чёрной заливкой и белым контуром | "
          "белая / чёрная шляпа (на чёрном фоне заливкой чёрную не показать) |")
    print("| пунктирный контур шляпы | человек не знает своего цвета — "
          "состояние знания, а не цвет: зритель цвет видит всегда |")
    print("| белый маркер над шляпой | эта шляпа сосчитана тем, кто сейчас думает |")
    print("| синий маркер над шляпой | цвет уже вычислен — результат |")
    print("| синий кружок на стрелке | тот самый один бит |")
    print("| дуга между маркерами + один без пары | чётность: «нечётно» |")
    print("| указатель под фигурой | речь сейчас про этого человека |")
    print(f"\nРяд из {N} фигур — не {PRISONERS}: сотня в полосе 730px нечитаема. "
          "Точное число несёт текст (белое **100** на плане `row`), тот же "
          "приём, что кольцо из 16 узлов для «100 друзей» в ролике 30. "
          f"Синее **99** на плане `ninetyNine` — тоже текст, рядом с ним "
          f"маркерами подсвечиваются {LAST} из {N} нарисованных.")
    print("\nЧисла на экране стоят там, где субтитр их не повторяет ни цифрой, "
          "ни словом (`qa32.digits_in_captions` = 0, "
          "`qa32.captions_on_number_shots` = 0): во время ревила синего 99 "
          "субтитра на экране нет вообще — блок «зато остальные» срезан на "
          "41.43, следующий стартует только на 42.40. На плане `A1word` "
          "субтитр обрывается на «шансом ради передачи», слово ИНФОРМАЦИЯ "
          "несёт крупная надпись R6.")
    print("\nМашинная проверка пересечения слоёв (`qa32.gfx_text_overlap`) — "
          "0 кадров; графика не выходит из зоны y700…1560 / x175…905 "
          "(`qa32.gfx_out_of_zone`) — 0 кадров и нигде не упирается во врезку "
          "маски (`qa32.gfx_clipped`) — 0 кадров. Текст за карточку не "
          "выходит (`qa32.text_out_of_card` и `qa32.bright_outside_card`) — "
          "0 кадров; строки блоков не пересекаются "
          "(`qa32.line_overlap_pairs`) — 0 пар.")

    print("\n## Почему в ролике нет стока")
    print("Тема целиком механическая: смысл держится на том, кто кого видит и "
          "что из этого выводит. Живого видео, буквально показывающего "
          "шеренгу заключённых в чёрных и белых шляпах, не существует, а "
          "перебивка «человек за решёткой» относится к слову «заключённые» "
          "ровно один раз — на 0.85–1.47, то есть внутри хука, где по "
          "`editing-taste §2` обязано быть лицо. Ставить сток ради ритма "
          "`assets-manifest §2` прямо запрещает: «если под конкретную тему нет "
          "очевидно релевантного живого видео — не ставь сток». Всё закрыто "
          "своей графикой R4/R10, как в ролике 30.")

    print("\n## Цвет")
    print("- Синим (#3B4BE8) — итоговое число **99**, бит чётности "
          "(непарный маркер и импульс на стрелке) и маркеры уже вычисленных "
          "шляп. Один код на весь ролик: синее = результат (brand-kit §4).")
    print("- Лайм не использован: в ролике нет матричных/табличных элементов, "
          "для которых он предусмотрен.")
    print(f"- Кегли субтитров {min(sizes)}–{max(sizes)}pt.")

    print("\n## Звук")
    print("- Речь исходника целиком, без резки.")
    print(f"- Whoosh на каждой из {len(SHOTS)-1} склеек (0.040 от пика), импакт "
          "под двумя ревилами чисел (0.070), тики под каскадами фигур и "
          "маркеров ряда (0.030).")
    print("- Музыка `audios/song2.mp3`: −19 dB от RMS голоса, фейды 0.8 / 2.0с.")
    print("- Финал: highpass 65 Гц + loudnorm I=-14 TP=-1.5 LRA=7 + добор "
          "volume 1.60 dB / alimiter limit=0.80.")
    print(f"- Замер готового `.mp4`: **{LUFS} LUFS**, истинный пик **{TP} dBTP**, "
          f"**LRA {LRA} LU**. LUFS и пик в норме; LRA ниже эталонных 3–5 LU — "
          "это свойство дубля (ровная подача без громкостных пиков), "
          "растягивать её обработкой значило бы качать голос.")

    print("\n## A-roll")
    print("Кадр с лицом идёт без грейда: только `hflip`, кроп и ресайз "
          "(`FRAMINGS` в render32.py). Кроп посчитан по детектору: 29 замеров "
          "по всему дублю дали cx 390±5, линию глаз y 648±5, ширину лица "
          "283±6 — окно 630×1000 от (75, 228) ставит глаза на 42% высоты "
          "карточки. Зеркальность проверена по кадру: сцена та же, что "
          "в ролике 30 (тёмная стена слева, светлая справа), штатный `hflip` "
          "подходит.")

    print("\n## Расшифровка")
    print("Пословные тайминги — `videos/32/words.json`, собраны по речевым "
          "отрезкам: границы сняты `ffmpeg silencedetect` (-34dB / 0.12с, "
          "зазоры <0.15с слиты), внутри каждого отрезка выдача whisper "
          "large-v3 растянута на измеренный интервал (`align32.py`). "
          "Слово «видимый» на 33.62 исправлено на «видимые» — по контексту "
          "«используя этот ответ и видимые шляпы».")


if __name__ == "__main__":
    emit()
