# --- точки и маршруты ------------------------------------------------------
def gen_points(n, seed, mind):
    """Детерминированный разброс адресов с минимальной дистанцией mind."""
    rnd = random.Random(seed)
    pts, guard = [], 0
    while len(pts) < n and guard < 400000:
        guard += 1
        p = (round(rnd.uniform(PX0, PX1), 1), round(rnd.uniform(PY0, PY1), 1))
        if all(math.dist(p, q) >= mind for q in pts):
            pts.append(p)
    if len(pts) < n:
        raise RuntimeError(f"не разложились {n} точек при mind={mind}")
    return pts


def tour_len(pts, order):
    return sum(math.dist(pts[order[i]], pts[order[(i + 1) % len(order)]])
               for i in range(len(order)))


def all_tours(n):
    """Все различные замкнутые маршруты по n точкам со стартом в точке 0.

    Маршрут и он же задом наперёд — один и тот же маршрут, поэтому из пары
    оставляем ту, где второй индекс меньше последнего. Их ровно (n-1)!/2.
    """
    out = []
    for perm in itertools.permutations(range(1, n)):
        if perm[0] < perm[-1]:
            out.append((0,) + perm)
    return out


def best_tour(pts):
    return min(all_tours(len(pts)), key=lambda o: tour_len(pts, o))


def nn_tour(pts, start=0):
    """Жадный маршрут: каждый раз едем в ближайший неотмеченный адрес."""
    left = set(range(len(pts))) - {start}
    order = [start]
    while left:
        c = order[-1]
        nxt = min(left, key=lambda i: math.dist(pts[c], pts[i]))
        order.append(nxt)
        left.discard(nxt)
    return tuple(order)


def _seg_cross(a, b, c, d):
    """Строгое пересечение отрезков ab и cd (общие концы не считаются)."""
    if a in (c, d) or b in (c, d):
        return False

    def s(p, q, r):
        v = (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])
        return (v > 1e-9) - (v < -1e-9)

    return s(a, b, c) * s(a, b, d) < 0 and s(c, d, a) * s(c, d, b) < 0


def crossings(pts, order):
    """Пары самопересекающихся рёбер маршрута."""
    n = len(order)
    edges = [(order[i], order[(i + 1) % n]) for i in range(n)]
    out = []
    for i in range(n):
        for j in range(i + 1, n):
            a, b = edges[i]
            c, d = edges[j]
            if _seg_cross(pts[a], pts[b], pts[c], pts[d]):
                out.append((i, j))
    return out


def two_opt(pts, order):
    """2-opt до локального оптимума: разворот куска маршрута, если короче."""
    order = list(order)
    improved = True
    while improved:
        improved = False
        n = len(order)
        for i in range(1, n - 1):
            for j in range(i + 1, n):
                cand = order[:i] + order[i:j + 1][::-1] + order[j + 1:]
                if tour_len(pts, cand) + 1e-9 < tour_len(pts, order):
                    order, improved = cand, True
    return tuple(order)


