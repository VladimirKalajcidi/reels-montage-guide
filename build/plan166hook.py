"""Монтажный лист версии с другим хуком ролика 66 (слот 166): python3 plan166hook.py h1 > montage-plan-hook1.md
Копия plan305hook.py."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hook166 as K
import render166 as R
from storyboard166 import NAMES, STOCK

key = sys.argv[1]
cfg = K.HOOKS[key]
shots = K.setup(key)
nf = cfg["frames"]
dt = nf / 30 - K.CUT_V
GFX = {"inf": "сетка: знак ∞ рисуется с реза на «бесконечно», затем по нему бежит точка (та же графика, что в старом хуке)"}
face = sum(t1 - t0 for t0, t1, k, _ in shots if k in R.FACE_KINDS)

print(f"# Монтажный лист — хук {key[1]} (версия {cfg['version']}) · обезьяна и Гамлет\n")
print(f"Файл: `videos/66/{os.path.basename(cfg['out'])}` · дубль `videos/66/hook{key[1]}.mov` · "
      f"скрипты `align166hooks.py`, `hook166.py`, `qa166hooks.py`, `plan166hook.py`, `contact166hooks.py`\n")
print(f"Новое начало: {cfg['title']}\n")
print("Выброшено старое начало целиком: «Это самый необычный пример того, как работает бесконечность. Есть знаменитая "
      "теорема: если обезьяна будет вечно нажимать случайные клавиши, она рано или поздно напечатает Гамлета» — планы "
      "0–9.95 (A1, ∞, A2, макака, клавиатура, машинка). Граница плана 9.95; тело взято с кадра **304** (10.1333) внутри "
      "тишины первого плана A1 — иначе пауза на шве была бы ≥0.28с. Тело — готовые кадры `_video_ape166.mp4` (v1) с «Это "
      f"звучит красиво, но давайте посчитаем», сдвиг {dt:+.3f}с.\n")
print(f"**Блок хука:** {nf} кадров = {nf / 30:.3f}с · планов {len(shots)} · лицо {face:.2f}с · первый рез {shots[1][0]:.3f}с · "
      f"вся версия {nf / 30 + (1175 - K.CUT_F) / 30:.2f}с\n")
print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
print("|---|---|---|---|---|---|")
for i, (t0, t1, kind, prm) in enumerate(shots, 1):
    rec, desc = NAMES[kind]
    if kind == "stock":
        desc = STOCK[prm["clip"]] + f", ss {prm['ss']}, cx {prm['cx']} (тот же клип и окно, что в старом хуке)"
    desc = GFX.get(kind, desc)
    txt = " / ".join(" ".join(r[0] for r in c[2]).replace(" /", "") for c in cfg["caps"] if t0 - 1e-6 <= c[0] < t1)
    print(f"| {i} | {t0:.3f}–{t1:.3f} | {t1 - t0:.2f}с | {rec} | {desc} | {txt} |")
print(f"| — | {nf / 30:.3f}– | — | тело | планы 7–21 сданной версии без изменений (первый — с 10.1333) | — |\n")
print("Последний план хука — машинка до конца блока: лицом «Вопрос только когда» вышло бы 0.93с (< 1с). «Бесконечно» несёт "
      "знак ∞ — в субтитре его нет. «КОГДА» — красным.\n")
print("## Шов и звук")
print("- Голос хука до 5.30 («когда» кончается 5.28), голос тела с кадра 303 (10.10) — на кадр раньше картинки (J-cut 1 "
      "кадр); «Это» звучит в 10.23. Пауза хук → тело ≈0.15с (норма 0.10–0.20, замер — `qa-report-hooks.md`).")
print("- Звук пересобран целиком: голос хука (уровень подогнан к телу ×1.036) + голос тела, whoosh на всех резах и на шве, "
      "impact/tick тела со сдвигом, тики ∞; музыка с нуля, loudnorm + доводка до громкости оригинала (−14.2).")
print(f"- Музыка `{os.path.relpath(cfg['music'], K.ROOT)}` — у каждой версии своя (оригинал — song1).")
print(f"- Уникализация: `{cfg['post_v']}`" + (f" + `{cfg['post_a']}`" if cfg["post_a"] else "") + ".")
print("\n## Дубль хука")
print("Теги 2160×3840 HEVC yuv420p smpte170m/bt709 — как у основного, HDR нет. Тракт A-roll тот же: FRAMINGS A1 2040×3236 "
      "от (114, 604), A2 1740×2760 от (264, 834), hflip (в дубле «dji» задом наперёд — `work/hook1_mic.jpg`), грейд «Г». "
      "Лицо дубля (720×1280, с отражением): центр (370, 704), ширина 456 против (379, 716), 463 у основного — "
      "расхождение 9–12px, кропом не правилось. Средний RGB карточки до грейда: 154/129/115 против 156/132/118.")
