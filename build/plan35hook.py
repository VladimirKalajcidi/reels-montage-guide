"""Монтажный лист версии ролика 35 с альтернативным хуком.

    python3 plan35hook.py h1 > ../videos/35/montage-plan-hook1.md
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from style import FPS
import storyboard35 as SB
import hook35 as HK
from plan35 import NAMES

# замеры готовых файлов
MEASURED = {
    "h1": dict(lufs=-14.17, tp=-1.68, frames=1533, dur=51.10,
               rgb_hook=(123, 110, 103), rgb_body=(124, 111, 102),
               scale=1.0207, speed=None, seam=(0.00041, 0.05433),
               pause=0.523, face_cx=369, face_eye=684, face_d=270),
    "h2": dict(lufs=-14.16, tp=-1.64, frames=1495, dur=49.83,
               rgb_hook=(124, 112, 104), rgb_body=(124, 111, 102),
               scale=None, speed=1.0201, seam=(0.00034, 0.05313),
               pause=0.502, face_cx=370, face_eye=687, face_d=265),
}
BODY_DIFF = (0.944, 0.082)      # макс. средняя разница и доля пикселей >8


def emit(key):
    cfg = HK.HOOKS[key]
    m = MEASURED[key]
    shots = HK.shots_of(cfg)
    n_body = m["frames"] if m["speed"] else cfg["frames"]
    dur_plain = (cfg["frames"] + 1321) / FPS

    print(f"# Монтажный лист — версия {cfg['version']}, хук {key[-1]}\n")
    print(f"Хук: `videos/35/hook{key[-1]}.mov` — {cfg['title']}")
    print(f"Тело: готовые кадры из `build/assets/_video_{SB.TAG}.mp4`, "
          f"с кадра **{HK.CUT_F}**. Ролик не пересобирался.")
    print(f"Готовый файл: `{os.path.relpath(cfg['out'], '/Users/vladimirkalajcidi/reels_good')}` "
          f"· 1080×1920 · 30 fps · {m['frames']} кадров · {m['dur']:.2f}с\n")

    print("## Блок хука\n")
    print("| # | тайминг | длит. | рецепт | что на экране | текст на экране |")
    print("|---|---|---|---|---|---|")
    for i, (t0, t1, kind, _) in enumerate(shots, 1):
        rec, desc = NAMES[kind] if kind in NAMES else (
            "R4+R10", {"boxesA": "сетка: каскадом встают три обычные коробки-множества "
                                 "(точки внутри — элементы)",
                       "boxesB": "сетка: три обычные уже стоят, каскадом появляются две "
                                 "коробки с копией себя внутри"}[kind])
        txt = " / ".join("".join(r[0] for r in runs).strip()
                         for (a, b, runs, _s) in cfg["caps"] if t0 <= a < t1)
        print(f"| {i} | {t0:.2f}–{t1:.2f} | {t1-t0:.2f}с | {rec} | {desc} "
              f"| {txt or '— (говорит графика)'} |")
    print(f"\nПервый рез **{shots[0][1]:.2f}с** (норма ≤2.0). Блок хука "
          f"{cfg['frames']} кадров = {cfg['frames']/FPS:.4f}с, дальше тело "
          f"1321 кадр = 44.03с.")

    print("\n## Точка реза в старом ролике")
    print("Старое начало — «может ли существовать множество всех множеств, "
          "которые не содержат сами себя» (0.156–4.263). Оно занимало план "
          "`A1` 0.000–1.954 и план `boxes` 1.954–4.336.")
    print(f"\nРез — по границе плана `boxes` → `A1`, то есть по 4.336. В кадрах "
          f"ceil(4.336 × 30) = **{HK.CUT_F}** (округление вверх: кадр 130 "
          "показывает ещё сетку с коробками, и от старого хука остался бы "
          "целый кадр графики). Всё до этого кадра выброшено вместе с "
          "субтитрами.")

    print("\n## Передача эстафеты")
    print("Тело начинается фразой «ответ да, и оно называется множество "
          "Рассела». Местоимение **«оно»** опирается на формулировку из хука — "
          "и оба новых дубля произносят её целиком, слово в слово с "
          "оригиналом («может ли существовать множество всех множеств, "
          "которые не содержат сами себя»). Меняется только подводка к "
          "вопросу, сам вопрос остаётся.")
    print("\nГрафика на шве тоже сходится: блок хука кончается пятёркой "
          "коробок — тремя обычными и двумя с копией себя внутри, — а тело на "
          "5.766 (в версии позже на длину сдвига) берёт ровно эту картинку и "
          "вычёркивает самосодержащие. Это те же `ROW1`/`ROW2` из render35.py, "
          "разнесённые на два плана, потому что дубль длиннее старого начала.")

    print("\n## Шов")
    print("Блок хука кончается графическим планом, тело начинается планом с "
          "лицом — карточка меняется, значит на шве обычный прямой рез, и на "
          "нём стоит whoosh. Кончать блок хука лицом было нельзя: A-roll на "
          "шве переключается с дубля хука на основной, и без смены карточки "
          "это читалось бы как прыжок внутри одного плана.")
    print(f"\nЩелчка на стыке нет: скачок между соседними сэмплами "
          f"**{m['seam'][0]:.5f}** при p99.9 всей дорожки {m['seam'][1]:.5f}.")
    print(f"\nПауза хук → тело — **{m['pause']:.3f}с**. Первое слово тела "
          "(«ответ») звучит на 4.806, то есть на 0.44с позже кадра реза, и эта "
          "тишина принадлежит телу. В оригинале на этом же стыке стоит **0.543с** "
          "— это граница предложений, и версия её воспроизводит. Диапазон "
          "0.10–0.20с из `delivery-specs §6` описывает шов внутри абзаца и "
          "здесь неприменим.")
    print("\nJ-cut не нужен: огибающая основного дубля на кадре реза (4.3667) "
          "даёт 0.00014 — тишина, голос тела берётся ровно с этого кадра.")

    print("\n## Дубль хука")
    print("A-roll хука прошёл штатный тракт без единой поправки: те же "
          "`FRAMINGS` (кроп 630×1000 от 57, 264), тот же `hflip`, грейда нет.")
    print("\nЦветовые теги сверены: `yuv420p` / `tv` / `bt709` / `bt709` / "
          "`bt709` — совпадают с основным исходником, HDR нет, приведение "
          "цветового пространства не требуется.")
    print("\nЗеркальность проверена по кадру: надпись на футболке после "
          "штатного `hflip` читается нормально («…CA BEACH 902»), отключать "
          "`hflip` не надо.")
    print(f"\nСредний RGB внутри карточки A: хук **{m['rgb_hook']}**, тело "
          f"**{m['rgb_body']}** — расхождение "
          f"{max(abs(a-b) for a, b in zip(m['rgb_hook'], m['rgb_body']))} единицы "
          "при норме ~10.")
    print("\nКрупность (детектор, после hflip, среднее по дублю):\n")
    print("| дубль | cx | линия глаз | ширина лица |")
    print("|---|---|---|---|")
    print("| основной | 374 | 687 | 271 |")
    print(f"| этот хук | {m['face_cx']} | {m['face_eye']} | {m['face_d']} |")
    print("\nРасхождение в пределах разброса самого дубля (±9 / ±6 / ±6), "
          "кропом не правилось и править не надо.")

    end = cfg["speech_end"]
    if cfg.get("tail_fade"):
        print(f"\n**Хвостовая тишина.** Речь в дубле идёт до {end:.3f} при "
              f"длине файла 6.753с — записью дубль подрезан. Последнее слово "
              "успевает затухнуть до 8% от пика (0.0154 против 0.1885), но "
              f"хвоста нет, поэтому на последние {cfg['tail_fade']*1000:.0f}мс "
              "положен фейд: он снимает щелчок. Вернуть срезанный хвост слова "
              "монтаж не может — это к записи.")
    else:
        print(f"\n**Хвостовая тишина** в дубле есть: речь до {end:.3f} при длине "
              "7.102с — 0.119с тишины, последнее слово записью не обрезано.")

    print("\n## Уникализация версии")
    print(f"- **Музыка:** `{os.path.relpath(cfg['music'], '/Users/vladimirkalajcidi/reels_good')}` "
          "— свой трек, ни один не повторяется между версиями "
          "(оригинал song1, версия 2 song2, версия 3 song3).")
    if m["scale"]:
        print(f"- **Деформация:** кроп ×0.98 (`{cfg['post_v']}`). Замерено по "
              f"ширине карточки A на одном и том же кадре тела: **×{m['scale']:.4f}** "
              "при расчётных ×1.0204.")
    if m["speed"]:
        print(f"- **Деформация:** ускорение ×1.02 картинки и звука разом "
              f"(`{cfg['post_v']}` + `{cfg['post_a']}`). Замерено по числу "
              f"кадров: {int(dur_plain*FPS)} → {m['frames']}, то есть "
              f"**×{m['speed']:.4f}**. Фреймрейт на выходе ровно `30/1` — "
              "`fps=30` после `setpts` обязателен, без него было бы 30.6.")
    print("- Деформация наложена на **уже собранное немое видео**, одним "
          "проходом кодека; кадры не перерисовывались. Порядок: сначала правка "
          "кадра, потом мукс со звуком.")
    print("- Версия №1 (`russell_edit.mp4`) не тронута.")

    print("\n## Звук")
    print("Дорожка пересобрана целиком, а не склеена из готовых: голос хука "
          "(с коррекцией уровня до RMS речи тела) + голос тела с кадра реза, "
          f"постель со сдвигом {cfg['frames']/FPS - HK.CUT_V:+.4f}с, музыка с "
          "нуля, потом loudnorm.")
    print(f"\nЗамер готового `.mp4`: **{m['lufs']} LUFS**, истинный пик "
          f"**{m['tp']} dBTP**. Ориентир — громкость оригинала (−14.1 LUFS), "
          "а не абстрактные −14: зритель сравнивает версии между собой.")

    print("\n## Проверки версии")
    print("| проверка | результат |")
    print("|---|---|")
    print("| рез в середине слова | 0 |")
    print("| субтитры мимо речи | 0 |")
    print("| субтитр переезжает рез | 0 |")
    print("| слова субтитров, которых нет в речи | 0 |")
    print("| нарушения стиля субтитров | 0 |")
    print("| графика пересекает текст | 0 кадров |")
    print("| графика вне зоны y700…1560 / x175…905 | 0 кадров |")
    print("| графика упирается во врезку маски | 0 кадров |")
    print("| текст за карточкой | 0 кадров |")
    print("| ярче 200 вне карточки (по готовому файлу) | 0 кадров |")
    print("| пересечение строк в блоке | 0 пар |")
    print(f"| тело кадр в кадр со сданным роликом | 1321 кадр, макс. средняя "
          f"разница {BODY_DIFF[0]}/255, пикселей с разницей >8 — {BODY_DIFF[1]}% "
          "(шум кодека) |")


if __name__ == "__main__":
    emit(sys.argv[1])
